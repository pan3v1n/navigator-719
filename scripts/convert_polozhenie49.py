"""PDF Положения об экспертизе страны происхождения (Приказ ТПП РФ №49) → текст корпуса (`K16` #48).

ЗАЧЕМ СКРИПТ, А НЕ РАЗОВАЯ КОНВЕРТАЦИЯ. Та же причина, что у `convert_metodrek.py`: исходник в
репозиторий не едет (`.gitignore`, `/*.pdf`), поэтому единственное, что связывает
`knowledge_base/pp719/polozhenie49_tpp.txt` с документом ТПП, — этот файл. Предохранитель вне
репозитория живёт один раз.

ЧТО ЭТО ЗА ДОКУМЕНТ. «Положение о порядке проведения экспертизы по определению страны
происхождения товара для оформления сертификатов о происхождении товара», приложение к приказу
ТПП РФ №49 от 14.07.2023. Он объясняет ПРОЦЕДУРУ, которая предшествует СТ-1: какие документы
подаёт заявитель, как проводится экспертиза, что попадает в акт экспертизы. В корпусе не было —
это вторая половина `K16`.

⚠⚠⚠ ПЕРВОИСТОЧНИК ОТДАЁТ УСТАРЕВШИЙ ТЕКСТ, И ЭТО ГЛАВНАЯ ТОНКОСТЬ. На своей странице
(`/ru/legal_provision/ved/certificates/`) ТПП РФ публикует файл `...20230714.pdf` — ИСХОДНУЮ
редакцию 2023 года. Документ же действует **в ред. Приказа ТПП РФ от 16.07.2026 N 59** (тот же
приказ, которым изменён и Приказ №14, уже лежащий в корпусе). Обновлённого PDF на tpprf.ru нет.
Сверка с действующей редакцией: похожесть тела 0.983, разница **+371 знак**, и она разложена
до конца: **254 знака — сам абзац**, введённый в п. 6.13 приказом №59 (дописывается здесь
дословно), **117 — типографика сносок** (агрегатор печатает их как «<1> …», PDF как «1 …»);
нормативного содержания в этих 117 знаках нет.
⚠ Прежняя формулировка «вся она — один абзац» была неточной: 117 знаков она не объясняла.

⚠ ПОЧЕМУ НЕ ВЗЯТЬ ЦЕЛИКОМ У АГРЕГАТОРА. Текст действующей редакции есть у правовых агрегаторов,
но первоисточник — ТПП РФ, а сервис печатает источники пользователю. Берём тело у ТПП, а поправку
дописываем ОДНИМ проверяемым куском: так расхождение с первоисточником видно глазами и его
сторожит контроль, а не «доверьтесь агрегатору».

⚠⚠ У КАЖДОЙ ЧИСТКИ ЕСТЬ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. «Ноль срабатываний» и «формат исходника
изменился, чистка ослепла» снаружи неразличимы, а второй случай тихо занёс бы в корпус номера
страниц и потерял бы поправку. Скрипт падает, если не нашёл того, что обязан найти.

Запуск:
    .venv\\Scripts\\python scripts/convert_polozhenie49.py --pdf "путь.pdf"
    .venv\\Scripts\\python scripts/convert_polozhenie49.py --pdf "путь.pdf" --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.core.console import enable_utf8  # noqa: E402

OUT = ROOT / "knowledge_base" / "pp719" / "polozhenie49_tpp.txt"

# Служебный дефис-буллет PDF (private use area) — в тексте их 79, это маркеры перечислений.
_BULLET = ""
_MIN_BULLETS = 50

# Тело кончается бланками заявлений — они из одних подчёркиваний и в индексе только шумят.
_APPENDIX_RE = re.compile(r"^\s*Приложение\s+\d+\s+к\s+Положению\s*$", re.M)
_SECTION_RE = re.compile(r"^Раздел\s+(\d+)\.\s*(.+)$", re.M)
_POINT_RE = re.compile(r"^(\d+(?:\.\d+){1,2})\.?\s+\S", re.M)
_PAGENUM_RE = re.compile(r"^\s*\d{1,2}\s*$", re.M)

# ⚠⚠⚠ ТЕЛО ПОСТРАНИЧНОЙ СНОСКИ ВКЛЕИВАЛОСЬ В ПУНКТ КАК ОЧЕРЕДНОЙ ЭЛЕМЕНТ ПЕРЕЧНЯ (находка
# раунда 12). Номер страницы вырезается, а ТЕЛО сноски остаётся, и разборщик приклеивает его к
# открытому пункту. В п. 4.3.2 сноска 1 вставала сразу после «- фитосанитарный (карантинный)
# сертификат; или», то есть МЕЖДУ двумя пунктами обязательного перечня, — а `text` цитируется
# эксперту ДОСЛОВНО. Разрешительная оговорка («Допускается представление документов,
# отличающихся по наименованию») читалась как следующий ОБЯЗАТЕЛЬНЫЙ документ раздела 4.
# ⚠ Сноска не удаляется: она содержательна. Она ПОМЕЧАЕТСЯ, и пометка видна в цитате.
# ⚠ Признак безопасен по построению: пункты этого документа всегда «N.N», поэтому ОДИНОЧНАЯ
# цифра в начале строки пунктом быть не может.
_FOOTNOTE_RE = re.compile(r"^([1-9])\s+(?=[А-ЯЁ])(.+)$", re.M)
_MIN_FOOTNOTES = 3

_MIN_SECTIONS = 6
_MIN_POINTS = 55

# ⚠ Поправка приказа №59 от 16.07.2026 — ДОСЛОВНО, вводится в конец п. 6.13.
_AMEND_ANCHOR = (
    "акт экспертизы составляется и направляется заявителю в электронной форме, "
    "подписанный электронной подписью уполномоченного сотрудника уполномоченной "
    "ТПП/экспертной организации."
)
_AMEND_TEXT = (
    " В этом случае допускается отступать от требований, предусмотренных Положением, в части "
    "наличия в акте экспертизы оттиска печати уполномоченной ТПП/экспертной организации и "
    "подписей их уполномоченных лиц. (абзац введен Приказом ТПП РФ от 16.07.2026 N 59)"
)
_EDITION_LINE = "(в ред. Приказа ТПП РФ от 16.07.2026 N 59)"


def extract(pdf_path: Path) -> str:
    try:
        import pdfplumber
    except ImportError:
        sys.exit("нужен pdfplumber: .venv\\Scripts\\pip install pdfplumber")
    with pdfplumber.open(pdf_path) as pdf:
        pages = [p.extract_text() or "" for p in pdf.pages]
    if len(pages) < 20:
        sys.exit(f"в PDF {len(pages)} страниц — ожидалось ≥20; это другой документ")
    return "\n".join(pages)


def clean(raw: str) -> str:
    """Чистка с положительными контролями на КАЖДОЕ правило."""
    n_bullets = raw.count(_BULLET)
    if n_bullets < _MIN_BULLETS:
        sys.exit(f"маркеров перечисления найдено {n_bullets}, ожидалось ≥{_MIN_BULLETS} — "
                 "формат PDF изменился, чистка ослепла")
    text = raw.replace(_BULLET, "-").replace("­", "")

    # Тело — до бланков приложений.
    m = _APPENDIX_RE.search(text)
    if not m:
        sys.exit("не найдена граница приложений («Приложение N») — бланки уехали бы в индекс")
    body = text[:m.start()]

    # Номера страниц — только ОДИНОКИЕ числа на строке.
    body, n_pages = _PAGENUM_RE.subn("", body)
    if n_pages < 15:
        sys.exit(f"номеров страниц вырезано {n_pages}, ожидалось ≥15 — проверьте формат")

    body, n_foot = _FOOTNOTE_RE.subn(r"[сноска \1] \2", body)
    if n_foot < _MIN_FOOTNOTES:
        sys.exit(f"сносок помечено {n_foot}, ожидалось ≥{_MIN_FOOTNOTES} — формат изменился, "
                 "и тело сноски снова уедет в пункт как очередной элемент перечня")

    body = re.sub(r"\n{3,}", "\n\n", body).strip()

    secs = _SECTION_RE.findall(body)
    if len(secs) < _MIN_SECTIONS:
        sys.exit(f"разделов найдено {len(secs)}, ожидалось ≥{_MIN_SECTIONS}")
    pts = _POINT_RE.findall(body)
    if len(pts) < _MIN_POINTS:
        sys.exit(f"пунктов найдено {len(pts)}, ожидалось ≥{_MIN_POINTS}")
    return body


def apply_amendment(body: str) -> str:
    """Поправка приказа №59 — с контролем на ЕДИНСТВЕННОСТЬ якоря и на отсутствие дубля.

    ⚠ Оба контроля обязательны и по разным причинам: несколько якорей означают, что текст
    изменился и поправка встанет не туда; уже присутствующая поправка означает, что на вход подали
    действующую редакцию — тогда дописывать нельзя, получится дубль абзаца в корпусе."""
    if "16.07.2026 N 59" in body:
        sys.exit("в исходнике уже есть отметка приказа №59 — подан текст действующей редакции, "
                 "дописывать поправку нельзя (получился бы дубль абзаца)")
    flat = re.sub(r"\s+", " ", body)
    if flat.count(_AMEND_ANCHOR) != 1:
        sys.exit(f"якорь поправки найден {flat.count(_AMEND_ANCHOR)} раз(а), нужен ровно один — "
                 "текст п. 6.13 изменился, поправка встала бы не туда")
    # Вставляем в исходный текст, где якорь может быть разбит переносами строк.
    pat = re.compile(r"\s+".join(map(re.escape, _AMEND_ANCHOR.split())))
    body, n = pat.subn(lambda m: m.group(0) + _AMEND_TEXT, body, count=1)
    if n != 1:
        sys.exit("поправка не вставилась — якорь не нашёлся в исходной разметке")
    return body


def build(pdf_path: Path) -> str:
    body = apply_amendment(clean(extract(pdf_path)))
    head = (
        "# Положение о порядке проведения экспертизы по определению страны происхождения "
        "товара для оформления сертификатов о происхождении товара\n"
        "# Приложение к приказу ТПП РФ №49 от 14 июля 2023 года\n"
        f"# {_EDITION_LINE}\n"
        "# Источник: tpprf.ru, раздел «Правовое обеспечение ВЭД / Сертификаты о происхождении».\n"
        "# ⚠ Тело — редакция 2023 г. с сайта ТПП РФ; абзац приказа №59 от 16.07.2026 дописан\n"
        "#   скриптом scripts/convert_polozhenie49.py (на tpprf.ru обновлённого PDF нет).\n"
    )
    return head + "\n" + body + "\n"


def main() -> None:
    enable_utf8()
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--pdf", required=True, help="путь к PDF Положения (tpprf.ru)")
    ap.add_argument("--check", action="store_true", help="только проверить, не писать файл")
    a = ap.parse_args()

    pdf = Path(a.pdf)
    if not pdf.exists():
        sys.exit(f"нет файла {pdf}")
    text = build(pdf)

    secs = _SECTION_RE.findall(text)
    pts = _POINT_RE.findall(text)
    print(f"разделов: {len(secs)} · пунктов: {len(pts)} · знаков: {len(text)}")
    print(f"поправка приказа №59: {'есть' if '16.07.2026 N 59' in text else 'НЕТ'}")
    if a.check:
        print("--check: файл не записан")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"записано: {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
