def dense_top1(query: str) -> tuple[float, str]:
    res = _client().query_points(
        collection_name=settings.QDRANT_CASES_COLLECTION,
        query=embed_query(query), using="dense", limit=1, with_payload=["_file"],
    )
    if not res.points:
        return 0.0, "—"
    p = res.points[0]
    return float(p.score), (p.payload or {}).get("_file", "?")


def sweep(title: str, queries: list[str]) -> list[float]:
    print(f"\n{'=' * 96}\n{title}\n{'=' * 96}")
    scores = []
    for q in queries:
        s, f = dense_top1(q)
        scores.append(s)
        print(f"  {s:.3f}  {q[:54]:56.56} -> {f[:40]}")
    return scores


def main() -> int:
    client = _client()
    name = settings.QDRANT_CASES_COLLECTION
    if not client.collection_exists(name):
        print(f"Коллекции '{name}' нет. Сначала: scripts/seed_cases.py")
        return 1
    n = client.get_collection(name).points_count
    print(f"Коллекция '{name}': {n} кейсов. Текущий порог CASE_RELEVANCE_MIN = {settings.CASE_RELEVANCE_MIN}")

    pos = sweep("ПОЗИТИВЫ — кейс уместен (перефразировки)", POSITIVES)
    neg = sweep("НЕГАТИВЫ — вне сферы 719", NEGATIVES_OUT)
    neg += sweep("НЕГАТИВЫ — профильные, но своего кейса нет", NEGATIVES_IN)
    neg += sweep("НЕГАТИВЫ — та же ФОРМА вопроса, другой товар (самые опасные)", NEGATIVES_FORM)

    print(f"\n{'=' * 96}\nСВОДКА\n{'=' * 96}")
    print(f"  ПОЗИТИВЫ : min={min(pos):.3f}  median={sorted(pos)[len(pos) // 2]:.3f}  max={max(pos):.3f}  (n={len(pos)})")
    print(f"  НЕГАТИВЫ : min={min(neg):.3f}  median={sorted(neg)[len(neg) // 2]:.3f}  max={max(neg):.3f}  (n={len(neg)})")

    gap = min(pos) - max(neg)
    if gap > 0:
        mid = (min(pos) + max(neg)) / 2
        print(f"  ✅ ПОЛОСА ЧИСТАЯ: разрыв {gap:.3f}. Любой порог в ({max(neg):.3f}, {min(pos):.3f}) "
              f"разделяет идеально; середина = {mid:.3f}")
    else:
        print(f"  ⚠ ПЕРЕСЕЧЕНИЕ: neg_max {max(neg):.3f} ≥ pos_min {min(pos):.3f} — идеального порога НЕТ.")
        print("     Выбирать в пользу меньшего числа ложных: показать чужой кейс дороже, чем не показать свой.")
        for t in (0.80, 0.82, 0.84, 0.85, 0.86, 0.88):
            print(f"     порог {t:.2f}: пропускает позитивов {sum(1 for s in pos if s >= t)}/{len(pos)}, "
                  f"ложных {sum(1 for s in neg if s >= t)}/{len(neg)}")

    cur = settings.CASE_RELEVANCE_MIN
    print(f"\n  При ТЕКУЩЕМ пороге {cur}: пройдёт позитивов {sum(1 for s in pos if s >= cur)}/{len(pos)}, "
          f"ложных {sum(1 for s in neg if s >= cur)}/{len(neg)}")

    real = sweep("РЕАЛЬНЫЙ ТРАФИК (июль 2026) — цена порога, а не его источник", REAL_TRAFFIC)
    passed = sum(1 for s in real if s >= cur)
    print(f"\n  На реальных запросах порог {cur} пропускает {passed}/{len(real)}.")
    print("  Остальные теряются — и это ОСОЗНАННАЯ плата: ложный кейс идёт в контекст с высшим")
    print("  приоритетом и выглядит достоверно, а пропущенный лишь лишает ответ подсказки,")
    print("  тогда как первоисточник и правила промпта остаются на месте.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
