"""Калибровка порога релевантности кейсов петли обучения (`CASE_RELEVANCE_MIN`, R30).

ЗАЧЕМ. Кейс эксперта уходит в контекст с ВЫСШИМ приоритетом (правило 1а промпта навигатора),
выше первоисточника. Нерелевантный кейс поэтому не шум, а правдоподобная дезинформация —
и её не поймает ни faithfulness-гард (он проверяет заземлённость числа, а не уместность
источника), ни эксперт. Отсюда порог: не показать лучше, чем показать чужое.

ПОЧЕМУ ЧИСТЫЙ DENSE, А НЕ ФЬЮЖН-SCORE. Фьюжн-score — результат RRF-слияния РАНГОВ. На
коллекции из десятка записей что-то всегда оказывается первым, и нормированный топ почти
всегда 1.0; абсолютной релевантности в этом числе нет. Замер 12.08.2026 это показал прямо:
«оказываем юридические услуги» тянули кейс НИОКР грузового автотранспорта со score 0.833,
а «стоимость экспертизы ТПП» — со score 1.000, столько же, сколько верное попадание.
На чистом dense-косинусе полоса, наоборот, чистая.

БАЗОВЫЙ ЗАМЕР (12.08.2026, 12 кейсов в коллекции):
    позитивы  min 0.839  median 0.870  max 0.922   (n=14, перефразировки)
    негативы  min 0.754  median 0.772  max 0.803   (n=16)
    разрыв 0.037 → порог 0.82 (середина полосы)

⚠ ПЕРЕКАЛИБРОВЫВАТЬ ПО МЕРЕ РОСТА КОЛЛЕКЦИИ. Чем больше кейсов, тем выше шанс, что
посторонний запрос окажется к какому-нибудь из них близок, — полоса будет сужаться.
Правило: добавили заметную порцию кейсов → прогнали этот скрипт → обновили порог.

ВАЖНО ПРО НАБОР. Позитивы обязаны быть ПЕРЕФРАЗИРОВКАМИ, а не дословными `query` кейсов:
на дословных косинус около единицы, и замер получится льстивым. Негативы нужны двух сортов —
вне сферы 719 И профильные товарные запросы, к которым просто нет своего кейса (вторых
больше в реальном трафике, и они опаснее: ближе по лексике).

ЗАПУСК (нужен поднятый Qdrant с коллекцией verified_cases; DeepSeek НЕ нужен):
    PYTHONUTF8=1 .venv/Scripts/python.exe scripts/calibrate_cases.py
"""
