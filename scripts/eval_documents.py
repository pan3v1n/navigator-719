# --- ДОКУМЕНТНЫЕ КЕЙСЫ (`EV21` #119) -----------------------------------------------------------
# До 26.08.2026 в наборе было НОЛЬ вопросов про состав документов — при том что это кластер жалоб
# №1 июля (31 упоминание). Всё, что делалось для темы (`K12`, `K15`, `EV18`), стандартным замером
# не проверялось вовсе: только адресными живыми прогонами, руками, ровно столько раз, сколько я
# вспомнил их сделать. Оба дефекта `K15` так и нашлись — уже ПОСЛЕ выкатки.

# Распознаватели закрытого перечня в СВОБОДНОМ тексте ответа. Ключ — имя ИЗ `CONFIRMING_DOCUMENTS`.
# ⚠ Ключи сверяются со справочником на старте (`check_documents_reference`): переименование или
# удаление документа в продукте обязано ОСТАНОВИТЬ замер, а не тихо выключить проверку. Это тот
# самый положительный контроль, без которого «ноль срабатываний» и «инструмент слеп» неразличимы.
_DOC_RECOGNIZERS: dict[str, re.Pattern[str]] = {
    "Акт экспертизы уполномоченной ТПП": re.compile(r"акт\w*\s+экспертизы", re.I),
    "Сертификат о происхождении товара формы СТ-1": re.compile(r"\bСТ-?\s?1\b", re.I),
    "Сведения о реестровой записи с выписками из реестра": re.compile(
        r"реестров\w+\s+запис|выписк\w+\s+из\s+реестр|сведени\w+\s+о\s+реестров", re.I),
}

# Источники, на которые ответ обязан сослаться. Ключ — `doc_type` корпуса (манифест `K8`).
#
# ⚠⚠ ПАТТЕРН ОБЯЗАН УЗНАВАТЬ ТУ ФОРМУ, КОТОРУЮ ВИДИТ МОДЕЛЬ, А НЕ ТУ, КОТОРУЮ ПРИДУМАЛ Я.
# Первая редакция искала «методические рекомендации» — и на первом же живом прогоне дала
# «источник не назван» кейсу #47. Разбор показал: два пункта Методрекомендаций В ОКНЕ БЫЛИ, а
# контекст подписывает их СОКРАЩЕНИЕМ из манифеста — «Методрекомендации ТПП РФ». Модель честно
# цитировала то, что видела; слеп был замер. Ровно тот класс, о котором предупреждает проект:
# инструмент, чьё «нет» неотличимо от «не умею смотреть».
# Поэтому ниже — обе формы, а `check_source_recognizers` сверяет каждый паттерн с ярлыком
# манифеста (`short`): переименуй документ — и замер остановится, а не ослепнет.
_SOURCE_RECOGNIZERS: dict[str, re.Pattern[str]] = {
    "tpp_order_52": re.compile(r"приказ\w*\s+ТПП|№\s*52\b|N\s*52\b|"
                               r"положени\w+\s+о\s+порядке\s+выдачи", re.I),
    "metodrek_tpp": re.compile(r"методрекомендаци|методическ\w+\s+рекомендац", re.I),
}


def check_source_recognizers() -> None:
    """Положительный контроль: каждый паттерн узнаёт ярлык, которым корпус подписывает документ."""
    from app.core.manifest import documents as manifest_documents

    labels = {d["doc_type"]: (d.get("short") or d.get("title") or "")
              for d in manifest_documents("pp719_rules")}
    blind = [dt for dt, pat in _SOURCE_RECOGNIZERS.items()
             if not pat.search(labels.get(dt, ""))]
    if blind:
        raise SystemExit(
            f"Распознаватель источника не узнаёт ярлык корпуса: {blind}.\n"
            f"  ярлыки манифеста: { {dt: labels.get(dt) for dt in blind} }\n"
            "Замер отчитался бы «источник не назван» на верных ответах.")

# ⚠⚠ ТЕРМИН ПРОВЕРЯЕТСЯ НЕЗАВИСИМО ОТ РАНТАЙМ-ГАРДА, И ЭТО НЕ ДУБЛИРОВАНИЕ, А УСЛОВИЕ ПРОВЕРКИ.
# `documents_ref.unverified_documents` — сам предохранитель продукта. Позови его оракул — и снятие
# гарда сделало бы метрику ЗЕЛЁНОЙ: набор остался бы зелёным при удалённом предохранителе, ровно
# класс `O3` #104. Поэтому здесь своя, нарочито простая пара регулярок, а значение гарда печатается
# РЯДОМ как наблюдаемая величина: расхождение двух чтений одного текста само по себе сигнал.
# ⚠ Faithfulness устроена наоборот (берёт `unverified_numbers` из пайплайна) — там выбор сделан
# осознанно и по другой причине: не дать замеру и рантайму разойтись в определении выдумки.
# ⚠ Две формы, а не одна. Первая редакция знала только «заключение ТПП» и не видела обратный
# порядок слов — «торгово-промышленная палата выдаёт заключение», — а это одна из ДВУХ реальных
# выдумок из кейса эксперта. Нашлось собственным тестом на второе упоминание в одном ответе.
FAKE_TERM_RE = re.compile(
    r"заключени\w*\s+(?:уполномоченн\w+\s+)?(?:ТПП|торгово-промышленн\w+\s+палат\w+)"
    r"|(?:ТПП|торгово-промышленн\w+\s+палат\w+)\s+(?:выда\w+|оформля\w+)\s+заключени\w*", re.I)
# «Экспертное заключение» — ДЕЙСТВУЮЩИЙ документ (п. 36-40 Правил, итог выездной проверки).
# Вырезаем ДО поиска выдумки, иначе проверка била бы по верному тексту.
EXPERT_CONCLUSION_RE = re.compile(r"экспертн\w*\s+заключени\w*", re.I)
DENIAL_RE = re.compile(r"не\s+существ|нет\s+так|так(ого|ой)\s+документа\s+нет|не\s+предусмотр|"
                       r"не\s+бывает|отсутству|ошибочн", re.I)
DENIAL_WINDOW = 200


def check_documents_reference() -> None:
    """Положительный контроль: распознаватели описывают РОВНО закрытый перечень продукта."""
    check_source_recognizers()
    names = {d["name"] for d in CONFIRMING_DOCUMENTS}
    if names != set(_DOC_RECOGNIZERS):
        raise SystemExit(
            "Закрытый перечень документов разошёлся с распознавателями замера.\n"
            f"  в справочнике, но не в замере: {sorted(names - set(_DOC_RECOGNIZERS))}\n"
            f"  в замере, но не в справочнике: {sorted(set(_DOC_RECOGNIZERS) - names)}\n"
            "Остановка намеренная: молча измерять устаревший перечень хуже, чем не измерять.")


def conclusion_mentions(text: str) -> tuple[int, list[str]]:
    """(сколько раз назван несуществующий «заключение ТПП», какие из них БЕЗ отрицания рядом).

    Отрицание рядом = ответ ОБЪЯСНЯЕТ, а не советует, и это цель `K15`, а не дефект: гард продукта
    наказывал за это самые правильные ответы, пока живой прогон на бою 25.08.2026 не показал."""
    cleaned = EXPERT_CONCLUSION_RE.sub(" ", text or "")
    affirmed: list[str] = []
    total = 0
    for m in FAKE_TERM_RE.finditer(cleaned):
        total += 1
        lo, hi = max(0, m.start() - DENIAL_WINDOW), min(len(cleaned), m.end() + DENIAL_WINDOW)
        if not DENIAL_RE.search(cleaned[lo:hi]):
            affirmed.append(" ".join(m.group(0).split()))
    return total, affirmed


def documents_row(case: dict, text: str) -> dict:
    """Что документный кейс обязан показать. Эталон — закрытый перечень экспертов, НЕ вывод сервиса."""
    want = list(case.get("expect_documents") or [])
    named = [d for d in want if _DOC_RECOGNIZERS[d].search(text)]
    mentions, affirmed = conclusion_mentions(text)
    if case.get("expect_explanation"):
        # Пользователь сам поднял тему — разъяснение обязано быть, и обязано быть отрицанием.
        explanation_ok = mentions > 0 and not affirmed
    else:
        # Пользователь про этот документ не спрашивал — термина в ответе быть не должно ВОВСЕ
        # (критерий приёмки `K15`; правка `dbfc622` — про то же самое).
        explanation_ok = mentions == 0
    want_src = list(case.get("expect_sources") or [])
    return {
        "want_docs": want,
        "named_docs": named,
        "docs_ok": len(named) == len(want),
        "want_explanation": bool(case.get("expect_explanation")),
        "term_mentions": mentions,
        "term_affirmed": affirmed,
        "explanation_ok": explanation_ok,
        "want_sources": want_src,
        "named_sources": [s for s in want_src if _SOURCE_RECOGNIZERS[s].search(text)],
    }
