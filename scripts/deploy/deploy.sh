# Проверка МАРКЕРА: строка вида «файл|шаблон|описание».
# ⚠⚠ O5 (#113): ГДЕ ИСКАТЬ ФАЙЛ МАРКЕРА. `MARKER_ROOTS` — каталоги в порядке приоритета;
# пусто = текущий каталог (историческое поведение, `cd "$SRC" && check_marker`).
#
# Нужно это сухому прогону НА VM. Пакет там — ДЕЛЬТА к выкаченному релизу: файл, который не
# менялся, в архив не попадает вовсе. Значит ни рабочая копия, ни пакет по отдельности не
# отвечают на вопрос «что будет после распаковки»: ответ — рабочая копия ПОВЕРХ которой лёг
# пакет. Два корня это и моделируют: сначала пакет (файл менялся и приедет), потом рабочая
# копия (файл не менялся и останется).
MARKER_ROOTS=""

check_marker() {
  local spec="$1" want_present="$2"
  local file="${spec%%|*}"; local rest="${spec#*|}"
  local pattern="${rest%%|*}"; local desc="${rest#*|}"
  local path="$file" root
  for root in ${MARKER_ROOTS}; do
    [ -f "$root/$file" ] && { path="$root/$file"; break; }
  done
  if grep -qE "$pattern" "$path" 2>/dev/null; then
    [ "$want_present" = "1" ] && return 0
    say "СТАРЫЙ КОД: $desc (в $path всё ещё есть «$pattern»)"; return 1
  else
    [ "$want_present" = "1" ] || return 0
    say "НЕ ДОЕХАЛО: $desc (в $path нет «$pattern»)"; return 1
  fi
}

# ⚠⚠ ГЕЙТ CI НА КОММИТЕ, КОТОРЫЙ ЕДЕТ. Куплен инцидентом 21.08.2026: батарея простояла красной
# ШЕСТЬ прогонов подряд, и в этой красноте PR #103 уехал в `main`, а `v0.5.0-test13` — на бой.
# Ломался один тест, переставший быть офлайновым; CI поймал его ВЕРНО и ровно так, как обещает
# комментарий в tests.yml, — сигнал просто некому было прочитать. Ровно тот класс, что уже
# записан в уроках: предохранитель, который сообщает о провале и не останавливает, равен
# отсутствующему. Здесь он останавливает.
#
# ПОЧЕМУ В СУХОМ ПРОГОНЕ. Он обязателен перед каждой выкаткой. ⚠ Гонять его можно И на машине
# разработчика, И на VM — usage в шапке предписывает второе, и до 25.08.2026 комментарий здесь
# утверждал обратное («идёт на машине разработчика»). Два места скрипта учили разному, а
# резолвинг был написан под одно из прочтений: на VM маркеры сверялись с РАБОЧЕЙ КОПИЕЙ, то
# есть с кодом, который выкатка как раз ЗАМЕНЯЕТ, — и верный профиль получал «13 маркеров не
# совпало, чинить ЗДЕСЬ». Предохранитель, бьющий по верному, дороже отсутствующего.
#
# Теперь: на VM маркеры сверяются с ПАКЕТОМ поверх рабочей копии (см. `MARKER_ROOTS`), а гейт
# CI там честно говорит «проверить не смог: нет gh» — это предупреждение, а не «зелено».
#
# ⚠ «Проверить не смог» НИКОГДА не печатается как «зелено»: нет gh, нет сети, нет прогона — это
# предупреждение и просьба посмотреть руками, но не провал. Предохранитель, бьющий по верному
# коду, дороже отсутствующего (урок 18.08), а отсутствие интернета кодом не является.
ci_gate() {
  local src="$1" sha concl from
  if [ "${SKIP_CI_GATE:-0}" = "1" ]; then
    say "  ⚠ ГЕЙТ CI ОТКЛЮЧЁН вручную (SKIP_CI_GATE=1) — осознанный риск, а не «зелено»"
    return 0
  fi
  command -v gh >/dev/null 2>&1 || {
    say "  ⚠ CI НЕ ПРОВЕРЕН: gh не установлен. Это НЕ «зелено» — смотрите прогон руками"; return 0; }
  # ⚠ КОММИТ БЕРЁТСЯ ИЗ ТЕГА РЕЛИЗА, А НЕ ИЗ HEAD. Первая редакция брала `git rev-parse HEAD`
  # каталога с исходниками — а это на машине разработчика вершина `dev` (после `v0.5.0-test13`
  # там успели лечь ещё два коммита), а на VM — `prod`, то есть ПРЕДЫДУЩИЙ релиз. Гейт, чья
  # единственная задача — «зелёный CI на коммите, который едет», проверял бы чужой коммит и
  # спокойно пропускал красный. Ревью 24.08.2026.
  # ⚠ `--verify --quiet` ОБЯЗАТЕЛЬНЫ. Голый `git rev-parse "$TAG^{commit}"` при отсутствии тега
  # печатает в stdout САМУ СТРОКУ («v0.5.0-test12^{commit}») и выходит с кодом 128 — то есть
  # переменная получает мусор вместо SHA, проверка уходит в `gh` с ним и молча ничего не находит.
  # Поймано CI на первом же прогоне этой правки: в чекауте GitHub Actions тегов нет.
  # Форма `if cmd; then` выбрана вместо `cmd && x=…` намеренно: под `set -u` вторая ветка
  # оставляла бы `from` неприсвоенной, и функция падала бы на печати.
  if sha=$(cd "$src" && git rev-parse --verify --quiet "$TAG^{commit}" 2>/dev/null); then
    from="тег $TAG"
  else
    # Тега ещё нет — сухой прогон часто идёт ДО тегирования, а в чекауте CI тегов не бывает
    # вовсе. HEAD честнее отсутствия проверки, но об этом надо сказать вслух: проверяется не то,
    # что поедет.
    sha=$(cd "$src" && git rev-parse --verify --quiet HEAD 2>/dev/null) || sha=""
    from="HEAD (тега $TAG нет — проверяется НЕ релизный коммит)"
  fi
  [ -n "$sha" ] || { say "  ⚠ CI НЕ ПРОВЕРЕН: в $src нет git-репозитория"; return 0; }
  say "  коммит под проверкой: $from → $sha"
  if [ -n "$(cd "$src" && git status --porcelain 2>/dev/null)" ]; then
    say "  ⚠ рабочее дерево ГРЯЗНОЕ: CI отвечает за $sha, а поедет не он"
  fi
  # ⚠ «gh не ответил» и «прогонов на коммите нет» — РАЗНЫЕ вещи, и раньше они сливались в одну
  # строку «не нашлось». Сеть в этом проекте рваная (DPI): на живом прогоне 24.08 запрос отвалился
  # по таймауту, и гейт сказал «прогона не нашлось» про коммит, у которого их два и оба красные.
  # Деградация безопасная, но оператор читает СТРОКУ — и «нет прогонов» звучит как «всё чисто».
  if ! concl=$(cd "$src" && gh run list --commit "$sha" --limit 20 --json conclusion \
                 --jq '[.[].conclusion] | join(" ")' 2>/dev/null); then
    say "  ⚠⚠ CI НЕ ПРОВЕРЕН: gh НЕ ОТВЕТИЛ (сеть?). Это НЕ «зелено» и не «прогонов нет» —"
    say "     повторите сухой прогон или откройте Actions руками"
    return 0
  fi
  case " $concl " in
    *" failure "*|*" timed_out "*|*" startup_failure "*)
      say "  ❌ CI НА $sha КРАСНЫЙ ($concl) — выкатывать нельзя, чинить батарею"
      say "     осознанный обход, если провал заведомо не про этот код: SKIP_CI_GATE=1"
      return 1 ;;
    *" success "*) say "  CI на $sha: зелёный" ;;
    *) say "  ⚠ CI НЕ ПРОВЕРЕН: gh ответил, но прогонов на $sha нет — он ещё идёт либо не запускался" ;;
  esac
  return 0
}

# --- сухой прогон -------------------------------------------------------------------------
if [ "$DRY_RUN" = "1" ]; then
  say "СУХОЙ ПРОГОН профиля $RELEASE"
  say "  тег: $TAG"
  say "  пакет: $PKG   рабочая копия: $APP"
  for c in "${!EXPECT[@]}"; do say "  ждём коллекцию $c = ${EXPECT[$c]}"; done
  if [ -n "$SNAPSHOT" ]; then
    say "  снапшот: $SNAPSHOT → коллекция $SNAPSHOT_COLLECTION"
  fi
  # ⚠ ЧТО БУДЕТ С КОРПУСОМ — ОТДЕЛЬНАЯ СТРОКА, И ОНА СЧИТАЕТ ВСЕ ТРИ СПОСОБА.
  # Прежняя редакция смотрела ТОЛЬКО на снапшот и печатала «выкатка рантаймовая, корпус
  # не трогаем» на релизе с REINDEX_FULL, который коллекцию ПЕРЕСОЗДАЁТ. Оператор читает
  # строку, а не профиль: сообщение, врущее в сторону «безопасно», хуже отсутствующего.
  if [ -n "${REINDEX_FULL:-}" ]; then
    say "  КОРПУС: ПОЛНАЯ переиндексация ${REINDEX_FULL} — коллекция ПЕРЕСОЗДАЁТСЯ,"
    say "          процедурная ветка будет пустой всё время прогона e5"
  elif [ -n "${REINDEX_DOCS:-}" ]; then
    say "  КОРПУС: переиндексация по документам (K11): ${REINDEX_DOCS} — коллекция не пустеет"
  elif [ -z "$SNAPSHOT" ]; then
    say "  КОРПУС: не трогаем — выкатка рантаймовая (ни снапшота, ни переиндексации)"
  fi
  # ⚠ Маркеры сверяем С КОДОМ, а не только считаем. Шаблон, не совпадающий с тем, что едет в
  # пакете, останавливает ВЕРНУЮ выкатку — это уже случалось (18.08). Дешевле поймать здесь.
  SRC="${SRC:-}"
  DRY_TMP=""
  # 1) Пакет рядом — распаковываем и сверяем С НИМ поверх рабочей копии. Это и есть «код,
  #    который поедет»; ровно так выглядит дерево после распаковки на шаге выкатки.
  if [ -z "$SRC" ] && [ -f "$PKG/navigator-719-$TAG.tar.gz" ]; then
    DRY_TMP="$(mktemp -d)"
    if tar -xzf "$PKG/navigator-719-$TAG.tar.gz" -C "$DRY_TMP" 2>/dev/null; then
      MARKER_ROOTS="$DRY_TMP $APP"
      say "  сверяю маркеры с ПАКЕТОМ поверх рабочей копии ($APP)"
    else
      say "  ⚠ архив пакета не распаковался — сверяю с тем, что найдётся"
      rm -rf "$DRY_TMP"; DRY_TMP=""
    fi
  fi
  # 2) Пакета нет (машина разработчика) — берём репозиторий. ⚠ `$APP` из кандидатов УБРАН
  #    намеренно: это код, который заменяют, и сверка с ним всегда обвиняет верный профиль.
  if [ -z "$SRC" ] && [ -z "$MARKER_ROOTS" ]; then
    for cand in "$PWD" "$SELF_DIR/../.."; do
      [ -f "$cand/app/core/config.py" ] && { SRC="$cand"; break; }
    done
  fi
  if [ -n "$SRC" ] || [ -n "$MARKER_ROOTS" ]; then
    [ -n "$SRC" ] && say "  сверяю маркеры с кодом в $SRC"
    dry_bad=0
    for m in ${MARKERS[@]+"${MARKERS[@]}"}; do
      (cd "${SRC:-$PWD}" && check_marker "$m" 1) || dry_bad=$((dry_bad + 1))
    done
    for m in ${ANTI_MARKERS[@]+"${ANTI_MARKERS[@]}"}; do
      (cd "${SRC:-$PWD}" && check_marker "$m" 0) || dry_bad=$((dry_bad + 1))
    done
    if [ "$dry_bad" != "0" ]; then
      say "  ❌ маркеров не совпало: $dry_bad — профиль остановил бы верную выкатку, чинить ЗДЕСЬ"
      [ -n "$DRY_TMP" ] && rm -rf "$DRY_TMP"
      exit 2
    fi
    say "  маркеры сошлись: ${#MARKERS[@]} + ${#ANTI_MARKERS[@]} анти"
  else
    say "  ⚠ исходников рядом нет — маркеры ${#MARKERS[@]}+${#ANTI_MARKERS[@]} проверятся на выкатке"
  fi
  common_n=$(ls "$SELF_DIR/checks/common"/*.py 2>/dev/null | wc -l)
  release_n=$(ls "$CHECKS_DIR"/*.py 2>/dev/null | wc -l)
  say "  проверки рантайма: общих $common_n, релизных $release_n"
  [ "$common_n" -gt 0 ] || say "  ⚠ общих проверок НЕТ — выкатка пойдёт вслепую"
  # ⚠⚠ ИСТОЧНИК ГЕЙТА CI ВЫБИРАЕТСЯ ОТДЕЛЬНО ОТ ИСТОЧНИКА МАРКЕРОВ (ревью захода 5.5,
  # 27.08.2026). Ветка «пакет рядом» ставит только `MARKER_ROOTS` и оставляет `SRC` ПУСТЫМ, а гейт
  # стоял под `if [ -n "$SRC" ]` без `else`. Значит в СЦЕНАРИИ ИЗ USAGE ЭТОЙ ШАПКИ — «ЗАПУСК
  # на VM, из каталога пакета» — гейт не звался вовсе и не печатал НИ СТРОКИ. Это хуже
  # инцидента `O3` #104, ради которого гейт и заведён: там предохранитель СКАЗАЛ, и его
  # не услышали; здесь он МОЛЧАЛ, а лог выглядел полным.
  #
  # ⚠ Пакет источником быть не может: в архиве нет `.git`. Рабочая копия `$APP` — может, но
  # НЕ как «код, который поедет» (для МАРКЕРОВ она именно поэтому из кандидатов убрана), а как
  # РЕПОЗИТОРИЙ, в котором резолвится тег релиза: коммит `ci_gate` берёт из `$TAG`, а состояние
  # рабочего дерева на выбор коммита не влияет. Если тега там нет, `ci_gate` скажет это вслух
  # («HEAD — проверяется НЕ релизный коммит»), а не промолчит.
  # ⚠⚠ $APP ГОДИТСЯ, ТОЛЬКО ЕСЛИ ТЕГ РЕЛИЗА ТАМ РЕЗОЛВИТСЯ (ревью PR #127, 27.08.2026). Первая
  # редакция этой правки брала $APP по одному наличию .git — а на VM это ПРЕДЫДУЩИЙ релиз, и
  # ничто не приносит туда новый тег: доставка идёт тарболом, не клоном. `ci_gate` откатился бы
  # на HEAD, то есть на прошлый релиз, и сказал бы «CI зелёный» про коммит, который НЕ едет —
  # ровно класс O3 #104, ради которого гейт и заведён. Обратная беда не легче: красный прогон на
  # прошлом коммите остановил бы ЗАКОННУЮ выкатку.
  # ⚠ ТОТ ЖЕ СПИСОК КАНДИДАТОВ, ЧТО У РЕАЛЬНОЙ ВЫКАТКИ (ревью PR #127, раунд 5). Прежде сухой
  # прогон смотрел только `$SRC` и `$APP`, а `$PKG` по умолчанию равен текущему каталогу: прогон
  # из корня репозитория с тарболом рядом оставлял гейт МОЛЧАТЬ, хотя тегированный репозиторий
  # был прямо под ногами. Два пути, решающие одну задачу, обязаны иметь один список.
  CI_DRY_SRC="$SRC"
  if [ -z "$CI_DRY_SRC" ]; then
    for cand in "$PWD" "$PKG" "$APP" "$SELF_DIR/../.."; do
      [ -d "$cand/.git" ] || continue
      (cd "$cand" && git rev-parse --verify --quiet "$TAG^{commit}" >/dev/null 2>&1) || continue
      CI_DRY_SRC="$cand"; break
    done
  fi
  if [ -n "$CI_DRY_SRC" ]; then
    ci_gate "$CI_DRY_SRC" || { say "  ❌ сухой прогон остановлен красным CI"
                               [ -n "$DRY_TMP" ] && rm -rf "$DRY_TMP"; exit 2; }
  else
    say "  ⚠⚠ CI НЕ ПРОВЕРЕН: рядом нет репозитория, где резолвится тег $TAG"
    say "     (в $APP его нет либо тег туда не доехал — доставка идёт тарболом, не клоном)."
    say "     Это НЕ «зелено». Гоните сухой прогон НА МАШИНЕ РАЗРАБОТЧИКА — там гейт проверяет"
    say "     по-настоящему; либо откройте Actions руками."
  fi

