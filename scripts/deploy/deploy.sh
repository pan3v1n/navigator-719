# --- уборка диска: только после УСПЕШНОЙ выкатки -------------------------------------------
# ⚠ Кэш сборки копится с каждой выкатки и ничем не ограничен: к 22.09.2026 после ~20 выкаток
# он занял 14.7 ГБ из 29, диск стоял на 81 %. Держим 5 ГБ — повторная сборка без правки
# requirements остаётся быстрой. Висячие образы — прежние релизы, потерявшие тег при пересборке;
# откат у нас идёт через тег кода и пересборку, а не через старый образ. На проваленной
# выкатке сюда не доходим НАМЕРЕННО: там прежний образ может понадобиться для разбора.
# Сбой уборки выкатку не валит — сервис к этому моменту уже проверен.
say "--- уборка: кэш сборки сверх 5 ГБ и висячие образы ---"
