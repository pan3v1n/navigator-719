# ⚠⚠ ПРИСВАИВАНИЕ ПЕРЕД `sudo` ДО КОМАНДЫ НЕ ДОЕЗЖАЕТ (ревью захода 5.5, 27.08.2026). `sudo` при
# `env_reset` — а это дефолт в sudoers — вычищает окружение дочернего процесса, поэтому и
# `DOCKER_BUILDKIT=0 sudo docker …`, и `env DOCKER_BUILDKIT=0 sudo docker …` собирают С BuildKit,
# ради отключения которого строка и написана. Дефект был не виден, потому что его гасил фолбэк
# на тонкий слой: сборка «получалась», просто каждый раз длинным путём через TLS к
# auth.docker.io — то есть ровно через то, от чего уходили. `env` обязан стоять ПОСЛЕ `sudo`.
# ⚠ КЛЮЧ — `sudo` В НАЧАЛЕ, А НЕ СУФФИКС « docker» (ревью PR #127, раунд 4). Прежняя форма
# ловила ровно строку `… docker`, и документированное переопределение путём
# (`DOCKER="sudo -n /usr/bin/docker"`) молча уходило в else — то есть собиралось обратно в
# `env` ПЕРЕД `sudo`, ту самую форму, которую этот блок и убирает, без предупреждения.
case "$DOCKER" in
  sudo|sudo[[:space:]]*)
    # env вставляется ПОСЛЕ sudo и его флагов, перед самой командой docker
    # Последний токен — сама команда docker (может быть путём); всё до него — sudo и его флаги.
    DOCKER_NOBUILDKIT="${DOCKER% *} env DOCKER_BUILDKIT=0 ${DOCKER##* }" ;;
  *)
    DOCKER_NOBUILDKIT="env DOCKER_BUILDKIT=0 $DOCKER" ;;                # docker без sudo
esac

# --- O6 (#114): КОД ВОЗВРАТА КОМАНДЫ, А НЕ КОНВЕЙЕРА ----------------------------------------
#
# ⚠⚠ ЧЕМ ЭТО БЫЛО КУПЛЕНО. `set -o pipefail` в скрипте нет, поэтому статус конвейера — это
# статус ПОСЛЕДНЕЙ команды. Четыре шага выкатки отправляли вывод в `tail`, и их проверки
# оказались недостижимым кодом:
#   * бэкап боевой БД («БЭКАП НЕ СНЯЛСЯ — выкатку не начинаю») — предохранитель B из шапки,
#     тот самый, который уже чинили 18.08 от ДРУГОГО дефекта: он был сломан ВТОРЫМ способом
#     всё это время;
#   * сборка образа (обе ветки: классическая и тонким слоем) — `BUILT=1` выставлялся при
#     провалившейся сборке, то есть на бою остался бы прежний образ;
#   * переиндексация по документам (K11) и полная (K15).
#
# ⚠ Почему не `set -o pipefail` глобально: его радиус — ВСЕ конвейеры скрипта, включая
# информационные (`ls … | awk`, `df -h / | tail -1`), и никто их так не мерил. Точечная
# обёртка меняет ровно те четыре места, где код возврата и нужен.
#
# ⚠ `env` перед командой обязателен: `DOCKER_BUILDKIT=0 …` — присваивание, а не команда, и
# без `env` обёртка попыталась бы его выполнить.
#
# Использование:  run_step <строк вывода> <команда…>   → код возврата КОМАНДЫ
run_step() {
  local lines="$1"; shift
  local log rc
  log="$(mktemp)"
  "$@" > "$log" 2>&1
  rc=$?
  tail -n "$lines" "$log"
  rm -f "$log"
  return $rc
}

