# --- проверки рантайма --------------------------------------------------------------------
# ⚠ ДВА КАТАЛОГА, И ЭТО НЕ УДОБСТВО. `checks/common` — проверки, которые обязаны проходить на
# КАЖДОМ релизе: однажды найденный дефект больше не должен вернуться незамеченным. Раньше они
# жили в скрипте очередного релиза и умирали вместе с ним: `D12` проверялась на test11 и
# исчезла в test12. `checks/<тег>` — только то, что специфично для этого релиза.
run_checks_dir() {
  local dir="$1" kind="$2"
  if [ ! -d "$dir" ]; then
    say "⚠ каталога проверок ($kind) нет: $dir"
    return 0
  fi
  local n=0
  for chk in "$dir"/*.py; do
    [ -e "$chk" ] || continue
    n=$((n + 1))
    say "--- проверка рантайма [$kind]: $(basename "$chk") ---"
    $DOCKER compose exec -T app python - < "$chk" || fail "$(basename "$chk")"
  done
  [ "$n" -gt 0 ] || say "⚠ в $dir нет ни одной проверки"
}

run_checks_dir "$SELF_DIR/checks/common" "общие"
run_checks_dir "$CHECKS_DIR" "релизные"

# --- доступность --------------------------------------------------------------------------
say "--- /ping и страницы ---"
# ⚠ По ПЕТЛЕ приложения (127.0.0.1:8000), а не через caddy: с самой VM домен может не
# резолвиться, а http://127.0.0.1 у caddy не имеет сайта. Проверяем сервис, не прокси.
PING="$(curl -fsS http://127.0.0.1:8000/ping)" || fail "/ping не ответил"
echo "$PING"
# ⚠⚠ МЕТКА РЕЛИЗА ИЗ ЖИВОГО ПРОЦЕССА — ЭТО ПРОВЕРКА СБОРКИ, А НЕ УКРАШЕНИЕ. Файл `RELEASE` лежит
# на диске всегда (мы его только что записали), но в `/ping` он попадает лишь через ОБРАЗ. Если
# ответ несёт прошлый тег, значит собрался не тот образ либо контейнер не перезапустился — тот
# самый исход, о котором шаг сборки предупреждает словами «код на диске обновлён, контейнер
# прежний», и до сих пор его ничто не ловило.
# ⚠ Отсутствие поля `release` — НЕ провал: так отвечает образ, собранный до появления метки
# (первая выкатка с ней). Предохранитель, бьющий по верному коду, дороже отсутствующего.
case "$PING" in
  *'"release"'*)
    case "$PING" in
      *"\"$TAG\""*) say "  метка релиза в живом процессе: $TAG" ;;
      *) fail "/ping отдаёт ЧУЖУЮ метку релиза — собрался не тот образ или контейнер прежний" ;;
    esac ;;
  *) say "  ⚠ в /ping нет поля release — образ собран до появления метки, это не «зелено»" ;;
esac
# ⚠ ПРОВЕРЯЕМ, ЧТО СТРАНИЦА ОТВЕТИЛА, А НЕ ЧТО ОНА ОТДАЛА РОВНО 200. Первая редакция требовала
# 200 у всех четырёх — и на выкатке v0.5.0-test13 объявила ПРОВАЛ на верном коде: `/` законно
# отдаёт 302 на `/login` неаутентифицированному пользователю (проверено там же: `/login` → 200).
# Ровно тот класс, о котором предупреждает шапка этого файла: предохранитель, бьющий по верному
# коду, дороже отсутствующего — он заставляет усомниться в правке. Ошибкой считаем 4xx/5xx и
# пустой ответ, то есть случаи, когда страницы действительно нет.
for p in / /help /terms /privacy; do
  code=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8000$p")
  echo "   $p → $code"
  case "$code" in
    2??|3??) ;;
    *) fail "страница $p отдала $code" ;;
  esac
done

# --- ПУБЛИЧНЫЙ ВХОД через caddy (ревью PR #140) ---------------------------------------------
# Петля выше проверяет СЕРВИС; здесь — то, что видит пользователь: оба имени через caddy на
# этой же машине (`--resolve`, чтобы не зависеть от DNS и от рваного канала). Сертификат
# Let's Encrypt выпускается асинхронно после старта — ждём до ~2 минут, потом провал.
if [ -n "$PUBLIC_DOMAIN_ENV" ]; then
  say "--- публичный вход через caddy ($PUBLIC_DOMAIN_ENV) ---"
  for host in "$PUBLIC_DOMAIN_ENV" "$APP_SUBDOMAIN_ENV.$PUBLIC_DOMAIN_ENV"; do
    path="/"; [ "$host" = "$PUBLIC_DOMAIN_ENV" ] || path="/login"
    code=000; n=0
    while [ $n -lt 12 ]; do
      code=$(curl -s -o /dev/null -w "%{http_code}" --max-time 15 \
             --resolve "$host:443:127.0.0.1" "https://$host$path" 2>/dev/null || echo 000)
      case "$code" in 2??|3??) break ;; esac
      n=$((n + 1)); sleep 10
    done
    echo "   https://$host$path → $code (попыток $((n + 1)))"
    case "$code" in
      2??|3??) ;;
      *) fail "публичный вход https://$host$path отдал $code — сертификат/caddy (compose logs caddy)" ;;
    esac
  done
  code=$(curl -s -o /dev/null -w "%{http_code}" --max-time 15 \
         --resolve "$PUBLIC_DOMAIN_ENV:80:127.0.0.1" "http://$PUBLIC_DOMAIN_ENV/" 2>/dev/null || echo 000)
  echo "   http://$PUBLIC_DOMAIN_ENV/ → $code (ожидается редирект на https)"
  case "$code" in 3??) ;; *) fail "http → https редирект не работает ($code)" ;; esac
fi
df -h / | tail -1

