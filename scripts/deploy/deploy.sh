# --- ПОЛНАЯ переиндексация процедурного корпуса --------------------------------------------
# ⚠⚠ КОГДА ОНА ОБЯЗАТЕЛЬНА, А `--doc` НЕ ГОДИТСЯ: когда релиз ДОБАВЛЯЕТ документ в корпус.
# `avgdl` считается по всему корпусу и ЗАПЕКАЕТСЯ в sparse-вектор каждой точки. Новый документ
# меняет среднюю длину для ВСЕХ — и в чужом масштабе BM25 оказываются не его точки, а точки
# СОСЕДЕЙ, загруженных раньше (замерено на K15: 95.84 -> 96.72). Сам загрузчик это и не даст
# сделать: `--doc` для отсутствующего в коллекции документа останавливается.
#
# ⚠ ЦЕНА, КОТОРУЮ НАДО ЗНАТЬ ЗАРАНЕЕ: `recreate_collection` СНОСИТ коллекцию, и всё время
# прогона e5 процедурная ветка отвечает пустотой (проверено локально: сразу после старта
# points_count = 0). Это ровно то окно, ради устранения которого делалась K11, — и здесь его
# не избежать. Выбирать момент выкатки соответственно.
