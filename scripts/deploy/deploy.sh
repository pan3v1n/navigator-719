  #
  # ⚠⚠ Куплено находкой 25.08.2026: перефраз и возмущения (уровень 3 гайда) не запускались НИ
  # РАЗУ в заходах 3 и 4 — их чисел нет ни в одном отчёте и в базе сравнения, а сводки писали
  # «Уровень 3 — устойчивость ✅». Уровень фактически сводился к детерминизму два релиза подряд.
  #
  # База защищает от тихой деградации ТОЛЬКО те метрики, что в ней есть; метрика, которую не
  # сняли ни разу, не деградирует — её просто нет. Значит сверять надо СОСТАВ прогона, а не
  # только пороги снятых чисел.
  #
  # ⚠ Это ПРЕДУПРЕЖДЕНИЕ, а не остановка. Замер — решение владельца: бывает осознанная выкатка
  # без полного прогона (рантаймовая правка, откат). Но оператор обязан увидеть, чего нет, и
  # решить сам, а не узнать через два релиза.
  BASE="$SELF_DIR/../../docs/eval_baseline/baseline.json"
  if [ -f "$BASE" ]; then
    miss=""
    for metric in recall@1 attribution@1 faithfulness decisive_numbers_stable \
                  paraphrase perturbation context_size; do
      # ⚠ КЛЮЧ, А НЕ УПОМИНАНИЕ (ревью захода 5.5, 27.08.2026). Голый греп по имени
      # удовлетворялся любой строкой-примечанием — напр. «"perturbation" в этом заходе не
      # снимали», — и гейт красил состав зелёным РОВНО там, где метрику не сняли. Это тот
      # класс, ради которого `EV19` и заводилась. Несущая проверка — в `test_deploy_script.py`,
      # там есть `json`; здесь, на VM без python в хосте, требуем хотя бы двоеточие после имени.
      grep -qE "\"$metric\"[[:space:]]*:" "$BASE" || miss="$miss $metric"
    done
    if [ -n "$miss" ]; then
      say "  ⚠ В БАЗЕ СРАВНЕНИЯ НЕТ МЕТРИК:$miss"
      say "    уровень протокола исполнен НЕ ЦЕЛИКОМ — см. EV19 #111"
    else
      say "  состав базы сравнения полон (7 обязательных метрик на месте)"
    fi
    base_tag=$(grep -o "\"release_tag\": \"[^\"]*\"" "$BASE" | head -1 | sed "s/.*: \"//;s/\"//")
    if [ "$base_tag" = "$TAG" ]; then
      say "  ⚠ база сравнения УЖЕ на теге $TAG — сравнивать этот релиз не с чем"
    fi
  else
    say "  ⚠ базы сравнения рядом нет — состав замера не проверить (это не «зелено»)"
  fi

  [ -n "$DRY_TMP" ] && rm -rf "$DRY_TMP"
  say "профиль читается, обязательные поля на месте"
  exit 0
fi

