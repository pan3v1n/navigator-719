"""test34: D14 #141 — иерархия ОКПД2 поразрядная, целевая — ближайшая по коду позиция. На БОЕВОМ индексе.

ЗАЧЕМ. Релиз рантаймовый (данные и индекс не тронуты), но меняет выбор позиции, о которой идёт
ответ. Маркеры пакета подтверждают, что код доехал; эта проверка — что на боевых коллекциях он
даёт то, ради чего писался, и не отнимает своё у кода, у которого своя позиция есть:

  1. офлайн: 20.14.11.112 входит в 20.14.11.110; 20.14.11.131 в 20.14.11.120 НЕ входит;
  2. «Н-бутан очищенный 20.14.11.112» → целевая XXI/142 (было: «Катализаторы …» XIV, код «20»);
  3. «Хладон 20.14.11.122» → целевая XXI/143;
  4. «Шкаф управления наружным освещением 27.12.31.000» → целевая V/31 (было: «Реле защиты»);
  5. второй ход диалога про 20.14.11.110 с кодом продукции 20.14.11.112 в истории — контекст
     сообщает модели, что код входит в группировку (на бою прозвучало «применять нельзя»);
  6. КОНТРОЛЬ ВРЕДА: «Светодиоды белого диапазона 26.11.22.216» → своя позиция IV/3, хотя
     категория 26.11.22.210 теперь тоже совпадает;
  7. КОНТРОЛЬ УЗКОГО D14 (ревью PR #177, раунд 4): широкий код с найденными потомками остаётся
     как на бою — «Мониторы» 26.40.34 → IV/12 (не «Гидрофоны» 26.40.3), «Насосы центробежные»
     28.13.14 → XIX/6 (не «Криогенный насос» 28.13.1), «Усилители» 26.40.43 → XXV/5. Блок 7 на
     коде `test33` проходит — это контроль вреда, а не признак релиза.

⚠ Реранкер при совпадении по коду не вызывается — DeepSeek проверка не трогает.
⚠ Положительный контроль: на коде `test33` блоки 1–5 проваливаются (проверено локально 08.10.2026).
"""
from app.core.console import enable_utf8

enable_utf8()  # #107: проверка печатает значки вне cp1251

from app.rag import okpd2_ref, pipeline, retriever  # noqa: E402

ANCHOR = "Приложение к ПП №719, Раздел {}"


def main() -> int:
    bad = 0

    def check(ok: bool, good: str, fail: str) -> None:
        nonlocal bad
        print(f"   OK: {good}" if ok else f"   ❌ {fail}")
        bad += not ok

    rel = getattr(okpd2_ref, "okpd2_relation", None)
    check(rel is not None and rel("20.14.11.110", "20.14.11.112") == 1
          and rel("20.14.11.120", "20.14.11.131") is None,
          "иерархия поразрядная: 112 входит в 110, 131 в 120 не входит",
          "поразрядной иерархии в коде нет")

    def target(query: str, code: str) -> list[str]:
        hits = retriever.search(query, okpd2=code, limit=8)
        return [h.source_anchor for h in pipeline.target_hits(hits, [code])]

    for query, code, want, before in [
        ("Н-бутан очищенный", "20.14.11.112", "XXI, позиция 142", "катализаторы раздела XIV"),
        ("Хладон", "20.14.11.122", "XXI, позиция 143", "катализаторы раздела XIV"),
        ("Шкаф управления наружным освещением", "27.12.31.000", "V, позиция 31", "«Реле защиты»"),
        ("Светодиоды белого диапазона", "26.11.22.216", "IV, позиция 3", "—"),
        ("Мониторы и проекторы, без встроенной телевизионной приемной аппаратуры и в основном не "
         "используемые в системах автоматической обработки данных", "26.40.34", "IV, позиция 12",
         "IV/12, как на бою; «Гидрофоны» — регрессия добора предков"),
        ("Насосы центробежные подачи жидкостей прочие; насосы прочие", "28.13.14", "XIX, позиция 6",
         "XIX/6, как на бою; «Криогенный насос» — регрессия добора предков"),
        ("Усилители электрические звуковых частот; установки электрических усилителей звука",
         "26.40.43", "XXV, позиция 5", "XXV/5, как на бою"),
    ]:
        got = target(f"{query} {code}", code)
        check(ANCHOR.format(want) in got, f"{code} → {want}",
              f"{code} → {got} (ожидалась {want}; до правки — {before})")

    hits = retriever.search("можно ли применять требования позиции 20.14.11.110", okpd2="20.14.11.110", limit=8)
    try:
        ctx = pipeline.format_context(hits, "вопрос", ["20.14.11.110"], dialog_codes=["20.14.11.112"])
    except TypeError:
        ctx = ""
    check("20.14.11.112 ВХОДИТ В ГРУППИРОВКУ ОКПД2 20.14.11.110" in ctx,
          "код из истории диалога связан с группировкой в контексте",
          "контекст второго хода не сообщает, что 20.14.11.112 входит в 20.14.11.110")

    print(f"\nИТОГ: провалов {bad}")
    return 1 if bad else 0


raise SystemExit(main())
