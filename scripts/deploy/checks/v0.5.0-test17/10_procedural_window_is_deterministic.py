"""Релиз `v0.5.0-test17`: состав процедурного окна воспроизводим (`M2` #115).

ЗАЧЕМ РАНТАЙМОМ, А НЕ МАРКЕРОМ. Маркер отвечает «доехал ли `_rules_order`». Здесь вопрос другой:
разрешает ли он ничью НА БОЕВЫХ ДАННЫХ. Дефект и был в том, что при равном score RRF состав окна
определял порядок ответа Qdrant — а он зависит от сегментов коллекции, то есть от того, КАК
именно она собрана. Локально коллекция пересобрана сегодня; на бою — переиндексацией 25.08.
Совпадение локального поведения ничего не обещает.

⚠ Проверка обязана быть ПОВТОРНОЙ по своей природе: единственный вызов не отличает
«детерминировано» от «повезло». Ровно та же причина, по которой живая проверка после выкатки
теперь тоже повторная.
"""
from app.core.console import enable_utf8
from app.rag import topics
from app.rag.pipeline import RULES_TOP_K
from app.rag.retriever import search_rules

enable_utf8()  # #107: проверка печатает значки вне cp1251

QUERIES = (
    "какие документы нужны для получения акта экспертизы",
    "сроки рассмотрения заявления о внесении в реестр",
    "что говорит подпункт г пункта 1 постановления",
)

RUNS = 5
unstable = []
for q in QUERIES:
    windows = []
    for _ in range(RUNS):
        pts = search_rules(q, limit=RULES_TOP_K,
                           primary_docs=topics.doc_types(topics.classify(q)))
        # Состав И порядок: M2 чинила именно разрешение ничьей, а она сдвигает и то, и другое.
        windows.append(tuple((p.get("doc_type"), p.get("point")) for p in pts))
    if len(set(windows)) != 1:
        unstable.append((q, len(set(windows))))
    print(f"   {q[:46]!r}: {len(pts)} пунктов, различных окон за {RUNS} прогонов — {len(set(windows))}")

assert not unstable, (
    f"состав окна плавает между прогонами: {unstable}. "
    f"M2 #115 не работает на боевой коллекции — эксперту один и тот же вопрос даёт разный контекст")

# Отрицательный контроль: проверка не должна быть зелёной от того, что выдача пуста.
pts = search_rules(QUERIES[0], limit=RULES_TOP_K)
assert len(pts) >= 3, f"выдача подозрительно мала ({len(pts)}) — проверка была бы зелёной вхолостую"

# ⚠⚠ ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ: проверки «ранжирование не тронуто». Я пробовал дважды — и дважды
# проверка падала по ВЕРНОМУ коду, потому что проверяла свойство ПУЛА на ВЫХОДЕ.
#
# Окно собирается из ТРЁХ разных запросов к Qdrant (основной пул и два добора), и их score
# несравнимы между собой; сверх того окно намеренно перегруппировано (`K9`/`P2`: пункты
# тематического документа и перечень документов идут первыми). Ни по всему окну, ни даже внутри
# одного документа порядок по score не обязан быть убывающим.
#
# «Ранжирование не тронуто» проверяется ТАМ, ГДЕ ВХОД КОНТРОЛИРУЕТСЯ: юнит-тест
# `tests/test_m2_rules_order.py::test_ranking_by_score_is_preserved` подаёт `_rules_order`
# готовый пул и сверяет порядок напрямую. Плюс косвенно — `eval_rules`: атрибуция@1 0.96 и
# представленность 1.00 не изменились, а именно они падают при перестановке ранга (урок K9).
print(f"   OK: {len(QUERIES)} запроса × {RUNS} прогонов — состав и порядок окна воспроизводимы"
      f" (ранжирование проверяется юнит-тестом на _rules_order, не здесь)")
