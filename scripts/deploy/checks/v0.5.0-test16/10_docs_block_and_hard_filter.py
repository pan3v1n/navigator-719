"""Релиз `v0.5.0-test16`: справочник условен, фильтр документов — жёсткий.

ЗАЧЕМ РАНТАЙМОМ. Обе правки этого релиза маркерами пакета не проверяются: маркер отвечает на
вопрос «доехал ли код», а здесь важно «что код ДЕЛАЕТ на боевых данных».

* Условное разъяснение (`dbfc622`) — правка ПОВЕДЕНИЯ, найденная замечанием владельца по живому
  ответу с боя: пользователь спросил «какие документы подготовить», а ответ сообщал ему, что
  «заключения ТПП» не существует — про документ, о котором тот не спрашивал. Проверяем обе
  стороны: на обычном вопросе разъяснения нет, на вопросе про заключение — есть.
* Жёсткий фильтр `only_docs` (`EV18` #110) — ходит в Qdrant, и его поведение зависит от РЕАЛЬНОЙ
  выдачи. Локально он давал 3/3; на боевой коллекции это надо подтвердить, а не предположить.
"""
from app.core.console import enable_utf8
from app.rag import documents_ref
from app.rag.pipeline import RULES_DOC_POINTS
from app.rag.retriever import search_rules

enable_utf8()  # #107: проверка печатает значки вне cp1251

# 1. Справочник: перечень всегда, разъяснение — только если спросили.
plain = documents_ref.documents_context_block("какие документы нужно подготовить для подтверждения производства")
asked = documents_ref.documents_context_block("нужно ли мне заключение ТПП для внесения в реестр")

assert "ЗАКРЫТЫЙ" in plain, "закрытый перечень пропал из контекста — K15 выключилась"
for d in documents_ref.CONFIRMING_DOCUMENTS:
    assert d["name"] in plain, f"документ {d['name']!r} исчез из справочника"
assert "не существует" not in plain, (
    "разъяснение про несуществующий документ снова приезжает БЕЗУСЛОВНО — "
    "пользователь получит текстовку про документ, о котором не спрашивал")
assert "не существует" in asked, "спросили про заключение, а разъяснения нет — K15 стала слепой"
print(f"   справочник: обычный вопрос {len(plain)} симв (без разъяснения), "
      f"с вопросом про заключение {len(asked)} симв")

# 2. Жёсткий фильтр: ВСЕ пункты окна переживают постфильтр, места не тратятся впустую.
QS = ("какие документы нужны для этикетировщиков",
      "производим гидравлические насосы, какой комплект документов подготовить")
for q in QS:
    pts = search_rules(q, limit=RULES_DOC_POINTS, only_docs=("tpp_order_52",))
    assert pts, f"пустая выдача на {q[:40]!r} — фильтр отсёк всё"
    foreign = [p.get("doc_type") for p in pts if p.get("doc_type") != "tpp_order_52"]
    assert not foreign, f"фильтр пропустил чужие документы: {foreign}"
    assert len(pts) == RULES_DOC_POINTS, (
        f"блок неполон: {len(pts)} из {RULES_DOC_POINTS} на {q[:40]!r}")
print(f"   жёсткий фильтр: {RULES_DOC_POINTS}/{RULES_DOC_POINTS} пунктов Приказа №52 на обоих вопросах")

# 3. Отрицательный контроль: без фильтра поведение прежнее — правка не тронула общий путь.
pts = search_rules(QS[0], limit=RULES_DOC_POINTS)
assert pts, "без фильтра выдача пуста — сломан общий путь"
print(f"   без фильтра выдача жива ({len(pts)} пунктов) — общий путь не задет")

# 4. Гард: отрицание — не дефект, рекомендация — дефект.
assert documents_ref.unverified_documents(
    "Документа «заключение ТПП» не существует.") == [], "гард снова бьёт по верному ответу"
assert documents_ref.unverified_documents(
    "потребуется заключение ТПП о подтверждении производства"), "гард ослеп на выдумке"
print("   гард: отрицание пропущено, рекомендация поймана")
