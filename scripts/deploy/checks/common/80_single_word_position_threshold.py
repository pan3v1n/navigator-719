"""Ревью захода 3 (#103, выкачено в `v0.5.0-test19`): порог ОДНОСЛОВНОЙ позиции доезжает до
эксперта.

Дефект: у «Мочеприемников» (32.50.13.190, разд. VII) в прим. 81 есть строка, названная ДОСЛОВНО
так же, с порогом 135 баллов, — рантайм отдавал `None`. Тай-брейк ветки «таблицы по коду» требовал
пересечения ≥2 значимых слов, а однословное наименование даёт максимум 1: НЕПРОХОДИМО ПО
ПОСТРОЕНИЮ. Не «редкий случай», а класс позиций, закрытый структурно.

⚠⚠ ПРЯТАЛСЯ МЕСЯЦ, ПОТОМУ ЧТО ОБА НАБЛЮДАТЕЛЯ БЫЛИ СЛЕПЫ: классификатор непокрытых позиций
складывал `covering = covering or row` и позицию не показывал, а `attachment_defects` гейтится
порогом 0 — гейт печатал НОЛЬ при живом дефекте. Отсюда правило: проверка обязана стоять на
ЗНАЧЕНИИ, которое видит эксперт, а не на счётчике дефектов.

⚠ ОРАКУЛ ВЗЯТ ИЗ ПЕРВОИСТОЧНИКА, А НЕ ИЗ ПРОВЕРЯЕМОГО МОДУЛЯ.
`knowledge_base/pp719/chunks/130_PRIMECHANIYA_prilozheniya.txt`, строка 1317:

    из 32.50.50.141|Мочеприемники|не менее 135 баллов|не менее 135 баллов|не менее 135 баллов|155 баллов|155 баллов|

⚠ ЧТО ЭТА ПРОВЕРКА НЕ ДОКАЗЫВАЕТ. Именная половина — единственная несущая: она падает на коде до
правки (проверено прогоном модуля из `2af38a3~1` — там `None`). Счётчик ниже несущим не является,
он наблюдаемая величина: структурный возврат тай-брейка уронил бы его не до нуля, а на сколько-то.
Печатается, чтобы сдвиг был виден глазами, и держится ПОЛОМ, а не равенством, — иначе законный
рост корпуса красит проверку в красное.
"""
import glob
import json

from app.core.console import enable_utf8
from app.rag.thresholds import lookup_threshold

enable_utf8()  # #107: проверка печатает значки вне cp1251

# --- половина несущая: именная, оракул из прим. 81 -------------------------------------------
thr = lookup_threshold(["32.50.13.190", "32.50.50", "32.50.50.141"], "Мочеприемники", "VII")
assert thr, "порог «Мочеприемников» снова НЕ находится: однословное имя не проходит тай-брейк"
assert "135 баллов" in thr, f"порог прим. 81 разошёлся с первоисточником: {thr[:120]}"
print("   OK: однословная позиция получает свой порог (мочеприемники → 135 баллов)")

# --- половина наблюдаемая: сколько однословных позиций вообще доезжает -----------------------
FLOOR = 30  # замерено 27.08.2026: 34 из 56. Пол ниже замера — законный рост корпуса не красный
one_word = with_threshold = 0
for f in glob.glob("knowledge_base/pp719/structured/*.json"):
    for rec in json.load(open(f, encoding="utf-8")):
        if (rec.get("min_threshold") or "").strip():
            continue
        name = (rec.get("product_name") or "").strip()
        if not name or len(name.split()) != 1:
            continue
        one_word += 1
        if lookup_threshold(rec.get("okpd2_codes") or [], name, rec.get("section_roman")):
            with_threshold += 1

assert with_threshold >= FLOOR, (
    f"однословных позиций с порогом стало {with_threshold} (пол {FLOOR}) — похоже на структурный "
    f"возврат тай-брейка «≥2 общих слова»")
print(f"   OK: однословных наименований {one_word}, порог получают {with_threshold} (пол {FLOOR})")
