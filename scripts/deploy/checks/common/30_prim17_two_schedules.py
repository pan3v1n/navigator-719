"""Прим. 17: два графика разведены — общий и оговорка про квотные инвестпроекты.

Дефект: одно предложение примечания несёт ДВА графика, и склеенные в одну строку они давали
ОДНУ дату с разными числами («с 1 июля 2025 г. не менее 3400» и «… не менее 2900»).

⚠ Проверяем ПРИВЯЗКУ даты к числу, а не наличие числа: первая редакция теста требовала, чтобы
«2900» не встречалось в общем графике, — а оно законно стоит там за 2023 год. Зеркало дефекта.
"""
import re

from app.rag.thresholds import lookup_threshold

thr = lookup_threshold(["30.11.31.110"], "Суда рыболовные <9>", "XVIII")
assert thr, "порог прим. 17 не находится"
MARK = "⚠ ИНОЙ порог"
assert MARK in thr, "оговорка НЕ отделена от общего графика"
general = thr.split(MARK, 1)[0]
steps = dict(re.findall(r"((?:с|до)\s+\d{1,2}\s+\w+\s+\d{4}\s*г\.)\s*[-—]?\s*не менее\s+(\d+)",
                        general))
assert steps.get("с 1 июля 2025 г.") == "3400", \
    f"в общем графике 2025 год получил порог оговорки: {steps.get('с 1 июля 2025 г.')}"
print("   OK: общий график 2025 → 3400, оговорка вынесена со своим условием")
