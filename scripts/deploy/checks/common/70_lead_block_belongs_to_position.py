"""Ревью захода 3 (#103, выкачено в `v0.5.0-test19`): ВЕДУЩИЙ блок порога принадлежит СПРОШЕННОЙ
позиции.

Дефект: `_qualified_list_rows` брал `blocks[0]` жёстко — какой график поедет первой строкой
«Порог:», НЕ ЗАВИСЕЛО от того, о какой продукции спросили. «Контакторы и пускатели
электромагнитные низковольтные» получали график ВАКУУМНЫХ контакторов со ступенью 51 балл, к ним
не относящейся, а собственные 41 балл уезжали в сноску. Обе позиции возвращали ПОБАЙТНО одну
строку. Самый дорогой класс дефекта проекта — правильное число, привязанное не к той позиции.

⚠ ОРАКУЛ ВЗЯТ ИЗ ПЕРВОИСТОЧНИКА, А НЕ ИЗ ПРОВЕРЯЕМОГО МОДУЛЯ. Прим. 27
(`knowledge_base/pp719/chunks/130_PRIMECHANIYA_prilozheniya.txt`, строки 535–536):

    для вакуумных контакторов низковольтных переменного тока - 41 балл, с 1 сентября 2025 г. - 51 балл;
    для контакторов и пускателей электромагнитных низковольтных - 41 балл;

Ступень «51 балл» есть ТОЛЬКО у вакуумных. Отсюда обе половины именной проверки: у контакторов и
пускателей её в ведущем блоке быть НЕ МОЖЕТ, у вакуумных — обязана быть.

⚠⚠ ЗАЧЕМ ЗДЕСЬ ЕЩЁ И КОРПУСНАЯ ПОЛОВИНА. Именная ловит возврат ровно этого дефекта; корпусная —
его КЛАСС: две РАЗНЫЕ позиции, получившие побайтно одну строку с «ИНОЙ порог». Слепое правило
«строки обязаны различаться» БИЛО БЫ ПО ВЕРНОМУ КОДУ: прим. 17 законно задаёт один график на
десять наименований промысловых судов. Поэтому закрепляется СОСТАВ известных склеек — тем же
приёмом, что состав ложных срабатываний свипа маршрута (`test_sweep_pins_the_false_positive_count`).
Новая склейка = красная проверка и разбор поимённо.
"""
import glob
import json

from app.core.console import enable_utf8
from app.rag.thresholds import lookup_threshold

enable_utf8()  # #107: проверка печатает значки вне cp1251

MARK = "⚠ ИНОЙ порог"


def lead(codes, name, section=None):
    """Первая строка «Порог:» — то, что эксперт читает как порог ЭТОЙ позиции."""
    return (lookup_threshold(codes, name, section) or "").split("\n", 1)[0]


# --- половина первая: именная, оракул из прим. 27 -------------------------------------------
CONTACTORS = "Контакторы и пускатели электромагнитные низковольтные"
VACUUM = "Вакуумные контакторы низковольтные переменного тока"

lead_c = lead(["27.33"], CONTACTORS, "V")
lead_v = lead(["27.12"], VACUUM, "V")

assert lead_c, "порог контакторов и пускателей не находится"
assert lead_v, "порог вакуумных контакторов не находится"
assert "51 балл" not in lead_c, \
    f"ведущим блоком контакторов и пускателей снова стал ЧУЖОЙ график: {lead_c[:120]}"
assert "41 балл" in lead_c, f"собственный порог контакторов уехал из ведущего блока: {lead_c[:120]}"
assert "51 балл" in lead_v, f"вакуумные потеряли СВОЮ ступень 51 балл: {lead_v[:120]}"
assert lead_c != lead_v, "обе позиции снова отдают ПОБАЙТНО одну строку — blocks[0] захардкожен"
print("   OK: контакторы и вакуумные ведут КАЖДЫЙ своим графиком (41 без ступени / 41 + 51)")

# --- половина вторая: корпусная, состав известных склеек -------------------------------------
# ЗАКОННО: прим. 17 задаёт ОДИН график на группу промысловых судов — наименований много,
# требование одно. Различаться эти строки не обязаны и не должны.
FISHING = frozenset({
    "Дрифтеры <9>", "Сейнеры <9>", "Суда зверобойные <9>", "Суда китобойные <9>",
    "Суда прочие для переработки или консервирования рыбных продуктов <9>",
    "Суда рыболовные <9>", "Суда рыболовные прочие <9>", "Суда-рыбозаводы <9>",
    "Траулеры <9>", "Ярусники",
})
REEFERS = frozenset({
    "Суда рефрижераторные морские, кроме танкеров <9>",
    "Суда рефрижераторные речные, кроме танкеров <9>",
    'Суда рефрижераторные смешанного плавания "река-море"',
})
# ⚠ ДОЛГ ЗАКРЫТ 27.08.2026 (`K2-2` #128, выкачено в v0.5.0-test21): позиция «на токи до 2000 А»
# больше не получает порог прим. 27, которое её не называет, и склейка распалась. Группа убрана
# из известных — проверка сама сообщила об этом строкой «склейка исчезла» на боевой выкатке.
# Историческая справка ниже оставлена: она объясняет, ЧЕМ была склейка и почему её держали.
#
# ⚠⚠ БЫЛО: ДОЛГ, А НЕ НОРМА — `K2-2` #128. Прим. 27 даёт выключателям ДВА блока — «на токи до 4000 А включительно»
# (147 → 187 баллов) и «на токи от 4000 А до 6300 А включительно» (105 → 167 баллов). Позиция
# «на токи до 6300 А» ведёт ПЕРВЫМ блоком, то есть чужим, — ровно дефект контакторов, только
# неисправленный. Причина записана в профиле `v0.5.0-test19.env`: правка намеренно исключила
# ЧИСЛА из сопоставления («идентичность несут слова, числа в квалификаторе это границы»), а эти
# два блока различаются ТОЛЬКО числами. Дефект НЕ регрессия релиза: проверено прогоном модуля
# из `2af38a3~1` — до правки обе позиции тоже отдавали побайтно одну строку.
# Держится здесь ЯВНО, чтобы «известная склейка» не превратилась в забытую: почините
# `K2-2` #128 — уберите отсюда, и проверка сама скажет, что склейка ушла.
BREAKERS = frozenset({
    "Выключатель автоматический (воздушный) низковольтный в литом корпусе (до 1000 В) "
    "на токи до 6300 А",
    "Выключатель автоматический низковольтный в литом корпусе (до 1000 В) на токи до 2000 А",
})
# ⚠ BREAKERS в списке БОЛЬШЕ НЕТ: долг закрыт, склейка распалась. Оставить её здесь значило бы
# держать запись, которая врёт про корпус, — а проверка печатает «склейка исчезла» именно чтобы
# такую запись заметили и убрали.
KNOWN_COLLAPSED = {FISHING, REEFERS}

shared: dict[str, set] = {}
scanned = multi = 0
for f in glob.glob("knowledge_base/pp719/structured/*.json"):
    for rec in json.load(open(f, encoding="utf-8")):
        if (rec.get("min_threshold") or "").strip():
            continue  # у позиции свой порог в приложении — примечание не при чём
        scanned += 1
        name = (rec.get("product_name") or "").strip()
        got = lookup_threshold(rec.get("okpd2_codes") or [], name, rec.get("section_roman"))
        if name and got and MARK in got:
            multi += 1
            shared.setdefault(got, set()).add(name)

# ⚠⚠ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ (ревью PR #127, 27.08.2026). Без него «новых склеек нет» и «я ничего
# не посмотрел» неразличимы снаружи: пустой glob (проверка идёт через `docker compose exec -T app
# python -`, то есть с чужим cwd) или сменившаяся строка MARK давали бы `shared = {}` и бодрое
# «OK: склеек 0». У соседней проверки такой контроль есть (FLOOR), у этой не было.
# Замерено 27.08.2026: просмотрено 1141, многоблочных 16. Полы ниже замера — законный рост
# корпуса не красит проверку в красное.
assert scanned >= 900, f"просмотрено всего {scanned} записей — корпус не на месте, проверка слепа"
assert multi >= 8, f"многоблочных порогов найдено {multi} — MARK разошёлся с thresholds.py?"

collapsed = {frozenset(v) for v in shared.values() if len(v) > 1}
new = collapsed - KNOWN_COLLAPSED
gone = KNOWN_COLLAPSED - collapsed
assert not new, ("НОВАЯ склейка: разные позиции получили побайтно одну строку порога — "
                 f"{[sorted(g)[:2] for g in new]}")
# ⚠ Исчезновение склейки — не провал: `BREAKERS` обязан когда-нибудь уйти отсюда. Но молча
# исчезнувшая группа означает, что позиции переименовали или потеряли порог, — это надо увидеть.
if gone:
    print(f"   ⚠ склейка исчезла (проверить, что порог не потерян): {[sorted(g)[:2] for g in gone]}")
print(f"   OK: просмотрено {scanned}, многоблочных {multi}, склеек {len(collapsed)} — все известные; новых нет "
      f"(суда {len(FISHING)} + рефрижераторы {len(REEFERS)}; выключатели ушли — K2-2 #128 закрыт)")
