"""EV13 (#97): в строке «Порог:» стоит график, а не абзац требований.

Сборщик ступеней брал ЛЮБУЮ строку со словами «не менее», и у прим. 17 в «Порог:» уезжал абзац
прозы на 1402 символа — там «не менее 5 ЛЕТ», срок хранения конструкторской документации.
«Танкеры морские» отдавали 1469 символов текста требований, «газовозы» не получали порога вовсе.
"""
from app.rag.thresholds import lookup_threshold

gas = lookup_threshold(["30.11.22.113"],
                       "Суда морские для перевозки сжиженных газов (газовозы)", "XVIII")
tank = lookup_threshold(["30.11.22.111"], "Танкеры морские", "XVIII")
print("   газовозы:", (gas or "")[:70])
print("   танкеры :", len(tank or ""), "символов")
assert gas and "2200" in gas, "газовозы снова без порога"
assert tank and len(tank) < 300, f"в «Порог:» снова абзац требований ({len(tank or '')} символов)"
assert "не оцениваются" not in (tank or ""), "проза вернулась в строку порога"
print("   OK: оба отдают график, а не абзац требований")
