"""`K14` #35: второй ключ классификации (СТ-1 / ТН ВЭД) — на боевом рантайме.

ЗАЧЕМ ИМЕННО ЭТА ПРОВЕРКА. Релиз добавляет в корпус два документа и заводит ВТОРОЙ КЛЮЧ: условия
достаточной переработки живут в разрезе ТН ВЭД, а весь корпус построен на ОКПД2. Ломается это
тихо и в трёх разных местах сразу, и каждое ломалось при сборке:

* **маршрут.** До правки 19 из 19 вопросов по СТ-1/ТН ВЭД уходили ТОВАРНОЙ веткой, где нет ни
  Соглашения, ни Приказа №14 ни при каком качестве поиска. Пять вопросов набора проходили по
  СЛУЧАЙНЫМ якорям (ГИСП, Минпромторг, ТПП) и создавали видимость покрытия;
* **лукап.** Перечень условий в векторный индекс НЕ ИНДЕКСИРУЕТСЯ намеренно — это список
  ИСКЛЮЧЕНИЙ, где промах поиска даёт не пустоту, а ДРУГОЕ правдоподобное условие. Значит без
  подключённого лукапа отвечать нечем, а модуль жил неиспользованным сутки;
* **извлечение кода.** Прежний извлекатель требует ШЕСТИ цифр (писался под переходные ключи
  уровня HS6), а Перечень ключуется на ЧЕТЫРЁХЗНАЧНОЙ товарной позиции.

⚠ Проверка держит ОБЕ стороны: блок условий не должен уезжать в чужие вопросы, а товарные
вопросы — менять ветку.

⚠ Первые три блока ОФЛАЙНОВЫЕ (регулярки, роутер, таблица фактов) и стоят ноль. Четвёртый зовёт
`plan_procedural`, то есть требует живого Qdrant — он и проверяет, что корпус на сервере доехал.
"""
from app.core.console import enable_utf8
from app.rag import procedural, st1_ref, topics
from app.rag.okpd2_ref import extract_tnved_position
from app.tools.navigator import extract_okpd2

enable_utf8()  # #107: проверка печатает значки вне cp1251

# Уехали на процедурную ветку этим релизом. Голые формы — до правки все три были товарными.
MOVED = (
    "как получить СТ-1",
    "что такое СТ-1",
    "какие условия достаточной переработки для кода ТН ВЭД 8403",
    "мой код ТН ВЭД 8501, какие условия достаточной переработки",
    "что такое кумулятивный принцип",
    "срок действия сертификата происхождения",
)

# ⚠ ОБЯЗАНЫ ОСТАТЬСЯ ТОВАРНЫМИ. Расширение словаря гейта опасно ровно этим.
STAYS = (
    "какие требования к бульдозерам 28.92.21.110",
    "сколько баллов нужно для лифтов 28.22.16.111",
)

# Код из вопроса → ожидание по ПЕРВОИСТОЧНИКУ (Перечень условий, приложение 1 Соглашения).
CODES = (
    ("какие условия достаточной переработки для кода ТН ВЭД 8403", "8403", True),
    ("мой код ТН ВЭД 8501, какие условия", "8501", True),
    # ⚠ Ключевой случай оси: 8402 в Перечне НЕТ, а СОСЕД 8403 есть — с адвалорным условием.
    ("какие условия для товарной позиции 8402 по ТН ВЭД", "8402", False),
    ("какие условия достаточной переработки для форвардеров ТН ВЭД 8704", "8704", True),
)

# Маркер обязателен: четыре цифры сами по себе — не код.
NOT_CODES = ("что говорит постановление № 1392", "приказ ТПП РФ №14 от 01.03.2024",
             "какие требования к 28.92.21.110")

BLOCK_HEADER = "УСЛОВИЯ ДОСТАТОЧНОЙ ПЕРЕРАБОТКИ"


def _route(q: str) -> bool:
    return procedural.is_procedural(q, has_code=bool(extract_okpd2(q)))


def main() -> int:
    bad = 0

    print("1. МАРШРУТ второго ключа")
    for q in MOVED:
        ok = _route(q)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}процедурная: {q[:58]}")
    for q in STAYS:
        ok = not _route(q)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}осталась товарной: {q[:52]}")

    print("2. ИЗВЛЕЧЕНИЕ товарной позиции (4 знака)")
    for q, code, _ in CODES:
        got = extract_tnved_position(q)
        ok = got == code
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}{str(got):<8} ждали {code}: {q[:44]}")
    for q in NOT_CODES:
        got = extract_tnved_position(q)
        ok = got is None
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}кода нет ({got}): {q[:44]}")

    print("3. ТАБЛИЦА ФАКТОВ доехала и отвечает по первоисточнику")
    if not st1_ref.is_available():
        print("   !! таблица условий недоступна — Перечень в вектор не индексируется, "
              "отвечать было бы НЕЧЕМ")
        bad += 1
    else:
        for _q, code, in_perechen in CODES:
            block = st1_ref.format_for_context(code)
            if in_perechen:
                ok = "включён в Перечень" in block and "НЕ включён" not in block
            else:
                ok = "НЕ включён" in block and "общее правило" in block
            bad += not ok
            state = "в Перечне" if in_perechen else "вне Перечня (общее правило)"
            print(f"   {'OK ' if ok else '!! '}{code}: {state}")

    print("4. ЛУКАП ПОДКЛЮЧЁН К ОТВЕТУ (нужен живой Qdrant с новым корпусом)")
    from app.rag.pipeline import plan_procedural

    for q, code, _ in CODES:
        planned = plan_procedural(q, q)
        if planned is None:
            print(f"   !! процедурный дефер (корпус недоступен или пуст): {q[:44]}")
            bad += 1
            continue
        user = planned[3]
        ok = BLOCK_HEADER in user and code in user
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}блок условий {code} в промпте: {q[:44]}")

    # ⚠ Отрицательная половина: блок не должен уезжать в чужие вопросы.
    for q in ("сроки рассмотрения заявки по коду ТН ВЭД 8403", "как получить сертификат СТ-1"):
        planned = plan_procedural(q, q)
        if planned is None:
            print(f"   !! процедурный дефер: {q[:44]}")
            bad += 1
            continue
        ok = BLOCK_HEADER not in planned[3]
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}блока НЕТ (и не должно быть): {q[:44]}")

    # ⚠⚠ БЛОК 4 НЕ ДОКАЗЫВАЕТ, ЧТО КОРПУС ДОЕХАЛ, и это стоит сказать прямо: блок условий берётся
    # из ТАБЛИЦЫ ФАКТОВ, а не из Qdrant, поэтому он появился бы и на старом корпусе. Счётчики
    # коллекций сверяет сам `deploy.sh` (`EXPECT`), но счётчик говорит лишь «точек столько» —
    # не «их находит поиск». Ниже — единственное утверждение, которое проверяет ИМЕННО ЭТО.
    print("5. НОВЫЕ ДОКУМЕНТЫ НАХОДЯТСЯ ПОИСКОМ (корпус доехал, а не только посчитан)")
    from app.rag.pipeline import RULES_TOP_K
    from app.rag.retriever import search_rules

    WINDOW = (
        ("какие условия достаточной переработки для кода ТН ВЭД 8403", "sng_origin_rules"),
        ("что такое кумулятивный принцип", "sng_origin_rules"),
        ("как получить сертификат СТ-1", "prikaz14_tpp"),
    )
    for q, want in WINDOW:
        topic = topics.classify(q)
        hits = search_rules(q, limit=RULES_TOP_K, primary_docs=topics.doc_types(topic))
        docs = [h.get("doc_type") for h in hits]
        ok = want in docs
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}{want} в окне: {q[:40]}  окно={docs}")

    print(f"\nИТОГ: провалов {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
