"""Релиз `v0.5.0-test22`: гард `K15` различает отрицание ТЕРМИНА и отрицание СОСЕДА.

⚠ Проверка ОФЛАЙНОВАЯ: гард — чистые регулярки над текстом. Ни DeepSeek, ни Qdrant не нужны,
стоит ноль.

⚠⚠ ЗАЧЕМ НА РАНТАЙМЕ, ЕСЛИ ЕСТЬ ЮНИТ-ТЕСТ. Батарея проверяет код В РЕПОЗИТОРИИ, а эта проверка —
код, который РЕАЛЬНО РАСПАКОВАЛСЯ НА БОЮ. Ровно на этом различии проект уже обжигался: у `K15`
все юнит-тесты были зелёными, а критерий не выполнялся, потому что до боя доехало не то.

⚠⚠ ЧТО ИМЕННО СТЕРЕЖЁТСЯ. `b890f69` добавил форму «…, а не «X», …» в СЛАБЫЙ тир — тот ищет
отрицание ГДЕ-ТО в предложении термина. Гард замолкал везде, где выдумка соседствует с
отрицанием ЧУЖОГО закавыченного документа: «заключение ТПП …, а не «сертификат СТ-1»». Радиус:
из 8 срабатываний осталось 3, погасли ЧЕТЫРЕ НАСТОЯЩИЕ ВЫДУМКИ ради одного ложного.
Исправлено привязкой к ПОЗИЦИИ: `а не «` обязано стоять вплотную слева от термина.
"""
from app.core.console import enable_utf8
from app.rag.documents_ref import unverified_documents

enable_utf8()  # #107: проверка печатает значки вне cp1251

# --- Несущая половина: цель `b890f69` сохранена ------------------------------------------------
# ⚠ Форма НАБЛЮДЕНА живой проверкой на бою (1 ответ из 10 после выкатки test21). Ответ ВЕРНЫЙ —
# он прямо говорит, что термин не является подтверждающим документом.
CORRECT = ("Определите, какой документ подтверждает производство: акт экспертизы или сертификат "
           "СТ-1. Именно эти документы, а не «заключение ТПП», являются подтверждением "
           "производства.")
assert unverified_documents(CORRECT) == [], \
    f"гард снова бьёт по ВЕРНОМУ ответу — потеряна цель b890f69: {unverified_documents(CORRECT)}"
print("   OK: верный ответ с «а не «заключение ТПП»» гард не трогает")

# --- Обратная половина: правило, которое только гасит, гасило бы и выдумку ---------------------
# ⚠⚠ ЭТИ ЧЕТЫРЕ ФОРМЫ ЛОВИЛИСЬ ДО `b890f69` И МОЛЧАЛИ ПОСЛЕ. Проверено прогоном модуля,
# `bac288d` против `b890f69`. Класс правдоподобен именно на кластере жалоб №1: в контексте лежит
# закрытый справочник из двух настоящих документов, и модель противопоставляет выдумку им.
INVENTIONS = (
    ("Для внесения в реестр представляется заключение ТПП о подтверждении производства, "
     "а не «сертификат СТ-1».", "отрицается СОСЕД — сертификат"),
    ("Производство подтверждает заключение ТПП, а не «акт экспертизы».",
     "отрицается СОСЕД — акт экспертизы"),
    ("Потребуется заключение ТПП о подтверждении производства, а не «выписка из ЕГРЮЛ».",
     "отрицается СОСЕД — выписка"),
    # ⚠ Без `\b` перед «а» гард снимался хвостом предыдущего слова: «выдаёт палатА не «…»».
    # Слова на «-а» в этом домене самые частые: палата, справка, форма, выписка.
    ("Заключение ТПП о подтверждении производства выдаёт палата не «в общем порядке», "
     "а по заявлению предприятия.", "«палатА не «…»» — граница слова"),
    # ⚠⚠ УТВЕРЖДАЮЩАЯ форма: определитель между отрицанием и термином отменяет отрицание, и
    # предложение УТВЕРЖДАЕТ выдумку. Допуск «любых двух слов» на ней был слеп (ревью раунд 2).
    ("Подтверждает акт экспертизы, а не менее важное «заключение ТПП» о подтверждении "
     "производства.", "определитель отменяет отрицание"),
)
silent = [(why, t[:60]) for t, why in INVENTIONS if not unverified_documents(t)]
assert not silent, f"гард ОСЛЕП на выдумке ({len(silent)} из {len(INVENTIONS)}): {silent}"
print(f"   OK: все {len(INVENTIONS)} формы выдумки с отрицанием СОСЕДА пойманы")

# --- Положительный контроль самой проверки ----------------------------------------------------
# ⚠ Без него «ноль ослепших» и «проверка ничего не звала» снаружи неразличимы: если бы
# `unverified_documents` возвращал что угодно непустое всегда, обратная половина зеленела бы,
# а несущая падала — но при пустом всегда зеленела бы несущая. Требуем ОБЕ стороны на заведомых
# входах.
assert unverified_documents("Дополнительно потребуется заключение ТПП о подтверждении "
                            "производства.") != [], "гард молчит на голой выдумке — он выключен"
assert unverified_documents("Производство подтверждается актом экспертизы ТПП РФ.") == [], \
    "гард срабатывает на тексте без термина — он сломан в другую сторону"
print("   OK: положительный контроль — гард видит голую выдумку и молчит на чистом тексте")
