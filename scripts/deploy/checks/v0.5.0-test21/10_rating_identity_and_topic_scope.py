"""Релиз `v0.5.0-test21`: `K2-2` #128 и `K12-1` #122 — на боевом рантайме.

⚠ Проверка ОФЛАЙНОВАЯ: разбор порогов читает корпус с диска, фрагмент темы и промпт —
константы. Ни DeepSeek, ни Qdrant не нужны, стоит ноль.
"""
from app.core.console import enable_utf8
from app.core.prompts import PROCEDURAL_SYSTEM_PROMPT
from app.rag import topics
from app.rag.thresholds import lookup_threshold

enable_utf8()  # #107: проверка печатает значки вне cp1251

# --- K2-2 #128: чужой порог снят, свой на месте ------------------------------------------------
NOT_NAMED = ("Выключатель автоматический низковольтный в литом корпусе (до 1000 В) "
             "на токи до 2000 А")
NAMED = ("Выключатель автоматический (воздушный) низковольтный в литом корпусе (до 1000 В) "
         "на токи до 6300 А")

assert lookup_threshold(["27.12"], NOT_NAMED, "V") is None, \
    "позиция снова получает порог примечания, которое её НЕ НАЗЫВАЕТ (K2-2 #128)"
named = lookup_threshold(["27.12"], NAMED, "V")
assert named and "147 баллов" in named and "167 баллов" in named, \
    f"названная примечанием позиция потеряла ветку порога: {(named or '')[:110]}"
print("   OK: чужой порог снят с «до 2000 А», у «до 6300 А» обе ветки на месте")

# ⚠ Обратный контроль ПЕРВЫЙ: правило локальное, строки без `strict_name` не задеты — иначе
# «починка» состоит в том, что порогов не получает никто.
cont = lookup_threshold(["27.33"], "Контакторы и пускатели электромагнитные низковольтные", "V")
assert cont and "41 балл" in cont, "правило задело строку без strict_name (контакторы)"
print("   OK: строки без strict_name не задеты (контакторы → 41 балл)")

# ⚠⚠ Обратный контроль ВТОРОЙ: имя с ОТКРЫТОЙ ГРАНИЦЕЙ описывает КЛАСС. Требовать от него
# дословности значило бы ронять порог у любой позиции внутри класса — первая редакция правки
# именно это и делала (ревью PR #133, раунд 2). 110 ≥ 6, порог написан ровно для неё.
for codes, name, expect in ((["27.12.10.110"],
                             "Выключатели силовые высоковольтные напряжением 110 кВ", "82 балла"),
                            (["27.11.4"],
                             "Измерительные трансформаторы напряжением 10 кВ", "не менее 72")):
    got = lookup_threshold(codes, name, "V")
    assert got and expect in got, f"позиция внутри класса «… и выше» потеряла порог: {name}"
print("   OK: позиции внутри класса «… и выше» порог сохраняют")

# --- K12-1 #122: фрагмент темы и пример в правиле стиля ---------------------------------------
frag = None
for attr in ("TOPIC_FRAGMENTS", "_FRAGMENTS", "FRAGMENTS", "TOPIC_PROMPT", "_TOPIC_PROMPT"):
    d = getattr(topics, attr, None)
    if isinstance(d, dict) and "registry_entry" in d:
        frag = d["registry_entry"]
        break
assert frag, "фрагменты тем не найдены — проверка устарела вместе с модулем"
low = frag.lower()
for word in ("внесен", "выписк", "изменени"):
    assert word in low, f"фрагмент темы снова не называет подслучай «{word}» (K12-1 #122)"
# ⚠⚠ ДЛИНА — ЭТО ЦЕНА. Развёрнутая редакция (747 знаков) уронила кейс #50 до «утверждает
# несуществующий документ» 2 прогона из 3, при том что справочник ОСТАВАЛСЯ в контексте.
assert len(frag) < 560, f"фрагмент темы разросся до {len(frag)} — перемерить документную популяцию"
print(f"   OK: фрагмент темы покрывает охват и держит длину ({len(frag)} знаков)")

assert "ПРО ТО, О ЧЁМ СПРОСИЛИ" in PROCEDURAL_SYSTEM_PROMPT, \
    "правило стиля снова не связывает вводную фразу с вопросом (K12-1 #122)"
assert "образец ТОНА, а не текст ответа" in PROCEDURAL_SYSTEM_PROMPT, \
    "пример снова подаётся как готовая фраза — модель скопирует его"
# ⚠⚠ СЧИТАЕМ МАРКЕР ПРИМЕРА, А НЕ КАВЫЧКИ (ревью PR #133). Прежняя форма `count("«") >= 3`
# засчитывала «воды» из соседней фразы — то есть требовала на деле ДВА примера при сообщении
# про три, а переформулировка несвязанного оборота уронила бы РЕЛИЗНУЮ проверку на верном коде.
# Предохранитель, бьющий по верному, дороже отсутствующего — правило старше этой проверки.
head = PROCEDURAL_SYSTEM_PROMPT[PROCEDURAL_SYSTEM_PROMPT.find("4. СТИЛЬ"):][:460]
# ⚠ ПОРОГ ДВА, А НЕ ТРИ, И ЭТО СВЕРЕНО С ТЕКСТОМ. Правило даёт две ЦИТИРУЕМЫЕ вводные фразы
# (внесение и выписка) плюс нецитируемое «про сроки — про сроки». Дефект состоял в ОДНОМ примере,
# который модель копировала; два примера его снимают. Требовать три значило бы подгонять промпт
# под утверждение — обратный порядок: утверждение описывает текст, а не наоборот.
assert head.count("— «") >= 2, f"в правиле стиля меньше двух образцов вводной фразы: {head.count('— «')}"
print("   OK: пример в правиле стиля перестал быть шаблоном ответа")
