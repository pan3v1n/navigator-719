"""`K16` #48: процедура экспертизы происхождения и разъяснения ГИСП — на боевом рантайме.

ЗАЧЕМ ИМЕННО ЭТА ПРОВЕРКА. Релиз добавляет в корпус два документа, и у каждого свой способ
сломаться тихо:

* **Положение №49** может доехать в индекс и при этом проигрывать СВОЙ ЖЕ предмет Приказу №52 —
  так и было до правки квоты: «какие документы нужны для экспертизы происхождения» возглавлял
  документ, у которого экспертиза подтверждает ПРОИЗВОДСТВО, а не определяет СТРАНУ. Счётчик
  точек этого не видит: там 752 в обоих случаях;
* **FAQ ГИСП** — не норма, и весь смысл его паспорта в том, чтобы это было видно в ответе.
  Критерий приёмки issue #48 сформулирован дословно: «ответы по процедуре ГИСП снабжены
  источником и пометкой "не норма"»;
* **фантом `K15`.** Главный риск релиза: в корпус приехал документ ПРО ГИСП, а несуществующее
  «заключение ТПП, подтверждающее производство» живёт ровно в этой теме. Настоящая страница
  портала его не содержит, но проверить это НА БОЮ обязательно — если уехал не тот файл,
  выдумка окажется ЗАЗЕМЛЁННОЙ, и рантайм-гард её пропустит: он ловит незаземлённое, а не
  неверное.

⚠ Блоки 1-2 офлайновые (таблица тем, паспорт манифеста) и стоят ноль. Блоки 3-5 зовут поиск,
то есть требуют живого Qdrant — они и проверяют, что корпус на сервере ДОЕХАЛ, а не только
посчитан счётчиком `EXPECT`.
"""
from app.core.console import enable_utf8

enable_utf8()  # #107: проверка печатает значки вне cp1251

# Вопросы Положения №49 — его собственный предмет.
# ⚠⚠ ДВА СПИСКА, А НЕ ОДИН, И РАЗНИЦА СОДЕРЖАТЕЛЬНАЯ. Таблица тем — решение ОФЛАЙНОВОЕ, ей всё
# равно, дойдёт ли вопрос до корпуса; блокам маршрута и окна — не всё равно. «Сроки проведения
# экспертизы происхождения» тему получает верно, но гейт его не пускает (`P3` #121), поэтому он
# живёт в `P49_TOPIC_ONLY` и в `KNOWN_UNROUTED`, а не в приёмочном списке. Смешать их значило бы
# либо валить выкатку зарегистрированным пробелом, либо печатать OK там, где вопрос до корпуса
# не доходит, — обе ошибки этот раунд уже нашёл.
P49_SUBJECT = (
    "какие документы нужны для экспертизы происхождения товара",
    "что входит в акт экспертизы происхождения",
    "как проводится экспертиза по определению страны происхождения",
)
P49_TOPIC_ONLY = P49_SUBJECT + ("сроки проведения экспертизы происхождения",)
# ⚠ ОБЯЗАНЫ ОСТАТЬСЯ ЗА ПРИКАЗОМ №52. Сужение ствола «экспертиз» опасно ровно этим.
O52_SUBJECT = (
    "какие документы нужны для получения акта экспертизы",
    "перечень документов для подтверждения производства",
    "что такое акт экспертизы и когда он нужен",
)
# Вопросы, на которые отвечает только FAQ портала.
# ⚠⚠⚠ ОТОБРАНЫ ПО ТОМУ, ЧТО ОНИ ДОХОДЯТ ДО КОРПУСА (находка раунда 12). Первая редакция брала
# «до какого числа подавать отчёт о произведённой продукции» и «включает ли стоимость реализации
# НДС», и блок «КРИТЕРИЙ ПРИЁМКИ #48» печатал по ним OK — хотя `procedural.is_procedural` для
# обоих FALSE, то есть на бою они уходят ТОВАРНОЙ веткой и коллекции `pp719_rules` не видят
# вовсе. Проверка звала `search_rules` НАПРЯМУЮ, минуя гейт, — дословно класс `P3` #121:
# «утверждение о качестве поиска В КОРПУСЕ, а не о попадании вопроса в корпус».
GISP_QUESTIONS = (
    "как попасть в реестр российской промышленной продукции",
    "как подать заявку на включение продукции в реестр через ГИСП",
    "можно ли подать заявку на включение в реестр не через ГИСП",
)
# ⚠ Отбор кандидатов делался ЗАМЕРОМ, а не на глаз: вопрос обязан И проходить гейт, И приводить
# FAQ в окно. Так, «какой порядок включения по сертификату СТ-1» отброшен — там окно законно
# занимают НОРМЫ (Приказ №14, тело 719, Правила), и требовать первого места для практики значило
# бы перевернуть иерархию `K13`. «Как получить знак в реестре» и «где найти единый реестр
# радиоэлектронной продукции» отброшены по другой причине: FAQ их отвечает, но гейт не пускает —
# это тот же зарегистрированный пробел `P3` #121, что и у KNOWN_UNROUTED.
# ⚠ ИЗВЕСТНЫЙ ПРОБЕЛ, НЕ ЗАМЕТЁННЫЙ ПОД КОВЁР: эти вопросы FAQ отвечает, но гейт их не пускает —
# ни маркера, ни темы, ни 719-якоря. Это остаток `P3` #121 («утвердительные, без глагола и без
# темы»), у которого в задачнике записан структурный ответ, а не расширение словаря. Блок 0 ниже
# ПЕЧАТАЕТ их состояние, но не валит выкатку: пробел зарегистрирован, а не обнаружен здесь.
KNOWN_UNROUTED = (
    "до какого числа подавать отчёт о произведённой продукции",
    "включает ли стоимость реализации НДС",
    "сроки проведения экспертизы происхождения",
)
# ⚠ Контроль `K15`: документа не существует, и корпус про ГИСП не должен это изменить.
PHANTOM = "нужно ли заключение ТПП для внесения продукции в реестр"
# ⚠ Товарный контроль: релиз не должен трогать ветку продукции.
PRODUCT = ("какие требования к бульдозерам 28.92.21.110",
           "сколько баллов нужно для лифтов 28.22.16.111")


def main() -> int:
    bad = 0

    print("0. ⚠⚠⚠ ВОПРОС ВООБЩЕ ДОХОДИТ ДО КОРПУСА (гейт, а не поиск)")
    # ⚠ Без этого блока вся проверка меряет КАЧЕСТВО ПОИСКА В КОРПУСЕ, а не попадание вопроса в
    # корпус: `search_rules` зовётся напрямую и отвечает даже там, где рантайм ушёл бы товарной
    # веткой. Ровно так `P3` #121 три месяца показывал зелёные числа на вопросах, которые живьём
    # отвечались по регистраторам данных рейса.
    from app.rag import procedural
    from app.tools.navigator import extract_okpd2

    def routed(q: str) -> bool:
        return procedural.is_procedural(q, has_code=bool(extract_okpd2(q)))

    for q in P49_SUBJECT + GISP_QUESTIONS + (PHANTOM,):
        ok = routed(q)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}процедурный маршрут: {q[:52]}")
    for q in KNOWN_UNROUTED:
        # Не валим: пробел зарегистрирован (`P3` #121). Но и не молчим — «ноль» инструмента,
        # не видящего популяцию, означает «не считаю», а не «чисто».
        print(f"   {'--  ЗАРЕГИСТРИРОВАННЫЙ ПРОБЕЛ' if not routed(q) else 'OK  ПОЧИНЕНО!'}: "
              f"{q[:48]}")

    print("1. ТАБЛИЦА ТЕМ РАЗВОДИТ ДВА ПРЕДМЕТА (офлайн)")
    from app.rag import retriever as R

    def scores(q):
        return {dt: sum(1 for p in pats if p.search(q)) for dt, pats in R._RULES_TOPIC}

    for q in P49_TOPIC_ONLY:
        s = scores(q)
        ok = s.get("polozhenie49_tpp", 0) > s.get("tpp_order_52", 0)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}№49 > №52 ({s.get('polozhenie49_tpp')}:"
              f"{s.get('tpp_order_52')}): {q[:46]}")
    for q in O52_SUBJECT:
        s = scores(q)
        ok = s.get("tpp_order_52", 0) > s.get("polozhenie49_tpp", 0)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}№52 удержал свой предмет: {q[:46]}")

    print("2. ПАСПОРТ: ГИСП — ПРАКТИКА, ПОЛОЖЕНИЕ — ВЕДОМСТВЕННЫЙ АКТ (офлайн)")
    from app.core import manifest as M

    by = {d["doc_type"]: d for d in M.load_manifest()["documents"]}
    for dt, force, topic in (("gisp_faq", 5, "ГИСП"), ("polozhenie49_tpp", 3, "СТ-1")):
        d = by.get(dt)
        ok = d is not None and d["legal_force"] == force and d["topic"] == topic
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}{dt}: legal_force={d and d['legal_force']} "
              f"topic={d and d['topic']}")

    print("3. НОВЫЕ ДОКУМЕНТЫ НАХОДЯТСЯ ПОИСКОМ (корпус доехал, а не только посчитан)")
    from app.rag import topics
    from app.rag.pipeline import RULES_TOP_K
    from app.rag.retriever import search_rules

    def window(q):
        hits = search_rules(q, limit=RULES_TOP_K,
                            primary_docs=topics.doc_types(topics.classify(q)))
        return [(h.get("doc_type"), h.get("source_anchor") or "") for h in hits]

    for q in P49_SUBJECT[:2]:
        docs = [d for d, _ in window(q)]
        ok = "polozhenie49_tpp" in docs
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}Положение №49 в окне: {q[:44]}  окно={docs[:4]}")
    for q in GISP_QUESTIONS:
        docs = [d for d, _ in window(q)]
        ok = "gisp_faq" in docs
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}FAQ ГИСП в окне: {q[:44]}  окно={docs[:4]}")

    print("4. ⚠⚠⚠ КРИТЕРИЙ ПРИЁМКИ #48: ИСТОЧНИК НЕСЁТ ПОМЕТКУ «НЕ НОРМА»")
    for q in GISP_QUESTIONS:
        anchors = [a for d, a in window(q) if d == "gisp_faq"]
        ok = bool(anchors) and all("не норма" in a for a in anchors)
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}пометка «не норма» у якоря: {q[:44]}")

    print("5. ⚠⚠⚠ КОНТРОЛЬ `K15`: ФАНТОМ НЕ ПРИЕХАЛ ВМЕСТЕ С КОРПУСОМ ПРО ГИСП")
    # ⚠ Детектор — ТОТ ЖЕ, что у рантайм-гарда (`K15`), а не своя регулярка: копия оказалась
    # слабее в обе стороны и пропускала ровно те формулировки, которыми пересказы называют
    # несуществующий документ (находка раунда 12).
    from app.rag.documents_ref import unverified_documents

    # ⚠⚠⚠ СКАНИРУЮТСЯ ВСЕ ЗАПИСИ FAQ, А НЕ ОКНА ЧЕТЫРЁХ ВОПРОСОВ (находка раунда 12).
    # Первая редакция смотрела только то, что вернулось на 4 запроса, — то есть 7 записей из 9.
    # Не просматривалась в том числе запись «Как получить подтверждение о производстве… если код
    # ОКПД2 не указан в ПП РФ № 719» — ровно та тема, где фантом и живёт. Уедь на сервер не тот
    # файл, блок напечатал бы «найдено: []» и сертифицировал бы релиз с ЗАЗЕМЛЁННОЙ выдумкой.
    # ⚠ И «ok = not leaked» было истинно ещё и когда записей не вернулось НИ ОДНОЙ — то есть
    # проверка не отличала «чисто» от «не смотрел».
    from qdrant_client import models

    from app.core.config import settings
    from app.rag.retriever import _client

    rows, offset = [], None
    while True:
        page, offset = _client().scroll(
            collection_name=settings.QDRANT_RULES_COLLECTION,
            scroll_filter=models.Filter(must=[models.FieldCondition(
                key="doc_type", match=models.MatchValue(value="gisp_faq"))]),
            limit=64, offset=offset, with_payload=True)
        rows.extend(page)
        if offset is None:
            break
    leaked = [((p.payload or {}).get("source_anchor") or "")[:48] for p in rows
              if unverified_documents((p.payload or {}).get("text") or "")]
    ok = bool(rows) and not leaked
    bad += not ok
    print(f"   {'OK ' if ok else '!! '}просмотрено записей FAQ: {len(rows)} (ожидается 9); "
          f"фантом найден в: {leaked[:2]}")

    # ⚠⚠ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: детектор обязан УМЕТЬ сработать. Без него «фантома нет»
    # неотличимо от «детектор сломан» — класс, которым в этом проекте уже дважды объявляли
    # чистым сломанный предохранитель.
    probe = "Для внесения в реестр получите заключение ТПП, подтверждающее производство."
    fires = bool(unverified_documents(probe))
    bad += not fires
    print(f"   {'OK ' if fires else '!! '}детектор срабатывает на подставном фантоме")

    print("6. ТОВАРНАЯ ВЕТКА НЕ ТРОНУТА")
    from app.rag import procedural
    from app.tools.navigator import extract_okpd2

    for q in PRODUCT:
        proc = procedural.is_procedural(q, has_code=bool(extract_okpd2(q)))
        ok = not proc
        bad += not ok
        print(f"   {'OK ' if ok else '!! '}остался товарным: {q[:46]}")

    print(f"\nИТОГ: провалов {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
