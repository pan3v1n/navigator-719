"""`P3` #121 + `K15-1` #120: маршрут вопроса и гейт закрытого справочника — на боевом рантайме.

ЗАЧЕМ ИМЕННО ЭТА ПРОВЕРКА. Релиз меняет РАЗВИЛКУ, после которой вопрос уже не встретит ни
требований приложения, ни корпуса Правил — смотря куда ушёл. До правки 13 из 25 вопросов
приёмочного набора `K9` уходили товарной веткой: «как получить выписку из реестра» отвечалось по
регистраторам данных рейса. Ни одна метрика этого не видела, потому что `eval_rules` дёргает
`search_rules` напрямую, минуя гейт.

⚠ Проверка держит ОБЕ стороны. Расширение маршрута опасно ровно тем же, чем узость: вопрос о
членстве в палате или о загранпаспорте не должен получить процедурный ответ вместо честного
«вне сферы 719». Отрицательная половина здесь не для симметрии — обе регрессии этого релиза
поймало именно её отсутствие в первой редакции свипа.

⚠ Проверка ОФЛАЙНОВАЯ: маршрут и гейт справочника детерминированы (регулярки плюс роутер тем),
поэтому стоит ноль и не зависит ни от DeepSeek, ни от выдачи Qdrant.
"""
from app.core.console import enable_utf8
from app.rag import documents_ref, procedural, topics

enable_utf8()  # #107: проверка печатает значки вне cp1251

# Переехали на процедурную ветку этим релизом. Первые четыре — из приёмочного набора K9,
# пятый — кейс #50 приёмочного набора, он же критерий K15-1 #120.
MOVED = (
    ("как получить выписку из реестра", "registry_entry"),
    ("что делать если заявку направили на доработку", "deadlines"),
    ("какой срок рассмотрения документов в ТПП", "deadlines"),
    ("чем подтвердить страну происхождения товара", "st1_origin"),
    ("нужно ли заключение ТПП для внесения продукции в реестр", "registry_entry"),
)

# ⚠ ОБЯЗАНЫ ОСТАТЬСЯ НА МЕСТЕ. Каждый — отдельный класс, и каждый уже ломался:
#   загранпаспорт   — вне-719 админ-вопрос, пример из шапки procedural.py;
#   вступление в ТПП — палата занимается многим помимо 719 (найдено ревью);
#   этикетировщики  — СМЕШАННЫЙ вопрос, ради него заводилась K12: он обязан остаться товарным
#                     и получить блок документов ДОПОЛНИТЕЛЬНО к требованиям позиции;
#   заключение СПИК — «заключение» здесь ДЕЙСТВИЕ, а не документ (найдено ревью).
STAYS = (
    "порядок получения загранпаспорта",
    "какие документы нужны для вступления в ТПП",
    "какие документы нужны для этикетировщиков",
    "какие требования при заключении СПИК для 27.11.42",
)

# Вопрос сам поднял документ → закрытый справочник обязан быть в контексте (K15-1 #120).
NEEDS_REFERENCE = (
    "нужно ли заключение ТПП для внесения продукции в реестр",
    "требуется ли заключение ТПП о подтверждении производства и какие ещё документы собрать",
    "а что есть Заключение Минпромторга?",
)

for q, want_topic in MOVED:
    got = topics.classify(q)
    assert procedural.is_procedural(q), f"вопрос ушёл ТОВАРНОЙ веткой: {q}"
    assert got == want_topic, f"тема сменилась: {q} → {got}, ждали {want_topic}"
print(f"   OK: {len(MOVED)} вопросов идут процедурной веткой, темы на месте")

for q in STAYS:
    assert not procedural.is_procedural(q), f"вопрос УЕХАЛ на процедурную ветку: {q}"
print(f"   OK: {len(STAYS)} контрольных вопросов остались на своей ветке")

for q in NEEDS_REFERENCE:
    assert documents_ref.asks_about_conclusion(q), f"справочник не доедет до вопроса: {q}"
for q in STAYS:
    assert not documents_ref.asks_about_conclusion(q), f"справочник уедет в чужой вопрос: {q}"
print("   OK: закрытый справочник приезжает ровно туда, где документ подняли")

# Гард на несуществующий документ: отрицание — ЦЕЛЬ K15, а не дефект (ddd3e16).
assert documents_ref.unverified_documents(
    "Документа «заключение ТПП», подтверждающего производство, не существует.") == []
assert documents_ref.unverified_documents(
    "Дополнительно потребуется заключение ТПП о подтверждении производства.") != []
print("   OK: гард ловит утверждение и молчит на отрицании")
