#!/usr/bin/env bash
# Один заход уровня 4 на боевой машине (`EV22` #130).
#
# ⚠⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ ДРАЙВЕР, А НЕ ДЕСЯТЬ КОМАНД ПО SSH. Канал до VM режет ПО ЧАСТОТЕ
# ПОДКЛЮЧЕНИЙ: 28.08.2026 SSH не прошёл 3 раза из 3, накануне рвался семь раз за одну выкатку.
# Десять шагов по одному соединению — это десять шансов оборваться на середине. Здесь один
# запуск, отвязанный (`setsid nohup`), пишущий всё в файлы: обрыв канала больше не отменяет
# работу, а результат забирается любым следующим успешным соединением.
#
# ⚠ ХАОСА ЗДЕСЬ НЕТ НАМЕРЕННО. Всё, что делает этот скрипт, безопасно для пользователей: он
# только задаёт вопросы. Хаос ломает сервис и запускается ОТДЕЛЬНО и ЯВНО (`eval_chaos.py`),
# в согласованное окно. Смешивать разрушительный шаг с безобидными в одном пакете нельзя:
# запустивший «замер» не должен обнаружить, что заодно уронил бой.
#
# ⚠ ЗАПУСКАТЬ НА ХОСТЕ, НЕ В КОНТЕЙНЕРЕ. Инструмент держится стандартной библиотеки именно ради
# этого, а `--base-url` смотрит в 127.0.0.1: замер снаружи меряет канал, а не сервис.
#
# ЗАПУСК:
#   cd ~/navigator-719
#   ACCOUNTS='lt.load1:PASS,lt.load2:PASS,lt.load3:PASS' \
#     setsid nohup bash scripts/deploy/level4_on_vm.sh > /tmp/level4/driver.log 2>&1 &
#   # позже, любым соединением:
#   tail -5 /tmp/level4/driver.log ; ls -l /tmp/level4
set -u

OUT=${OUT:-/tmp/level4}
BASE=${BASE:-http://127.0.0.1}
PY=${PY:-python3}
ACCOUNTS=${ACCOUNTS:-}
N_SINGLE=${N_SINGLE:-30}
TIMEOUT=${TIMEOUT:-90}

mkdir -p "$OUT"
say() { echo "[$(date +%H:%M:%S)] $*"; }
fail=0

if [ -z "$ACCOUNTS" ]; then
  say "ОСТАНОВ: не задан ACCOUNTS. Горячий путь требует сессии, а лимит — 20 запросов/мин"
  say "         НА ПОЛЬЗОВАТЕЛЯ: одного аккаунта на нагрузку не хватит, и запросы развернутся"
  say "         на пороге с кодом 429, не дойдя до движка."
  exit 2
fi
n_acc=$(echo "$ACCOUNTS" | tr ',' '\n' | grep -c . )
say "аккаунтов: $n_acc, ёмкость $((n_acc * 20)) запросов/мин"

# ⚠⚠ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ПЕРВЫМ И БЛОКИРУЮЩИМ. Инструмент, чьё «ноль отказов» является
# результатом, обязан сначала доказать, что вообще способен видеть отказ. Не доказал — числа
# не снимаем: «ноль» и «слеп» снаружи неразличимы.
say "=== положительный контроль инструмента ==="
if ! $PY scripts/eval_level4.py --mode selftest > "$OUT/selftest.log" 2>&1; then
  say "ОСТАНОВ: контроль инструмента ПРОВАЛЕН — см. $OUT/selftest.log. Числа не интерпретируются."
  exit 1
fi
say "контроль пройден"

# ⚠⚠ ПАУЗА МЕЖДУ СРЕЗАМИ — НЕ ВЕЖЛИВОСТЬ, А УСЛОВИЕ ДЕЙСТВИТЕЛЬНОСТИ ЗАМЕРА (ревью PR #135).
# Оба лимита сервиса СКОЛЬЗЯЩИЕ, окно 60 с, и срезы идут встык:
#   * вход — 10/мин НА IP (`RATE_LIMIT_LOGIN_PER_MIN`, ключ по адресу клиента). Каждый срез
#     логинит ВСЕ аккаунты заново, и три-четыре среза подряд дают 3–4 × n_acc входов в одном окне:
#     при 4 аккаунтах это уже 12 > 10, и срез падает с 429 ещё до первого вопроса;
#   * чат — 20/мин НА ПОЛЬЗОВАТЕЛЯ. Предполётная проверка считает ёмкость ПОСРЕЗОВО, а окно общее:
#     при минимально разрешённых трёх аккаунтах load25 и load50 дают одному аккаунту 9 + 17 = 26
#     запросов внутри одного окна — 429, «ЗАМЕР НЕДЕЙСТВИТЕЛЕН», выход 1.
# Пауза в 65 с даёт обоим окнам полностью стечь. Цена — три минуты на заход; альтернатива —
# числа, которые нельзя использовать.
COOLDOWN=${COOLDOWN:-65}
first_stage=1
cooldown() {
  [ "$first_stage" = "1" ] && { first_stage=0; return 0; }
  say "пауза ${COOLDOWN} с — даём стечь окнам лимитов (вход 10/мин на IP, чат 20/мин на юзера)"
  sleep "$COOLDOWN"
}

run() {  # run <имя> <аргументы...>
  local name=$1; shift
  cooldown
  say "=== $name ==="
  if $PY scripts/eval_level4.py "$@" --accounts "$ACCOUNTS" --base-url "$BASE" \
       --timeout "$TIMEOUT" --json "$OUT/$name.json" > "$OUT/$name.log" 2>&1; then
    say "$name: ок"
  else
    # ⚠ НЕ выходим: провал одного среза не отменяет остальные, а «ничего не сняли» — худший
    # исход захода, за который заплачено окном на боевой машине. Провалы считаем и покажем в конце.
    say "$name: ПРОВАЛ (код $?) — см. $OUT/$name.log"
    fail=$((fail + 1))
  fi
  tail -6 "$OUT/$name.log" | sed 's/^/    /'
}

run single --mode single --n "$N_SINGLE" --warmup 1

# ⚠ Нагрузка по возрастанию: если сервис ляжет на 10, гнать 50 незачем, а предел уже известен.
for c in 10 25 50; do
  need=$(( (c + 19) / 20 ))
  if [ "$n_acc" -lt "$need" ]; then
    say "load$c ПРОПУЩЕН: нужно ≥$need аккаунтов, есть $n_acc. ⚠ Пропуск ЗАПИСАН — молчаливо"
    say "       урезанное покрытие читается как «проверено всё», а это не так."
    echo "{\"skipped\": true, \"why\": \"аккаунтов $n_acc < $need\"}" > "$OUT/load$c.json"
    continue
  fi
  run "load$c" --mode load --n "$c" --concurrency "$c" --warmup 0
done

say "=== итог ==="
say "провалов: $fail; файлы в $OUT"
# ⚠⚠ УБОРКА — ЧАСТЬ ЗАХОДА, А НЕ ДОБРАЯ ВОЛЯ ОПЕРАТОРА (ревью PR #135). Каждый успешный запрос
# пишет пару реплик в боевую БД, и заход из ~115 запросов оставляет ~115 искусственных диалогов,
# видимых в админке и в скоркарте волны. Драйвер не ходит в БД сам (он на хосте и без зависимостей
# проекта), поэтому печатает ГОТОВУЮ команду — чтобы шаг нельзя было «забыть, потому что не
# записан».
say "⚠ УБОРКА ОБЯЗАТЕЛЬНА. Реплики нагрузочных аккаунтов остались в боевой БД:"
say "   docker compose exec -T app python - <<'"'"'EOF'"'"' < /dev/null"
say "   from app.db.engine import get_session; from app.db.models import User, Message"
say "   with get_session() as db:"
say "       u=db.query(User).filter(User.username.like('"'"'lt.load%'"'"')).all(); ids=[x.id for x in u]"
say "       m=db.query(Message).filter(Message.user_id.in_(ids)).all()"
say "       [db.delete(x) for x in m]; [db.delete(x) for x in u]; db.commit()"
say "       print('"'"'осталось:'"'"', db.query(User).count(), db.query(Message).count())"
say "   EOF"
ls -l "$OUT" | sed 's/^/    /'
say "⚠ ХАОС НЕ ЗАПУСКАЛСЯ — он отдельным вызовом scripts/eval_chaos.py, в согласованное окно."
exit $((fail > 0 ? 1 : 0))
