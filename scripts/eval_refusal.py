"""`EV11` #92 — отказ «вне сферы / не найдено» распознаётся по ФОРМЕ ответа, а не по списку слов.

ЗАЧЕМ. Детекторы отказа в замерах (`eval_answers.DECLINE_RE`, `eval_guard._REFUSAL_MARKERS`) искали его
по СЛОВАМ, и модель регулярно отказывает, не употребив ни одного: «прямой позиции … не нашлось», «это
услуга, а не промышленная продукция», «подходящей нет». 18.08 так «пропал» отказ кейса #28 (гейт «отказ
вне сферы 3/4» при верном ответе), 28.10 на замере `R40` — три отказа из 18. Признак «какой это ответ»
надо брать из ФОРМЫ, предписанной промптом (урок 36), а не из фразы, которая может и не появиться.

ФОРМА. Разбор позиции идёт по шаблону правила 4: блок «**Позиция:**», баллы, порог. Отказ (правило 1б)
и уточнение (правило 1г) НЕ опираются ни на одну позицию: блока нет, чисел баллов/процентов нет —
кандидатов они перечисляют только наименованием и кодом (правило 1г прямо запрещает их требования).

ДВА ВОПРОСА — ДВЕ ФУНКЦИИ, ОДНО ОПРЕДЕЛЕНИЕ ФОРМЫ:
  * `declines` — ответ НЕ опирается на позицию: отказ ИЛИ уточнение. Гейт «отказ вне сферы» уровня 2
    (`eval_answers`): на продукции вне 719 верно и то, и другое — неверно только привязать её к позиции;
  * `refuses` — ЯВНЫЙ отказ: не опирается на позицию И говорит, что продукции в приложении нет / она вне
    сферы. Просьба уточнить код отказом не является (`eval_guard`: на пограничных профильных вопросах
    отказа быть не должно, уточнение — законно).
Слова в `refuses` — уже не единственный признак, а различитель отказа и уточнения ВНУТРИ формы.

ВАЖНО: рантайм решает ту же задачу формы сам (`pipeline._keep_points_table`) и этот модуль НЕ импортирует:
оракул, повторяющий код, слеп к его ошибке (урок `O3`). Согласие двух определений заголовка на списке его
форм держит тест (`tests/test_ev11_refusal_form.py`).
"""
from __future__ import annotations

import re

# Ответ назвал целевую позицию — заголовок шаблона правила 4. Терпимо к форме (ревью PR #263, MED):
# «**Позиция:**», «**Позиция**:», «**Позиция.**», «**Позиция**» отдельной строкой, «Позиция:» без жирного.
# ⚠ Одно определение на все замеры: `eval_completeness.is_clarifying` берёт его отсюда.
COMMIT_RE = re.compile(r"\*\*\s*Позиция\s*\**\s*[:.\n]|^\s*Позиция\s*:", re.I | re.M)
# Число баллов или процентов — требование позиции. Отказ и уточнение их не называют (правила 1б, 1г).
CLAIM_RE = re.compile(r"\d+(?:[.,]\d+)?\s*(?:балл|процент|%)", re.I)
# ⚠ Граница отказа и уточнения на словах размыта по природе — тексты ответов замера читаются глазами
# (`eval_guard --dump`). Поэтому маркеры двух сил:
#   * СИЛЬНЫЕ — «вне сферы», «это услуга», «нет в приложении»: отказ при любом окружении;
#   * СЛАБЫЕ — «прямого совпадения нет», «подходящей нет», «не найдена»: так говорит и уточнение по 1г
#     («Прямого совпадения по наименованию нет. Ближайшие позиции: …»), поэтому отказ — только если
#     ответ НЕ предлагает кандидатов на выбор (`CLARIFY_RE`).
OUT_STRONG_RE = re.compile(
    r"вне\s+сфер|не\s+относ\S*\s+к\s+(?:сфер|промышлен|продукци\S*\s+из\s+приложени)|нет\s+в\s+приложени|"
    r"в\s+приложени\S*[^.]{0,40}\s+(?:такой\s+)?позиции\s+нет|не\s+являет\S*\s+промышлен|"
    r"а\s+не\s+промышлен|(?:это|речь\s+(?:идёт\s+)?о)\s+(?:об\s+)?услуг|не\s+подпада|не\s+регулир|"
    r"не\s+распространя|не\s+входит\s+в\s+(?:приложени|сфер)|по\s+смыслу\s+не\s+соответству",
    re.I)
OUT_WEAK_RE = re.compile(
    r"позиции\s+(?:с\s+требованиями\s+)?[^.]{0,30}не\s+нашлось|"
    r"прям\S*\s+(?:позици|совпадени)\S*[^.]{0,60}(?:нет|не\s+нашл|не\s+найд)|"
    r"подходящ\S*\s+(?:позици\S*\s+)?нет|(?<!совпадени[ея]\s)не\s+найден[аоы]?\b(?!\s+точн)",
    re.I)
# Уточнение по правилу 1г: кандидаты на выбор и просьба подтвердить.
CLARIFY_RE = re.compile(
    r"ближайш\S*\s+(?:позици|кандидат)|какая\s+из\s+(?:них|позиций)|подтвердите|выберите|"
    r"точного\s+совпадения",
    re.I)


def relies_on_position(text: str) -> bool:
    """Ответ опирается на позицию: назвал её по шаблону или привёл её баллы/проценты."""
    t = text or ""
    return bool(COMMIT_RE.search(t) or CLAIM_RE.search(t))


def declines(text: str) -> bool:
    """Отказ ИЛИ уточнение — ответ не привязал продукцию ни к одной позиции (гейт «вне сферы»)."""
    return not relies_on_position(text)


def refuses(text: str) -> bool:
    """ЯВНЫЙ отказ: не опирается на позицию и говорит, что продукции нет / она вне сферы."""
    t = text or ""
    if not declines(t):
        return False
    if OUT_STRONG_RE.search(t):
        return True
    return bool(OUT_WEAK_RE.search(t)) and not CLARIFY_RE.search(t)
