class _FakePoint:
    """Точка выдачи Qdrant — минимум, который читает `search_cases`.

    `id` обязателен: порог релевантности (R30) сопоставляет гибридную выдачу с dense-пробой
    ПО ID, и точка без него молча вылетает из результата."""

    def __init__(self, payload: dict, score: float = 1.0, id: int = 1):  # noqa: A002
        self.payload = payload
        self.score = score
        self.id = id


# Payload РЕАЛЬНОГО кейса `okpd2_27_40_33_130_prozhektory.json`: код есть, `section_roman` НЕТ
# (так в файле — из 13 кейсов раздел проставлен у 7). Взят именно он: на нём фильтр области
# обязан сработать по-настоящему — раздела нет, ветка кода с окном не совпадает, — и кейс
# доезжает до выдачи ИСКЛЮЧИТЕЛЬНО путём `_case_code_hit`.
PROJECTORS = {
    "okpd2": "27.40.33.130",
    "query": "Что означает код ОКПД2 27.40.33.130?",
    "product_name": "Прожекторы и аналогичные светильники узконаправленного света",
    "expert_answer": "Эксперт ТПП: по классификатору это светотехническая продукция.",
}


class TestNamedCodeBeatsScope(unittest.TestCase):
    """Код, НАЗВАННЫЙ пользователем, авторитетнее эвристики о разделе.

    Путь `_case_code_hit` идёт мимо И порога релевантности, И фильтра области: спросили про
    конкретный код — значит про эту продукцию. Проверяется на СВЯЗКЕ (`search_cases`), а не на
    `case_fits_scope`: важно, что кейс по названному коду доезжает до ВЫДАЧИ при чужом окне.

    ⚠⚠ QDRANT ЗДЕСЬ ЗАГЛУШЕН, И ЭТО НЕ УДОБСТВО, А УСЛОВИЕ. Прежняя редакция звала `embed_query`
    и ЖИВУЮ коллекцию: на машине с поднятым Docker тест был зелёным, в CI — красным. Батарея
    простояла красной шесть прогонов подряд (21.08.2026, начиная с `35a7682`), и в этой красноте
    PR #103 уехал в `main`, а релиз `v0.5.0-test13` — на бой. Workflow предупреждал ровно об
    этом: «тест, которому понадобятся Qdrant или ключ, упадёт — и это правильный сигнал, что он
    перестал быть офлайновым». Сигнал был верен и не прочитан. Свойство «батарея офлайновая»
    держится каждым тестом по отдельности, общего предохранителя у него нет.

    ⚠ Сообщение прежнего падения ВРАЛО о причине: «кейс отсечён фильтром области», хотя до
    фильтра исполнение не доходило вовсе — `search_cases` уходила в свой `except` по обрыву
    соединения и возвращала пусто. Диагностика, называющая не ту причину, дороже отсутствующей.
    """

    def setUp(self):
        from app.rag import retriever as r
        self.r = r
        self._orig = (r._client, r._hybrid, r._case_dense_scores)
        r._client = lambda: type("C", (), {"collection_exists": lambda self, n: True})()

    def tearDown(self):
        self.r._client, self.r._hybrid, self.r._case_dense_scores = self._orig

    def _wire(self, dense: float) -> None:
        """Один кейс в гибридной выдаче с заданным ЧИСТЫМ dense-косинусом."""
        self.r._hybrid = lambda *a, **kw: [_FakePoint(dict(PROJECTORS), id=1)]
        self.r._case_dense_scores = lambda qvec, probe: {1: dense}

    def test_case_found_by_named_code_survives_foreign_window(self):
        """Косинус НИЖЕ порога (0.79 < 0.84) — один путь обходит оба предохранителя сразу.

        Это не выдуманное число: замер, ради которого лексический канал и заводился, дал на
        «что означает код 27.40.33.130» dense 0.847 при пороге, который его срезал."""
        self._wire(0.79)
        got = self.r.search_cases("что означает код 27.40.33.130", qvec=[0.1] * 4,
                                  sections={"XXIX"}, codes=["05.10.10"])
        self.assertEqual([c.get("okpd2") for c in got], ["27.40.33.130"],
                         "кейс по НАЗВАННОМУ коду не доехал до выдачи")
        self.assertTrue(got[0]["_by_code"], "кейс прошёл не тем путём: `_by_code` не выставлен")

    def test_same_case_without_named_code_is_dropped(self):
        """⚠ ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: без него тест выше зелен и при УДАЛЁННОМ фильтре области.

        Проводка та же, отличается только запрос — кода в нём нет, значит `_case_code_hit`
        молчит и решает `case_fits_scope`. Раздела у кейса нет, ветка 27.40 с окном 05.10 не
        совпадает: кейс обязан быть отсечён. Косинус заведомо ВЫШЕ порога, чтобы отсекала
        именно область, а не релевантность."""
        self._wire(0.99)
        self.assertEqual(self.r.search_cases("сколько баллов для прожекторов", qvec=[0.1] * 4,
                                             sections={"XXIX"}, codes=["05.10.10"]), [])


