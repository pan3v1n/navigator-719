class TestDeferredImportIsForcedByACycle(unittest.TestCase):
    """Отложенный импорт `st1_ref` обоснован ЦИКЛОМ — и цикл проверяется, а не декларируется.

    ⚠ Находка 12 десятого раунда: довод отложенного импорта в `procedural.py` оказался ложным
    («тянет torch»), и читатель, поверивший ему, вернул бы локальный импорт. Здесь довод другой
    и проверяемый: `st1_ref` импортирует имя ИЗ ЭТОГО модуля, значит импорт на уровне файла
    замкнул бы цикл. Если зависимость когда-нибудь исчезнет — тест покраснеет, и отложенный
    импорт можно будет поднять наверх."""

    def test_st1_ref_imports_from_okpd2_ref(self):
        src = (ROOT / "app" / "rag" / "st1_ref.py").read_text(encoding="utf-8")
        self.assertIn("from app.rag.okpd2_ref import", src,
                      "цикла больше нет — отложенный импорт в `_climb_resolves` потерял довод")

    def test_okpd2_ref_does_not_import_st1_ref_at_module_level(self):
        """Обратная половина: импорт наверху вернул бы цикл.

        ⚠ Считаем ПРОСТРАНСТВО ИМЁН МОДУЛЯ, а не `co_names` и не текст файла. Первая редакция
        этого теста смотрела в `co_names` и покраснела на ВЕРНОМ коде: локальный
        `from app.rag import st1_ref` кладёт имя в `co_names` ровно так же, как импорт наверху,
        то есть признак не различал то, ради чего заводился. Тот же класс, что находки 4 и 13
        десятого раунда, — пойман здесь мутацией, а не следующим раундом.
        Модульный импорт создал бы АТРИБУТ модуля; локальный живёт только в кадре вызова."""
        self.assertFalse(hasattr(okpd2_ref, "st1_ref"),
                         "`st1_ref` стал атрибутом модуля — импорт уехал наверх, цикл вернулся")

    def test_the_namespace_check_can_actually_fail(self):
        """Отрицательный контроль к предыдущему: признак обязан уметь краснеть."""
        with mock.patch.object(okpd2_ref, "st1_ref", st1_ref, create=True):
            self.assertTrue(hasattr(okpd2_ref, "st1_ref"),
                            "признак не реагирует на модульный импорт — он выродился")


class TestClimbAsksTheTableNotTheShape(unittest.TestCase):
    """Ядро правки: подъём к родителю разрешён фактом наличия записи, а не формой записи."""

    def setUp(self):
        # ⚠ Провал, а не пропуск: таблица коммитится в репозиторий, её отсутствие — дефект
        # выкатки (находка 9 одиннадцатого раунда: `skipTest` снимал шесть сторожей HIGH разом).
        if not st1_ref.is_available():
            self.fail("таблица условий Перечня недоступна — это дефект выкатки, "
                      "сторожа HIGH не должны молча исчезать")

    def test_parent_present_climb_allowed(self):
        self.assertTrue(st1_ref.conditions_for("8403")["matched"], "пример протух")
        self.assertEqual(extract_tnved_position("ТН ВЭД 8403 12 шт"), "8403")

    def test_parent_absent_refuses_instead_of_asserting(self):
        """⚠⚠⚠ ПРИМЕР ЗАМЕНЁН ПОСЛЕ НАХОДКИ РАУНДА 12: 2101 НЕ подходит, он покрыт `narrower`.

        Первая редакция брала 2101 «отсутствующим родителем», потому что `matched` там False.
        Но у него ТРИ записи `narrower`, и лукап о нём знает: прежний ответ печатал общее правило
        И оговорку «отдельные условия установлены для более узких кодов: 21011100; 210112;
        210130910», то есть называл пользователю ровно тот код, который он написал. Отказ здесь
        был потерей, а не починкой. Настоящий «родителя нет» — это ни `exact`, ни `narrower`."""
        cond = st1_ref.conditions_for("7326 90")
        self.assertFalse(cond["matched"], "пример протух")
        self.assertFalse(cond["narrower"], "пример протух: у 7326 90 появились узкие записи")
        self.assertIsNone(extract_tnved_position("ТН ВЭД 7326 90 9 позиций"))

    def test_parent_known_only_by_narrower_still_answers(self):
        """Обратная половина: покрытый `narrower` родитель обязан ДОЕХАТЬ, а не быть отброшенным."""
        self.assertTrue(st1_ref.conditions_for("2101")["narrower"], "пример протух")
        self.assertEqual(extract_tnved_position("ТН ВЭД 2101 12 шт"), "2101")
        self.assertIn("более узких", st1_ref.format_for_context("2101"),
                      "оговорка `narrower` пропала — подъём к такому родителю потерял смысл")

    def test_the_refusal_is_what_prevents_a_false_negative(self):
        """⚠ Проверяем ПОСЛЕДСТВИЕ отказа, а не факт отказа.

        Без этого тест утверждал бы «здесь None», не сказав, почему None лучше кода."""
        with mock.patch.object(okpd2_ref, "_climb_resolves", return_value=True):
            key = extract_tnved_position("ТН ВЭД 7326 90 9 позиций")
        self.assertEqual(key, "7326 90")
        rendered = st1_ref.format_for_context(key)
        self.assertIn("НЕ включён", rendered,
                      "без проверки подъём печатал бы именно этот уверенный вердикт")
        self.assertNotIn("более узких", rendered,
                         "у этого родителя нет узких записей — сказать нечего, и это весь довод")

    def test_missing_table_degrades_to_the_old_behaviour(self):
        """⚠⚠ «Таблицы нет» ≠ «кода нет»: дефект выкатки не должен выключать ВСЕ подъёмы.

        Слой поломки совпадает со слоем наблюдения — глушится `is_available`, а не файл."""
        with mock.patch.object(st1_ref, "is_available", return_value=False):
            self.assertTrue(okpd2_ref._climb_resolves("2101"),
                            "при недоехавшей таблице подъём обязан остаться разрешённым")


class TestOrdinaryPathHasNoLengthGate(unittest.TestCase):
    """HIGH раунда 11: то, что написал пользователь, отдаётся как есть — решает лукап."""

    def setUp(self):
        # ⚠ Провал, а не пропуск: таблица коммитится в репозиторий, её отсутствие — дефект
        # выкатки (находка 9 одиннадцатого раунда: `skipTest` снимал шесть сторожей HIGH разом).
        if not st1_ref.is_available():
            self.fail("таблица условий Перечня недоступна — это дефект выкатки, "
                      "сторожа HIGH не должны молча исчезать")

    def test_over_long_but_resolvable_key_survives(self):
        for q, want in (("какие условия по ТН ВЭД 2101 121", "2101 121"),
                        ("ТН ВЭД 0710 40 00005 какие условия", "0710 40 00005")):
            with self.subTest(q=q):
                key = extract_tnved_position(q)
                self.assertEqual(key, want)
                self.assertTrue(st1_ref.conditions_for(key)["matched"],
                                "ключ обязан доезжать до своей строки — на этом стоит вся правка")

    def test_the_high_of_round_ten_is_still_fixed(self):
        """Положительный контроль: снимая гейт, нельзя вернуть дефект, ради которого его ставили."""
        self.assertEqual(extract_tnved_position("ТН ВЭД 8544 70 000 0 позиции"), "8544 70 000 0")
        self.assertEqual(extract_tnved_position("по ТН ВЭД 0710 40 00 0 шт какие условия"),
                         "0710 40 00 0")

    def test_the_counter_still_disqualifies_a_bare_group(self):
        """Положительный контроль: решение раунда 9 не отменено — голый счётчик не станет кодом."""
        for q in ("по ТН ВЭД поставлено 1500 единиц, какие условия происхождения",
                  "по ТН ВЭД 2026 позиций, какие условия достаточной переработки"):
            with self.subTest(q=q):
                self.assertIsNone(extract_tnved_position(q))


