"""Разбор ИСХОДНИКОВ для сторожей: счёт по КОДУ, а не по тексту файла.

⚠⚠⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ (находка 7 одиннадцатого раунда). Стриппер комментариев жил
статическим методом в `test_k14_review_pr137_round7.py`, а соседний сторож
`TestSharedFragmentsAreEnumerated` в `test_k14_review_round10.py` считал СЫРОЙ исходник — в
двадцати строках от него и ровно тем способом, который стриппер и заводился заменить. Итог: тот
сторож был слеп на двух своих шести фрагментах (`кумулятивн` и `адвалорн` — raw 3 / code 2, и
лишнее вхождение добавил комментарий ТОГО ЖЕ коммита), то есть удаление обоих настоящих
определений оставляло его зелёным.

Копировать стриппер во второй файл нельзя: «две копии про одно» — тот самый класс, который дал
HIGH-2 восьмого раунда и находку шестого. Поэтому одно определение здесь, оба файла зовут его.

⚠⚠ МОДЕЛЬ СТРОК СОВПАДАЕТ С МОДЕЛЬЮ `tokenize` (находка 15 одиннадцатого раунда): режем по
`\\n`, а не `splitlines()`. `splitlines()` дополнительно режет по `\\x0b`, `\\x0c`, `\\x1c`-`\\x1e`,
`\\x85`, `\\u2028`, `\\u2029`, тогда как `tokenize` считает строки только по `\\n`, — один такой
знак выше по файлу сдвигал все номера строк, и срез комментария уезжал на ЧУЖУЮ строку молча.
Для проекта, где комментарии — русская проза из Word и PDF, это не теория.
"""

from __future__ import annotations

import io
import tokenize
from pathlib import Path


def strip_comments(src: str) -> str:
    """Исходник БЕЗ комментариев — по ТОКЕНАМ, а не по началу строки.

    Снимает и хвостовые комментарии (`X = ...  # ...`), и целые строки, и при этом не трогает
    строковые литералы: наивный срез по «#» порезал бы сам шаблон регулярки."""
    lines = src.split("\n")
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            row = tok.start[0] - 1
            lines[row] = lines[row][:tok.start[1]] + lines[row][tok.end[1]:]
    return "\n".join(lines)


def code_only(path: Path) -> str:
    """Текст файла без комментариев. Докстринги остаются — они часть кода."""
    return strip_comments(Path(path).read_text(encoding="utf-8"))
