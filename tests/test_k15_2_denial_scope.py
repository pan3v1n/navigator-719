class TestGuardSparesCorrectAnswers(unittest.TestCase):
    def test_no_false_positives(self):
        """Несущая половина: 0 ложных срабатываний на 11 формах верного ответа."""
        fired = [t for t in CORRECT_ANSWERS if documents_ref.unverified_documents(t)]
        self.assertEqual(fired, [], f"гард ударил по ВЕРНОМУ ответу: {[t[:60] for t in fired]}")

    def test_inventions_are_caught(self):
        """⚠ Обратная половина: правило, никогда не срабатывающее, тоже даёт 0 ложных."""
        silent = [t for t in INVENTIONS if not documents_ref.unverified_documents(t)]
        self.assertEqual(silent, [], f"гард ослеп на выдумке: {[t[:60] for t in silent]}")


class TestKnownLimitIsRecorded(unittest.TestCase):
    """⚠⚠ Предел показан числом, а не спрятан. Если он однажды закроется — тест скажет об этом,
    и запись в `K15-2` #129 надо будет обновить, а не оставить врать про механизм."""

    def test_limit_still_holds(self):
        for text in KNOWN_LIMIT:
            self.assertEqual(
                documents_ref.unverified_documents(text), [],
                f"предел закрылся — обновить K15-2 #129 и перенести форму в INVENTIONS: {text[:70]!r}")

    def test_limit_is_narrow(self):
        """Предел касается ТОЛЬКО соседнего предложения: в предложении термина правило работает."""
        one_sentence = ("Заключение ТПП о подтверждении производства выдаёт палата, "
                        "отдельного реестра таких документов не существует.")
        self.assertEqual(documents_ref.unverified_documents(one_sentence), [],
                         "в ОДНОМ предложении отрицание засчитывается — это ожидаемо")


