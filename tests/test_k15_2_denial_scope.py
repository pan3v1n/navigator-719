class TestGuardSparesCorrectAnswers(unittest.TestCase):
    def test_no_false_positives(self):
        """Несущая половина: 0 ложных срабатываний на ВСЕХ формах верного ответа.

        ⚠ Числа форм в тексте намеренно нет. Оно уже разошлось однажды: докстринг говорил
        «на 11 формах», когда в наборе было 12, и то же число стояло в комментарии модуля и в
        коммит-месседже. В проекте, где число — критерий приёмки, устаревший счётчик рядом с
        правкой читается как «замер не пересчитывали». Счёт берётся из данных."""
        fired = [t for t in CORRECT_ANSWERS if documents_ref.unverified_documents(t)]
        self.assertEqual(
            fired, [],
            f"гард ударил по ВЕРНОМУ ответу ({len(fired)} из {len(CORRECT_ANSWERS)}): "
            f"{[t[:60] for t in fired]}")

    def test_inventions_are_caught(self):
        """⚠ Обратная половина: правило, никогда не срабатывающее, тоже даёт 0 ложных."""
        silent = [t for t in INVENTIONS if not documents_ref.unverified_documents(t)]
        self.assertEqual(silent, [], f"гард ослеп на выдумке: {[t[:60] for t in silent]}")


