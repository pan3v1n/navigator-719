class TestDenialMustBelongToTheDocument(unittest.TestCase):
    """Находка 2: `_DENIAL` глушил гард отрицанием, относящимся к ДРУГОМУ предмету.

    Гард `K15` — последний рубеж перед экспертом: правило промпта может не сработать, и тогда
    выдуманный документ обязан хотя бы попасть в админ-журнал. Глушилка срабатывала дважды:
    голое «отсутству» ловилось независимо от того, что отрицается, а окно ±200 знаков
    перешагивало границу предложения.
    """

    def test_negation_of_another_subject_does_not_shield_the_invention(self):
        """Отрицается ПРОДУКЦИЯ, а прикрывало выдуманный документ в том же предложении.

        ⚠⚠ ФОРМУЛИРОВКА ИЗ ОТЧЁТА РЕВЬЮ НЕ ВОСПРОИЗВОДИЛАСЬ, И ЭТО ПРОВЕРЕНО, А НЕ ПРИНЯТО НА
        ВЕРУ. Ревью привело пример «При ОТСУТСТВИИ продукции…», но прежняя регулярка искала
        основу «отсутству», которая формы «отсутствии» не покрывает: на этом тексте гард
        срабатывал и ДО правки. Тест на нём был бы фиктивным контролем — зелёным на обоих
        версиях кода. Здесь стоят формы, воспроизведённые прогоном модуля из `HEAD`:
        на них гард ослеп (`False`), после правки видит (`True`).
        """
        for text in ("Если продукция отсутствует в приложении, потребуется заключение ТПП "
                     "о подтверждении производства.",
                     "Продукция отсутствует в реестре, поэтому нужно заключение ТПП "
                     "о подтверждении производства."):
            self.assertTrue(documents_ref.unverified_documents(text),
                            f"гард ослеп: отрицается продукция, а не документ — {text[:60]!r}")

    def test_negation_in_the_neighbouring_sentence_does_not_shield_it(self):
        """Отрицание относится к СТ-1, а прикрывало выдумку из соседнего предложения.

        ⚠⚠ ТОЧКА ОБЯЗАТЕЛЬНА В НАБОРЕ, И ЭТО КУПЛЕНО РЕВЬЮ PR #127. Первая редакция теста несла
        ОДИН пример — через точку с запятой, — и была ЗЕЛЁНОЙ на сломанном коде: `_denial_scope`
        искал границу через `finditer(text, lo, start)`, а обрезка по `start` делала невыполнимым
        lookahead альтернативы с ТОЧКОЙ (ему нужна первая буква термина). Работали только `;` и
        перевод строки — ровно те альтернативы, у которых lookahead нет. То есть правка чинила
        самый частый разделитель ХУЖЕ ВСЕГО, а тест этого не показывал.
        """
        for text in (
            "Заключение ТПП о подтверждении производства выдаёт уполномоченная палата; "
            "сертификат СТ-1 в этом случае не применяется.",
            "Сертификат СТ-1 в этом случае не применяется. Заключение ТПП о подтверждении "
            "производства выдаёт уполномоченная палата.",
            "Такой документ отсутствует в реестре. Заключение ТПП о подтверждении производства "
            "оформляется палатой.",
        ):
            self.assertTrue(documents_ref.unverified_documents(text),
                            f"отрицание соседнего предложения оправдало выдумку: {text[:60]!r}")

    def test_real_denials_are_still_spared(self):
        """⚠ Обратная половина: цель `K15` — чтобы ответ ОБЪЯСНЯЛ. Наказывать за это нельзя."""
        for text in (
            "Документа «заключение ТПП», подтверждающего производство, не существует.",
            "Не используйте термин «заключение ТПП» — такого документа нет.",
            "Такой документ отсутствует: заключение ТПП не выдаётся.",
            "Перечень закрытый: производство подтверждается актом экспертизы ТПП или "
            "сертификатом СТ-1. Документа «заключение ТПП» не существует.",
        ):
            self.assertEqual(documents_ref.unverified_documents(text), [],
                             f"гард ударил по ВЕРНОМУ ответу: {text[:70]!r}")

    def test_strong_denial_reaches_across_a_sentence_boundary(self):
        """⚠⚠ ЛОЖНОЕ СРАБАТЫВАНИЕ ПЕРВОЙ РЕДАКЦИИ ЭТОЙ ЖЕ ПРАВКИ, пойманное сверкой вердиктов
        на 65 абзацах документации.

        Сплошное сужение до предложения красило дефектом ВЕРНЫЙ ответ в два предложения: термин
        в первом, отрицание во втором. Отсюда два тира: «не существует» и «нет такого» отрицают
        документ и ничего другого — им хватает окна; «не применяется» и «отсутствует» цепляются
        к любому соседнему существительному — им нужно предложение термина."""
        for text in ("Вы спрашиваете, нужно ли заключение ТПП. Такого документа не существует.",
                     "Речь про заключение ТПП? Такого документа не бывает — нужен акт экспертизы."):
            self.assertEqual(documents_ref.unverified_documents(text), [],
                             f"гард ударил по ВЕРНОМУ ответу в два предложения: {text!r}")

    def test_sentence_scope_does_not_break_on_abbreviations(self):
        """⚠ Точка в «п. 4.1» и «ред. от 22.07.2026» НЕ должна резать предложение.

        Иначе гард ослеп бы от собственной границы: отрицание осталось бы за обрезом."""
        text = ("Согласно п. 4.1 Приказа ТПП РФ N 52 в ред. от 29.10.2025 документа "
                "«заключение ТПП» не существует.")
        self.assertEqual(documents_ref.unverified_documents(text), [],
                         "граница предложения разорвала текст по сокращению")


class TestOneGateForTheBlockAndItsContents(unittest.TestCase):
    """Находка 3: разъяснение решалось ГОЛОЙ регуляркой, не знавшей «заключение как ДЕЙСТВИЕ».

    ⚠⚠ Третий заход одного и того же разъезда. `dbfc622` убрала безусловное разъяснение,
    `K15-1` #120 свела гейт блока с гейтом содержимого — но содержимое осталось на своём
    предикате. Блок кладётся ещё и по ТЕМЕ, без всякого вопроса про заключение, и на вопросе
    «какие документы готовить при ЗАКЛЮЧЕНИИ ДОГОВОРА поставки» термин уезжал пользователю,
    который про него не спрашивал.
    """

    ACTS = ("какие документы готовить при заключении договора поставки",
            "какие требования при заключении СПИК для 27.11.42",
            "что нужно для заключения контракта на поставку станков")

    def test_conclusion_as_an_act_gets_no_explanation(self):
        for q in self.ACTS:
            self.assertNotIn(documents_ref.NONEXISTENT_EXPLANATION,
                             documents_ref.documents_context_block(q),
                             f"разъяснение уехало в вопрос про действие: {q!r}")

    def test_conclusion_as_a_document_still_gets_it(self):
        """⚠ Обратная половина: сузить до слепоты — тот же дефект с другой стороны.

        «Экспертное заключение» здесь НАМЕРЕННО проходит: это действующий документ п. 36–40
        Правил, и разъяснение как раз разводит его с выдуманным."""
        for q in ("нужно ли заключение ТПП для внесения продукции в реестр",
                  "требуется ли заключение ТПП о подтверждении производства",
                  "что такое экспертное заключение"):
            self.assertIn(documents_ref.NONEXISTENT_EXPLANATION,
                          documents_ref.documents_context_block(q),
                          f"разъяснение не доехало до вопроса о ДОКУМЕНТЕ: {q!r}")

    def test_document_sense_wins_over_act_sense(self):
        """⚠⚠ РЕГРЕССИЯ ПОКРЫТИЯ, ВНЕСЁННАЯ ПЕРВОЙ РЕДАКЦИЕЙ ЭТОЙ ЖЕ ПРАВКИ (ревью PR #127).

        Исключение «действие» применялось ко ВСЕМУ вопросу, поэтому «нужно ли ЗАКЛЮЧЕНИЕ ТПП при
        ЗАКЛЮЧЕНИИ СПИК» теряло разъяснение — а это ровно вопрос кластера жалоб №1, ради которого
        справочник и заведён: СПИК и госконтракт — самая частая рамка, в которой про «заключение
        ТПП» и спрашивают. До PR голая регулярка разъяснение давала.
        ⚠ Замер радиуса по 213 вопросам наборов показал НОЛЬ и этого не поймал: класс смешанных
        вопросов наборами не покрыт вовсе. Поймано ревью, воспроизведено сверкой с `main`."""
        for q in ("нужно ли заключение ТПП при заключении СПИК",
                  "нужно ли заключение ТПП для заключения контракта по 44-ФЗ"):
            self.assertTrue(documents_ref.mentions_conclusion(q), q)
            self.assertIn(documents_ref.NONEXISTENT_EXPLANATION,
                          documents_ref.documents_context_block(q),
                          f"смешанный вопрос потерял разъяснение: {q!r}")

    def test_both_gates_share_the_act_exclusion(self):
        """Один гейт, а не два похожих: исключение «действие» обязано жить в одном месте."""
        for q in self.ACTS:
            self.assertFalse(documents_ref.mentions_conclusion(q), q)
            self.assertFalse(documents_ref.asks_about_conclusion(q), q)

    def test_narrow_gate_is_unchanged_for_document_questions(self):
        """⚠ Радиус правки `asks_about_conclusion` обязан быть НУЛЕВЫМ: он втаскивает справочник
        в контекст, когда тема не документная, и его расширение уронило бы блок в товарные
        вопросы."""
        self.assertTrue(documents_ref.asks_about_conclusion(
            "нужно ли заключение ТПП для внесения продукции в реестр"))
        self.assertFalse(documents_ref.asks_about_conclusion("что такое экспертное заключение"),
                         "узкий гейт расширился — справочник поедет в товарные вопросы")
        self.assertFalse(documents_ref.asks_about_conclusion("какие документы нужны для "
                                                             "этикетировщиков"))


if __name__ == "__main__":
    unittest.main()
