def build_navigator_user_prompt(
    query: str,
    context: str,
    okpd2: str | None = None,
    cases: str | None = None,
    low_relevance: bool = False,
    resolved: str | None = None,
) -> str:
    """Собирает сообщение пользователя для навигатора: вопрос + (кейсы) + найденный контекст.

    `low_relevance=True` — сигнал out-of-scope guard (низкое dense-сходство найденного):
    подмешиваем явное предупреждение, чтобы модель перепроверила соответствие тематики
    и при несовпадении честно сказала «вне сферы 719», а не подгоняла ответ.
    `resolved` — уточнённая по диалогу формулировка follow-up (мультитёрн): показываем модели,
    как понят вопрос в контексте прошлых ходов, если она отличается от исходной."""
    head = f"ВОПРОС: {query}"
    if resolved and resolved.strip() and resolved.strip() != query.strip():
        head += f"\n(в контексте диалога вопрос означает: {resolved})"
    if okpd2:
        head += f"\nКод ОКПД2 (указан пользователем): {okpd2}"
    parts = [head]
    if low_relevance:
        parts.append(
            "⚠️ СИГНАЛ РЕЛЕВАНТНОСТИ: сходство найденных позиций с запросом НИЗКОЕ — велика "
            "вероятность, что продукция вне сферы ПП №719. Особенно тщательно примени правило 1б: "
            "если позиции ниже по СМЫСЛУ не соответствуют запросу — ответь, что подходящая позиция "
            "не найдена / продукция вне сферы 719, и не привязывай ответ к неподходящим позициям."
        )
    if cases:
        parts.append("ПОДТВЕРЖДЁННЫЕ ЭКСПЕРТОМ КЕЙСЫ (высший приоритет):\n" + cases)
    parts.append("НАЙДЕННЫЕ ПОЗИЦИИ:\n" + context)
    return "\n\n".join(parts)
