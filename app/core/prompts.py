def build_procedural_user_prompt(query: str, rules_context: str, topic_fragment: str = "") -> str:
    """Сообщение пользователя для процедурного ответчика: вопрос + найденные пункты Правил.

    `topic_fragment` (K12) — оговорки под НАМЕРЕНИЕ вопроса (состав документов / сроки / путь СТ-1 /
    критерии / классификация / порядок внесения). Идёт в сообщение пользователя, а не в системный
    промпт, намеренно: системный промпт один на все процедурные ответы и держит общие правила
    (заземление, ссылки [N], запрет выдумывать сроки), а тема меняется от вопроса к вопросу. Пусто —
    тема не распознана, работают только общие правила."""
    parts = [f"ВОПРОС: {query}"]
    if topic_fragment:
        parts.append(topic_fragment)
    parts.append(f"ПУНКТЫ ПРАВИЛ:\n{rules_context}")
    return "\n\n".join(parts)
