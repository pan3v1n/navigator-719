# -*- coding: utf-8 -*-
"""Метка релиза: что ИМЕННО крутится на этой машине (пометка версии во фронте).

ЗАЧЕМ ОТДЕЛЬНАЯ МЕТКА, А НЕ `APP_VERSION`. `APP_VERSION` держится на `0.5.0` до приёмки эксперта
≥ 70 % — это гейт версии `1.0`, и он намеренно не двигается от релиза к релизу. За август-сентябрь
2026 под одним и тем же «0.5.0» на бой уехало полтора десятка сборок от `test10` до `test24`, и
вопрос «а что сейчас на машине» по этому числу не решался вовсе. Отвечает на него ТЕГ РЕЛИЗА.

ОТКУДА БЕРЁТСЯ, В ПОРЯДКЕ ПРИОРИТЕТА:
  1. `RELEASE_TAG` из окружения — ручное переопределение (эксперимент, локальный прогон);
  2. файл `RELEASE` в корне рабочей копии — его пишет `scripts/deploy/deploy.sh` сразу после
     распаковки пакета, из `TAG` профиля релиза. Именно поэтому метка не может разойтись с тем,
     что выкачено: источник у неё тот же, что у маркеров и счётчиков коллекций;
  3. ничего не нашлось.

⚠⚠ ТРЕТИЙ ИСХОД НЕ ВЫДУМЫВАЕТ ТЕГ. Пометка, назвавшая версию наугад, хуже отсутствующей: она
читается как факт. Не зная тега, говорим ровно то, что знаем — `APP_VERSION` и что тег не задан.
Тот же принцип, что у пробников выкатки: здоров / нездоров / НЕ ИЗМЕРЕНО.

⚠ Файл `RELEASE` — артефакт ВЫКАТКИ, а не исходник: он в `.gitignore`, поэтому не попадает в
`git archive` и распаковка пакета его не затирает.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from app.core.config import settings

_RELEASE_FILE = Path(__file__).resolve().parents[2] / "RELEASE"

# Что печатаем, когда тега нет. Отдельной константой — её проверяет тест, а строка обязана быть
# одна: две копии «неизвестной версии» разъезжаются при первой же правке формулировки.
UNTAGGED = "тег сборки не задан"


@lru_cache(maxsize=1)
def release_label() -> str:
    """«v0.5.0-test24» либо «0.5.0 · тег сборки не задан». Читается один раз за процесс.

    Кэш здесь уместен: и переменная окружения, и файл фиксируются на старте контейнера, а
    выкатка всегда перезапускает приложение (`compose up -d app`). Перечитывать на каждый запрос
    значило бы ходить в файловую систему ради строки, которая не меняется.
    """
    tag = (settings.RELEASE_TAG or "").strip()
    if not tag:
        try:
            tag = _RELEASE_FILE.read_text(encoding="utf-8").strip().splitlines()[0].strip()
        except (OSError, IndexError):
            tag = ""
    return tag or f"{settings.APP_VERSION} · {UNTAGGED}"
