"""Манифест корпуса — единственный источник правды о его составе (`K8` #39, `#106`).

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Читалка родилась внутри `scripts/load_rules_kb.py`, а манифест нужен уже
ТРЁМ загрузчикам: процедурный корпус, товарный (приложение) и кейсы экспертов. Копия правил
разбора в каждом означала бы три расходящихся понимания того, что такое «состав корпуса», —
ровно то, ради устранения чего манифест и заводился. Здесь же, в `app/core/`, он доступен и
рантайму: `legal_force` понадобится `K13` для иерархии источников в промпте.

ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ: не читает сами документы и не знает их форматов. Разбор — забота
загрузчика (у каждого корпуса свой парсер), манифест отвечает на вопросы «какие документы»,
«какой они силы», «что действует» и «где лежат файлы».
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = ROOT / "knowledge_base" / "manifest.yaml"
KB_DIR = ROOT / "knowledge_base"

# Поля паспорта, которые уезжают в payload КАЖДОЙ записи документа. `edition` сюда не входит:
# её считает загрузчик из текста, а манифест лишь заявляет ожидаемую (`edition_expected`).
PASSPORT_FIELDS = ("authority", "legal_force", "doc_kind", "topic", "key_type",
                   "status", "valid_from", "valid_to", "supersedes")
RETIRED = "утратил силу"
ACTIVE = "действует"


class ManifestError(RuntimeError):
    """Манифест не читается или противоречив. Скрипты превращают её в `sys.exit`.

    Исключение, а не `sys.exit` внутри: модуль зовётся и из тестов, и из рантайма, а библиотека,
    гасящая процесс, — плохой сосед."""


def load_manifest(path: Path | None = None) -> dict:
    """Читает манифест и проверяет значения по его же словарям.

    ⚠ Проверка словарём — не бюрократия. Опечатка в `status` («утратила силу») тихо превратила бы
    исключённый документ в действующий, а `legal_force: "2"` строкой сломала бы сравнение силы
    источников при `K13`. Ошибка здесь останавливает загрузку: индексировать корпус с неизвестным
    паспортом хуже, чем не индексировать вовсе."""
    import yaml  # локально: парсеры документов тестируются без внешних зависимостей

    path = path or MANIFEST_PATH
    if not path.exists():
        raise ManifestError(f"нет манифеста корпуса: {path} (состав корпуса задаётся им)")
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    docs = data.get("documents") or []
    if not docs:
        raise ManifestError(f"в манифесте {path.name} нет ни одного документа")
    vocab = data.get("vocabularies") or {}
    seen: set[str] = set()
    for d in docs:
        dt = d.get("doc_type")
        if not dt:
            raise ManifestError(f"документ без doc_type: {d.get('title')!r}")
        if dt in seen:
            raise ManifestError(f"doc_type {dt!r} встречается дважды — идентификатор обязан быть уникален")
        seen.add(dt)
        if not d.get("collection"):
            raise ManifestError(f"{dt}: не указана коллекция (collection)")
        for field, allowed in vocab.items():
            if field not in d:
                continue
            value = d[field]
            if value is None and None in allowed:
                continue
            if value not in allowed:
                raise ManifestError(f"{dt}: недопустимое {field}={value!r}; словарь: {allowed}")
        missing = [f for f in PASSPORT_FIELDS if f not in d]
        if missing:
            raise ManifestError(f"{dt}: в паспорте нет полей {missing}")
    return data


def documents(collection: str, path: Path | None = None) -> list[dict]:
    """Документы одной коллекции, в порядке манифеста.

    Разделение по коллекциям обязательно: `load_rules_kb` итерирует документы и зовёт для каждого
    свой парсер — без фильтра он попытался бы разобрать товарное приложение парсером норм."""
    return [d for d in load_manifest(path)["documents"] if d.get("collection") == collection]


def passport(doc: dict) -> dict:
    """Поля паспорта одной записи + человекочитаемое имя документа для атрибуции."""
    out = {f: doc.get(f) for f in PASSPORT_FIELDS}
    out["doc_title"] = doc.get("short") or doc.get("title") or doc.get("doc_type")
    return out


def resolve_sources(doc: dict, kb_dir: Path | None = None) -> list[Path]:
    """Файлы документа: точные пути и/или шаблоны, минус исключения.

    ⚠ ШАБЛОН РАЗРЕШЁН ОСОЗНАННО, но не везде. У процедурного корпуса файлы перечислены поимённо:
    их пять, они разные по структуре, и подстановка `1[1-5]*.txt` однажды уже цепляла товарные
    чанки. У приложения секций 29, они ГЕНЕРИРУЮТСЯ — перечислять их значит заводить второй
    список, который начнёт расходиться с каталогом молча.

    `exclude` нужен, чтобы решение «эти файлы не индексируем» жило в манифесте, а не в условии
    внутри загрузчика: так исключение видно тому, кто читает состав корпуса."""
    base = kb_dir or KB_DIR
    files: list[Path] = []
    for pattern in doc.get("sources") or []:
        if any(ch in pattern for ch in "*?["):
            found = sorted(base.glob(pattern))
            if not found:
                raise ManifestError(f"{doc.get('doc_type')}: шаблон {pattern!r} не нашёл ни одного файла")
            files.extend(found)
        else:
            p = base / pattern
            if not p.exists():
                raise ManifestError(f"{doc.get('doc_type')}: нет файла {p} (перечислен в манифесте)")
            files.append(p)
    for pattern in doc.get("exclude") or []:
        dropped = {p for p in files if p.match(pattern)}
        files = [p for p in files if p not in dropped]
    return files


# --- Юридическая сила источника (`K13` #46) ---------------------------------------------------

# Ранг → как он называется в ответе. Формулировки пользовательские, а не внутренние: критерий
# приёмки K13 требует, чтобы ответ ЯВНО назвал, на норму какой силы он опирается, — значит слова
# отсюда уедут в текст эксперту, и «сила 3» без расшифровки там читаться не должна.
# ⚠ У 4 и 5 оговорка «не норма» — часть названия, а не комментарий: разъяснение и практика не
# создают обязанности, и ответ, ссылающийся на них как на требование, дефектен.
LEGAL_FORCE_NAMES = {
    # ⚠ Ступень 0 — международный договор: выше внутреннего акта по ст. 15 Конституции. Заведена
    # находкой ревью PR #137: без неё Соглашение СНГ подписывалось в окне модели как
    # «постановление Правительства РФ».
    0: "международный договор (ратифицирован)",
    1: "постановление Правительства РФ",
    2: "правила и приложение к постановлению",
    3: "ведомственный акт ТПП РФ",
    4: "разъяснение, не норма",
    5: "практика, не норма",
}


def legal_force_by_doc() -> dict[str, int]:
    """`doc_type` → юридическая сила документа. Для РАНТАЙМА, поэтому деградирует, а не падает.

    ⚠ ПОЧЕМУ ИЗ МАНИФЕСТА, А НЕ ИЗ PAYLOAD. Паспорт лежит в payload каждой точки, и соблазн взять
    `legal_force` оттуда велик — но:
    * паспорт есть только у переиндексированных корпусов. На бою это `pp719_rules` (311 точек,
      переиндексирован 24.08); у товарного `pp719` (1377) и у кейсов (12) его НЕТ, и чтение из
      payload молча вернуло бы пусто — ровно там, где кейс эксперта обязан быть помечен «практика,
      не норма». Молча — потому что отсутствие поля неотличимо от «сила не задана»;
    * сила — свойство ДОКУМЕНТА, а не пункта. Это же рассуждение закрыло `A3` #58 как ненужную.
      Читая из payload, мы допускаем расхождение силы между пунктами одного документа — состояние,
      которого не должно существовать;
    * и практическое: манифест делает правку РАНТАЙМОВОЙ. Через payload `K13` потребовала бы
      переиндексации всех трёх корпусов до выкатки.

    ⚠ ПОЧЕМУ ДЕГРАДИРУЕТ. Загрузчики на битом манифесте падают намеренно — индексировать корпус с
    неизвестным паспортом хуже, чем не индексировать. Рантайм так вести себя не может: манифест
    здесь УКРАШАЕТ контекст, и его поломка не повод оставить пользователя без ответа. Пустой
    словарь = пометок нет, ответ собирается как до `K13`. Второй контур при этом на месте:
    испорченный манифест не доедет до боя незамеченным — на нём остановится загрузка.

    Кэш на процесс: манифест читается с диска и парсится yaml'ом, а зовётся это на КАЖДОМ
    процедурном ответе. В тестах сбрасывается `legal_force_by_doc.cache_clear()`.

    ⚠⚠ КЭШИРУЕТСЯ ТОЛЬКО УСПЕХ (ревью захода 5, 26.08.2026). Прежде `@lru_cache` висел прямо на
    этой функции, и деградация запоминалась НАВСЕГДА: одна временная ошибка чтения — манифест
    подменён в момент выкатки, файл под блокировкой, контейнер читает посреди rsync — и пустой
    словарь оставался в кэше до перезапуска процесса. Каждый следующий процедурный ответ молча
    терял пометки `K13`, ВТОРОГО предупреждения в логе не было, а проверки рантайма выкатки этого
    не видели вовсе: одно предупреждение при старте легко пропустить, а состояние необратимо.
    Теперь кэш стоит на внутренней функции, которая БРОСАЕТ: `lru_cache` исключения не запоминает,
    поэтому следующий вызов пробует прочитать манифест заново.
    """
    try:
        return _legal_force_loaded()
    except Exception as exc:  # noqa: BLE001 — любой сбой чтения манифеста, не только ManifestError
        from loguru import logger
        logger.warning("K13: манифест не прочитан ({}), иерархия источников в контекст не пойдёт", exc)
        return {}


@lru_cache(maxsize=1)
def _legal_force_loaded() -> dict[str, int]:
    """Чтение манифеста БЕЗ деградации: бросает, значит результат не попадёт в кэш."""
    docs = load_manifest()["documents"]
    return {d["doc_type"]: d["legal_force"] for d in docs
            if d.get("doc_type") and isinstance(d.get("legal_force"), int)}


# Прежний интерфейс сохранён: тесты и диагностика зовут `legal_force_by_doc.cache_clear()`.
legal_force_by_doc.cache_clear = _legal_force_loaded.cache_clear  # type: ignore[attr-defined]


def legal_force_label(doc_type: str | None) -> str:
    """«юр. сила 3 — ведомственный акт ТПП РФ» либо пусто, если сила документа неизвестна.

    Пусто — законный ответ, а не сбой: у записи может не быть `doc_type` (тесты, старые точки),
    документа может не быть в манифесте. Пометка тогда просто не печатается — блок контекста
    выглядит как до `K13`.

    ⚠ Число печатается ВМЕСТЕ со словами. Одно число модель обязана была бы уметь ранжировать сама
    (и «1 главнее 3» неочевидно — интуиция подсказывает обратное); одни слова не дают порядка.
    """
    if not doc_type:
        return ""
    force = legal_force_by_doc().get(doc_type)
    if force is None:
        return ""
    name = LEGAL_FORCE_NAMES.get(force)
    return f"юр. сила {force} — {name}" if name else f"юр. сила {force}"
