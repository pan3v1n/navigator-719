# Список для выпадающего <select> в профиле (отсортирован; из него выбирает пользователь).
REGIONS: list[str] = sorted(set(REGION_BY_PREFIX.values()))


def region_from_username(username: str) -> str:
    """Регион по префиксу логина: «moscow.expert1» → «Москва». Бесточечный/неизвестный → ''."""
    uname = username or ""
    prefix = uname.split(".", 1)[0].lower() if "." in uname else ""
    return REGION_BY_PREFIX.get(prefix, "")


def known_prefix(prefix: str) -> bool:
    """Известен ли префикс региона (для валидации при сидинге аккаунтов)."""
    return (prefix or "").lower() in REGION_BY_PREFIX
