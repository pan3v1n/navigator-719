HELD = "held:"


@dataclass(frozen=True)
class Field:
    label: str          # подпись и плейсхолдер поля ввода
    kind: str           # product | tnved | point — примеры для тестов
    max_len: int = 200  # поле — не второй канал для произвольного вопроса


@dataclass(frozen=True)
class Command:
    key: str            # стабильный id, см. шапку модуля
    title: str
    desc: str
    ref: str            # плашка источника на карточке
    icon: str           # имя иконки из `commands_icon` в chat.html
    corpus: str         # режим `L1`: корпус, который задаёт команда
    template: str       # текст запроса; место значения — VALUE
    field: Field | None = None        # None — команде ничего не нужно, запуск без ввода
    expect_topic: str | None = None   # тема `K12`, которую обязан дать собранный запрос (тест)
    topic_by_value: bool = False      # тему задаёт значение поля: сноска и подпункт — разные темы
    # Поиск и гейт релевантности видят значение, а не весь шаблон: слова шаблона уводили выдачу, замер —
    # `docs/eval_runs/2026-11-02_l8_search_by_value.md`. У `st1` значение — только код, смысл в шаблоне.
    search_by_value: bool = False
    home: bool = False                # среди восьми карточек главной
    pinned: bool = False              # в сайдбаре по умолчанию (в макете пять)

    def render(self, value: str = "") -> str:
        """ЕДИНСТВЕННОЕ место сборки текста запроса. `replace`, а не `format`: фигурная скобка в
        значении поля не должна ни ронять сборку, ни читаться как место подстановки."""
        return self.template.replace(VALUE, clean_value(value))


