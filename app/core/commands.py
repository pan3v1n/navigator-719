    """Каталог для шаблона чата. Шаблон запроса идёт на страницу открыто: скрытого промпта нет, и
    фронт показывает в пузыре тот же текст, который уйдёт в модель."""
    return {
        "active": [{**asdict(c), "corpus_title": corpora.MODE_TITLES[c.corpus]} for c in COMMANDS],
        "soon": [asdict(s) for s in SOON],
    }
