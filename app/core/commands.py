_BY_KEY = {c.key: c for c in COMMANDS}


def find(key: str | None) -> Command | None:
    return _BY_KEY.get(key or "")


def held(key: str) -> str:
    """Ключ реплики-уточнения: см. `HELD`."""
    return key if key.startswith(HELD) else HELD + key


def title_of(key: str | None) -> str:
    """Название команды по ключу из реплики, в том числе уточнения. Ключа нет в каталоге (команду
    убрали) — сам ключ: подпись не вернётся к «выбран вручную», выбирал всё равно не человек."""
    if not key:
        return ""
    base = key[len(HELD):] if key.startswith(HELD) else key
    cmd = find(base)
    return cmd.title if cmd else base


def corpus_of(key: str | None) -> str | None:
    """Источник команды по ключу реплики. Ответ без корпуса («спасибо», отказ) его не теряет: колонка
    `corpus` у такого ответа пуста, а ключ записан, и по нему источник держится дальше."""
    if not key:
        return None
    cmd = find(key[len(HELD):] if key.startswith(HELD) else key)
    return cmd.corpus if cmd else None


def short_title(text: str) -> str:
    """Заголовок беседы в сайдбаре. Запуски одной команды начинаются одинаково, а значение стоит
    дальше 48 знаков заголовка: без этого все беседы команды неразличимы."""
    for cmd in COMMANDS:
        head, sep, tail = cmd.template.partition(VALUE)
        if not sep and text == cmd.template:
            return cmd.title
        if sep and text.startswith(head) and text.endswith(tail) and len(text) > len(head) + len(tail):
            return f"{cmd.title}: {text[len(head):len(text) - len(tail)]}"
    return text


def clean_value(value: str | None) -> str:
    """Значение поля — одной строкой: перевод строки в поле не должен менять форму запроса."""
    return " ".join((value or "").split())


def value_error(cmd: Command, value: str | None) -> str:
    """Текст отказа по значению поля; «» — значение годится. Проверка до движка и до записи вопроса."""
    value = clean_value(value)
    if cmd.field is None:
        return "Эта команда не требует уточнений: отправьте её без текста." if value else ""
    if not value:
        return f"Укажите: {cmd.field.label[0].lower()}{cmd.field.label[1:]}"
    if len(value) > cmd.field.max_len:
        return f"Слишком длинное значение: не больше {cmd.field.max_len} символов."
    return ""


