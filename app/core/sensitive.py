"""Проверка вопроса на данные, которые нельзя отправлять во внешнюю языковую модель.

ЗАЧЕМ. Текст вопроса уходит в DeepSeek (КНР) — без этого сервис не построит ответ. Политика
конфиденциальности просит не вводить персональные данные третьих лиц и сведения ограниченного
доступа, но просьба без проверки — правило на бумаге: помешать было нечему.

ПОЧЕМУ БЕЗ LLM. Отправлять текст на анализ во внешнюю модель, чтобы найти в нём персональные
данные, — значит сделать ровно то, от чего защищаемся. Поэтому только детерминированные правила,
локально и мгновенно.

ПОЧЕМУ КОНТРОЛЬНЫЕ СУММЫ. Одиннадцать цифр подряд встречаются в технических текстах сплошь и рядом.
СНИЛС, ИНН и номер карты несут проверочные разряды, и случайное число их почти никогда не проходит —
это и отделяет реальный документ от совпадения по длине.

ЧЕГО ЗДЕСЬ НЕТ. ФИО в свободном тексте не детектируется: отличить «главный технолог Иванов И.И.» от
фамилии в названии предприятия регулярным выражением нельзя без потока ложных срабатываний, а ложная
блокировка эксперту дороже, чем пропущенная фамилия.
"""

from __future__ import annotations

import re

# Названия для пользователя — их видно в сообщении об отказе, поэтому по-человечески.
KIND_NAMES = {
    "snils": "СНИЛС",
    "inn_person": "ИНН физического лица",
    "passport": "данные паспорта",
    "card": "номер банковской карты",
    "phone": "номер телефона",
    "email": "адрес электронной почты",
    "restricted": "пометка ограниченного доступа",
}

_DIGITS = re.compile(r"\d")

# Телефон. Просто «8 и десять цифр» брать нельзя: коды ТН ВЭД пишут группами и начинаются с восьмёрки
# («8544 49 910 0» — это 8 + десять цифр). Поэтому нужен явный признак телефона: знак «+», скобки
# вокруг кода города или слово рядом. Российский код города бывает и четырёхзначным (4712 — Курск),
# так что жёсткая разбивка 3-3-2-2 тоже не годится.
_PHONE_PATTERNS = (
    re.compile(r"\+7[\s\-()]*\d[\d\s\-()]{8,14}\d"),
    re.compile(r"\b8[\s\-]*\(\d{3,5}\)[\s\-]*\d[\d\s\-]{4,10}\d"),
    re.compile(r"(?:тел|телефон|моб|звон|whats|viber|вайбер)\w*[^0-9+]{0,12}\+?[78][\d\s\-()]{9,16}\d",
               re.IGNORECASE),
)
_EMAIL_RE = re.compile(r"\b[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}\b")
# Паспорт — только рядом со словом: «4611 123456» сам по себе может быть чем угодно.
_PASSPORT_RE = re.compile(r"паспорт\w*[^0-9]{0,20}\d{4}\s?\d{6}\b", re.IGNORECASE)
_SNILS_RE = re.compile(r"\b\d{3}[\s\-]?\d{3}[\s\-]?\d{3}[\s\-]?\d{2}\b")
_INN12_RE = re.compile(r"\b\d{12}\b")
_CARD_RE = re.compile(r"\b(?:\d[ \-]?){13,19}\b")
# Грифы и пометки ограниченного доступа — по словам, цифр здесь нет.
_RESTRICTED_RE = re.compile(
    r"совершенно\s+секретно|\bсекретно\b|для\s+служебного\s+пользования|\bдсп\b|"
    r"коммерческ\w+\s+тайн\w+|служебн\w+\s+тайн\w+|государственн\w+\s+тайн\w+",
    re.IGNORECASE,
)


def _digits(s: str) -> str:
    return "".join(_DIGITS.findall(s))


def _snils_ok(d: str) -> bool:
    """Контрольное число СНИЛС: сумма цифр с весами 9..1, остаток от 101."""
    if len(d) != 11 or len(set(d[:9])) == 1:  # 000-000-000 и подобные — не документ
        return False
    total = sum(int(d[i]) * (9 - i) for i in range(9))
    check = total % 101
    check = 0 if check in (100, 101) else check
    return check == int(d[9:])


def _inn12_ok(d: str) -> bool:
    """ИНН физлица/ИП — два контрольных разряда."""
    if len(d) != 12:
        return False
    w1 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    w2 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
    n11 = sum(int(d[i]) * w1[i] for i in range(10)) % 11 % 10
    n12 = sum(int(d[i]) * w2[i] for i in range(11)) % 11 % 10
    return n11 == int(d[10]) and n12 == int(d[11])


def _luhn_ok(d: str) -> bool:
    if not 13 <= len(d) <= 19:
        return False
    total, alt = 0, False
    for ch in reversed(d):
        n = int(ch)
        if alt:
            n *= 2
            if n > 9:
                n -= 9
        total += n
        alt = not alt
    return total % 10 == 0


def detect(text: str | None) -> list[str]:
    """Виды чувствительных данных, найденные в тексте (пустой список — можно отправлять)."""
    t = text or ""
    found: list[str] = []

    if _RESTRICTED_RE.search(t):
        found.append("restricted")
    if _PASSPORT_RE.search(t):
        found.append("passport")
    if any(_snils_ok(_digits(m.group(0))) for m in _SNILS_RE.finditer(t)):
        found.append("snils")
    if any(_inn12_ok(m.group(0)) for m in _INN12_RE.finditer(t)):
        found.append("inn_person")
    if any(_luhn_ok(_digits(m.group(0))) for m in _CARD_RE.finditer(t)):
        found.append("card")
    if any(p.search(t) for p in _PHONE_PATTERNS):
        found.append("phone")
    if _EMAIL_RE.search(t):
        found.append("email")
    return found


def message(kinds: list[str]) -> str:
    """Текст отказа для пользователя: что именно нашли и что с этим делать."""
    if not kinds:
        return ""
    names = [KIND_NAMES.get(k, k) for k in kinds]
    listed = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " и " + names[-1]
    if kinds == ["restricted"]:
        return ("Похоже, в вопросе есть сведения ограниченного доступа. Такие сведения нельзя "
                "передавать в сервис — уберите их из текста и отправьте вопрос снова.")
    return (f"Похоже, в вопросе есть {listed}. Сервис не передаёт персональные данные во внешнюю "
            f"языковую модель — уберите их из текста и отправьте вопрос снова. Для ответа по ПП №719 "
            f"достаточно наименования продукции и кода ОКПД2 или ТН ВЭД.")
