"""Вывод скриптов не должен падать на кодировке консоли Windows.

ЗАЧЕМ. По умолчанию stdout на Windows — **cp1251**, и кириллица в него укладывается, а вот
символы разметки вывода — нет: `⚠`, `✅`, `→`, `⏭`, `≥`. Любая такая строка роняет скрипт
`UnicodeEncodeError`'ом прямо в момент печати. Дефект тихий вдвойне:

* он живёт в РЕДКО исполняемых ветках («не распознано ни одного пункта», «позиции разошлись»),
  то есть срабатывает ровно тогда, когда скрипт пытался сообщить о проблеме;
* CI на ubuntu по умолчанию UTF-8 и не видит его никогда.

Найдено 24.08.2026 ревью: новая строка в `load_rules_kb.load_records` печатала `⏭` **всегда**,
и документированная команда переиндексации умирала до первой записи. Батарея при этом была
«зелёной» — потому что запускалась с `PYTHONUTF8=1`, то есть в среде, настроенной под себя,
а не в той, что описана в `CLAUDE.md`. Замер в собственной среде — не замер.

⚠ `errors="replace"` намеренно: пропажа значка в выводе несравнима с падением скрипта, который
этим значком хотел о чём-то предупредить.
"""

from __future__ import annotations

import sys


def enable_utf8() -> None:
    """Переводит stdout/stderr процесса на UTF-8. Идемпотентна, зовётся из скриптов на импорте."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:  # подменённый поток (io.StringIO в тестах) — ничего не делаем
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):  # поток уже закрыт или не поддерживает смену кодировки
            pass
