def lead_kind(tariff: str, kind: str) -> str | None:
    """Вид заявки — данными (ревью PR #186): «corporate» — корпоративная карточка или «Для организаций»,
    «tester» — тариф «Тестировщик»; иначе личная (None). Одно правило для лендинга и кабинета."""
    if tariff == TESTER_TARIFF:
        return "tester"
    if kind == "corporate" or tariff == ORG_TARIFF:
        return "corporate"
    return None


def price_line(tariff: str, *, kind: str = "individual", period: str = "month", seats: int = 1,
               trial: bool = False) -> str | None:
    """Стоимость выбранного на карточке — для подтверждения заявки и панели продления. Корпоративный —
    цена × пользователи (× 12 за год). None — тариф без цены на витрине."""
    if tariff == TESTER_TARIFF:
        return TESTER_PRICE
    if tariff == ORG_TARIFF:
        return ORG_PRICE
    base = PRICES.get(tariff)
    if base is None:
        return None
    if kind == "corporate":
        year = period == "year"
        return f"{rub(base * seats * (12 if year else 1))} ₽/{PERIODS['year' if year else 'month']}"
    if trial:
        return f"{TRIAL_TEXT}, далее {rub(base)} ₽/мес"
    return f"{rub(base)} ₽/мес"


def parse_options(tariff: str, *, kind: str = "individual", period: str = "month",
                  seats: int = 1, trial: bool = False) -> tuple[str | None, dict[str, str]]:
    """Опции заявки → (строка для заявки или None, ошибки). Проба за 1 ₽ — только «Старт» на
    индивидуальной вкладке; период и число пользователей — только у корпоративных. Заявки «Для
    организаций» и «Тестировщик» — без опций; вкладка «Тестирование» — только для «Тестировщика»."""
    e: dict[str, str] = {}
    if kind not in KINDS:
        e["kind"] = "Неизвестный вид тарифа"
    elif (kind == "tester" and tariff != TESTER_TARIFF) or (kind == "corporate" and tariff == TESTER_TARIFF):
        # «Тестировщик» без вида — заявка чипом в форме лендинга (вид там не шлётся): это «individual»
        e["kind"] = f"Вкладка «Тестирование» — только для тарифа «{TESTER_TARIFF}»"
    if period not in PERIODS:
        e["period"] = "Период — месяц или год"
    if not isinstance(seats, int) or isinstance(seats, bool) or not 1 <= seats <= MAX_SEATS:
        e["seats"] = f"Число пользователей — от 1 до {MAX_SEATS}"
    if trial and not (tariff == "Старт" and kind == "individual"):
        e["trial"] = "Пробная неделя за 1 ₽ — только у тарифа «Старт»"
    if e or tariff in (ORG_TARIFF, TESTER_TARIFF):
        return None, e
    parts = []
    if kind == "corporate":
        parts += [KINDS[kind], "год" if period == "year" else "месяц", f"{seats} польз."]
    if trial:
        parts.append(f"пробная неделя за {TRIAL_PRICE}")
    return (" · ".join(parts) or None), e
