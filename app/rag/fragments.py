"""Пометки НЕПОЛНОТЫ данных позиции: расколотая ячейка требований (R29) и потерянный порог (D9).

Общий принцип обеих: данные восстановить достоверно нельзя, поэтому дефект делается ВИДИМЫМ, а не
угадывается. Правдоподобно достроенный перечень прошёл бы faithfulness-гард (он проверяет
заземлённость числа, а не правильность привязки) и обманул бы эксперта — этого класса ошибок
проект избегает намеренно.

--- R29: расколотая общая ячейка ---

ПРОБЛЕМА. В приложении 719 группа видов продукции делит одну ячейку требований. Когда текст в ней
длинный, при конвертации RTF→текст его абзацы распределяются по ячейкам СОСЕДНИХ строк — и каждая
позиция получает ОБРЫВОК общего списка как будто это её собственные требования. Видно невооружённым
глазом: «Светодиоды зеленого диапазона» начинаются с «правообладателем которого является…» —
с середины фразы; «Хладон-218» получил 4 операции по 100 баллов, «Хладон-125 ХП» — 2, «Хладон 14» —
3, хотя в первоисточнике это ОДИН список процессов на всю группу.

ПОЧЕМУ НЕ ПЕРЕПИСАЛИ ДАННЫЕ. Восстановить границу группы по расплющенному тексту достоверно
нельзя — только угадать. Угаданный перечень операций и баллов выглядел бы правдоподобно и прошёл
бы faithfulness-гард (он проверяет заземлённость числа в контексте, а не правильность привязки),
то есть мы получили бы ровно то «правдоподобно, но неверно», против чего построен весь проект.
Поэтому дефект СДЕЛАН ВИДИМЫМ, а корректный перечень должен подтвердить эксперт по первоисточнику.

ПОБОЧНЫЙ ЭФФЕКТ РАСКОЛА, КОТОРЫЙ ВИДЕЛ ПОЛЬЗОВАТЕЛЬ (`EV6`, исправлено 17.08.2026). Раскол бьёт не
только по полноте данных, но и по РАНЖИРОВАНИЮ. Голова общей ячейки оседает на строке-КВАЛИФИКАТОРЕ
(«Светодиоды (в части светодиодов белого диапазона)», код 26.11.22.210, 4 операции), а сама
продукция названа отдельной строкой («Светодиоды белого диапазона», 26.11.22.216, 4 блока и 15
операций). На дословном запросе «светодиоды белого диапазона» квалификатор выигрывал top-1 —
и целевой позицией пайплайн назначал обрывок. Поэтому здесь есть `group_of`: он говорит, у КОГО
лежит остальное, и `pipeline._target_hit` предпочитает содержательного сиблинга той же группы.
⚠ Правило узкое намеренно: первая версия брала «запись группы с наибольшим числом операций» и на
запросе «светодиоды красного диапазона» уводила ответ с верной позиции на общую строку
«за исключением белого» — чинила один запрос и ломала соседний.

КАК РАБОТАЕТ. Список позиций генерируется из исходных чанков детерминированно
(`scripts/diag_orphan_requirements.py --fragments`) и лежит в
`knowledge_base/pp719/fragmented_requirements.json`. В контекст добавляется маркер
«СПИСОК ОПЕРАЦИЙ НЕПОЛНЫЙ» — тот же, что у мега-позиций, поэтому правило 2а промпта навигатора
срабатывает без изменений: модель обязана предупредить эксперта и не делать вывод «наберётся ли
порог». Переиндексация Qdrant НЕ нужна: сверка идёт по наименованию позиции в рантайме.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

_PATH = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719"
         / "fragmented_requirements.json")

# Пометка неполноты. Специально повторяет формулировку `format_context` для мега-позиций, чтобы
# сработало правило 2а промпта («СПИСОК ОПЕРАЦИЙ НЕПОЛНЫЙ» → предупредить, не суммировать баллы).
NOTICE = (
    "СПИСОК ОПЕРАЦИЙ НЕПОЛНЫЙ: в первоисточнике эта позиция входит в группу с ОБЩИМИ "
    "требованиями, и показанное — лишь часть общего перечня (остальное значится у соседних "
    "позиций той же группы). Полный перечень требований и баллов — в первоисточнике ПП №719 "
    "(этот раздел); состав группы подтверждает эксперт ТПП."
)


def _key(name: str | None) -> str:
    """Ключ сверки — первая строка наименования, нормализованная.

    Именно первая строка: в исходной таблице ячейка наименования бывает многострочной
    («Хладон-218 (октафторпропан)\\nХладон-23…»), а в записи базы остаётся только первый продукт."""
    first = (name or "").strip().split("\n")[0]
    return re.sub(r"\s+", " ", first).strip().lower()


def _keys(name: str | None) -> tuple[str, ...]:
    """ОБЕ формы ключа: по первой строке и по полному имени со схлопнутыми переносами.

    ⚠ Одной первой строки не хватает, и это не гипотеза: из 15 позиций списка одна
    («Светодиоды, включая светодиодные модули по технологии chip-on-board … \\n(за исключением
    светодиодов белого диапазона)») хранит квалификатор ВТОРОЙ СТРОКОЙ, тогда как в корпусе то же
    наименование лежит одной строкой. Ключи расходились молча: позиция теряла пометку неполноты
    `R29` — ровно то, ради чего список и заведён, — а `group_of` не находил её сиблингов, то есть
    `EV6` на этой группе не работал вовсе. Тот же класс, что «висячая ; в ключе наследования»
    (47 молчаливых отказов R6): ключ, собранный из имени, обязан допускать обе формы записи."""
    first = _key(name)
    whole = re.sub(r"\s+", " ", (name or "").strip()).lower()
    return tuple(dict.fromkeys(k for k in (first, whole) if k))


@lru_cache(maxsize=1)
def _fragmented() -> frozenset[str]:
    """Ключи позиций с расколотой ячейкой. Файла нет — пустое множество (пометка просто не ставится)."""
    if not _PATH.exists():
        return frozenset()
    try:
        groups = json.loads(_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):  # битый/недочитанный файл не должен ронять ответ
        return frozenset()
    return frozenset(
        k
        for g in groups for p in (g.get("positions") or [])
        for k in _keys(p.get("product_name"))
    )


def is_fragmented(product_name: str | None) -> bool:
    """True — требования позиции в базе заведомо неполны (обрывок общего списка группы)."""
    listed = _fragmented()
    return any(k in listed for k in _keys(product_name))


@lru_cache(maxsize=1)
def _group_index() -> dict[str, int]:
    """Ключ позиции → номер группы с расколотой ячейкой. Нужен, чтобы отличать СВОИХ сиблингов.

    Пометки `is_fragmented` мало: она говорит «требования неполны», но не говорит, у КОГО лежит
    остальное. А остальное лежит ровно у строк ТОЙ ЖЕ группы — это одна ячейка первоисточника,
    растёкшаяся по нескольким строкам кода."""
    if not _PATH.exists():
        return {}
    try:
        groups = json.loads(_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    out: dict[str, int] = {}
    for i, g in enumerate(groups):
        for p in (g.get("positions") or []):
            for k in _keys(p.get("product_name")):
                out.setdefault(k, i)
    return out


@lru_cache(maxsize=1)
def _role_index() -> dict[str, str]:
    """Ключ позиции → роль строки в расколотой ячейке (`qualifier` / `product`).

    ⚠ Роль — ФАКТ ДАННЫХ, проставленный при генерации списка и видимый эксперту в JSON. Рантайм её
    только читает. Раньше `pipeline` вычислял её регуляркой по наименованию, и под ту регулярку
    подходили 16 записей корпуса, из которых 13 — настоящая продукция; от подмены ответа их спасало
    лишь то, что они не входят в расколотые группы (`EV9`, issue #89)."""
    if not _PATH.exists():
        return {}
    try:
        groups = json.loads(_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}
    out: dict[str, str] = {}
    for g in groups:
        for p in (g.get("positions") or []):
            role = p.get("role")
            if not role:
                continue
            for k in _keys(p.get("product_name")):
                out.setdefault(k, role)
    return out


def is_scope_qualifier(product_name: str | None) -> bool:
    """True — строка задаёт ОБЛАСТЬ действия кода и продукцию не называет (опорой быть не может).

    Позиция вне списка расколотых ячеек квалификатором быть не может по построению: роли есть
    только у перечисленных позиций."""
    index = _role_index()
    return any(index.get(k) == "qualifier" for k in _keys(product_name))


@lru_cache(maxsize=256)
def group_codes(product_name: str | None) -> tuple[str, ...]:
    """Коды ОКПД2 СОДЕРЖАТЕЛЬНЫХ строк той же расколотой ячейки (без квалификаторов).

    ⚠ Зачем (ревью PR #94). Правило `EV6` меняет строку-квалификатор на содержательного сиблинга
    ТОЛЬКО если тот есть в окне. Когда пользователь называет код квалификатора (26.11.22.210),
    поиск по коду приносит записи ровно этого кода — сиблинг с требованиями (26.11.22.216) в окно
    не попадает вовсе, и менять не на что. Эти коды и нужны, чтобы добрать его отдельным запросом.

    ⚠ ТРИ ПРАВКИ ПОСЛЕ ПОВТОРНОГО РЕВЬЮ:
    1. Строки с ролью `qualifier` отсюда исключены. Прежде порядок был файловый, и на группе 2
       («светодиоды») первым шёл код `26.11.22.200` — САМ квалификатор, которого `_content_sibling`
       отвергает по построению. Бюджет добора уходил на него, зелёный и красный диапазоны не
       добирались вовсе, и правило не срабатывало на группе, ради которой писалось.
    2. Группа берётся ОДНА — своя (`_group_index`, первая по вхождению). Прежде объединялись коды
       ВСЕХ групп, где встретилось имя, а `26.11.22.200` и `26.11.22.210` входят в ДВЕ разные
       группы под разными наименованиями: добор мог принести строку чужой группы, и целевой
       становилась запись, прямо ИСКЛЮЧАЮЩАЯ спрошенную продукцию.
    3. `@lru_cache`, как у соседей модуля: это был единственный читатель файла без кэша — файл
       перечитывался и разбирался на КАЖДЫЙ запрос."""
    group = group_of(product_name)
    if group is None:
        return ()
    if not _PATH.exists():
        return ()
    try:
        groups = json.loads(_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return ()
    if group >= len(groups):
        return ()
    keys = set(_keys(product_name))
    out: list[str] = []
    for p in (groups[group].get("positions") or []):
        if keys & set(_keys(p.get("product_name"))):
            continue
        if p.get("role") == "qualifier":
            continue
        for c in (p.get("okpd2_codes") or []):
            if c not in out:
                out.append(c)
    return tuple(out)


def group_of(product_name: str | None) -> int | None:
    """Номер группы с расколотой ячейкой, если позиция в неё входит."""
    index = _group_index()
    for k in _keys(product_name):
        if k in index:
            return index[k]
    return None


# --- D9: у позиции несколько порогов, а в записи поместился один ---
#
# В схеме записи одно поле `min_threshold`, а приложение задаёт для части позиций НЕСКОЛЬКО
# порогов: по узлам изделия («криогенный насос низкого давления — не менее 100 баллов»,
# «термоизолированный резервуар — не менее 60») и по видам работ (у блока «Изготовление смычков»
# своя шкала по годам, отдельно от шкалы инструментов). Всё, что не поместилось, теряется молча:
# пользователь видит один порог и считает его порогом всей позиции, а недобор по конкретному узлу
# остаётся незамеченным — сумма по изделию при этом сходится.
#
# ✅ ИСПРАВЛЕНО 14.08.2026 (`D9`). Порог получил место в схеме блока
# (`requirement_blocks[].min_threshold`); `scripts/backfill_block_thresholds.py` вернул пороги
# узлов и вторых шкал ИЗ ПЕРВОИСТОЧНИКА — детерминированно, без перепарса моделью (перегенерация
# раздела — обмен, а не улучшение, урок `D6`), а рантайм печатает их вплотную к узлу. Список
# позиций с потерянными порогами стал ПУСТЫМ: пометка сейчас не ставится никому.
#
# Механизм оставлен СЕТКОЙ, а не удалён: новая редакция приложения может снова принести позицию
# с несколькими порогами, и тогда дефект обязан стать видимым, а не молчаливым. Список
# генерируется сверкой по записи (пустой файл — нормальное состояние):
#     python scripts/verify_structured.py --json knowledge_base/pp719/incomplete_thresholds.json
_GAPS_PATH = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719"
              / "incomplete_thresholds.json")

THRESHOLD_NOTICE = (
    "ПОРОГИ ПОКАЗАНЫ НЕ ПОЛНОСТЬЮ: в первоисточнике у этой позиции несколько порогов — отдельно "
    "по узлам изделия и (или) по видам работ, — а в базе сохранён один. НЕ выдавай показанный "
    "порог за единственный и НЕ делай вывод «порог набирается»: сверь пороги по узлам с "
    "первоисточником ПП №719 и предупреди об этом эксперта."
)


@lru_cache(maxsize=1)
def _threshold_gaps() -> frozenset[tuple[str, str]]:
    """Ключи (раздел, наименование) позиций с неполными порогами.

    Раздел в ключе обязателен: одноимённые позиции встречаются в разных разделах, и пометка не
    должна уезжать к чужой. Файла нет — пустое множество (пометка просто не ставится)."""
    if not _GAPS_PATH.exists():
        return frozenset()
    try:
        data = json.loads(_GAPS_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):  # битый файл не должен ронять ответ
        return frozenset()
    return frozenset(
        ((p.get("section") or "?").strip().upper(), _key(p.get("product_name")))
        for p in (data.get("positions") or []) if _key(p.get("product_name"))
    )


def has_incomplete_thresholds(section_roman: str | None, product_name: str | None) -> bool:
    """True — у позиции в первоисточнике несколько порогов, а в базе сохранён один (D9)."""
    k = _key(product_name)
    return bool(k) and ((section_roman or "?").strip().upper(), k) in _threshold_gaps()
