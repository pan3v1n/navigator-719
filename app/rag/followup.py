"""Подсказка в поле ввода: что осмысленно спросить СЛЕДУЮЩИМ ходом (U5, issue #74).

Плейсхолдер был зашит в шаблон статикой и висел одинаково в пустом чате и на десятой реплике
диалога. В пустом чате это полезная инструкция («с чего начать»), внутри начатого разговора — шум:
подсказка зовёт назвать НОВУЮ продукцию там, где человек уточняет уже найденную позицию, то есть
подталкивает начать заново вместо уточнения.

⚠ ГЛАВНОЕ ПРАВИЛО МОДУЛЯ. Подсказка, ведущая к вопросу, на который движок ответить не может, ХУЖЕ
пустого поля: она обещает от имени системы. Поэтому здесь не «удачные формулировки», а короткий
закрытый список, и у каждого пункта проверяется маршрут (`tests/test_followup.py`):

* обе подсказки несут 719-ЯКОРЬ («реестр», «заявление») — без него процедурный детектор считает
  вопрос товарным, и вместо перечня документов человек получает ближайшую товарную позицию. Это не
  теория: ровно так ведёт себя живой дефект `K12` — «какие документы нужны для этикетировщиков»
  роутер относит к товарным (`app/rag/procedural.py`, GENERIC-маркер требует якоря);
* темы выбраны не по догадке о спросе: состав документов — кластер жалоб №1 июльского теста
  (31 упоминание), сроки рассмотрения — из того же кластера. Обе ветки закрыты и замерены
  (`P2`: атрибуция@1 0.96, «нужный пункт» 5/5).

Где подсказки НЕ даём (пустое поле честнее): позиция не найдена, сработал out-of-scope guard,
процедурный корпус недоступен. Там ответ и сам просит уточнить продукцию или сообщает о сбое —
подсказка следующего шага в этот момент обещала бы то, чего система сейчас не может.

Текст отдаётся СЕРВЕРОМ готовым к показу, включая стартовую подсказку: своей копии у фронта нет
ни одной. Копия константы в двух слоях уже стоила проекту ссылки на недействующую редакцию
(см. `app/rag/edition.py`) — здесь тот же класс ошибки закрыт заранее.
"""

from __future__ import annotations

# Стартовая подсказка пустого чата — ЕДИНСТВЕННАЯ копия в проекте. Шаблон получает её через
# `app/api/web.py` (`input_hint`), фронт читает из отрендеренного атрибута, а не хранит свою.
START_HINT = "Спросите про 719 — продукцию, код ОКПД2 или ТН ВЭД…"

# Ничего не обещаем: поле остаётся пустым.
NO_HINT = ""

# Вопросы следующего шага. Формулировки НЕ произвольные — см. правило про 719-якорь выше.
DOCS_QUESTION = "какие документы нужны для внесения в реестр"
DEADLINE_QUESTION = "сроки рассмотрения заявления"


def _example(question: str) -> str:
    """Показываем ПРИМЕРОМ, а не командой: поле ввода принадлежит человеку, а не сервису."""
    return f"Например: {question}"


def ask_for_product() -> str:
    """Продукция ещё не названа или не опознана — зовём её назвать (та же стартовая подсказка).

    Сюда попадают приветствие и «что умеешь», перевод кода ТН ВЭД↔ОКПД2, «позиция не найдена» и
    сработавший out-of-scope guard. Формально диалог начат, но по сути нет: позиции нет, уточнять
    нечего, и «назовите продукцию или код» здесь не шум, а ровно следующий шаг. Это единственный
    случай, когда стартовая подсказка уместна в непустом чате."""
    return START_HINT


def after_product(low_relevance: bool) -> str:
    """Товарный ответ: позиция найдена → следующий шаг «документы»; не уверены в позиции → старт.

    При `low_relevance` ответ сам просит назвать код или уточнить наименование (правило 1г
    промпта) — подсказка обязана вести туда же, а не к документам по неподтверждённой позиции."""
    return ask_for_product() if low_relevance else _example(DOCS_QUESTION)


def after_procedural(topic: str | None) -> str:
    """Процедурный ответ: тема уже определена роутером (`retriever.rules_topic`).

    Спросили про состав документов (Приказ №52) → следующий вопрос про сроки; во всех остальных
    темах (сроки, критерии постановления, сноски) → про документы: это самый частый следующий шаг
    по июльской выгрузке."""
    return _example(DEADLINE_QUESTION if topic == "tpp_order_52" else DOCS_QUESTION)


