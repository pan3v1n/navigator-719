"""Пороги баллов из примечаний к приложению ПП №719 (таблицы «код | наименование | по годам»).

Порог (min_threshold) для многих позиций живёт НЕ в самой позиции, а в нумерованных примечаниях к
разделам: напр. прим. 77 к разд. XVI — «Чиллеры | 270 | 320 | 480 | 542 балла» по годам. В структуру
продукта эти пороги не попали (примечания не структурируются, см. память об актуализации), поэтому
`format_context` показывал «порог не указан». Здесь мы парсим эти таблицы из чанка примечаний
(закоммичен в git → есть и на VM) и отдаём порог для позиции — БЕЗ переиндексации pp719.

Числа берутся ДОСЛОВНО из первоисточника, поэтому при вставке в контекст ответа они заземлены
(faithfulness-гард `unverified_numbers` их пропускает). Матчим порог по НАИМЕНОВАНИЮ позиции (у одного
кода бывает несколько строк: общая категория и конкретный продукт «Чиллеры»), в рамках раздела.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

_CHUNK = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719" / "chunks"
          / "130_PRIMECHANIYA_prilozheniya.txt")

# Интро примечания-таблицы: «77. Продукция … в раздел XVI настоящего приложения …»
# ⚠ ВВОДНАЯ ПРИМЕЧАНИЯ-ТАБЛИЦЫ (K2, #47). Прежний шаблон требовал буквально «Продукция,» и
# обязательно называл раздел — под него подходили 10 таблиц из 30+. Мимо проходили ходовые
# формулировки: «Отнесение продукции радиоэлектроники …» (прим. 38), «Продукция медицинской
# промышленности может быть отнесена …» (прим. 81, 28, 33) — а это 53 позиции одного только
# раздела VII. Теперь вводная — это просто заголовок примечания, а РАЗДЕЛ необязателен:
# у таких таблиц есть коды, и привязка идёт по коду (см. `_lookup`).
# ⚠ ПОДПУНКТ — ТОЖЕ ГРАНИЦА ТАБЛИЦЫ (A1 #56, 21.08.2026). Прежний шаблон не видел «17.1.»,
# «26.1.», «72.1…72.3», то есть таблица могла проехать сквозь начало следующего пункта и
# набрать его строки — тот же дефект границы, что уже дал прим. 72 текст про оптические
# волокна в строке «Порог». Пять подпунктов в чанке, поэтому проверено замером, а не на глаз.
_NOTE_INTRO_RE = re.compile(r"^\s*(\d+(?:\(\d+\))?(?:\.\d+)*)\.\s+\S")
_INTRO_SECTION_RE = re.compile(r"в\s+раздел[еа]?\s+([IVXLC]+)\s+настоящего")
_COEFF_INTRO_RE = re.compile("коэффициент", re.IGNORECASE)


def _is_coefficient_note(intro_line: str) -> bool:
    """Вводная примечания объявляет коэффициенты, а не пороги баллов (прим. 79, 80)."""
    return bool(_COEFF_INTRO_RE.search(intro_line or ""))
# Заголовок таблицы: «с 1 января 2024 г.» ЛИБО «2024 год» / «2028 год и далее» / «с 2027 года».
_YEAR_RE = re.compile(r"с 1 января (\d{4})")
_YEAR_ANY_RE = re.compile(r"(?:с 1 января\s+|с\s+)?(\d{4})\s*(?:г\.|год)")
_CODE_RE = re.compile(r"\d{2}\.\d{2}(?:\.\d+)*")
# Начало НОВОЙ строки таблицы: «28.30.59.114|…» или «из 26.51.66.190|…».
_ROW_START_RE = re.compile(r"(?:из\s+)?\d{2}\.\d{2}(?:\.\d+)*\s*\|")


@lru_cache(maxsize=1)
def _tables() -> list[dict]:
    """Парсит все таблицы-пороги из чанка примечаний. Кэш на процесс."""
    if not _CHUNK.exists():
        return []
    lines = _CHUNK.read_text(encoding="utf-8").splitlines()
    tables: list[dict] = []
    i, n = 0, len(lines)
    while i < n:
        m = _NOTE_INTRO_RE.match(lines[i])
        if not m:
            i += 1
            continue
        note_no = m.group(1)
        # Раздел — если примечание его называет. ⚠ Часть таблиц раздела не называет вовсе
        # (прим. 38, 81, 28, 33): у них привязка идёт по КОДУ, и это надёжнее имени.
        sm = _INTRO_SECTION_RE.search(lines[i])
        section = sm.group(1) if sm else None
        # ⚠ ТАБЛИЦА КОЭФФИЦИЕНТОВ — НЕ ТАБЛИЦА ПОРОГОВ, и признак берётся из ВВОДНОЙ (ревью
        # 20.08.2026). Прежний страж стоял на ШАПКЕ и не исполнялся ни разу: прим. 80 не
        # разбирается по другой причине — в его шапке нет двух дат, поэтому до шапки дело не
        # доходит. Оба теста к тому стражу проходили и при его удалении. Хуже: он промахивался
        # мимо будущего, которое сам предсказывал, — перепиши следующая редакция шапку в ходовую
        # форму («с 1 января 2026 г.|с 1 января 2028 г.»), слово «Коэффициент» УШЛО БЫ из шапки,
        # таблица начала бы разбираться, и коэффициент СЭЗ снова поехал бы строкой «Порог: … 0,5».
        # Вводная же говорит это прямо и переживает переписывание колонок:
        # «…применяется… с учетом следующих коэффициентов:» (прим. 79 и 80).
        if _is_coefficient_note(lines[i]):
            i += 1
            continue
        # Заголовок таблицы: строка с разделителями «|» и минимум двумя годами.
        j, header = i + 1, None
        while j < n:
            if _NOTE_INTRO_RE.match(lines[j]):
                break
            cand = lines[j]
            # ⚠ Шапка бывает разорвана переносом («Код по ОК 034-2014» / «(КПЕС 2008)|Наименование…»,
            # прим. 81): склеиваем с предыдущей строкой, иначе таблица не находится вовсе.
            if "|" in cand and j > i + 1 and "|" not in lines[j - 1] and lines[j - 1].strip():
                cand = lines[j - 1].strip() + " " + cand
            if "|" in cand and len(_YEAR_ANY_RE.findall(cand)) >= 2:
                header = cand
                break
            j += 1
        if header is None:
            i += 1
            continue
        # ⚠ Подписи колонок берём ДОСЛОВНО из шапки («2028 год и далее», «с 1 января 2024 г.»):
        # синтез «с 1 января {год}» переписывал бы первоисточник — «2028 год» и «с 1 января
        # 2028 г.» это разные утверждения, а порог показывается эксперту как цитата.
        hcells = [c.strip() for c in header.split('|')[2:] if c.strip()]
        # ⚠ СИНТЕЗ ПОДПИСЕЙ УБРАН (ревью 20.08.2026). Здесь стоял фолбэк
        # `_YEAR_ANY_RE.findall(header)`, прямо противоречивший инварианту двумя строками выше:
        # регулярка имеет группу, поэтому `findall` возвращает ГОЛЫЙ год, и колонка «2022 - 2023
        # годы» подписывалась как «2023» — диапазон схлопывался в свою последнюю дату, а «с 1
        # января» терялось. Фолбэк не был спящим: он срабатывал на 3 таблицах из 30 (прим. 11, 37,
        # 74), и молчали они лишь потому, что в их первой колонке нет кода ОКПД2. Подписи берём
        # ДОСЛОВНО или не берём вовсе — цитата эксперту важнее полноты разбора.
        years = hcells
        rows: list[dict] = []
        pending = ""  # строка-продолжение многострочной ячейки кода («из 28.25.12»)
        k = j + 1
        while k < n:
            raw = lines[k]
            if not raw.strip() or _NOTE_INTRO_RE.match(raw):
                break
            cells = raw.split("|")
            if len([c for c in cells if c.strip()]) < 3:  # ячейка кода на отдельной строке
                pending = (pending + " " + raw.strip()).strip()
                k += 1
                continue
            code_cell = (pending + " " + cells[0]).strip()
            pending = ""
            name = cells[1].strip()
            # ⚠ ПУСТЫЕ ЯЧЕЙКИ НЕЛЬЗЯ ВЫБРАСЫВАТЬ (ревью 20.08.2026): подписи колонок берутся
            # ПОЗИЦИОННО, а `if c.strip()` схлопывал пропуски и сдвигал все значения строки
            # ВЛЕВО — на чужой год. Замер: «из 26.51.66.190|Меры твердости Роквелла…| |
            # не менее 95 процентов| |» (первая ячейка — неразрывный пробел, для `strip()`
            # это пустота) давал «2023 год — не менее 95 процентов», тогда как первоисточник
            # относит это значение к 2024-му. Правильное число из первоисточника, привязанное
            # не к тому году, — тот же класс, ради которого писался весь заход.
            thr = [c.strip() for c in cells[2:]]
            # ⚠ ЯЧЕЙКА ЗНАЧЕНИЯ ТОЖЕ ПЕРЕНОСИТСЯ, НЕ ТОЛЬКО ЯЧЕЙКА КОДА (ревью 20.08.2026).
            # У прим. 39 логическая строка разорвана на четыре физических, и разрывы падают
            # ВНУТРИ значений: «…|Подборщики для зерновых…|от» / «40 процентов|от» / …
            # Разбор считал первую строку законченной и печатал «Порог: … — от [прим. 39]» —
            # подлинную ссылку на примечание БЕЗ величины, а настоящие 40/55/70 % не доезжали
            # никогда. Признак недочитанности берём у самой таблицы: значений меньше, чем
            # подписей колонок. Хвостовая «|» для этого не годится — 51 строка чанка её не
            # имеет, и часть из них полные.
            # Дочитываем, пока значений меньше подписей ИЛИ последнее значение — обрывок
            # без цифры («от»): у прим. 39 разрыв падает после предлога, и одной проверки
            # на количество не хватает — третья колонка осталась бы как «от».
            while k + 1 < n and (len([t for t in thr if t]) < len(years)
                                 or (thr[-1] and not any(c.isdigit() for c in thr[-1]))):
                nxt = lines[k + 1]
                if (not nxt.strip() or _NOTE_INTRO_RE.match(nxt)
                        or _ROW_START_RE.match(nxt.strip())):
                    break
                ncells = nxt.split("|")
                thr[-1] = (thr[-1] + " " + ncells[0].strip()).strip()
                thr.extend(c.strip() for c in ncells[1:])
                k += 1
            codes = _CODE_RE.findall(code_cell)
            by_year = {years[x]: thr[x] for x in range(min(len(years), len(thr))) if thr[x]}
            if codes and name and by_year:
                rows.append({"codes": codes, "name": name, "by_year": by_year})
            k += 1
        if rows:
            tables.append({"note": note_no, "section": section, "years": years, "rows": rows})
        i = k
    return tables


def _strip_fn(s: str | None) -> str:
    """Снимает хвостовой маркер сноски: «Ледоколы <9>» → «Ледоколы»."""
    return re.sub(r"\s*<[\d.,\s]+>\s*$", "", s or "").strip()


def _norm(s: str | None) -> str:
    return re.sub(r"\s+", " ", (s or "").strip().lower())


def _fmt(row: dict, note: str, section: str | None) -> str:
    # Подпись колонки печатается как в первоисточнике; «с 1 января YYYY» уже содержит предлог,
    # «2028 год и далее» — нет, поэтому соединяем нейтральным тире, а не дописываем «с 1 января».
    steps = "; ".join(f"{lbl} — {val}" for lbl, val in row["by_year"].items())
    src = f"прим. {note} к разд. {section}" if section else f"прим. {note}"
    return f"{steps} [{src}]"


# --- Простые пороги-списки из примечаний (прим. 7/11/31/52/53…) --------------------------
# Формат строки: «[из ]КОД "Наименование"[, [из ]КОД "…"…] - не менее N баллов[…]; (в ред. …)».
# Отличается от таблиц-по-годам (те через «|»); порог привязан к КОДУ (у строки бывает несколько
# кодов, у кода — несколько строк с разными порогами → дизамбигуация по наименованию). Описательные
# примечания (прим. 8(1): «…не менее N баллов для лопастей…», без кода) сюда НЕ попадают — покрыты
# verified_cases / отдельной доработкой.
_NOTE_HDR_RE = re.compile(r"^(\d+(?:\(\d+\))?)\.\s")            # «7.», «8(1).», «52.»
# ⚠ ГРАНИЦА ПРИМЕЧАНИЯ ШИРЕ ЕГО ЗАГОЛОВКА: есть ПОДПУНКТЫ «72.1.», «72.2.» (A1 #56, 21.08.2026).
# `_NOTE_HDR_RE` требует пробел сразу после точки и на «72.1.» не срабатывает — сборщик ступеней
# проезжал сквозь подпункт и тащил его текст в «Порог». Замер: у прим. 72 в строку порога уехали
# 72.1 и 72.2 про оптические волокна («…с 1 августа 2026 г. - не менее 100 баллов… Волокна
# оптические многомодовые…»), то есть ЧУЖИЕ числа с подлинной ссылкой — ровно тот дефект, что
# `EV13` вычищала у прим. 17. Останавливаться надо на ЛЮБОМ новом номере, включая подпункт.
_NOTE_START_RE = re.compile(r"^\s*(\d+(?:\(\d+\))?(?:\.\d+)*)\.\s")
# Нулевой ширины пробелы приезжают из конвертации RTF и рвут сравнения строк.
_ZERO_WIDTH_RE = re.compile(r"[​‌‍﻿]")
# ⚠ СТУПЕНЬ ПОРОГА — «не менее N баллов/процентов», И ТОЛЬКО ОНА (ревью 20.08.2026).
# Многострочный сборщик брал ЛЮБУЮ строку со словами «не менее», и у прим. 17 в ступени уезжал
# абзац прозы на 1402 символа: в нём есть «не менее 5 ЛЕТ» — срок хранения конструкторской
# документации, а не порог. Итог: «Танкеры морские» показывали в «Порог:» 1469 символов текста
# требований, начинавшихся с «до 1 июля 2022 г. операции (условия) не оцениваются», а настоящая
# ступень («с 1 июля 2022 г. не менее 2200 баллов…») стояла СТРОКОЙ НИЖЕ и терялась.
# Признак взят замером по всему чанку: после «не менее N» стоит «баллов» 1244 раза,
# «процентов» — 97, «лет» — 2, «м» — 2. То есть единица и отделяет порог от прозы.
_STEP_RE = re.compile(r"не менее\s+[\d\s.,]+\s*(?:балл|процент|%)", re.IGNORECASE)
# Строка-порог начинается с кода (кодов) и кавычки. Два реальных усложнения корпуса, из-за которых
# раньше терялись десятки порогов (R7):
#   * СНОСКА между кодом и наименованием: «19.20.31 <11> "Пропан и бутан сжиженные" - не менее 300…»
#   * НЕСКОЛЬКО КОДОВ через запятую: «из 20.13.43.110, из 20.13.43.111, из 20.13.43.119 "Сода…"»
# Прежняя регулярка требовала кавычку сразу за первым кодом и не брала ни то, ни другое.
_CODE_TOKEN = r"(?:из\s+)?\d{2}(?:\.\d+)*(?:\s*<[^>\n]{1,16}>)?"
# ⚠ Строка-порог начинается со списка кодов, за которым идёт ЛИБО наименование в кавычках,
# ЛИБО сразу двоеточие: «30.11.31.110, 30.11.31.111, …: до 30 июня 2023 г. не менее 2500 баллов»
# (прим. 17). Требование кавычки теряло такие строки целиком (K2, #47).
_FLAT_ROW_RE = re.compile(rf'^\s*{_CODE_TOKEN}(?:\s*,\s*{_CODE_TOKEN})*\s*[":]', re.IGNORECASE)
# ⚠ ДВА ГРАФИКА В ОДНОЙ СТРОКЕ (найдено ревью 20.08.2026, дефект внесён самой K2).
# Приняв строку с «голым» двоеточием, разбор впустил прим. 17, где ОДНО предложение несёт ДВА
# графика: общий и оговорку «за исключением судов, инвестиционные проекты по строительству
# которых реализуются в рамках договоров о закреплении доли квоты добычи … и которые
# оцениваются <свой график>». Склеенные в одну строку «Порог:», они дают одну и ту же дату с
# РАЗНЫМИ числами: «с 1 июля 2025 г. не менее 3400» и, тремястами символов ниже, «с 1 июля
# 2025 г. не менее 2900». Замер: 13 позиций (Траулеры, Ярусники, Сейнеры, Суда-рыбозаводы,
# рефрижераторные — 3200 против 3750).
#
# Это ровно тот класс, ради которого писалась K2: оба числа дословны, гард молчит, а условие
# теряется в середине 708-символьного блока. Решение — то же, что для закупочного порога:
# график не выбрасываем, а перестаём выдавать за общий, вынося вместе с его условием.
#
# Делим ТОЛЬКО когда в оговорке есть свой порог: «за исключением X» без «не менее» — это
# обычное сужение охвата, оно относится к общему графику и резать его нельзя.
_EXCEPTION_RE = re.compile("за исключением", re.IGNORECASE)
# ⚠ Глагол оценки, вводящий СОБСТВЕННЫЙ график оговорки. Отрицание «не оцениваются» — не он:
# в прим. 17 этой фразой открывается абзац о том, что операции до 2022 г. не оцениваются вовсе.
_EXC_VERB_RE = re.compile("(?<!не )оценива", re.IGNORECASE)


def _split_exception(text: str) -> tuple[str, str | None]:
    """«общий график, за исключением … которые оцениваются <свой график>» → (общий, оговорка).

    Иначе — (текст, None): признака не хватило, и мы ничего не переписываем.

    ⚠ ТРИ ФОРМЫ ОТКАЗА, НАЙДЕННЫЕ РЕВЬЮ 20.08.2026 в первой редакции этой функции — все дают
    ЗЕРКАЛО того дефекта, ради которого она написана (действующая ступень уезжает в оговорку,
    а в «Порог» остаётся просроченная):

    1. Резали по ПЕРВОМУ «за исключением», а признак искали по всему хвосту. В строке
       «…не менее 250 баллов, за исключением судов рыбопромыслового флота, с 1 июля 2025 г.
       не менее 300 баллов, которые оцениваются по акту экспертизы» глагол стоит ПОСЛЕ графика,
       и это обычное сужение охвата. Теперь глагол обязан стоять ДО первой ступени хвоста —
       именно так устроена настоящая оговорка прим. 17 («…и которые оцениваются до 30 июня
       2025 г. не менее 2300 баллов»).
    2. Признак «оценива» матчил и ОТРИЦАНИЕ «не оцениваются».
    3. Проверка «не менее» была регистрозависимой, тогда как обе соседние регулярки —
       IGNORECASE. Теперь ступень ищется общим `_STEP_RE` (он же требует единицу измерения).
    """
    for m in _EXCEPTION_RE.finditer(text):
        general = text[:m.start()].rstrip(" ,;")
        tail = text[m.start():]
        if not general or not _STEP_RE.search(general):
            continue                     # общий график пуст или без ступени — резать нечего
        step = _STEP_RE.search(tail)
        if not step:
            continue                     # у оговорки нет своего порога — это сужение охвата
        verb = _EXC_VERB_RE.search(tail[:step.start()])
        if not verb:
            continue                     # глагол оценки не предшествует ступени
        return general, tail.strip().rstrip(";. ")
    return text, None


_FOOTNOTE_RE = re.compile(r"<[^>\n]{1,16}>")
_CODE_ONLY_RE = re.compile(r"\d{2}(?:\.\d+)*")
_NAME_Q_RE = re.compile(r'"([^"]+)"')
_QUOTED_RE = re.compile(r'"[^"]*"')


# ⚠ ГРАНИЦЫ ЗАКРЫВАЮЩЕЙ КАВЫЧКИ ВЗЯТЫ ЗАМЕРОМ ПО ПЕРВОИСТОЧНИКУ (ревью 20.08.2026).
# Прежний набор — «,», «:», « -», конец строки — покрывал не всё, и имя, за которым идёт « и »
# или « (», не закрывалось: разбор уходил до следующей кавычки и съедал остаток строки.
# Замер: «Танкеры морские …» получали в «Порог:» абзац требований на 1469 символов
# («…операции (условия) не оцениваются. При этом… наличие прав на техническую документацию…»),
# а 30.11.22.113 «газовозы», названные в прим. 17 прямо, теряли порог совсем.
#
# Что реально стоит после закрывающей кавычки в чанке примечаний (частоты):
#   « - » 187 · «,» ~108 · «:» ~54 · «;» 8 · « (» 17 · « и » 2 · « для» 3 · «)» 5
# Внутреннюю кавычку («Суда наливные смешанного плавания "река - море"») от закрывающей отличает
# то, что за ней ВСЕГДА идёт буква или вторая кавычка, — ни один из этих признаков в набор не
# входит, поэтому семь судов, ради которых вводился `_name_spans`, остаются защищены.
_NBSP = " "
_CONNECTIVES = ("и ", "для ")


def _closes_name(line: str, j: int) -> bool:
    """Кавычка на позиции `j` закрывает наименование, а не стоит внутри него."""
    rest = line[j + 1:].lstrip(" " + _NBSP)
    if not rest:                       # конец строки
        return True
    if rest[0] in ',:;()':
        return True
    if rest.startswith("-"):           # « - » между именем и порогом
        return True
    return any(rest.startswith(c) for c in _CONNECTIVES)


def _name_spans(line: str) -> list[tuple[int, int]]:
    """Границы закавыченных НАИМЕНОВАНИЙ. Общая основа для затирания кодов и для сбора имён.

    ⚠ Парная регулярка `"[^"]*"` не годится: в приложении встречаются ВЛОЖЕННЫЕ кавычки —
    «Суда наливные смешанного плавания "река - море"». Одна такая пара сбивает разбивку для всего
    ОСТАТКА строки: в длинной строке прим. 17 из 22 кодов собиралось 6, а имена после вложенности
    превращались в мусор («, 30.11.32.110»). Семь судов («Буровые суда», «Суда снабжения»,
    «Суда обслуживающего флота» …) оставались без порога, хотя он написан для них тем же
    предложением; до правки они брали порог СОСЕДНЕЙ строки — 1950 вместо 2450 (K2, #47).

    Правило: имя заканчивается на кавычке, за которой идёт «,», «:», « -» или конец строки.
    Внутренние кавычки этому не удовлетворяют и остаются частью имени."""
    spans: list[tuple[int, int]] = []
    i, n = 0, len(line)
    while i < n:
        if line[i] != '"':
            i += 1
            continue
        j = i + 1
        while j < n:
            if line[j] == '"' and _closes_name(line, j):
                break
            j += 1
        spans.append((i, min(j, n - 1)))
        i = j + 1
    return spans


def _blank_names(line: str) -> str:
    """Затирает пробелами закавыченные наименования, оставляя коды и служебные символы."""
    out = list(line)
    for a, b in _name_spans(line):
        for x in range(a, b + 1):
            out[x] = " "
    return "".join(out)


# ⚠⚠ ЗАГОЛОВОК НОРМАТИВНОГО АКТА В КАВЫЧКАХ — НЕ НАИМЕНОВАНИЕ ПРОДУКЦИИ (ревью захода 3,
# 26.08.2026). Прим. 8(1) цитирует «Об утверждении Правил квалификации генерирующего объекта…»,
# и эта цитата становилась «именем» строки-порога. Сегодня безвредно (у той строки нет кодов),
# но пост-проход `if r.get("intro") and r["names"]: r["codes"] = []` снимает коды ИМЕННО по
# признаку «вводная назвала продукт». Вводная, которая цитирует акт И перечисляет коды ОКПД2,
