# Формы взяты стандартные для российских НПА; продукция в этом корпусе так не называется.
_ACT_TITLE_RE = re.compile(r"^\s*(?:Об?\s+утверждении|О\s+внесении|О\s+порядке|О\s+мерах)\b", re.I)


def _quoted_names(line: str) -> list[str]:
    """Наименования ПРОДУКЦИИ из кавычек — тем же сканером, что и затирание (иначе списки
    разъезжаются). Заголовки нормативных актов отсеиваются: см. `_ACT_TITLE_RE`."""
    return [n for a, b in _name_spans(line) if b > a + 1
            if (n := line[a + 1:b].strip()) and not _ACT_TITLE_RE.match(n)]


def _codes_before_quote(line: str) -> list[str]:
    """ВСЕ коды строки-порога примечания.

    ⚠ Имя обманчиво историческое: раньше брались коды строго ДО первой кавычки, чтобы в «коды» не
    попали числа из наименования («чистотой менее 95 процентов»). Но строки примечаний часто несут
    НЕСКОЛЬКО пар «код + имя» подряд:

        30.11.22.110 "Суда наливные морские", 30.11.22.112 "Суда морские для перевозки химических
        продуктов", 30.11.22.119 "…": до 30 июня 2023 г. - не менее 1750 баллов, …

    и до 19.08.2026 привязывался только ПЕРВЫЙ код — остальные позиции оставались без порога,
    хотя он написан для них тем же предложением (K2, #47; в прим. 17 так устроена половина строк).

    Опасность чисел из наименования снимается иначе и надёжнее: вырезаем ВСЕ закавыченные куски
    целиком, а из остатка берём коды. Хвост с самим порогом отсекаем по первому «:» или «не менее» —
    там даты («до 30 июня 2023 г.»), и хотя точек в них нет, отсечка дешевле рассуждения."""
    # ⚠ «(в ред. … от 29.12.2022 N 2519)» ЗАТИРАЕМ: дата с точками проходит фильтр «есть точка»
    # и становилась кодом. У строк прим. 27 порог написан без «не менее», поэтому отсечка ниже
    # до амендмента не доходила, и в коды попадали `29.12.2022`, `17.05.2024` (замер 21.08.2026).
    body = _blank_names(_blank_amend(line))
    for cut in (":", "не менее", "не оцениваются"):
        pos = body.find(cut)
        if pos > 0:
            body = body[:pos]
    return [c for c in _CODE_ONLY_RE.findall(_FOOTNOTE_RE.sub(" ", body)) if "." in c]
_AMEND_STRIP_RE = re.compile(r"\s*\(в ред\.(?:[^()]|\([^()]*\))*\)")

def _clean_step(line: str) -> str:
    """Строка-ступень без ссылки на редакцию и без нулевой ширины пробелов."""
    return _ZERO_WIDTH_RE.sub("", _AMEND_STRIP_RE.sub("", line)).strip().rstrip(";. ").strip()


# --- ⚠ ТРЕТЬЯ ФОРМА ПРИМЕЧАНИЯ: КОДЫ ВО ВВОДНОЙ, СТУПЕНИ ПРОЗОЙ (A1 #56, остаток K2 #47) ------
#
# Найдено 21.08.2026 при классификации непокрытых позиций. Разбор знал две формы — строку,
# НАЧИНАЮЩУЮСЯ с кода («28.22.14.125 "Краны…" - не менее 450 баллов»), и таблицу с шапкой по
# годам. Мимо проходила третья, где код назван в самой вводной примечания, а график идёт ниже
# отдельными строками:
#
#   18. Продукция, классифицируемая кодом по ОК 034-2014 (КПЕС 2008) 28.22.16.111, может быть
#       отнесена к российской промышленной продукции при условии достижения … баллов:
#       до 31 декабря 2026 г. - не менее 120 баллов;
#       с 1 января 2027 г. - не менее 135 баллов.
#
# Таких примечаний в чанке 13. Порог написан для КОНКРЕТНОГО кода дословно, а позиция отвечала
# «порог не предусмотрен»: «Лифты пассажирские» (28.22.16.111) и «Счетчики электрической
# энергии» (26.51.63.130) — обе в корпусе, обе без порога до этой правки.
#
# ⚠ ДАТА ПОХОЖА НА КОД ОКПД2, и это не теория: во вводных стоит «(в ред. Постановления
# Правительства РФ от 15.06.2026 N 746)», а `15.06.2026` подходит под общий шаблон кода.
# Защита двойная: сначала срезаем «(в ред. …)», затем требуем, чтобы у сегментов ПОСЛЕ первого
# было не больше трёх цифр — у ОКПД2 их 2–3, у года всегда 4.
# ⚠ ФРАГМЕНТ БЕРЁТСЯ ЦЕЛИКОМ, А НЕ ЖАДНОЙ ЧАСТЬЮ. Первая редакция шаблона
# (`\d{2}(?:\.\d{1,3})+`) выкусывала из «02.04.2021» подстроку «02.04.202» — три цифры года
# проходили за сегмент кода, и дата становилась кодом ОКПД2 `02.04.202`. В корпусе это молчало
# только потому, что даты стоят внутри «(в ред. …)», а его срезают строкой выше, — то есть
# защита держалась на удаче, а не на устройстве. Теперь берём ВЕСЬ точечный фрагмент
# (границы `(?<![\d.])` / `(?![\d.])`) и проверяем его сегменты целиком.
_INTRO_CODE_RE = re.compile(r"(?<![\d.])(?:из\s+)?(\d+(?:\.\d+)+)(?![\d.])")


# ⚠ ЧАСТЬ ПРИМЕЧАНИЙ АДРЕСУЕТ ПРОДУКЦИЮ ПО ИМЕНИ, А НЕ ПО КОДУ (найдено 21.08.2026 проверкой
# полноты классификации `A1`). Прим. 67, 68, 69 начинаются прямо с наименования:
# «67. Электрозарядные станции постоянного тока для электротранспорта могут быть отнесены к
# российской промышленной продукции при условии …». Кода в такой вводной нет вовсе, поэтому
# привязка по коду до них не доходит, и три позиции раздела V отвечали «порог не предусмотрен»
# при дословно написанном пороге.
#
# ⚠ Совпадение требуется ТОЧНОЕ (после нормализации и снятия сносок). Наименование —
# единственный ключ, и «похоже» здесь недопустимо: у прим. 69 в имени сидит длинная оговорка
# «(кроме конверторов и инверторов …)», отличающая позицию от соседних.
_INTRO_NAME_RE = re.compile(
    r"^\s*\d+(?:\(\d+\))?\.\s+(.+?)\s+мог(?:ут|ет)\s+быть\s+отнесен", re.IGNORECASE)
# Величина порога целиком, вместе с единицей: «не менее 20 баллов».
_INLINE_VALUE_RE = re.compile(r"не менее\s+[\d\s.,]+\s*балл\w*", re.IGNORECASE)


def _intro_name(line: str) -> str | None:
    """Наименование продукции, названное во вводной примечания вместо кода."""
    m = _INTRO_NAME_RE.match(_AMEND_STRIP_RE.sub("", line))
    if not m:
        return None
    name = m.group(1).strip()
    # Форма «Продукция, классифицируемая кодом …» — это адресация КОДОМ, её разбирает `_intro_codes`.
    if not name or len(name) > 250 or name.lower().startswith("продукция"):
        return None
    if "настоящего приложения" in name.lower():
        return None
    return name


def _intro_codes(line: str) -> list[str]:
    """Коды ОКПД2, названные во вводной примечания (даты редакций отброшены).

    Код ОКПД2: две цифры класса, дальше сегменты по 1–3 цифры (`28.22.16.111`).
    Дата: `15.06.2026` — четырёхзначный последний сегмент, такого в ОКПД2 не бывает.
    """
    clean = _AMEND_STRIP_RE.sub("", line)
    out: list[str] = []
    for m in _INTRO_CODE_RE.finditer(clean):
        code = m.group(1)
        segs = code.split(".")
        if len(segs[0]) != 2 or any(not 1 <= len(s) <= 3 for s in segs[1:]):
            continue  # 02.04.2021 — дата, а не код
        if code not in out:
            out.append(code)
    return out


@lru_cache(maxsize=1)
def _flat_thresholds() -> list[dict]:
    """Строки-пороги «код "имя" - не менее N баллов» из примечаний-списков (прим. 7/8/9/31/52/53…).
    Два формата: ИНЛАЙН — порог на той же строке, что и код («…"имя": … - не менее N баллов…»);
    МНОГОСТРОЧНЫЙ (прим. 9) — строка «код "имя":» и ниже отдельные строки-ступени «- не менее N
    баллов;» до следующего кода/примечания. Кэш на процесс."""
    if not _CHUNK.exists():
        return []
    lines = _CHUNK.read_text(encoding="utf-8").split("\n")
    rows: list[dict] = []
    note = None
    i, n = 0, len(lines)
    while i < n:
        ln = lines[i]
        # ⚠ НОМЕР ПРИМЕЧАНИЯ БЕРЁТСЯ С УЧЁТОМ ПОДПУНКТОВ (A1 #56, 21.08.2026). С `_NOTE_HDR_RE`
        # заголовок «26.1.» не распознавался, и 27 строк-порогов подпункта 26.1 уходили в выдачу
        # со ссылкой «[прим. 26]» — цитата вела не на тот пункт первоисточника. Эксперт сверяет
        # ответ по ссылке, поэтому неверный номер обесценивает верное число.
        h = _NOTE_START_RE.match(ln)
        if h:
            note = h.group(1)
            # Третья форма: коды названы во ВВОДНОЙ, график идёт ниже строками-ступенями.
            # ⚠ `i` НЕ двигаем: за ступенями внутри того же примечания могут идти обычные
            # строки-пороги, и пропустить их нельзя. Сами ступени под `_FLAT_ROW_RE` не подходят
            # (начинаются с «до»/«с»), поэтому повторно не разберутся.
            head = _AMEND_STRIP_RE.sub("", ln).rstrip()
            # ⚠ ЧЕТВЁРТАЯ ФОРМА: имя И ПОРОГ в одной фразе вводной, без графика по годам —
            # «59. Кремниевые слитки могут быть отнесены … при условии достижения в совокупности
            # не менее 20 баллов за выполнение …». Двоеточия в конце нет, ступеней ниже нет.
            # ⚠ Берём ТОЛЬКО саму величину, а не хвост предложения: иначе в «Порог» уедет проза
            # («…за выполнение на территории Российской Федерации технологических операций…»),
            # ровно как было у прим. 17 до `EV13`.
            # ⚠ И только когда ступень ОДНА: несколько ступеней в прозе — это график, где легко
            # выдать просроченную величину за действующую. Там не гадаем.
            if not head.endswith(":") and not _is_coefficient_note(ln):
                iname = _intro_name(ln)
                vals = _INLINE_VALUE_RE.findall(head)
                if iname and len(vals) == 1:
                    rows.append({"codes": [], "names": [iname], "threshold": vals[0].strip(),
                                 "exception": None, "note": note})
            if head.endswith(":") and not _is_coefficient_note(ln):
                icodes = _intro_codes(ln)
                # ⚠ ИМЯ ИЗ ВВОДНОЙ БЕРЁТСЯ ДАЖЕ ПРИ НАЛИЧИИ КОДА (найдено 21.08.2026 сверкой
                # радиуса). Прим. 72.1, 72.2 и 72.3 делят ОДИН код `27.31.12.110` и различаются
                # только наименованием в кавычках: одномодовые волокна, многомодовые, преформы.
                # Строка без имени отдала порог прим. 72.1 (50/100) и многомодовым, и преформам —
                # то есть правильное число не той позиции, самый дорогой класс. С именем
                # `_lookup` различает их, а при несовпадении не показывает ничего.
                qnames = _quoted_names(ln)
                inames = qnames or [n for n in [_intro_name(ln)] if n]
                # ⚠ НАЗВАЛИ ПРОДУКЦИЮ В КАВЫЧКАХ — ЗНАЧИТ СУЗИЛИ ПРИМЕЧАНИЕ ДО НЕЁ, и матч по
                # коду отключается. Прим. 72.1, 72.2 и 72.3 делят ОДИН код `27.31.12.110`
                # («из 27.31.12.110 "Волокна оптические одномодовые…"», «…"многомодовые…"»,
                # «…"Преформы…"»), а ступени в нашем чанке есть только у 72.1 — то есть по коду
                # находилась ОДНА строка и уходила всем трём. Правильное число не той позиции,
                # с подлинной ссылкой: гард молчит, эксперт видит подтверждение.
                # ⚠ Проверять имя у единственной строки-кандидата НЕЛЬЗЯ (замерено): так снеслись
                # бы 18 законных ГРУППОВЫХ порогов, где строка называет представителя группы
                # («Перчатки хирургические» ← прим. 7 для всей 22.19). Отличие здесь в том, что
                # примечание САМО назвало продукт, а не группу.
                if icodes or inames:
                    steps: list[str] = []
                    k = i + 1
                    while (k < n and lines[k].strip()
                           and not _FLAT_ROW_RE.match(lines[k])
                           and not _NOTE_START_RE.match(lines[k])):
                        # ⚠ Ступень бывает и БЕЗ «не менее»: «до 1 января 2022 г. - 70 баллов»
                        # (прим. 10, редкоземельные магниты). Без второго признака примечание не
                        # давало ни одной строки, и позиция оставалась без порога.
                        if _STEP_RE.search(lines[k]) or _P27_VALUE_RE.search(lines[k]):
                            steps.append(_clean_step(lines[k]))
                        k += 1
                    thr, exc = _split_exception("; ".join(steps)) if steps else ("", None)
                    if thr:
                        # Либо коды без имён (вводная называет только коды — прим. 18, 71, 72),
                        # либо имя без кодов (прим. 67, 68, 69). ⚠ При споре двух примечаний за
                        # один код `_lookup` не угадывает: пересечение имён равно нулю, и это
                        # НАМЕРЕННО — прим. 71 и 72 текстуально одинаковы и оба называют
                        # `26.11.22.200`/`.210`, различить их может только эксперт.
                        rows.append({"codes": icodes, "names": inames, "intro": True,
                                     "threshold": thr, "exception": exc, "note": note})
        if _FLAT_ROW_RE.match(ln):
            if "не менее" in ln:  # инлайн: код и порог на одной строке
                # ⚠ Порог начинается ПОСЛЕ имени/кодов, а не со слова «не менее». Отсечка по
                # «не менее» срезала первую ступень вместе с её датой: «до 30 июня 2023 г. -
                # не менее 250 баллов, с 1 июля 2023 г. - …» превращалось в «не менее 250
                # баллов, …», то есть ПРОШЛЫЙ порог читался как действующий (K2, #47). Режем по
                # границе «конец последнего имени / список кодов», а её даёт двоеточие или тире.
                head = _blank_names(ln)
                nm = head.find("не менее")
                # Двоеточие — граница «коды/имена | порог», и оно приоритетнее тире: тире стоит
                # ещё и ВНУТРИ порога, между датой и числом («до 30 июня 2023 г. - не менее 250»).
                sep = head.rfind(":", 0, nm)
                if sep < 0:
                    sep = head.rfind(" - ", 0, nm)
                j = sep + 1 if sep > 0 else ln.find("не менее")
                left = ln[:ln.find("не менее")]
                thr = _AMEND_STRIP_RE.sub("", ln[j:]).strip(" -—").rstrip(";. ").strip()
                codes = _codes_before_quote(ln)
                thr, exc = _split_exception(thr)
                if codes and thr:
                    rows.append({"codes": codes, "names": _quoted_names(left),
                                 "threshold": thr, "exception": exc, "note": note})
            elif _AMEND_STRIP_RE.sub("", ln).rstrip().endswith(":"):  # многостроч. (прим.9): «код "имя":» + ступени
                codes = _codes_before_quote(ln)
                names = _quoted_names(ln)
                steps: list[str] = []
                k = i + 1
                while (k < n and lines[k].strip()
                       and not _FLAT_ROW_RE.match(lines[k])
                       and not _NOTE_START_RE.match(lines[k])):
                    if _STEP_RE.search(lines[k]):
                        steps.append(_clean_step(lines[k]))
                    k += 1
                # ⚠ Порядок «сначала разделить, потом проверить» — тот же, что в инлайн-ветке
                # (ревью 20.08.2026). Раньше здесь проверялось `if codes and steps` ДО разделения,
                # и пустой общий график попадал в строку: `format_context` печатал бы
                # «Порог:  [прим. 9]» — подлинную ссылку без величины. Две ветки одного разбора
                # обязаны одинаково отвечать на один вход.
                thr, exc = _split_exception("; ".join(steps)) if steps else ("", None)
                if codes and thr:
                    rows.append({"codes": codes, "names": names,
                                 "threshold": thr, "exception": exc, "note": note})
                i = k
                continue
        i += 1
    # ⚠ КОД, ЗА КОТОРЫЙ СПОРЯТ НЕСКОЛЬКО ИМЕНОВАННЫХ ВВОДНЫХ, МАТЧИТСЯ ТОЛЬКО ПО ИМЕНИ.
    # Прим. 72.1, 72.2 и 72.3 делят `27.31.12.110` и различаются лишь наименованием в кавычках
    # (одномодовые волокна / многомодовые / преформы), а ступени в нашем чанке есть только у
    # 72.1 — по коду находилась ОДНА строка и уходила всем трём: правильное число не той
    # позиции, да ещё с подлинной ссылкой.
    #
    # ⚠ Решается ПОСЛЕ разбора и ПО ДАННЫМ, а не признаком «в вводной есть кавычки». Прежняя
    # редакция снимала коды у всякой именованной вводной — и прим. 26(2)/26(3), где кавычки
    # просто поясняют код, переставали находиться, а позиции откатывались на групповой порог
    # прим. 26 (55 вместо 45/55/75). Замер радиуса это и показал.
    for r in rows:
        if r.get("intro") and r["names"]:
            r["codes"] = []
    rows.extend(_qualified_list_rows(lines))
    rows.extend(_named_block_rows(lines))
    return rows


# --- ⚠ ПЯТАЯ ФОРМА: «классифицируемой кодом … из CODE "ИМЯ" - N баллов» (прим. 27) ------------
#
# Строка НЕ начинается с кода — она начинается со слова «классифицируемой», поэтому `_FLAT_ROW_RE`
# её не видел, и прим. 27 (энергомаш, электротехника, кабельная промышленность) не разбиралось
# вовсе. Вторая особенность: величина написана БЕЗ «не менее» — «- 60 баллов», «с 2024 года -
# 73 балла», — то есть общий признак ступени здесь не работает.
#
# ⚠ ПОЧЕМУ ПРИЗНАК ЛОКАЛЬНЫЙ, А НЕ ОБЩИЙ. Расширить `_STEP_RE` до «любое число + баллы» нельзя:
# тогда ступенью станут баллы ОТДЕЛЬНЫХ ОПЕРАЦИЙ («литье, ковка, штамповка (3 балла)»), которых
# в корпусе сотни, и «Порог» наполнится значениями операций. Признак работает только внутри этой
# формы, где величина стоит после тире и относится ко всей позиции.
_P27_ROW_RE = re.compile(r"^\s*классифицируем\w+\s+код", re.IGNORECASE)
# ⚠ ДАТА ОБЯЗАНА ЕХАТЬ ВМЕСТЕ СО СВОИМ ЧИСЛОМ. Первая редакция шаблона отделяла дату классом
# `[^;.]`, а в «с 1 сентября 2026 г. - 92 балла» точка стоит внутри «г.» — префикс обрывался, и
# порог печатался как «82 балла; 92 балла», без единой даты. Это ровно тот дефект, который
# `EV13` вычищала у прим. 17: число без своего условия.
_P27_VALUE_RE = re.compile(
    r"(?:(?:до|с|начиная\s+с)\s+(?:\d{1,2}\s+[а-яё]+\s+)?\d{4}\s*(?:г\.|года|год)?\s*,?\s*)?"
    r"[-—]\s*(?:не менее\s+)?\d[\d\s]*\s*балл\w*",
    re.IGNORECASE)
_P27_QUALIFIER_RE = re.compile(r"^\s*для\s+.+:\s*$")


def _blank_amend(line: str) -> str:
    """Затирает «(в ред. …)» пробелами, СОХРАНЯЯ длину строки.

    ⚠ Именно затирает, а не вырезает: позиции закавыченных имён (`_name_spans`) считаются по
    исходной строке, и вырезание сдвинуло бы их — имена начали бы разъезжаться с величинами.
    """
    out = list(line)
    for m in _AMEND_STRIP_RE.finditer(line):
        for x in range(m.start(), m.end()):
            out[x] = " "
    return "".join(out)


def _qualified_list_rows(lines: list[str]) -> list[dict]:
    """Строки-пороги формы прим. 27, включая подблоки «для …: <график>»."""
    rows: list[dict] = []
    note = None
    n = len(lines)
    for i, ln in enumerate(lines):
        h = _NOTE_START_RE.match(ln)
        if h:
            note = h.group(1)
        if not _P27_ROW_RE.match(ln):
            continue
        masked = _blank_names(_blank_amend(ln))
        codes = _codes_before_quote(ln)
        if not codes:
            continue
        vals = [m for m in _P27_VALUE_RE.finditer(masked)]
        # Наименования берём только ДО первой величины: дальше в строке идёт проза, где тоже
        # встречаются кавычки («с примечанием "при наличии"»), и она не наименование продукции.
        cut = vals[0].start() if vals else len(ln)
        names = [ln[a + 1:b].strip() for a, b in _name_spans(ln) if b < cut and b > a + 1]
        if vals:
            thr = "; ".join(ln[m.start():m.end()].strip(" ,;-—") for m in vals)
            rows.append({"codes": codes, "names": names, "threshold": thr,
                         "exception": None, "note": note, "strict_name": True})
            continue
        if not masked.rstrip().endswith(":"):
            continue
        # Подблоки «для <условие>:» со своими графиками. Условие едет ВМЕСТЕ с числами —
        # график без своего условия и есть неверный ответ (тот же принцип, что у прим. 17).
        blocks: list[tuple[str, list[str]]] = []
        k = i + 1
        while k < n and not _P27_ROW_RE.match(lines[k]) and not _NOTE_START_RE.match(lines[k]):
            cand = _blank_amend(lines[k]).rstrip()
            vals_here = list(_P27_VALUE_RE.finditer(cand))
            if _P27_QUALIFIER_RE.match(cand):
                blocks.append((cand.strip().rstrip(":"), []))
            elif cand.strip().lower().startswith("для") and vals_here:
                # ⚠ Оговорка и её величины на ОДНОЙ строке: «для вакуумных контакторов
                # низковольтных переменного тока - 41 балл, с 1 сентября 2025 г. - 51 балл;»
                # (прим. 27, контакторы). Без этой ветки строка не давала блока вовсе, и порог
                # терялся целиком.
                blocks.append((cand[:vals_here[0].start()].strip(" ,;-—:"),
                               [cand[m.start():m.end()].strip(" ,;-—") for m in vals_here]))
            elif blocks:
                for m in vals_here:
                    blocks[-1][1].append(cand[m.start():m.end()].strip(" ,;-—"))
            k += 1
        blocks = [(q, v) for q, v in blocks if v]
        if not blocks:
            continue
        # ⚠⚠ БЛОКИ ХРАНЯТСЯ СЫРЫМИ, А ПОРЯДОК РЕШАЕТСЯ ПРИ ЛУКАПЕ (ревью захода 3, 26.08.2026).
        # Прежде `blocks[0]` жёстко становился главным `Порог:`, и какой график поедет первым, не
        # зависело от того, о какой продукции спросили. Живой пример прим. 27, код 27.33:
        # «Контакторы и пускатели электромагнитные низковольтные» получали главной строкой
        # «для ВАКУУМНЫХ КОНТАКТОРОВ …: 41 балл; с 1 сентября 2025 г. — 51 балл», то есть чужой
        # график со ступенью, к ним не относящейся, а собственное значение уезжало в сноску
        # «⚠ ИНОЙ порог». Обе позиции возвращали побайтно одну строку.
        #
        # Это «правильное число, привязанное НЕ К ТОЙ позиции» — по урокам проекта самый дорогой
        # класс дефекта, и чинить его в разборе нельзя ПО ПОСТРОЕНИЮ: на этапе парсинга ещё не
        # известно, кто спросит. Поэтому строка несёт все блоки, а ведущий выбирает `_fmt_flat`.
        fmt = lambda q, v: f"{q}: " + "; ".join(v)  # noqa: E731
        rows.append({"codes": codes, "names": names,
                     "blocks": blocks,
                     "threshold": fmt(*blocks[0]),
                     "exception": " · ".join(fmt(q, v) for q, v in blocks[1:]) or None,
                     "note": note, "strict_name": True})
    return rows


# --- ⚠ ШЕСТАЯ ФОРМА: подзаголовок «из CODE "ИМЯ":» + таблица по УЗЛАМ (прим. 74) -------------
#
# Таблица есть, но её первая колонка — не код, а УЗЕЛ изделия («Компрессор», «Компрессорная
# установка»), поэтому `_tables` её не берёт: он ищет строки, начинающиеся с кода. Продукт
# называет подзаголовок над таблицей.
#
# ⚠ БЕРЁМ ТОЛЬКО СТРОКУ САМОГО ИЗДЕЛИЯ, А НЕ ЕГО УЗЛА. У «Компрессорной установки смешанного
# хладагента» в таблице две строки: «Компрессор» (170/230) и «Компрессорная установка»
# (160/210). Первая — порог УЗЛА, и его место не в строке «Порог» (это правило `D9`). Признак
# изделия: все слова строки входят в наименование подзаголовка — «компрессорная установка» ⊂
# «компрессорная установка смешанного хладагента», а «компрессор» отдельным словом туда не входит.
_NAMED_BLOCK_RE = re.compile(rf'^\s*{_CODE_TOKEN}\s*"')


def _named_block_rows(lines: list[str]) -> list[dict]:
    """Строки-пороги формы прим. 74: подзаголовок с наименованием + таблица по узлам."""
    rows: list[dict] = []
    note = None
    n = len(lines)
    for i, ln in enumerate(lines):
        h = _NOTE_START_RE.match(ln)
        if h:
            note = h.group(1)
        if not _NAMED_BLOCK_RE.match(ln) or not _blank_amend(ln).rstrip().endswith(":"):
            continue
        names = _quoted_names(ln)
        if not names:
            continue
        # Ищем шапку таблицы, пропуская пустые строки и строки-ссылки на редакцию.
        k, header = i + 1, None
        while k < n and k <= i + 6:
            cand = _blank_amend(lines[k]).strip()
            if cand and "|" in cand and len(_YEAR_ANY_RE.findall(cand)) >= 2:
                header = cand
                break
            if cand and "|" not in cand:
                break            # начался обычный текст — таблицы здесь нет
            k += 1
        if header is None:
            continue
        years = [c.strip() for c in header.split("|") if c.strip()]
        want = set(_norm(names[0]).split())
        # ⚠ БЕРЁМ ВСЕ СТРОКИ, ЧЕЙ ПРЕДМЕТ НАЗВАН В ПОДЗАГОЛОВКЕ, И КАЖДУЮ СО СВОЕЙ ПОДПИСЬЮ.
        # Прим. 37: подзаголовок — «Насосы центробежные … И АГРЕГАТЫ НА ИХ ОСНОВЕ», а в таблице
        # две строки с РАЗНЫМИ порогами: «Насосы» 750/850 и «Насосные агрегаты» 1300/1800.
        # Показать одну значило бы выдать заявителю с агрегатом порог насоса — вдвое меньший.
        # Прим. 74: подзаголовок «Компрессорная установка смешанного хладагента», строки
        # «Компрессор» (170/230) и «Компрессорная установка» (160/210). Слова «компрессор»
        # в подзаголовке НЕТ (там «компрессорная»), поэтому строка узла отсекается — порог узла
        # не место в строке «Порог» (правило `D9`).
        picked: list[tuple[str, str]] = []
        k += 1
        while k < n and "|" in lines[k]:
            # ⚠⚠ ПУСТЫЕ ЯЧЕЙКИ НЕЛЬЗЯ ВЫБРАСЫВАТЬ — тот же инвариант, что у `_tables` (см. ⚠ выше),
            # и здесь он был нарушен (ревью захода 3, 26.08.2026). `if c.strip()` схлопывал
            # пропуск и `zip(years, …)` сдвигал ВСЕ значения строки ВЛЕВО, на чужой год: строка
            # «Компрессорная установка| |не менее 210 баллов|» напечатала бы «до 31 декабря
            # 2025 г. — не менее 210 баллов». Правильное число, привязанное не к тому году, —
            # тот же класс, ради которого писался весь заход 3.
            # Края (`|a|b|` даёт пустые первый и последний элементы) отбрасываем ПОЗИЦИОННО,
            # середину сохраняем целиком; пустое значение отсеивает уже `if v` при сборке.
            parts = [c.strip() for c in lines[k].split("|")]
            while parts and not parts[0]:
                parts.pop(0)
            while parts and not parts[-1]:
                parts.pop()
            cells = parts
            if len(cells) >= 2 and any(len(w) >= 5 and w in want
                                       for w in _norm(cells[0]).split()):
                vals = "; ".join(f"{y} — {v.rstrip(';')}"
                                 for y, v in zip(years, cells[1:]) if v)
                if vals:
                    picked.append((cells[0], vals))
            k += 1
        if not picked:
            continue
        # Одна строка — порог как есть; несколько — каждая со своей подписью, чтобы величина
        # не отрывалась от того, к чему она относится.
        thr = picked[0][1] if len(picked) == 1 else f"{picked[0][0]}: {picked[0][1]}"
        exc = " · ".join(f"{nm}: {v}" for nm, v in picked[1:]) or None
        rows.append({"codes": [], "names": [names[0]], "threshold": thr,
                     "exception": exc, "note": note})
    return rows


# --- ⚠ ОБЛАСТЬ ДЕЙСТВИЯ ПРИМЕЧАНИЯ (K2, #47) -------------------------------------------
# Часть примечаний задаёт порог НЕ для подтверждения российского происхождения, а «для целей
# осуществления закупок … для обеспечения государственных и муниципальных нужд». Это ДРУГОЙ вопрос
# и другой порог: у одной позиции они могут различаться, а «Порог:» в ответе означает первое.
#
# ⚠ ЗАМЕР 19.08.2026: 57 позиций корпуса получали закупочный порог как СВОЙ ОБЩИЙ — с настоящей
# ссылкой на первоисточник («не менее 75 баллов [прим. 53]»). Неверный порог с подлинной ссылкой
# опаснее отсутствующего: faithfulness-гард молчит (число дословно), а эксперт видит подтверждение.
# Тот же класс, что утечка порога вверх по иерархии в `_code_applies`: гард проверяет
# заземлённость, а не правильность привязки.
#
# Признак берётся из ТЕКСТА примечания, а не из списка номеров: список устареет на следующей
# редакции, а формулировка живёт в первоисточнике.
_PROCUREMENT_RE = re.compile(r"[Дд]ля целей осуществления закупок")


@lru_cache(maxsize=1)
def _note_scopes() -> dict[str, str]:
    """Номер примечания → 'procurement' | 'general' (по его вводной фразе)."""
    if not _CHUNK.exists():
        return {}
    lines = _CHUNK.read_text(encoding="utf-8").splitlines()
    out: dict[str, str] = {}
    # Границы — по тому же правилу, что и нумерация строк-порогов: у подпункта «26.1»
    # должна быть СВОЯ область действия, а не унаследованная от «26». Иначе закупочный
    # подпункт молча стал бы общим — тот самый класс, что стоил 57 позиций.
    bounds = [(m.group(1), i) for i, ln in enumerate(lines) if (m := _NOTE_START_RE.match(ln))]
    for k, (num, i) in enumerate(bounds):
        j = bounds[k + 1][1] if k + 1 < len(bounds) else len(lines)
        head = " ".join(lines[i:j])[:900]
        out.setdefault(num, "procurement" if _PROCUREMENT_RE.search(head) else "general")
    return out


def note_scope(note: str | None) -> str:
    """Область действия примечания. Неизвестное примечание считаем общим — это прежнее поведение."""
    return _note_scopes().get(str(note or ""), "general")


def _segs(code: str) -> list[str]:
    return [s for s in str(code).strip().split(".") if s]


def _code_applies(note_code: str, pos_code: str) -> bool:
    """Применим ли порог примечания к позиции. НАПРАВЛЕНИЕ ПРИНЦИПИАЛЬНО (R8).

    Условие: код примечания — ПРЕДОК ИЛИ РАВЕН коду позиции. Тогда позиция лежит внутри ветки,
    на которую распространяется примечание, и порог к ней относится.

    Раньше матч был симметричным, и порог «утекал» ВВЕРХ по иерархии — примечание для узкого кода
    применялось ко всей группе. Живые последствия: «Система электродвижения» (27.11) получала порог
    «Детандер-генераторов жидкостных для СПГ» (27.11.32.120); «Обувь с верхом из текстильных
    материалов» (15.20.14) — порог «Обуви валяной» (15.20.14.130). Число дословно из первоисточника,
    поэтому faithfulness-гард молчит: он проверяет заземлённость, а не правильность привязки.
    Порог — самый дорогой факт продукта, поэтому здесь лучше не показать, чем показать чужой."""
    n, p = _segs(note_code), _segs(pos_code)
    return bool(n) and len(n) <= len(p) and p[:len(n)] == n


# Номинал в наименовании: «на токи до 6300 А», «(до 1000 В)», «до 125 А». Для электроаппарата
# номинал — часть ИДЕНТИЧНОСТИ изделия, а не описание: «выключатель до 2000 А» и «выключатель до
# 6300 А» — разная продукция, и примечание, написанное про одну, к другой не относится.
_RATING_RE = re.compile(r"(\d[\d\s]*)\s*(А|В|кВ|кВт|мм|кг|т)\b", re.I)


def _ratings(text: str | None) -> dict[str, set[int]]:
    """Номиналы наименования по ЕДИНИЦАМ: {"а": {4000, 6300}, "в": {1000}}."""
    out: dict[str, set[int]] = {}
    for num, unit in _RATING_RE.findall(_norm(text or "")):
        digits = re.sub(r"\D", "", num)
        if digits:
            out.setdefault(unit.lower(), set()).add(int(digits))
    return out


def _rating_conflict(product_name: str | None, names: list[str]) -> bool:
    """Номиналы ОДНОЙ единицы названы у обоих и НЕ пересекаются → строка не про эту позицию.

    ⚠⚠ ЗАЧЕМ. `strict_name` пропускает по пересечению «≥2 значимых слова», а два наименования,
    различающиеся только квалификатором и номиналом, делят их десяток: «Выключатель автоматический
    низковольтный в литом корпусе (до 1000 В) на токи до 2000 А» и названное во вводной прим. 27
    «Выключатель автоматический (ВОЗДУШНЫЙ) … на токи до 6300 А» совпадают по девяти словам.
    Итог: позиция «до 2000 А» получала график прим. 27, хотя «2000 А» не встречается во ВСЕХ
    примечаниях ни разу (проверено grep). Самый дорогой класс дефекта проекта — правильное число,
    привязанное не к той позиции.

    ⚠ Сравнение ПО ЕДИНИЦАМ, а не общим множеством: «(до 1000 В)» стоит в обоих наименованиях и
    погасило бы вето, если считать номиналы одной кучей.
    ⚠ Вето срабатывает, только когда единица названа У ОБОИХ: наименование без номинала
    («Суда рыболовные», «Контакторы и пускатели») ведёт себя как прежде.
    ⚠ Основы слов числа НЕ включают намеренно (`_stems`, ревью захода 3) — там задача другая:
    выбрать ведущий блок среди подблоков ОДНОЙ позиции. Здесь решается, та ли это позиция вообще.
    """
    want = _ratings(_strip_fn(product_name))
    if not want:
        return False
    for nm in names:
        have = _ratings(_strip_fn(nm))
        shared = set(want) & set(have)
        # ⚠ `all`, а не `any`: имя конфликтует, если РАСХОДИТСЯ ХОТЬ ПО ОДНОЙ общей единице.
        # С `any` совпадение по «(до 1000 В)» гасило расхождение по «на токи до 2000/6300 А» —
        # то есть вето снималось ровно там, ради чего заводилось.
        if not shared or all(want[u] & have[u] for u in shared):
            return False        # это имя не конфликтует — вето снимается
    return True


def _name_overlap(product_name: str | None, names: list[str]) -> int:
    pt = set(re.findall(r"\w{4,}", _norm(product_name)))
    return max((len(pt & set(re.findall(r"\w{4,}", _norm(nm)))) for nm in names), default=0)


def _stems(text: str) -> set[str]:
    """Основы СЛОВ текста. ⚠ Морфология одна на проект — та же, что у BM25 (`sparse.tokenize`).

    Вторая копия стемминга разошлась бы с первой при первой же правке; в этом проекте так уже
    расходились адрес первоисточника и «кто целевой».

    ⚠⚠ ЧИСЛА ИСКЛЮЧЕНЫ, И ЭТО НЕ ОПТИМИЗАЦИЯ. Замер радиуса поймал дефект в первой редакции этой
    правки: у позиции «Выключатель автоматический … на токи ДО 6300 А» два подблока — «на токи до
    4000 А» и «на токи ОТ 4000 А ДО 6300 А». Позиция накрывает ОБА диапазона, а совпадение токена
    «6300» вытащило вперёд второй — то есть УЖЕ, чем позиция. Число в квалификаторе означает
    границу диапазона, а не тождество продукции; идентичность несут слова. Без чисел эти два
    квалификатора становятся пословно одинаковыми → ничья → порядок первоисточника сохраняется,
    и оба графика по-прежнему видны, каждый со своим условием. Это честнее выдуманного выбора."""
    from app.rag.sparse import tokenize

    return {t for t in tokenize(text or "") if len(t) > 2 and not t.isdigit()}


def _lead_first(r: dict, product_name: str) -> tuple[str, str | None]:
    """`(ведущий график, остальные)` для строки с подблоками «для …» — по ИМЕНИ позиции.

    ⚠⚠ ЗАЧЕМ. Подблоки прим. 27 описывают РАЗНУЮ продукцию под одним кодом, и какой из них
    «Порог:», а какой «⚠ ИНОЙ порог», зависит от того, кто спрашивает. Разбор этого знать не
    может, поэтому порядок решается здесь (ревью захода 3, 26.08.2026).

    ⚠ Совпадение считается по ОСНОВАМ слов, а не по подстроке: квалификатор пишется в родительном
    («для вакуумных контакторов низковольтных переменного тока»), наименование позиции — в
    именительном («Контакторы вакуумные низковольтные переменного тока»). Подстрока не совпала бы
    ни разу, и правка выглядела бы работающей, ничего не меняя.

    ⚠ НИЧЬЯ ОСТАВЛЯЕТ ПОРЯДОК ПЕРВОИСТОЧНИКА. Если ни один блок не ближе прочих, менять порядок
    не на чем — и выдумывать его хуже, чем сохранить исходный: так ответ хотя бы воспроизводит
    примечание. Тот же принцип, что у `rules_topic` при ничьей."""
    blocks = r.get("blocks") or []
    fmt = lambda q, v: f"{q}: " + "; ".join(v)  # noqa: E731
    if len(blocks) < 2 or not product_name:
        return r["threshold"], r.get("exception")
    want = _stems(_strip_fn(product_name))
    if not want:
        return r["threshold"], r.get("exception")
    scores = [len(want & _stems(q)) for q, _ in blocks]
    best = max(scores)
    # Ноль общих основ — блок не про эту позицию; одна и та же лучшая оценка у двух блоков — ничья.
    if best == 0 or scores.count(best) != 1:
        return r["threshold"], r.get("exception")
    i = scores.index(best)
    rest = [b for j, b in enumerate(blocks) if j != i]
    return fmt(*blocks[i]), (" · ".join(fmt(q, v) for q, v in rest) or None)


def _fmt_flat(r: dict, group: bool = False, product_name: str = "") -> str:
    lead, rest = _lead_first(r, product_name)
    r = {**r, "threshold": lead, "exception": rest}
    out = f"{r['threshold']} [прим. {r['note']}]" if r.get("note") else r["threshold"]
    if group:
        # Порог задан для ветки-предка, а не для самой позиции: показываем, но честно называем
        # уровень — иначе групповой порог читается как собственный порог позиции.
        # ⚠ Приписка идёт К ОБЩЕМУ ГРАФИКУ и ДО оговорки (ревью 20.08.2026): раньше она
        # добавлялась в самый конец, то есть после перевода строки, и оговорка получала
        # предупреждение о группе, а строка «Порог:» оставалась без него вовсе.
        out += (f" — порог задан для группы кодов {', '.join(r['codes'])}; "
                f"проверьте применимость к вашей позиции по первоисточнику")
    if r.get("exception"):
        # Отдельной строкой и ВСЕГДА с условием: график без своего условия и есть неверный ответ
        # (тот же принцип, что у закупочного порога). Отступ повторяет отступ строки «Порог:»
        # в `format_context`, поэтому в контексте это читается как её продолжение, а не как
        # вторая величина того же графика.
        # ⚠ ЯРЛЫК «ИНОЙ порог» ТОЧЕН НЕ ВСЕГДА, И ЭТО ЗАПИСАНО В `K2-2` #128 (27.08.2026).
        # Вводная примечания называет позиции поимённо, и ЧИСЛО ИМЁН отвечает прямо: имён
        # несколько (контакторы) — подблоки про разную продукцию, ярлык верен; имя ОДНО
        # (выключатели «… на токи до 6300 А») — подблоки делят ОДНУ позицию по параметру
        # изделия, оба к ней относятся, и «ИНОЙ порог» читается как «это не про вас».
        # ⚠ НЕ ПРАВЛЮ ЗДЕСЬ: ярлык — КОНТРАКТ. На него завязаны правило 2г промпта,
        # `eval_completeness` (регулярка оговорки), две проверки `checks/common` и три теста.
        # Радиус самой правки — 1 позиция, радиус правки промпта — вся товарная популяция с
        # платным перезамером. Разводить ярлыки отдельной задачей, вместе с промптом.
        out += ("\n    ⚠ ИНОЙ порог — " + r["exception"])
    return out


def lookup_threshold(codes: list[str], product_name: str, section: str | None = None) -> str | None:
    """ОБЩИЙ порог позиции из примечаний (для подтверждения российского происхождения), либо None.

    ⚠ Закупочные примечания сюда НЕ входят — см. `_note_scopes`. Их порог отдаёт
    `lookup_procurement_threshold`, и показывать его надо ВМЕСТЕ с условием, при котором он читается."""
    return _lookup(codes, product_name, section, "general")


def lookup_procurement_threshold(codes: list[str], product_name: str,
                                 section: str | None = None) -> str | None:
    """Порог «для целей осуществления закупок» — ДРУГОЙ вопрос и другой ответ, чем `lookup_threshold`."""
    return _lookup(codes, product_name, section, "procurement")


def _lookup(codes: list[str], product_name: str, section: str | None, scope: str) -> str | None:
    """Порог по годам для позиции (из примечаний), либо None. Матч по НАИМЕНОВАНИЮ в рамках раздела
    (у одного кода бывают строки «общая категория» и «конкретный продукт» — имя различает)."""
    name = _norm(product_name)
    # 1) таблицы-пороги по годам (прим.77 и т.п.) — матч по НАИМЕНОВАНИЮ
    if name:
        tables = _tables()
        for t in tables:  # точный матч имени в нужном разделе
            if section and t["section"] != section:
                continue
            if note_scope(t["note"]) != scope:
                continue
            for r in t["rows"]:
                if _norm(r["name"]) == name:
                    return _fmt(r, t["note"], t["section"])
        if section is None:
            # Матч имени без ограничения раздела — ТОЛЬКО когда раздел неизвестен (R8). Раньше этот
            # проход выполнялся всегда, и одноимённая позиция из ДРУГОГО раздела могла отдать свой
            # порог. Сейчас на корпусе это не срабатывает, но защита нужна: данные меняются.
            for t in tables:
                if note_scope(t["note"]) != scope:
                    continue
                for r in t["rows"]:
                    if _norm(r["name"]) == name:
                        return _fmt(r, t["note"], t["section"])
    # 1а) ПРИМЕЧАНИЯ, АДРЕСУЮЩИЕ ПРОДУКЦИЮ ПО ИМЕНИ (прим. 59, 60, 67, 68, 69, 72.1–72.3).
    #     ⚠ ИДЁТ ДО КОДОВЫХ ВЕТОК, и это не удобство. Такое примечание САМО назвало продукт —
    #     значит оно конкретнее и группового порога, и любой строки, найденной по коду.
    #     Пример, ради которого ветка поднята: прим. 72.1 «Волокна оптические ОДНОМОДОВЫЕ»,
    #     72.2 «многомодовые», 72.3 «Преформы» делят один код `27.31.12.110`, а ступени в
    #     нашем чанке есть только у 72.1 — по коду она уходила всем трём.
    #     ⚠ Совпадение только ТОЧНОЕ и только когда таких строк ровно одна: «похоже» здесь
    #     означало бы выбор между соседними позициями по длине общей части наименования
    #     («одномодовые» и «многомодовые» отличаются одним словом из шести).
    if name:
        named = [r for r in _flat_thresholds()
                 if not r["codes"] and note_scope(r.get("note")) == scope
                 and any(_norm(_strip_fn(nm)) == _norm(_strip_fn(product_name))
                         for nm in r["names"])]
        if len(named) == 1:
            return _fmt_flat(named[0], product_name=product_name)

    # 1б) ТАБЛИЦЫ, ПРИВЯЗАННЫЕ ПО КОДУ (K2, #47). Часть примечаний-таблиц раздела не называет
    #     (прим. 38 радиоэлектроника, 81/28/33 медизделия), поэтому матч по имени в рамках раздела
    #     до них не доходил, а сами таблицы прежде даже не разбирались. У них есть КОДЫ — привязка
    #     по коду надёжнее имени: наименование в примечании и в приложении расходится формулировкой.
    #     ⚠ Направление то же, что в `_code_applies`: код примечания — предок ИЛИ равен коду позиции.
    #     Порог не «утекает» вверх по иерархии; при неоднозначности разрешаем по наименованию и,
    #     если оно не различает, НЕ ГАДАЕМ — лучше не показать, чем показать чужой порог.
    if codes:
        tcands: list[tuple[dict, dict, bool]] = []   # (таблица, строка, точное ли совпадение кода)
        for t in _tables():
            if note_scope(t["note"]) != scope:
                continue
            for r in t["rows"]:
                exact = None
                for c in codes:
                    for rc in r["codes"]:
                        if _code_applies(rc, c):
                            exact = bool(exact) or (_segs(rc) == _segs(c))
                if exact is not None:
                    tcands.append((t, r, exact))
        if len(tcands) == 1:
            t, r, _ = tcands[0]
            return _fmt(r, t["note"], t["section"])
        if len(tcands) > 1:
            # ⚠⚠ ДОСЛОВНОЕ СОВПАДЕНИЕ ИМЕНИ — ДО правила «≥2 общих слова» (ревью захода 3, 26.08.2026).
            # Тай-брейк по пересечению слов СТРУКТУРНО НЕДОСТИЖИМ для однословных наименований:
            # `_name_overlap("Мочеприемники", ["Мочеприемники"])` = 1 при пороге 2. Позиция
            # «Мочеприемники» (32.50.13.190) имела в прим. 81 строку, названную ДОСЛОВНО так же,
            # с порогом «2026 год — не менее 135 баллов», и рантайм отдавал None: у кода 11
            # кандидатов из прим. 28/33/81, а различить их было нечем.
            # ⚠ Тождество имени — свидетельство сильнее любого пересечения, и оно безопаснее:
            # совпади имя у двух строк, кандидатов снова больше одного и мы падаем в прежнее
            # правило, то есть НЕ ГАДАЕМ (принцип этой ветки не меняется).
            same = [x for x in tcands
                    if _norm(_strip_fn(x[1]["name"])) == _norm(_strip_fn(product_name))]
            if len(same) == 1:
                t, r, _ = same[0]
                return _fmt(r, t["note"], t["section"])
            best = max(tcands, key=lambda x: (_name_overlap(product_name, [x[1]["name"]]), x[2]))
            if _name_overlap(product_name, [best[1]["name"]]) >= 2:
                t, r, _ = best
                return _fmt(r, t["note"], t["section"])

    # 2) простые пороги-списки (прим. 7/11/31/52/53…) — матч по КОДУ; при неоднозначности (у кода
    #    несколько строк с разными порогами) разрешаем по наименованию, иначе НЕ гадаем.
    if codes:
        cands: list[tuple[dict, bool]] = []  # (строка примечания, точное ли совпадение кода)
        for r in _flat_thresholds():
            if note_scope(r.get("note")) != scope:
                continue
            exact = None
            for c in codes:
                for rc in r["codes"]:
                    if _code_applies(rc, c):
                        exact = bool(exact) or (_segs(rc) == _segs(c))
            if exact is None:
                continue
            # ⚠ «ИЗ 27.12 "Выключатель автоматический…"» ЧИТАЕТСЯ КАК «ЧАСТЬ КОДА, А ИМЕННО ЭТО
            # ИЗДЕЛИЕ». Без проверки имени график выключателей уходил ОДИННАДЦАТИ чужим позициям
            # группы 27.12 — «Реле управления», «Зажимы и блоки зажимов наборные»,
            # «Предохранители плавкие», «Главные распределительные щиты судовые» (замер 21.08.2026).
            # Правило локальное: только для строк формы прим. 27, где наименование и есть ключ.
            # Обычные групповые строки (прим. 7, 37) работают как прежде — там имя строки законно
            # называет представителя группы, и требование совпадения снесло бы 18 верных порогов.
            # ⚠ ПРОВЕРКА ИМЕНИ ЗДЕСЬ БЕЗУСЛОВНА, а не «только при групповом коде». У позиции
            # «Реле управления» СОБСТВЕННЫЙ код — ровно `27.12`, то есть совпадение формально
            # точное, и условие «not exact» фильтр отключало: график выключателей уходил ей,
            # «Зажимам и блокам зажимов наборным», «Предохранителям плавким» и судовым щитам.
            if r.get("strict_name"):
                # ⚠⚠ ВЕТО ПО НОМИНАЛУ — ДО правила «≥2 общих слова» (`K2-2` #128, 27.08.2026).
                # Два наименования, различающиеся только квалификатором и номиналом, делят десяток
                # значимых слов, и порог прим. 27 уходил позиции «на токи до 2000 А», которой это
                # примечание НЕ НАЗЫВАЕТ: «2000 А» не встречается во всех примечаниях ни разу.
                if _rating_conflict(product_name, r["names"]):
                    continue
                if not (_name_overlap(product_name, r["names"]) >= 2
                        or any(_norm(_strip_fn(nm)) == _norm(_strip_fn(product_name))
                               for nm in r["names"])):
                    continue
            cands.append((r, exact))
        if len(cands) == 1:
            row, is_exact = cands[0]
            return _fmt_flat(row, group=not is_exact, product_name=product_name)
        if len(cands) > 1:
            # ⚠ ТОЧНОЕ СОВПАДЕНИЕ ИМЕНИ РЕШАЕТ СРАЗУ. Правило «пересечение ≥2 слов» слепо к
            # ОДНОСЛОВНЫМ наименованиям: «Ледоколы», «Буровые суда», «Суда снабжения» названы в
            # прим. 17 поимённо, но давали пересечение 1 и отбрасывались — а код 30.11.33.190
            # делят несколько строк примечания, и позиция оставалась без порога при том, что он
            # написан прямо для неё. Сноски у имени («Ледоколы <9>») снимаем перед сравнением.
            exact_name = [rc for rc in cands
                          if any(_norm(_strip_fn(nm)) == _norm(_strip_fn(product_name))
                                 for nm in rc[0]["names"])]
            if len(exact_name) == 1:
                row, is_exact = exact_name[0]
                return _fmt_flat(row, group=not is_exact, product_name=product_name)
            # ⚠ ЕДИНСТВЕННОЕ ТОЧНОЕ СОВПАДЕНИЕ КОДА РЕШАЕТ СРАЗУ — даже если имён у строки нет
            # (A1 #56, 21.08.2026). Примечание, написанное ДЛЯ ЭТОГО кода, конкретнее примечания,
            # написанного для его группы: спор прим. 26 (группа 26.20.22, «не менее 55 баллов»)
            # и прим. 26(3) (ровно `26.20.22.160`, «не менее 45 баллов») выигрывает второе.
            # Без этой ветки позиция теряла порог ВОВСЕ: у строк новой формы наименований нет,
