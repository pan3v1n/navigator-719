            # ⚠ Правило требует ЕДИНСТВЕННОСТИ: прим. 71 и 72 оба называют `26.11.22.200`
            # точно и текстуально неразличимы — там мы по-прежнему не гадаем.
            exact_code = [rc for rc in cands if rc[1]]
