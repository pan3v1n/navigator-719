"""Пороги баллов из примечаний к приложению ПП №719 (таблицы «код | наименование | по годам»).

Порог (min_threshold) для многих позиций живёт НЕ в самой позиции, а в нумерованных примечаниях к
разделам: напр. прим. 77 к разд. XVI — «Чиллеры | 270 | 320 | 480 | 542 балла» по годам. В структуру
продукта эти пороги не попали (примечания не структурируются, см. память об актуализации), поэтому
`format_context` показывал «порог не указан». Здесь мы парсим эти таблицы из чанка примечаний
(закоммичен в git → есть и на VM) и отдаём порог для позиции — БЕЗ переиндексации pp719.

Числа берутся ДОСЛОВНО из первоисточника, поэтому при вставке в контекст ответа они заземлены
(faithfulness-гард `unverified_numbers` их пропускает). Матчим порог по НАИМЕНОВАНИЮ позиции (у одного
кода бывает несколько строк: общая категория и конкретный продукт «Чиллеры»), в рамках раздела.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

_CHUNK = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719" / "chunks"
          / "130_PRIMECHANIYA_prilozheniya.txt")

# Интро примечания-таблицы: «77. Продукция … в раздел XVI настоящего приложения …»
# ⚠ ВВОДНАЯ ПРИМЕЧАНИЯ-ТАБЛИЦЫ (K2, #47). Прежний шаблон требовал буквально «Продукция,» и
# обязательно называл раздел — под него подходили 10 таблиц из 30+. Мимо проходили ходовые
# формулировки: «Отнесение продукции радиоэлектроники …» (прим. 38), «Продукция медицинской
# промышленности может быть отнесена …» (прим. 81, 28, 33) — а это 53 позиции одного только
# раздела VII. Теперь вводная — это просто заголовок примечания, а РАЗДЕЛ необязателен:
# у таких таблиц есть коды, и привязка идёт по коду (см. `_lookup`).
_NOTE_INTRO_RE = re.compile(r"^\s*(\d+(?:\(\d+\))?)\.\s+\S")
_INTRO_SECTION_RE = re.compile(r"в\s+раздел[еа]?\s+([IVXLC]+)\s+настоящего")
# Заголовок таблицы: «с 1 января 2024 г.» ЛИБО «2024 год» / «2028 год и далее» / «с 2027 года».
_YEAR_RE = re.compile(r"с 1 января (\d{4})")
_YEAR_ANY_RE = re.compile(r"(?:с 1 января\s+|с\s+)?(\d{4})\s*(?:г\.|год)")
_CODE_RE = re.compile(r"\d{2}\.\d{2}(?:\.\d+)*")


@lru_cache(maxsize=1)
def _tables() -> list[dict]:
    """Парсит все таблицы-пороги из чанка примечаний. Кэш на процесс."""
    if not _CHUNK.exists():
        return []
    lines = _CHUNK.read_text(encoding="utf-8").splitlines()
    tables: list[dict] = []
    i, n = 0, len(lines)
    while i < n:
        m = _NOTE_INTRO_RE.match(lines[i])
        if not m:
            i += 1
            continue
        note_no = m.group(1)
        # Раздел — если примечание его называет. ⚠ Часть таблиц раздела не называет вовсе
        # (прим. 38, 81, 28, 33): у них привязка идёт по КОДУ, и это надёжнее имени.
        sm = _INTRO_SECTION_RE.search(lines[i])
        section = sm.group(1) if sm else None
        # Заголовок таблицы: строка с разделителями «|» и минимум двумя годами.
        j, header = i + 1, None
        while j < n:
            if _NOTE_INTRO_RE.match(lines[j]):
                break
            cand = lines[j]
            # ⚠ Шапка бывает разорвана переносом («Код по ОК 034-2014» / «(КПЕС 2008)|Наименование…»,
            # прим. 81): склеиваем с предыдущей строкой, иначе таблица не находится вовсе.
            if "|" in cand and j > i + 1 and "|" not in lines[j - 1] and lines[j - 1].strip():
                cand = lines[j - 1].strip() + " " + cand
            if "|" in cand and len(_YEAR_ANY_RE.findall(cand)) >= 2:
                header = cand
                break
            j += 1
        if header is None:
            i += 1
            continue
        # ⚠ Подписи колонок берём ДОСЛОВНО из шапки («2028 год и далее», «с 1 января 2024 г.»):
        # синтез «с 1 января {год}» переписывал бы первоисточник — «2028 год» и «с 1 января
        # 2028 г.» это разные утверждения, а порог показывается эксперту как цитата.
        hcells = [c.strip() for c in header.split('|')[2:] if c.strip()]
        # ⚠ ТАБЛИЦА КОЭФФИЦИЕНТОВ — НЕ ТАБЛИЦА ПОРОГОВ (ревью 20.08.2026). Прим. 80 задаёт
        # коэффициент СЭЗ и срок его действия; рантайм печатал «Порог: с 1 января 2026 г. — 0,5».
        # Сейчас оно не разбирается лишь ПО СЛУЧАЙНОСТИ — в шапке нет двух дат, поэтому она не
        # опознаётся как шапка. Стоит следующей редакции переписать её в ходовую форму (как уже
        # сделано в прим. 56/58/61) — и коэффициент снова поедет в строку порога. Признак берётся
        # из шапки, потому что именно она объявляет, ЧТО стоит в колонках.
        if any("коэффициент" in c.lower() for c in header.split('|')):
            i = j + 1
            continue
        # ⚠ СИНТЕЗ ПОДПИСЕЙ УБРАН (ревью 20.08.2026). Здесь стоял фолбэк
        # `_YEAR_ANY_RE.findall(header)`, прямо противоречивший инварианту двумя строками выше:
        # регулярка имеет группу, поэтому `findall` возвращает ГОЛЫЙ год, и колонка «2022 - 2023
        # годы» подписывалась как «2023» — диапазон схлопывался в свою последнюю дату, а «с 1
        # января» терялось. Фолбэк не был спящим: он срабатывал на 3 таблицах из 30 (прим. 11, 37,
        # 74), и молчали они лишь потому, что в их первой колонке нет кода ОКПД2. Подписи берём
        # ДОСЛОВНО или не берём вовсе — цитата эксперту важнее полноты разбора.
        years = hcells
        rows: list[dict] = []
        pending = ""  # строка-продолжение многострочной ячейки кода («из 28.25.12»)
        k = j + 1
        while k < n:
            raw = lines[k]
            if not raw.strip() or _NOTE_INTRO_RE.match(raw):
                break
            cells = raw.split("|")
            if len([c for c in cells if c.strip()]) < 3:  # ячейка кода на отдельной строке
                pending = (pending + " " + raw.strip()).strip()
                k += 1
                continue
            code_cell = (pending + " " + cells[0]).strip()
            pending = ""
            name = cells[1].strip()
            thr = [c.strip() for c in cells[2:] if c.strip()]
            codes = _CODE_RE.findall(code_cell)
            by_year = {years[x]: thr[x] for x in range(min(len(years), len(thr)))}
            if codes and name and by_year:
                rows.append({"codes": codes, "name": name, "by_year": by_year})
            k += 1
        if rows:
            tables.append({"note": note_no, "section": section, "years": years, "rows": rows})
        i = k
    return tables


def _strip_fn(s: str | None) -> str:
    """Снимает хвостовой маркер сноски: «Ледоколы <9>» → «Ледоколы»."""
    return re.sub(r"\s*<[\d.,\s]+>\s*$", "", s or "").strip()


def _norm(s: str | None) -> str:
    return re.sub(r"\s+", " ", (s or "").strip().lower())


def _fmt(row: dict, note: str, section: str | None) -> str:
    # Подпись колонки печатается как в первоисточнике; «с 1 января YYYY» уже содержит предлог,
    # «2028 год и далее» — нет, поэтому соединяем нейтральным тире, а не дописываем «с 1 января».
    steps = "; ".join(f"{lbl} — {val}" for lbl, val in row["by_year"].items())
    src = f"прим. {note} к разд. {section}" if section else f"прим. {note}"
    return f"{steps} [{src}]"


# --- Простые пороги-списки из примечаний (прим. 7/11/31/52/53…) --------------------------
# Формат строки: «[из ]КОД "Наименование"[, [из ]КОД "…"…] - не менее N баллов[…]; (в ред. …)».
# Отличается от таблиц-по-годам (те через «|»); порог привязан к КОДУ (у строки бывает несколько
# кодов, у кода — несколько строк с разными порогами → дизамбигуация по наименованию). Описательные
# примечания (прим. 8(1): «…не менее N баллов для лопастей…», без кода) сюда НЕ попадают — покрыты
# verified_cases / отдельной доработкой.
_NOTE_HDR_RE = re.compile(r"^(\d+(?:\(\d+\))?)\.\s")            # «7.», «8(1).», «52.»
# Строка-порог начинается с кода (кодов) и кавычки. Два реальных усложнения корпуса, из-за которых
# раньше терялись десятки порогов (R7):
#   * СНОСКА между кодом и наименованием: «19.20.31 <11> "Пропан и бутан сжиженные" - не менее 300…»
#   * НЕСКОЛЬКО КОДОВ через запятую: «из 20.13.43.110, из 20.13.43.111, из 20.13.43.119 "Сода…"»
# Прежняя регулярка требовала кавычку сразу за первым кодом и не брала ни то, ни другое.
_CODE_TOKEN = r"(?:из\s+)?\d{2}(?:\.\d+)*(?:\s*<[^>\n]{1,16}>)?"
# ⚠ Строка-порог начинается со списка кодов, за которым идёт ЛИБО наименование в кавычках,
# ЛИБО сразу двоеточие: «30.11.31.110, 30.11.31.111, …: до 30 июня 2023 г. не менее 2500 баллов»
# (прим. 17). Требование кавычки теряло такие строки целиком (K2, #47).
_FLAT_ROW_RE = re.compile(rf'^\s*{_CODE_TOKEN}(?:\s*,\s*{_CODE_TOKEN})*\s*[":]', re.IGNORECASE)
# ⚠ ДВА ГРАФИКА В ОДНОЙ СТРОКЕ (найдено ревью 20.08.2026, дефект внесён самой K2).
# Приняв строку с «голым» двоеточием, разбор впустил прим. 17, где ОДНО предложение несёт ДВА
# графика: общий и оговорку «за исключением судов, инвестиционные проекты по строительству
# которых реализуются в рамках договоров о закреплении доли квоты добычи … и которые
# оцениваются <свой график>». Склеенные в одну строку «Порог:», они дают одну и ту же дату с
# РАЗНЫМИ числами: «с 1 июля 2025 г. не менее 3400» и, тремястами символов ниже, «с 1 июля
# 2025 г. не менее 2900». Замер: 13 позиций (Траулеры, Ярусники, Сейнеры, Суда-рыбозаводы,
# рефрижераторные — 3200 против 3750).
#
# Это ровно тот класс, ради которого писалась K2: оба числа дословны, гард молчит, а условие
# теряется в середине 708-символьного блока. Решение — то же, что для закупочного порога:
# график не выбрасываем, а перестаём выдавать за общий, вынося вместе с его условием.
#
# Делим ТОЛЬКО когда в оговорке есть свой порог: «за исключением X» без «не менее» — это
# обычное сужение охвата, оно относится к общему графику и резать его нельзя.
_EXCEPTION_RE = re.compile(r",?\s*(за исключением\b.*)$", re.IGNORECASE | re.DOTALL)


def _split_exception(text: str) -> tuple[str, str | None]:
    """«общий график, за исключением … <свой график>» → (общий, оговорка) либо (текст, None)."""
    m = _EXCEPTION_RE.search(text)
    if not m or "не менее" not in m.group(1):
        return text, None
    return text[:m.start()].rstrip(" ,;"), m.group(1).strip().rstrip(";. ")


_FOOTNOTE_RE = re.compile(r"<[^>\n]{1,16}>")
_CODE_ONLY_RE = re.compile(r"\d{2}(?:\.\d+)*")
_NAME_Q_RE = re.compile(r'"([^"]+)"')
_QUOTED_RE = re.compile(r'"[^"]*"')


def _name_spans(line: str) -> list[tuple[int, int]]:
    """Границы закавыченных НАИМЕНОВАНИЙ. Общая основа для затирания кодов и для сбора имён.

    ⚠ Парная регулярка `"[^"]*"` не годится: в приложении встречаются ВЛОЖЕННЫЕ кавычки —
    «Суда наливные смешанного плавания "река - море"». Одна такая пара сбивает разбивку для всего
    ОСТАТКА строки: в длинной строке прим. 17 из 22 кодов собиралось 6, а имена после вложенности
    превращались в мусор («, 30.11.32.110»). Семь судов («Буровые суда», «Суда снабжения»,
    «Суда обслуживающего флота» …) оставались без порога, хотя он написан для них тем же
    предложением; до правки они брали порог СОСЕДНЕЙ строки — 1950 вместо 2450 (K2, #47).

    Правило: имя заканчивается на кавычке, за которой идёт «,», «:», « -» или конец строки.
    Внутренние кавычки этому не удовлетворяют и остаются частью имени."""
    spans: list[tuple[int, int]] = []
    i, n = 0, len(line)
    while i < n:
        if line[i] != '"':
            i += 1
            continue
        j = i + 1
        while j < n:
            if line[j] == '"':
                rest = line[j + 1:j + 3]
                if rest[:1] in (",", ":", "") or rest.startswith(" -"):
                    break
            j += 1
        spans.append((i, min(j, n - 1)))
        i = j + 1
    return spans


def _blank_names(line: str) -> str:
    """Затирает пробелами закавыченные наименования, оставляя коды и служебные символы."""
    out = list(line)
    for a, b in _name_spans(line):
        for x in range(a, b + 1):
            out[x] = " "
    return "".join(out)


def _quoted_names(line: str) -> list[str]:
    """Наименования из кавычек — тем же сканером, что и затирание (иначе списки разъезжаются)."""
    return [line[a + 1:b].strip() for a, b in _name_spans(line) if b > a + 1]


def _codes_before_quote(line: str) -> list[str]:
    """ВСЕ коды строки-порога примечания.

    ⚠ Имя обманчиво историческое: раньше брались коды строго ДО первой кавычки, чтобы в «коды» не
    попали числа из наименования («чистотой менее 95 процентов»). Но строки примечаний часто несут
    НЕСКОЛЬКО пар «код + имя» подряд:

        30.11.22.110 "Суда наливные морские", 30.11.22.112 "Суда морские для перевозки химических
        продуктов", 30.11.22.119 "…": до 30 июня 2023 г. - не менее 1750 баллов, …

    и до 19.08.2026 привязывался только ПЕРВЫЙ код — остальные позиции оставались без порога,
    хотя он написан для них тем же предложением (K2, #47; в прим. 17 так устроена половина строк).

    Опасность чисел из наименования снимается иначе и надёжнее: вырезаем ВСЕ закавыченные куски
    целиком, а из остатка берём коды. Хвост с самим порогом отсекаем по первому «:» или «не менее» —
    там даты («до 30 июня 2023 г.»), и хотя точек в них нет, отсечка дешевле рассуждения."""
    body = _blank_names(line)
    for cut in (":", "не менее", "не оцениваются"):
        pos = body.find(cut)
        if pos > 0:
            body = body[:pos]
    return [c for c in _CODE_ONLY_RE.findall(_FOOTNOTE_RE.sub(" ", body)) if "." in c]
_AMEND_STRIP_RE = re.compile(r"\s*\(в ред\.(?:[^()]|\([^()]*\))*\)")


@lru_cache(maxsize=1)
def _flat_thresholds() -> list[dict]:
    """Строки-пороги «код "имя" - не менее N баллов» из примечаний-списков (прим. 7/8/9/31/52/53…).
    Два формата: ИНЛАЙН — порог на той же строке, что и код («…"имя": … - не менее N баллов…»);
    МНОГОСТРОЧНЫЙ (прим. 9) — строка «код "имя":» и ниже отдельные строки-ступени «- не менее N
    баллов;» до следующего кода/примечания. Кэш на процесс."""
    if not _CHUNK.exists():
        return []
    lines = _CHUNK.read_text(encoding="utf-8").split("\n")
    rows: list[dict] = []
    note = None
    i, n = 0, len(lines)
    while i < n:
        ln = lines[i]
        h = _NOTE_HDR_RE.match(ln)
        if h:
            note = h.group(1)
        if _FLAT_ROW_RE.match(ln):
            if "не менее" in ln:  # инлайн: код и порог на одной строке
                # ⚠ Порог начинается ПОСЛЕ имени/кодов, а не со слова «не менее». Отсечка по
                # «не менее» срезала первую ступень вместе с её датой: «до 30 июня 2023 г. -
                # не менее 250 баллов, с 1 июля 2023 г. - …» превращалось в «не менее 250
                # баллов, …», то есть ПРОШЛЫЙ порог читался как действующий (K2, #47). Режем по
                # границе «конец последнего имени / список кодов», а её даёт двоеточие или тире.
                head = _blank_names(ln)
                nm = head.find("не менее")
                # Двоеточие — граница «коды/имена | порог», и оно приоритетнее тире: тире стоит
                # ещё и ВНУТРИ порога, между датой и числом («до 30 июня 2023 г. - не менее 250»).
                sep = head.rfind(":", 0, nm)
                if sep < 0:
                    sep = head.rfind(" - ", 0, nm)
                j = sep + 1 if sep > 0 else ln.find("не менее")
                left = ln[:ln.find("не менее")]
                thr = _AMEND_STRIP_RE.sub("", ln[j:]).strip(" -—").rstrip(";. ").strip()
                codes = _codes_before_quote(ln)
                thr, exc = _split_exception(thr)
                if codes and thr:
                    rows.append({"codes": codes, "names": _quoted_names(left),
                                 "threshold": thr, "exception": exc, "note": note})
            elif _AMEND_STRIP_RE.sub("", ln).rstrip().endswith(":"):  # многостроч. (прим.9): «код "имя":» + ступени
                codes = _codes_before_quote(ln)
                names = _quoted_names(ln)
                steps: list[str] = []
                k = i + 1
                while (k < n and lines[k].strip()
                       and not _FLAT_ROW_RE.match(lines[k]) and not _NOTE_HDR_RE.match(lines[k])):
                    if "не менее" in lines[k]:
                        steps.append(_AMEND_STRIP_RE.sub("", lines[k]).strip().rstrip(";. ").strip())
                    k += 1
                if codes and steps:
                    thr, exc = _split_exception("; ".join(steps))
                    rows.append({"codes": codes, "names": names,
                                 "threshold": thr, "exception": exc, "note": note})
                i = k
                continue
        i += 1
    return rows


# --- ⚠ ОБЛАСТЬ ДЕЙСТВИЯ ПРИМЕЧАНИЯ (K2, #47) -------------------------------------------
# Часть примечаний задаёт порог НЕ для подтверждения российского происхождения, а «для целей
# осуществления закупок … для обеспечения государственных и муниципальных нужд». Это ДРУГОЙ вопрос
# и другой порог: у одной позиции они могут различаться, а «Порог:» в ответе означает первое.
#
# ⚠ ЗАМЕР 19.08.2026: 57 позиций корпуса получали закупочный порог как СВОЙ ОБЩИЙ — с настоящей
# ссылкой на первоисточник («не менее 75 баллов [прим. 53]»). Неверный порог с подлинной ссылкой
# опаснее отсутствующего: faithfulness-гард молчит (число дословно), а эксперт видит подтверждение.
# Тот же класс, что утечка порога вверх по иерархии в `_code_applies`: гард проверяет
# заземлённость, а не правильность привязки.
#
# Признак берётся из ТЕКСТА примечания, а не из списка номеров: список устареет на следующей
# редакции, а формулировка живёт в первоисточнике.
_PROCUREMENT_RE = re.compile(r"[Дд]ля целей осуществления закупок")


@lru_cache(maxsize=1)
def _note_scopes() -> dict[str, str]:
    """Номер примечания → 'procurement' | 'general' (по его вводной фразе)."""
    if not _CHUNK.exists():
        return {}
    lines = _CHUNK.read_text(encoding="utf-8").splitlines()
    out: dict[str, str] = {}
    bounds = [(m.group(1), i) for i, ln in enumerate(lines) if (m := _NOTE_HDR_RE.match(ln))]
    for k, (num, i) in enumerate(bounds):
        j = bounds[k + 1][1] if k + 1 < len(bounds) else len(lines)
        head = " ".join(lines[i:j])[:900]
        out.setdefault(num, "procurement" if _PROCUREMENT_RE.search(head) else "general")
    return out


def note_scope(note: str | None) -> str:
    """Область действия примечания. Неизвестное примечание считаем общим — это прежнее поведение."""
    return _note_scopes().get(str(note or ""), "general")


def _segs(code: str) -> list[str]:
    return [s for s in str(code).strip().split(".") if s]


def _code_applies(note_code: str, pos_code: str) -> bool:
    """Применим ли порог примечания к позиции. НАПРАВЛЕНИЕ ПРИНЦИПИАЛЬНО (R8).

    Условие: код примечания — ПРЕДОК ИЛИ РАВЕН коду позиции. Тогда позиция лежит внутри ветки,
    на которую распространяется примечание, и порог к ней относится.

    Раньше матч был симметричным, и порог «утекал» ВВЕРХ по иерархии — примечание для узкого кода
    применялось ко всей группе. Живые последствия: «Система электродвижения» (27.11) получала порог
    «Детандер-генераторов жидкостных для СПГ» (27.11.32.120); «Обувь с верхом из текстильных
    материалов» (15.20.14) — порог «Обуви валяной» (15.20.14.130). Число дословно из первоисточника,
    поэтому faithfulness-гард молчит: он проверяет заземлённость, а не правильность привязки.
    Порог — самый дорогой факт продукта, поэтому здесь лучше не показать, чем показать чужой."""
    n, p = _segs(note_code), _segs(pos_code)
    return bool(n) and len(n) <= len(p) and p[:len(n)] == n


def _name_overlap(product_name: str | None, names: list[str]) -> int:
    pt = set(re.findall(r"\w{4,}", _norm(product_name)))
    return max((len(pt & set(re.findall(r"\w{4,}", _norm(nm)))) for nm in names), default=0)


def _fmt_flat(r: dict, group: bool = False) -> str:
    out = f"{r['threshold']} [прим. {r['note']}]" if r.get("note") else r["threshold"]
    if r.get("exception"):
        # Отдельной строкой и ВСЕГДА с условием: график без своего условия и есть неверный ответ
        # (тот же принцип, что у закупочного порога). Отступ повторяет отступ строки «Порог:»
        # в `format_context`, поэтому в контексте это читается как её продолжение, а не как
        # вторая величина того же графика.
        out += ("\n    ⚠ ИНОЙ порог — " + r["exception"])
    if group:
        # Порог задан для ветки-предка, а не для самой позиции: показываем, но честно называем
        # уровень — иначе групповой порог читается как собственный порог позиции.
        out += (f" — порог задан для группы кодов {', '.join(r['codes'])}; "
                f"проверьте применимость к вашей позиции по первоисточнику")
    return out


def lookup_threshold(codes: list[str], product_name: str, section: str | None = None) -> str | None:
    """ОБЩИЙ порог позиции из примечаний (для подтверждения российского происхождения), либо None.

    ⚠ Закупочные примечания сюда НЕ входят — см. `_note_scopes`. Их порог отдаёт
    `lookup_procurement_threshold`, и показывать его надо ВМЕСТЕ с условием, при котором он читается."""
    return _lookup(codes, product_name, section, "general")


def lookup_procurement_threshold(codes: list[str], product_name: str,
                                 section: str | None = None) -> str | None:
    """Порог «для целей осуществления закупок» — ДРУГОЙ вопрос и другой ответ, чем `lookup_threshold`."""
    return _lookup(codes, product_name, section, "procurement")


def _lookup(codes: list[str], product_name: str, section: str | None, scope: str) -> str | None:
    """Порог по годам для позиции (из примечаний), либо None. Матч по НАИМЕНОВАНИЮ в рамках раздела
    (у одного кода бывают строки «общая категория» и «конкретный продукт» — имя различает)."""
    name = _norm(product_name)
    # 1) таблицы-пороги по годам (прим.77 и т.п.) — матч по НАИМЕНОВАНИЮ
    if name:
        tables = _tables()
        for t in tables:  # точный матч имени в нужном разделе
            if section and t["section"] != section:
                continue
            if note_scope(t["note"]) != scope:
                continue
            for r in t["rows"]:
                if _norm(r["name"]) == name:
                    return _fmt(r, t["note"], t["section"])
        if section is None:
            # Матч имени без ограничения раздела — ТОЛЬКО когда раздел неизвестен (R8). Раньше этот
            # проход выполнялся всегда, и одноимённая позиция из ДРУГОГО раздела могла отдать свой
            # порог. Сейчас на корпусе это не срабатывает, но защита нужна: данные меняются.
            for t in tables:
                if note_scope(t["note"]) != scope:
                    continue
                for r in t["rows"]:
                    if _norm(r["name"]) == name:
                        return _fmt(r, t["note"], t["section"])
    # 1б) ТАБЛИЦЫ, ПРИВЯЗАННЫЕ ПО КОДУ (K2, #47). Часть примечаний-таблиц раздела не называет
    #     (прим. 38 радиоэлектроника, 81/28/33 медизделия), поэтому матч по имени в рамках раздела
    #     до них не доходил, а сами таблицы прежде даже не разбирались. У них есть КОДЫ — привязка
    #     по коду надёжнее имени: наименование в примечании и в приложении расходится формулировкой.
    #     ⚠ Направление то же, что в `_code_applies`: код примечания — предок ИЛИ равен коду позиции.
    #     Порог не «утекает» вверх по иерархии; при неоднозначности разрешаем по наименованию и,
    #     если оно не различает, НЕ ГАДАЕМ — лучше не показать, чем показать чужой порог.
    if codes:
        tcands: list[tuple[dict, dict, bool]] = []   # (таблица, строка, точное ли совпадение кода)
        for t in _tables():
            if note_scope(t["note"]) != scope:
                continue
            for r in t["rows"]:
                exact = None
                for c in codes:
                    for rc in r["codes"]:
                        if _code_applies(rc, c):
                            exact = bool(exact) or (_segs(rc) == _segs(c))
                if exact is not None:
                    tcands.append((t, r, exact))
        if len(tcands) == 1:
            t, r, _ = tcands[0]
            return _fmt(r, t["note"], t["section"])
        if len(tcands) > 1:
            best = max(tcands, key=lambda x: (_name_overlap(product_name, [x[1]["name"]]), x[2]))
            if _name_overlap(product_name, [best[1]["name"]]) >= 2:
                t, r, _ = best
                return _fmt(r, t["note"], t["section"])

    # 2) простые пороги-списки (прим. 7/11/31/52/53…) — матч по КОДУ; при неоднозначности (у кода
    #    несколько строк с разными порогами) разрешаем по наименованию, иначе НЕ гадаем.
    if codes:
        cands: list[tuple[dict, bool]] = []  # (строка примечания, точное ли совпадение кода)
        for r in _flat_thresholds():
            if note_scope(r.get("note")) != scope:
                continue
            exact = None
            for c in codes:
                for rc in r["codes"]:
                    if _code_applies(rc, c):
                        exact = bool(exact) or (_segs(rc) == _segs(c))
            if exact is not None:
                cands.append((r, exact))
        if len(cands) == 1:
            row, is_exact = cands[0]
            return _fmt_flat(row, group=not is_exact)
        if len(cands) > 1:
            # ⚠ ТОЧНОЕ СОВПАДЕНИЕ ИМЕНИ РЕШАЕТ СРАЗУ. Правило «пересечение ≥2 слов» слепо к
            # ОДНОСЛОВНЫМ наименованиям: «Ледоколы», «Буровые суда», «Суда снабжения» названы в
            # прим. 17 поимённо, но давали пересечение 1 и отбрасывались — а код 30.11.33.190
            # делят несколько строк примечания, и позиция оставалась без порога при том, что он
            # написан прямо для неё. Сноски у имени («Ледоколы <9>») снимаем перед сравнением.
            exact_name = [rc for rc in cands
                          if any(_norm(_strip_fn(nm)) == _norm(_strip_fn(product_name))
                                 for nm in rc[0]["names"])]
            if len(exact_name) == 1:
                row, is_exact = exact_name[0]
                return _fmt_flat(row, group=not is_exact)
            # При равном пересечении имён точное совпадение кода приоритетнее группового.
            row, is_exact = max(cands, key=lambda rc: (_name_overlap(product_name, rc[0]["names"]), rc[1]))
            if _name_overlap(product_name, row["names"]) >= 2:
                return _fmt_flat(row, group=not is_exact)
    return None
