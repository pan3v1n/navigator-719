"""Второй сигнал «вне сферы 719» — по классу ОКПД2, а не по близости векторов.

ЗАЧЕМ. Out-of-scope guard построен на одном сигнале: чистый dense-косинус top-1 ниже
`RELEVANCE_SOFT`. Замер 16.08.2026 показал, что этот сигнал исчерпан — полоса перекрытия
расширилась с 14 тысячных до 44:

    было (калибровка):  вне-719 ≤ 0.822   ·   in-scope ≥ 0.808
    стало (замер):      вне-719 ≤ 0.852   ·   in-scope ≥ 0.808

Пять негативов из 36 проходят порог: разведение КРС (0.844), утилизация отходов (0.840),
монтаж вентиляции (0.833), грузоперевозки (0.830), косметика (0.852). Крутить сам порог нельзя:
набора пограничных in-scope нет, и ужесточение легко превращается в ложные отказы — гайд об этом
предупреждает прямо («guard пережат — перекалибровать, а не радоваться цифре»).

ИДЕЯ. Приложение к 719 покрывает ровно 20 классов ОКПД2 (13–32 и 42) — это обрабатывающая
промышленность. Сельское хозяйство (01), обращение с отходами (38), транспортные услуги (49),
строительство (43) в нём отсутствуют КОНСТРУКТИВНО, а не случайно. Классификатор ОК 034-2014
у нас уже есть целиком (19 200 строк), и подобрать по наименованию класс — детерминированная
операция без сети и модели.

ПОЧЕМУ ЕДИНОГЛАСИЕ, А НЕ TOP-1. Лексический подбор по названию иногда мажет: «декоративная
косметика» цепляется за «23.41.9 изделия керамические», а этот класс в 719 есть. Требование
«ВСЕ кандидаты вне покрытия» отсекает такие случайности: на замере оно ловит КРС, отходы и
грузоперевозки (3 из 5), не трогая ни один профильный запрос и ни один неоднозначный
(«монтаж вентиляции» даёт и 43.22, и 28.25 — единогласия нет, флаг не поднимается).

ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он только ПОДНИМАЕТ флаг, никогда не снимает: решение «вне сферы»
по-прежнему принимает модель по смыслу контекста (правило 1б промпта). Ошибка сигнала стоит
лишней осторожности в ответе, а не отказа.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from app.rag import okpd2_ref

_STRUCT = Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719" / "structured"

# Сколько кандидатов классификатора требуют единогласия. Больше — строже к сигналу (реже флаг).
SUGGEST_K = 3


@lru_cache(maxsize=1)
def divisions_in_719() -> frozenset[str]:
    """Классы ОКПД2 (первые два знака), встречающиеся в приложении к 719.

    Считается из корпуса, а НЕ из константы: приложение правится несколько раз в год, и
    зашитый список молча устареет — та же ошибка, из-за которой ссылка на первоисточник
    отстала на две редакции (см. `app/rag/edition.py`)."""
    out: set[str] = set()
    try:
        for f in sorted(_STRUCT.glob("*.json")):
            for rec in json.loads(f.read_text(encoding="utf-8")):
                for code in rec.get("okpd2_codes") or []:
                    head = str(code).strip().split(".")[0]
                    if head.isdigit():
                        out.add(head)
    except (OSError, json.JSONDecodeError):
        return frozenset()  # корпуса нет — сигнал просто не работает, гард остаётся прежним
    return frozenset(out)


def out_of_scope_by_classifier(query: str, k: int = SUGGEST_K) -> bool:
    """True — по классификатору ОКПД2 запрос ЕДИНОГЛАСНО ведёт в класс, которого нет в 719.

    Пусто/нет совпадений → False: молчание сигнала не означает «вне сферы»."""
    divisions = divisions_in_719()
    if not divisions:
        return False
    sugg = okpd2_ref.suggest_okpd2_by_name(query, k=k)
    if not sugg:
        return False
    return all(str(code).split(".")[0] not in divisions for code, _name, _score in sugg)


def classifier_divisions(query: str, k: int = SUGGEST_K) -> list[str]:
    """Классы, в которые классификатор относит запрос (для логов и объяснимости)."""
    return [str(c).split(".")[0] for c, _n, _s in okpd2_ref.suggest_okpd2_by_name(query, k=k)]
