"""Тематический роутер процедурной ветки: шесть намерений вместо одного (K12, issue #45).

ЗАЧЕМ. `procedural.is_procedural` отвечает на ОДИН вопрос — «товар или процедура». Внутри
«процедуры» намерений минимум шесть, и они требуют разных пунктов и разных оговорок:

  • `documents`      — какие документы собрать (кластер жалоб №1 июля, 31 упоминание);
  • `deadlines`      — сроки рассмотрения, доработка, отказ, обжалование;
  • `registry_entry` — порядок внесения, подача через ГИСП, реестровая запись, выписка;
  • `st1_origin`     — путь СТ-1 и страна происхождения (вторая претензия июля, 29 упоминаний);
  • `criteria`       — критерии подтверждения производства (пункт 1 и подпункты постановления);
  • `classification` — как классифицировать продукцию, что означает сноска приложения.

До K12 все шесть обслуживались одним промптом и одним окном: ответ про сроки строился теми же
правилами, что ответ про состав документов, а квота K10 знала только ДОКУМЕНТ (`rules_topic`), но
не НАМЕРЕНИЕ. Разница видна на данных: «сроки рассмотрения» устанавливают Правила ведения реестра,
«состав документов» — раздел 4 Приказа №52, «подпункт г» — тело постановления.

ПОЧЕМУ РЕГУЛЯРКИ, А НЕ МОДЕЛЬ. Ровно по той же причине, что и `procedural`/`meta`: маршрутизация
обязана быть детерминированной и бесплатной. Каждый лишний вызов модели на горячем пути — точка
отказа на рваной сети и удар по детерминизму, а свип по реальным вопросам показывает, что тем
хватает шести и они различаются лексикой.

⚠ ПРАВИЛА ЖИВУТ В ОДНОМ МЕСТЕ. Тема `documents` не заводит своих шаблонов — она спрашивает
`retriever.asks_document_list`, тот же детектор, которым P2 добирает раздел 4 Приказа №52. Вторая
копия правил разошлась бы с первой при первой же правке (в этом проекте так уже было с адресом
первоисточника).
"""

