def classify(query: str) -> str | None:
    """Тема процедурного вопроса либо None, если ни одно намерение не распознано.

    None — нормальный результат, а не сбой: тогда работает общий процедурный промпт и квота по
    `rules_topic`. Придумывать тему «на всякий случай» опаснее, чем не иметь её: фрагмент промпта
    задаёт оговорки, и не та тема даст не те оговорки.

    ⚠ ПРИОРИТЕТ ВЫШЕ ЧИСЛА СОВПАДЕНИЙ, и это стоило первой версии 0.71 на свипе. Считая
    совпадения, «Какие документы нужны для внесения в реестр Минпромторга» уходило в
    `registry_entry`: там срабатывали два шаблона («внесение в реестр», «Минпромторг») против
    одного у `documents`. Но намерение вопроса — СОСТАВ ДОКУМЕНТОВ, а «для внесения в реестр» лишь
    называет цель. Общее правило: чем УЖЕ намерение, тем оно важнее — «какие документы для X» и
    «сколько времени на X» конкретнее, чем «как сделать X»."""
    from app.rag.retriever import asks_document_list

    q = query or ""
    matched = {t for t, pats in _PATTERNS.items() if any(p.search(q) for p in pats)}
    if asks_document_list(q):
        matched.add("documents")
    for topic in TOPICS:            # TOPICS упорядочен от самого узкого намерения к самому общему
        if topic in matched:
            return topic
    return None


def doc_types(topic: str | None) -> tuple[str, ...]:
    """Документы корпуса, приоритетные для темы (пусто — решает общий `rules_topic`)."""
    return _DOC_TYPES.get(topic or "", ())


def fragment(topic: str | None) -> str:
    """Фрагмент промпта под тему (пусто — общий процедурный промпт без добавок)."""
    return _FRAGMENTS.get(topic or "", "")
