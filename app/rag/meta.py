"""Базовые (meta) ответы: приветствие, «что умеешь», «как работать», помощь, благодарность.

Такие реплики НЕ про продукцию 719 — обычный RAG вернул бы «ближайший мусор». Ловим их
ДЕТЕРМИНИРОВАННО (регулярки, без LLM) и отвечаем заготовкой. Приоритет в pipeline.answer:
meta → процедурный дефер → поиск. Гейт от ложных срабатываний: если в запросе есть код ОКПД2 —
это товарный вопрос, meta не применяем.
"""

from __future__ import annotations

import re

_CODE_RE = re.compile(r"\b\d{2}\.\d{2}(?:\.\d+)*\b")

_GREETING = re.compile(
    r"^(привет\w*|здравствуй\w*|добр(ый|ое) (день|вечер|утро)|хай|hello|hi|доброе утро)\b", re.I
)
_CAPABILITIES = re.compile(
    r"что (ты )?(умеешь|можешь|знаешь|делаешь)|тво(и|й) возможност|чем (ты )?(можешь )?помоч|"
    r"для чего ты|кто ты( такой| такое)?|что ты (такое|за|умеешь)|зачем ты|о чём ты|о чем ты",
    re.I,
)
_HOWTO = re.compile(
    r"как (с тобой )?(работать|пользоваться)|как (задавать|задать|формулировать) (тебе )?вопрос|"
    r"как (тебя |это |с тобой )?использовать|как ты работаешь|как это работает|как начать|"
    r"с чего начать|как (мне )?(тут |здесь )?(спрашивать|искать)",
    re.I,
)
_THANKS = re.compile(r"^(спасибо\w*|благодар\w+|спс|thanks|thx)\b", re.I)

HELP = (
    "Я — ассистент по Постановлению Правительства РФ №719 (подтверждение производства "
    "промышленной продукции в России). Помогаю сориентироваться по приложению к 719.\n\n"
    "**Что я умею:**\n"
    "- найти позицию приложения по вашей продукции или коду ОКПД2;\n"
    "- показать требования к локализации и баллы (порог) по найденной позиции;\n"
    "- перевести код ТН ВЭД в ОКПД2 и обратно (по официальному переходному ключу);\n"
    "- дать ссылки на источник в тексте ПП №719;\n"
    "- ответить на процедурные вопросы (внесение в реестр, ГИСП, состав документов, сроки) — по Правилам "
    "ведения реестра, телу ПП №719 и Приказу ТПП РФ №52;\n"
    "- подсказать путь в реестр для продукции вне приложения 719 — через сертификат СТ-1;\n"
    "- честно предупредить, когда продукция вне сферы ПП №719.\n\n"
    "**Как задать вопрос:**\n"
    "- опишите продукцию своими словами — например «производим гидравлические насосы»;\n"
    "- или укажите код ОКПД2 («28.13.14»); можно и код ТН ВЭД из сертификата — переведу в ОКПД2;\n"
    "- уточняйте по ходу в том же чате: «а какой порог?», «а какие операции?» — я помню контекст беседы.\n\n"
    "Я даю предварительную навигацию — окончательное решение принимает уполномоченный эксперт ТПП; "
    "по важным значениям сверяйтесь с первоисточником по ссылке под ответом."
)

GREETING = (
    "Здравствуйте! Я ассистент по ПП №719. Опишите продукцию или укажите код ОКПД2 — "
    "подскажу позицию приложения, требования и баллы. Спросите «что ты умеешь» — расскажу подробнее."
)

THANKS = "Пожалуйста. Если нужно — спрашивайте по другой продукции или коду ОКПД2."


def is_meta(query: str) -> bool:
    """True — это приветствие/вопрос о возможностях/как работать/благодарность (не про продукцию)."""
    q = (query or "").strip()
    if _CODE_RE.search(q):  # есть код ОКПД2 → товарный вопрос
        return False
    return bool(
        _CAPABILITIES.search(q) or _HOWTO.search(q) or _GREETING.search(q) or _THANKS.search(q)
    )


def response(query: str) -> str:
    """Заготовленный ответ под тип реплики."""
    q = (query or "").strip()
    if _CAPABILITIES.search(q) or _HOWTO.search(q):
        return HELP
    if _THANKS.search(q):
        return THANKS
    return GREETING
