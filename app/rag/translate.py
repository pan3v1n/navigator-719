"""Детерминированный перевод кодов ТН ВЭД↔ОКПД2 по прямому запросу (T9).

Навигатор (LLM) намеренно отвечает СТРОГО по приложению к ПП №719 и не знает о переходных
ключах — поэтому на прямой вопрос «переведи код» / «умеешь переводить ОКПД2» он раньше
ОТКАЗЫВАЛ («это не моя функция»), хотя данные для перевода в проекте есть. Здесь ловим такой
запрос ДЕТЕРМИНИРОВАННО и отвечаем из справочника `okpd2_ref` (те же официальные переходные
ключи, что и в ретриве) — без LLM, без риска выдумать код.

Гейт КОНСЕРВАТИВЕН: обычные товарные вопросы (в т.ч. «какой ОКПД2 у насоса», где код нужно
подобрать по наименованию, или «подпадает ли под 719 продукция с ТН ВЭД …», где код — лишь буст
ретрива) сюда НЕ попадают — их обрабатывает обычный пайплайн. Перехватываем только запрос
именно на перевод КОДА в КОД (или вопрос о самой такой возможности).
"""
from __future__ import annotations

import re

from app.rag import okpd2_ref

# Код ОКПД2 в тексте (та же форма, что в meta): «28.13» / «28.13.14.190».
# Код ОКПД2 разбирает `okpd2_ref` — одно место на весь проект (ревью PR #94).

_TNVED_MENTION = re.compile(r"тн\s*вэд|тнвэд", re.I)
_OKPD_MENTION = re.compile(r"окпд", re.I)
# Глаголы перевода/сопоставления кодов.
_VERB = re.compile(r"перевед|переводи|перевод|конверт|сопоставл", re.I)
# Явно названное целевое направление.
_TO_OKPD2 = re.compile(r"в\s+окпд|->\s*окпд|→\s*окпд|какой\s+(?:код\s+)?окпд", re.I)
_TO_TNVED = re.compile(r"в\s+тн\s*вэд|->\s*тн|→\s*тн|какой\s+(?:код\s+)?тн\s*вэд", re.I)
# Признак вопроса «умеешь ли / можно ли» (без конкретного кода).
_CAP_ASK = re.compile(r"умеешь|умеете|можешь|можете|можно ли|способ\w+|как\s+переве", re.I)


def is_translate(query: str) -> bool:
    """True — это запрос на ПЕРЕВОД кода между классификаторами (или вопрос о такой возможности).

    Не срабатывает на товарных вопросах: «какой ОКПД2 у насоса» (подбор кода по наименованию),
    «требования к 28.13.14», «подпадает ли ТН ВЭД 8471 30 под 719» — там нет намерения ПЕРЕВЕСТИ
    один код в другой, это обрабатывает навигатор."""
    q = query or ""
    tnved_code = okpd2_ref.extract_tnved(q) is not None
    okpd_code = okpd2_ref.has_okpd2_code(q)
    tn = bool(_TNVED_MENTION.search(q))
    ok = bool(_OKPD_MENTION.search(q))
    verb = bool(_VERB.search(q))

    # Дан код ТН ВЭД и явно просят/упоминают ОКПД (или глагол перевода) — перевод ТН ВЭД→ОКПД2.
    if tnved_code and (ok or verb or _TO_OKPD2.search(q)):
        return True
    # Дан код ОКПД2 и явно просят ТН ВЭД — перевод ОКПД2→ТН ВЭД.
    if okpd_code and tn and (verb or _TO_TNVED.search(q)):
        return True
    # Вопрос о самой возможности перевода между классификаторами (кода не дали).
    if verb and tn and ok:
        return True
    if verb and (tn or ok) and _CAP_ASK.search(q):
        return True
    return False


def _tnved_to_okpd(tnved: str) -> str:
    codes = okpd2_ref.tnved_to_okpd2(tnved)
    if not codes:
        return (
            f"По коду ТН ВЭД {tnved} соответствие в переходном ключе ТН ВЭД↔ОКПД2 не нашлось. "
            "Проверьте код (обычно 10 знаков, например «8471 30 000 0») или назовите наименование "
            "продукции — тогда поищу позицию в приложении к ПП №719."
        )
    lines = []
    for c in codes:
        name = okpd2_ref.okpd2_name(c)
        lines.append(f"- ТН ВЭД {tnved} → ОКПД2 {c}" + (f" — {name}" if name else ""))
    body = "\n".join(lines)
    return (
        f"**Перевод ТН ВЭД в ОКПД2 (по переходному ключу):**\n{body}\n\n"
        "Соответствие предварительное, по официальному переходному ключу (ключи заданы на 6-значном "
        "уровне ГС): у одного кода ТН ВЭД бывает несколько кодов ОКПД2 — сверьте наименование и при "
        "необходимости уточните.\n\n"
        "Хотите, проверю эту продукцию по приложению к ПП №719 (требования локализации и баллы)? "
        "Назовите нужный код ОКПД2 или наименование."
    )


def _okpd_to_tnved(okpd: str) -> str:
    tns = okpd2_ref.okpd2_to_tnved(okpd)
    name = okpd2_ref.okpd2_name(okpd)
    head = f"ОКПД2 {okpd}" + (f" ({name})" if name else "")
    if not tns:
        return (
            f"Для кода {head} прямого соответствия в переходном ключе ОКПД2→ТН ВЭД не нашлось "
            "(ключи заданы не для всех кодов). Уточните код или назовите продукцию — посмотрю "
            "позицию в приложении к ПП №719."
        )
    return (
        "**Перевод ОКПД2 в ТН ВЭД (по переходному ключу):**\n"
        f"- {head} → ТН ВЭД {', '.join(tns)}\n\n"
        "Соответствие предварительное, по официальному переходному ключу; при таможенном оформлении "
        "сверьте по действующей ТН ВЭД ЕАЭС.\n\n"
        "Хотите, посмотрю требования по этой продукции в приложении к ПП №719?"
    )


def _capability() -> str:
    return (
        "Да, перевод кода между классификаторами по официальному переходному ключу я делаю:\n"
        "- ТН ВЭД в ОКПД2 — например «переведи ТН ВЭД 8471 30 000 0 в ОКПД2»;\n"
        "- ОКПД2 в ТН ВЭД — например «какой ТН ВЭД у ОКПД2 26.20.11».\n\n"
        "Назовите код — верну соответствие (предварительно: у одного кода бывает несколько "
        "соответствий, стоит сверить) и при необходимости проверю продукцию по приложению к ПП №719."
    )


def answer(query: str) -> str:
    """Готовый текст ответа на запрос перевода. Вызывать только если `is_translate(query)`."""
    q = query or ""
    tnved = okpd2_ref.extract_tnved(q)
    _codes = okpd2_ref.extract_codes(q)
    okpd = _codes[0] if _codes else None

    # Явно просят ТН ВЭД по коду ОКПД2 → обратное направление.
    if okpd and (_TO_TNVED.search(q) or (not tnved and _TNVED_MENTION.search(q))):
        return _okpd_to_tnved(okpd)
    # Есть код ТН ВЭД → прямое направление.
    if tnved:
        return _tnved_to_okpd(tnved)
    # Есть только код ОКПД2, направление не названо → по умолчанию в ТН ВЭД.
    if okpd:
        return _okpd_to_tnved(okpd)
    # Кода не дали — рассказываем о возможности.
    return _capability()
