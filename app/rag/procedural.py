"""Детектор процедурного интента — маршрутизатор на корпус процедурных норм.

Товарные записи (требования локализации и баллы) и процедурные нормы живут в РАЗНЫХ коллекциях:
`pp719` — приложение к ПП №719, `pp719_rules` — Правила формирования и ведения реестра + ТЕЛО
ПП №719 (критерии п.1, включая СТ-1) + Приказ ТПП РФ №52 (состав документов, сроки, акт на
компоненты). У них разные промпты и разные гарды, поэтому вопрос надо развести ДО поиска.

Без детектора чистый процедурный вопрос («какой порядок внесения в реестр») уходит в товарный
поиск → возвращаются ближайшие ТОВАРНЫЕ позиции (мусор) → LLM может «сочинить» порядок действий
и сроки. Здесь мы ловим процедурный интент ДЕТЕРМИНИРОВАННО (регулярками, без LLM) и уводим
вопрос на корпус Правил: ноль стоимости на маршрутизацию, воспроизводимо.

ИСТОРИЯ И ТЕКУЩАЯ РОЛЬ `DEFLECTION`. Изначально (до индексации Правил) детектор короткозамыкал
ответ честным дефером — «процедуру не знаю, вот первоисточники». Теперь корпус загружен, и дефер
остался ФОЛБЭКОМ внутри `pipeline._answer_procedural`: срабатывает, только если корпус выключен
флагом `PROCEDURAL_ANSWER_FROM_RULES`, коллекции нет или поиск ничего не вернул. Порядок действий
и сроки не выдумываем ни при каких условиях.

Дисциплина ложных срабатываний: детектор бьёт только по ЧИСТО процедурным вопросам. Если в
запросе есть код ОКПД2 или явный товарно-балльный сигнал («требования к локализации», «сколько
баллов») — это товарный или СМЕШАННЫЙ вопрос, его НЕ деферим (отвечаем по базе; про процедурную
часть модель предупредит по правилу 1в промпта навигатора).
"""

from __future__ import annotations

import re

# --- Маркеры ПРОЦЕССА (внесение/подача/сроки/обжалование/ведомство), а не продукта. -------
# Осознанно НЕ триггерим на одиночные «реестр»/«документы»/«требования» — они встречаются и в
# нормальных товарных вопросах («требования к локализации насосов для внесения в реестр»).
#
# Два тира, чтобы не хватать вне-719 админ-вопросы («как зарегистрировать ИП», «порядок получения
# загранпаспорта»): STRONG — самодостаточные маркеры регистра 719 (ГИСП/внесение в реестр/…);
# GENERIC — общие процедурные глаголы (порядок получения/как оформить/сроки), которые триггерят
# ТОЛЬКО при наличии 719-ЯКОРЯ (реестр/промышленная продукция/ГИСП/Минпромторг/заявление). Вне-719
# админ-вопросы без якоря уходят в обычный отказ «вне сферы 719» (правило 1б), а не в этот дефер.
_STRONG_PATTERNS = [
    r"\bгисп\b",
    r"минпромторг",
    # ⚠⚠ ОДИН ШАБЛОН НА ВСЕ ФОРМЫ, И ЭТО ИСПРАВЛЕНИЕ АСИММЕТРИИ (`K15-1` #120).
    # Здесь стояли ТРИ строки с РАЗНЫМИ правилами разрыва: у отглагольного существительного
    # («внесение … в реестр») разрыв был запрещён вовсе, у глагола («внести его в реестр») —
    # разрешён до четырёх слов. Дефект и был в этой разнице: «нужно ли заключение ТПП для
    # ВНЕСЕНИЯ ПРОДУКЦИИ В РЕЕСТР» не проходило маркер из-за одного слова, уходило товарной
    # веткой, не получало закрытый справочник документов и утверждало несуществующий документ
    # (3 прогона из 3). Тем же промахом страдали «откажут во ВНЕСЕНИИ ИЗМЕНЕНИЙ в реестр» и
    # «заявка на ВКЛЮЧЕНИЕ СВЕДЕНИЙ в реестр» — оба из приёмочного набора `K9`.
    # ⚠ Ровно этот случай уже был разобран и починен в `topics.py` (разрыв до трёх слов, с
    # комментарием про реальный вопрос волны) — и не переехал через модуль. Урок живёт рядом с
    # местом, где его выучили, и при правке соседа не ищется.
    # Ложные срабатывания держит не узость шаблона, а `_PRODUCT_HINT_RE`: «требования к
    # локализации насосов для внесения в реестр» уводит на товарный путь словом «требования».
    r"(?:внесени|включени|внести|включит)\w*(?:\s+\S+){0,4}\s+в\s+реестр",
    r"реестр\w*\s+(?:российской\s+)?промышленной\s+продукции",
    r"заявлени\w*\s+(?:о\s+)?(?:внесени|включени)",
    r"отказ\w*\s+во?\s+(?:внесени|включени)",
    r"пода(?:ть|ча|чи|чу)\s+заяв(?:ку|ки|ление|ления)",
    r"выдач\w*\s+заключени",
    r"как\s+получить\s+заключени\w*\s+о\s+производств",
    # документы подтверждения производства — процедурные по своей сути (порядок выдачи по Приказу №52).
    # \w* — чтобы ловить склонения: «акта/акте/актом экспертизы», а не только именительный «акт».
    r"акт\w*\s+экспертизы",
    r"акт\w*\s+о\s+проведении\s+оценки",
    # ⚠⚠ ПРЕДЛОГ «о» НЕОБЯЗАТЕЛЕН — ТРЕТИЙ СЛУЧАЙ КЛАССА `K15-1` #120 (замер 31.08.2026).
    # Здесь стояло `сертификат\w*\s+о\s+происхождени`, а в `topics.py` тот же термин давно
    # записан с необязательным предлогом и комментарием «без предлога — так пишут В ПОЛОВИНЕ
    # РЕАЛЬНЫХ ВОПРОСОВ». Урок снова не переехал через модуль, и цена видна на одном слове:
    # «срок действия сертификата О происхождении» шло процедурной веткой, «срок действия
    # сертификата происхождения» — товарной. Разница не в смысле вопроса, а в предлоге.
    r"сертификат\w*\s+(?:о\s+)?происхожден",
    r"срок\w*\s+действия\s+акт",
]
_GENERIC_PATTERNS = [
    r"порядок\s+(?:подач|внесени|включени|рассмотрени|получени|оформлени|регистрац)",
    r"как\s+(?:внести|включить|подать|оформить|зарегистрировать)\b",
    r"срок\w*\s+рассмотрени",
    r"в\s+течение\s+скольких\s+(?:дней|рабочих)",
    r"обжалов",
    # документы: собрать/подготовить/представить/подать/нужны (0-2 слова между «документы» и глаголом,
    # чтобы ловить «какие документы НУЖНО СОБРАТЬ»); + «перечень/состав/комплект документов». GENERIC —
    # срабатывает ТОЛЬКО с 719-якорем (реестр/заявление/ГИСП/…), поэтому вне-719 «документы» не задевает.
    r"какие\s+документы(?:\s+\w+){0,2}\s+(?:собра\w*|подгото\w*|представ\w*|пода|нужн\w*|необходим\w*|требу\w*)",
    r"(?:перечень|состав|список|комплект|пакет)\s+документ",
]
# 719-якорь для GENERIC-маркеров (без него общий глагол = не наш процедурный вопрос).
_ANCHOR_PATTERNS = [
    r"реестр",
    r"промышленной\s+продукции",
    r"\bгисп\b",
    r"минпромторг",
    r"заявлени\w*",
    r"заявк\w*",
    r"заключени\w*\s+о\s+производств",
    r"подтвержд\w*\s+производств",
    # ⚠⚠ ТПП В СПИСКЕ 719-ЯКОРЕЙ НЕ БЫЛО (`P3` #121). Список называл ГИСП и Минпромторг — и
    # пропускал организацию, ради которой построен весь сервис и которая выдаёт оба
    # подтверждающих документа. Это не патч под конкретный вопрос: пробел того же рода, что
    # отсутствие «Минпромторга» было бы.
    r"\bТПП\b|торгово-промышленн\w*\s+палат\w*",
    # Страна происхождения — критерий подпункта «г» пункта 1, то есть 719-понятие, а не общая
    # лексика. Берём в связке с товаром/продукцией/сырьём: голое «происхождение» слишком широко.
    r"стран\w*\s+происхожден|происхожден\w*\s+(?:товар|продукц|сырь)",
    # ⚠⚠ СЛОВАРЬ ВТОРОГО КЛЮЧА (`K14` #35, замер 31.08.2026). Ни «СТ-1», ни «ТН ВЭД» не
    # встречались в этом модуле НИ РАЗУ — ни маркером, ни якорем, — при том что `topics.py`
    # знает оба. Итог замера: 19 из 19 вопросов по СТ-1/ТН ВЭД уходили ТОВАРНОЙ веткой, где нет
    # ни Соглашения СНГ, ни Приказа ТПП №14. Пять вопросов с темой `st1_origin` в приёмочных
    # наборах проходили по СЛУЧАЙНЫМ причинам (ГИСП, Минпромторг, ТПП, «страна происхождения»,
    # «подпункт г») — и создавали видимость покрытия: голое «как получить СТ-1» было товарным.
    r"\bст-?1\b",
    # ⚠⚠ «ТН ВЭД» ЯКОРИТ ТОЛЬКО РЯДОМ С ПРЕДМЕТОМ ВТОРОГО КЛЮЧА (находки MED-4 и MED-5 третьего
    # раунда ревью PR #137 — у них ОДИН корень). Голым якорем он лицензировал любой GENERIC-глагол,
    # а ТН ВЭД — ТАМОЖЕННЫЙ классификатор, живущий далеко за пределами 719:
    #   «порядок оформления таможенной декларации по ТН ВЭД 8703»       → процедурный ответ
    #   «порядок получения лицензии на импорт по ТН ВЭД 8703 21»        → процедурный ответ
    # синтезированные из Правил и Приказа №14. ⚠ У процедурной ветки НЕТ гейта вне-сферы, а в
    # `eval_golden_negative.json` ноль вопросов с ТН ВЭД — свип этот класс не видел вовсе.
    # Второй симптом того же корня: путь `T9` (у пользователя ТОЛЬКО код ТН ВЭД, без ОКПД2) уходил
    # процедурной веткой, и перевод ТН ВЭД → ОКПД2 → требования приложения не исполнялся.
    # ⚠ ЦЕНА ИЗМЕРЕНА И ПРИНЯТА: узкий якорь теряет одну формулировку — «укажите ваш код ТН ВЭД,
    # распишите требования» (она пересекается с T9 по слову «требования» и отделима только
    # искусственно). Направление ошибки решило выбор: таможенный вопрос с выдуманным 719-ответом
    # — дефект корректности, вопрос СТ-1 на товарной ветке — дефект полезности.
    # Замер: утечка таможни 3 → 0, путь T9 2 → 0, потеряно вопросов СТ-1 1, вне-сферы 0.
    r"(?:тн\s*вэд|тнвэд)[^.\n]{0,40}"
    r"(?:услови|переработк|обработк|происхожден|перечн|сертификат)"
    r"|(?:услови|переработк|обработк|происхожден|перечн|сертификат)"
    r"[^.\n]{0,40}(?:тн\s*вэд|тнвэд)",
    # Термины Соглашения СНГ. Не общая лексика: так называется критерий, по которому решается
    # страна происхождения, и вне этой темы слова не встречаются. ⚠ «достаточной ОБРАБОТКИ/
    # переработки» — форма САМОГО документа (13 вхождений в корпусном тексте), поэтому
    # альтернатива, а не `переработк` в одиночку.
    r"достаточн\w*\s+(?:обработк|переработк)",
    r"кумулятивн\w*\s+принцип|адвалорн",
]
# P1 (12.08.2026): ссылки на СТРУКТУРУ постановления — тоже процедурный вопрос.
#
# Найдено живым прогоном: «что говорит подпункт г пункта 1 постановления 719» не ловил ни один
# маркер и уходил на ТОВАРНЫЙ путь. В контекст попадали позиции приложения (автомобили,
# медизделия), модель честно писала, что они нерелевантны, и объясняла подпункт «г» ВЕРНО —
# но из собственных знаний, а не из корпуса. То есть ответ по процедуре оказывался НЕ ЗАЗЕМЛЁН,
# а faithfulness-гард этого не ловит: выдумки в числах нет, есть неподтверждённое утверждение.
#
# Класс вопросов частый: подпункт «г» — путь СТ-1 для продукции вне приложения, вторая по частоте
# претензия июльского теста (29 упоминаний).
#
# ⚠ Узко намеренно. «Пункт» и «подпункт» — слова, которыми пестрит и товарная сторона, поэтому
# ловим только явные ссылки на структуру ПОСТАНОВЛЕНИЯ: подпункт с буквой а–д, пункт 1 рядом со
# словом «постановление», формулу «критерии подтверждения производства». Свип по 604 реальным
# вопросам июльского теста: ложных срабатываний на товарных запросах — ноль.
_STRUCTURE_PATTERNS = [
    r"подпункт\w*\s*[«\"']?\s*[а-дА-Д]\b",           # подпункт «г», подпункта д
    r"пункт\w*\s*1\b[^.]{0,40}постановлени",          # пункт 1 ... постановления
    r"постановлени\w*[^.]{0,40}пункт\w*\s*1\b",       # постановления ... пункт 1
    r"критери\w*\s+подтвержд\w*\s+производств",       # критерии подтверждения производства
]
_STRONG_PATTERNS = _STRONG_PATTERNS + _STRUCTURE_PATTERNS

_STRONG_RE = re.compile("|".join(_STRONG_PATTERNS), re.IGNORECASE)
_GENERIC_RE = re.compile("|".join(_GENERIC_PATTERNS), re.IGNORECASE)
_ANCHOR_RE = re.compile("|".join(_ANCHOR_PATTERNS), re.IGNORECASE)


def _has_procedural_marker(q: str) -> bool:
    """STRONG-маркер сам по себе ИЛИ GENERIC-глагол + 719-якорь."""
    return bool(_STRONG_RE.search(q)) or bool(_GENERIC_RE.search(q) and _ANCHOR_RE.search(q))


def _has_routing_topic(q: str) -> bool:
    """Намерение вопроса как сигнал маршрута — вторая половина `P3` #121.

    ⚠⚠ ЗАЧЕМ. Два детектора решали близкие вопросы РАЗНЫМИ словарями: `topics.classify` — «о чём
    спросили», этот модуль — «куда вести». Словарь маршрута оказался беднее, и вопрос получал ТЕМУ,
    не получая ВЕТКИ, на которой тема применяется (фрагмент промпта и квота окна живут на
    процедурном пути). Свипом 26.08.2026: 17 вопросов приёмочных наборов уходили товарной веткой,
    и «как получить выписку из реестра» отвечалось по регистраторам данных рейса.

    ⚠ ПОЧЕМУ ТЕМЕ МОЖНО ВЕРИТЬ — И ТОЛЬКО С 719-ЯКОРЕМ. `topics` не догадка: набор размечен
    руками, а критерий приёмки прямо требует НОЛЬ тем на ТОВАРНЫХ вопросах. Но калиброван он на
    вопросах, которые этот гейт УЖЕ пропустил, — вне-719 он не видел никогда, и первая редакция
    правки это показала: «порядок получения загранпаспорта» получает тему `registry_entry`
    («порядок получения») и уехал бы на процедурную ветку. Ровно тот пример, которым шапка этого
    модуля объясняет, зачем нужны два тира.

    Поэтому тема требует якоря — того же, что и GENERIC-глагол. Замер: пропуски 17 → 11,
    ложных срабатываний на товарных 0 новых, вне-сферы 0.

    ⚠⚠ КРОМЕ `documents` — И ЭТО НЕ ОГОВОРКА, А УСТРОЙСТВО. Тема состава документов ЕДИНСТВЕННАЯ
    работает на ОБЕИХ ветках: ради смешанного вопроса («какие документы нужны для этикетировщиков»)
    и заводилась `K12` — он обязан остаться товарным и получить блок документов ДОПОЛНИТЕЛЬНО к
    требованиям позиции. Пропусти я эту оговорку — смешанный вопрос уехал бы на процедурную ветку
    и потерял требования продукции; первая редакция замера этого не показала, потому что считала
    документные кейсы отдельным классом. Остальные пять тем означают «вопрос про процедуру».
    """
    from app.rag import topics  # отложенный импорт: `topics` тянет retriever → embeddings

    topic = topics.classify(q)
    if topic is None or topic == topics.DOCUMENTS:
        return False
    return bool(_ANCHOR_RE.search(q))

# Товарно-балльный сигнал: если он есть, вопрос про требования конкретной продукции (может быть
# смешанным) → НЕ короткозамыкаем, отвечаем по базе.
_PRODUCT_HINT_RE = re.compile(r"баллов?|локализац|требован\w*", re.IGNORECASE)

# ⚠⚠ ЯВНЫЙ ТОКЕН ВТОРОГО КЛЮЧА — УЗКОЕ ИСКЛЮЧЕНИЕ ИЗ ТОВАРНОГО ДИСКВАЛИФИКАТОРА (`K14` #35).
# Дисквалификатор читает «требования» как «вопрос про требования к продукции по 719». Для второго
# ключа это неверно ровно наоборот: дословное ожидание эксперта из ТЗ — «укажите ваш код ТН ВЭД,
# распишу ТРЕБОВАНИЯ», и требования там берутся из Соглашения СНГ, а не из приложения 719. У
# продукции по подпункту «г» требований приложения может не быть вовсе — она вне приложения.
# ⚠ Уступает только ЯВНЫЙ ТОКЕН (СТ-1 / ТН ВЭД), а не широкая тема `st1_origin`: тема шире и
# ловит «страну происхождения» вообще, а инвариант гейта дырявить настолько нельзя. Замер:
# уступка закрывает +2 вопроса пробника, ложных срабатываний на 191 вопросе наборов НОЛЬ.
_SECOND_KEY_RE = re.compile(r"\bст-?1\b|тн\s*вэд", re.IGNORECASE)

# ⚠⚠ ОДНОЗНАЧНО ТОВАРНЫЕ СИГНАЛЫ — УСТУПКА ИХ НЕ СНИМАЕТ (находка 1 ревью PR #137).
# Первая редакция уступала любому вопросу со словом «ТН ВЭД», и это ломало инвариант `K12`:
# «сколько баллов нужно для 28.22.16.111, код ТН ВЭД 8428 10» уходило ПРОЦЕДУРНОЙ веткой, теряя
# требования позиции, а весь путь `T9` (код ТН ВЭД → ОКПД2 → требования) становился недостижим
# ровно для той формулировки, ради которой строился — когда код взят из сертификата или
# декларации. ⚠ Свип этого не показал: в наборе второго ключа не было НИ ОДНОГО контроля такой
# формы, то есть «0 ложных срабатываний» снова означало «не считаю».
# Различитель выбран ЗАМЕРОМ четырёх вариантов: уступать можно только НЕОДНОЗНАЧНОМУ «требования»
# (они есть и у СТ-1), а «баллы» и «локализация» — понятия балльной модели 719, у второго ключа
# их нет ни в каком виде. Числа: новых пропусков 0, смешанных сломано 0 (было 3); отказ от
# уступки целиком стоил бы 3 пропуска, включая дословные формулировки экспертов.
# ⚠⚠ КОД ОКПД2 — ЧЕРЕЗ `has_okpd2_code`, А НЕ СВОЕЙ РЕГУЛЯРКОЙ (находка 3 второго раунда ревью).
# Первая редакция несла `\b\d{2}\.\d{2}[\d.]*`, и это ловило ДАТУ: «какие требования по ТН ВЭД
# 8403 в редакции от 01.07.2026» уходило на товарную ветку, теряя уступку. Ровно та регрессия,
# ради которой `has_okpd2_code` и написан — у него в шапке стоит «⚠ Не `\d{2}\.\d{2}`: дата в
# вопросе выключала мультитёрн». Хелпер уже импортирован в этом модуле; своя копия правила
# разошлась с оригиналом ровно на том, от чего оригинал защищает.
# ⚠⚠ «719» УБРАН ИЗ ТОВАРНОГО СИГНАЛА (находка MED-4 пятого раунда ревью PR #137). Номер
# постановления появляется в вопросах про СТ-1 ПО ПОСТРОЕНИЮ — путь СТ-1 и описан подпунктом «г»
# пункта 1 этого постановления. Он глушил уступку у самого класса, ради которого `K14` делалась:
#   «какие требования по СТ-1, если продукции нет в приложении 719»  → товарная ветка
#   «какие требования для получения СТ-1 по постановлению 719»        → товарная ветка
# ⚠ Он к тому же оказался ИЗБЫТОЧНЫМ: смешанные вопросы держит узкий якорь раунда 3 («требования»
# не в списке спутников ТН ВЭД), а не этот сигнал. Замер трёх вариантов: без «719» потеряно
# вопросов СТ-1 0, смешанных сломано 0; с ним — 2 потерянных при тех же нулях в другой колонке.
_MIXED_PRODUCT_RE = re.compile(r"баллов?|локализац", re.IGNORECASE)


def _has_mixed_product_signal(q: str) -> bool:
    """Однозначно товарный сигнал: код ОКПД2 либо лексика балльной модели 719."""
    return bool(_MIXED_PRODUCT_RE.search(q)) or has_okpd2_code(q)

# ⚠⚠ ВОПРОС О САМОЙ ПАЛАТЕ — НЕ ВОПРОС О 719. Найдено ревью пакета 26.08.2026 как цена нового
# якоря `ТПП`: «какие документы нужны для вступления в ТПП» проходил GENERIC-глагол плюс этот
# якорь и получал ответ, синтезированный из Правил реестра, вместо честного «вне сферы 719».
# Палата занимается многим помимо подтверждения производства; членство, взносы и аккредитация —
# ровно тот класс вне-719 админ-вопросов, ради которого шапка этого модуля и завела два тира.
# ⚠ Соседство с палатой обязательно: «вступление В СИЛУ постановления» — законный 719-вопрос,
# и запрет по одному слову «вступление» убил бы его.
_CHAMBER_MEMBERSHIP_RE = re.compile(
    r"(?:вступлени\w*|вступит\w*|членств\w*|член\w*|взнос\w*|аккредитац\w*)"
    r"(?:\W+\w+){0,3}\W+(?:ТПП|торгово-промышленн\w*|палат\w*)"
    r"|(?:ТПП|торгово-промышленн\w*\s+палат\w*|палат\w*)"
    r"(?:\W+\w+){0,3}\W+(?:вступлени\w*|членств\w*|взнос\w*)", re.IGNORECASE)

# Код ОКПД2 в тексте запроса («29.20.23») — товарная привязка.
from app.rag.okpd2_ref import has_okpd2_code  # разбор кода — одно место (ревью PR #94)

# Ссылка на СНОСКУ приложения: «сноска 44», «что значит <44>» (D3). Отдельно от прочих маркеров,
# потому что вопрос про сноску почти всегда содержит слово «требование» — а оно уводит на товарный
# путь. Определение сноски товарным путём недостижимо: чанки приложения в индекс не идут, и модель
# отвечала бы из собственных знаний — ровно та незаземлённость, что чинилась в P1.
# ⚠ Узко намеренно: нужен НОМЕР сноски. Код ОКПД2 в запросе отменяет правило — «требования к
# 28.22.14 и что значит сноска 6» это товарный вопрос, там сноска идёт довеском к позиции.
_FOOTNOTE_REF_RE = re.compile(r"сноск\w*\s*(?:N\s*)?\d{1,2}\b|<\s*\d{1,2}(?:\.\d)?\s*>", re.IGNORECASE)


def is_procedural(query: str, has_code: bool = False) -> bool:
    """True — вопрос процедурный (порядок/сроки/документы по реестру) → отвечаем по Правилам реестра.

    Логика: нужен процедурный маркер (STRONG сам по себе ИЛИ GENERIC-глагол + 719-якорь). Явный
    ТОВАРНО-БАЛЛЬНЫЙ сигнал (баллы/локализация/требования) уводит на товарный путь — это вопрос про
    требования конкретной продукции. Код ОКПД2 сам по себе процедурный путь НЕ отменяет: «процедура
    внесения в реестр чиллеров 28.25.13» — ПРОЦЕДУРНЫЙ вопрос (порядок один для всех продуктов), код
    здесь вторичен. `has_code` оставлен для совместимости сигнатуры (больше НЕ блокирует):
    раньше код деферил процедуру, но теперь Правила индексированы и смешанный вопрос отвечается."""
    q = query or ""
    # Вопрос об определении сноски — процедурный, даже если в нём есть слово «требование».
    if _FOOTNOTE_REF_RE.search(q) and not has_okpd2_code(q):
        return True
    # `P3` #121: маркер ЛИБО намерение вопроса. Товарно-балльный сигнал глушит оба — он и был
    # инвариантом этого гейта, и дырявить его ради темы незачем: на замере обе формы дают
    # одинаковые числа, а эта сохраняет правило целым.
    if not (_has_procedural_marker(q) or _has_routing_topic(q)):
        return False
    # Два дисквалификатора, оба финальные: товарно-балльный сигнал (вопрос про требования к
    # продукции) и вопрос про САМУ ПАЛАТУ (членство/взносы — вне 719).
    # ⚠ Явный токен второго ключа снимает ПЕРВЫЙ дисквалификатор, но НЕ второй: «как вступить в
    # ТПП, чтобы получить СТ-1» — по-прежнему вопрос про членство, то есть вне 719.
    if _SECOND_KEY_RE.search(q) and not _has_mixed_product_signal(q):
        return not _CHAMBER_MEMBERSHIP_RE.search(q)
    return not (_PRODUCT_HINT_RE.search(q) or _CHAMBER_MEMBERSHIP_RE.search(q))


