"""Детектор процедурного интента — маршрутизатор на корпус процедурных норм.

Товарные записи (требования локализации и баллы) и процедурные нормы живут в РАЗНЫХ коллекциях:
`pp719` — приложение к ПП №719, `pp719_rules` — Правила формирования и ведения реестра + ТЕЛО
ПП №719 (критерии п.1, включая СТ-1) + Приказ ТПП РФ №52 (состав документов, сроки, акт на
компоненты). У них разные промпты и разные гарды, поэтому вопрос надо развести ДО поиска.

Без детектора чистый процедурный вопрос («какой порядок внесения в реестр») уходит в товарный
поиск → возвращаются ближайшие ТОВАРНЫЕ позиции (мусор) → LLM может «сочинить» порядок действий
и сроки. Здесь мы ловим процедурный интент ДЕТЕРМИНИРОВАННО (регулярками, без LLM) и уводим
вопрос на корпус Правил: ноль стоимости на маршрутизацию, воспроизводимо.

ИСТОРИЯ И ТЕКУЩАЯ РОЛЬ `DEFLECTION`. Изначально (до индексации Правил) детектор короткозамыкал
ответ честным дефером — «процедуру не знаю, вот первоисточники». Теперь корпус загружен, и дефер
остался ФОЛБЭКОМ внутри `pipeline._answer_procedural`: срабатывает, только если корпус выключен
флагом `PROCEDURAL_ANSWER_FROM_RULES`, коллекции нет или поиск ничего не вернул. Порядок действий
и сроки не выдумываем ни при каких условиях.

Дисциплина ложных срабатываний: детектор бьёт только по ЧИСТО процедурным вопросам. Если в
запросе есть код ОКПД2 или явный товарно-балльный сигнал («требования к локализации», «сколько
баллов») — это товарный или СМЕШАННЫЙ вопрос, его НЕ деферим (отвечаем по базе; про процедурную
часть модель предупредит по правилу 1в промпта навигатора).
"""

