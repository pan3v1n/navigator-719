"""Процедурный дефер-предохранитель (демо-safety-net).

RAG индексирует ТОЛЬКО приложение к ПП №719 с продукцией — требования локализации и баллы.
Процедурный регламент (внесение в реестр российской промышленной продукции, работа с ГИСП,
подача заявления, сроки рассмотрения, обжалование отказа, состав документов) в базу НЕ загружен.

Без предохранителя чистый процедурный вопрос («какой порядок внесения в реестр») уходит в
обычный поиск → возвращаются ближайшие ТОВАРНЫЕ позиции (мусор) → LLM может «сочинить» порядок
действий и сроки. Здесь мы ловим процедурный интент ДЕТЕРМИНИРОВАННО (регулярками, без LLM) и
короткозамыкаем ответ честным дефером с указателем на первоисточники: ноль галлюцинаций, ноль
стоимости, воспроизводимо.

Дисциплина ложных срабатываний: детектор бьёт только по ЧИСТО процедурным вопросам. Если в
запросе есть код ОКПД2 или явный товарно-балльный сигнал («требования к локализации», «сколько
баллов») — это товарный или СМЕШАННЫЙ вопрос, его НЕ деферим (отвечаем по базе; про процедурную
часть модель предупредит по правилу 1в промпта навигатора).
"""

from __future__ import annotations

import re

# --- Маркеры ПРОЦЕССА (внесение/подача/сроки/обжалование/ведомство), а не продукта. -------
# Осознанно НЕ триггерим на одиночные «реестр»/«документы»/«требования» — они встречаются и в
# нормальных товарных вопросах («требования к локализации насосов для внесения в реестр»).
#
# Два тира, чтобы не хватать вне-719 админ-вопросы («как зарегистрировать ИП», «порядок получения
# загранпаспорта»): STRONG — самодостаточные маркеры регистра 719 (ГИСП/внесение в реестр/…);
# GENERIC — общие процедурные глаголы (порядок получения/как оформить/сроки), которые триггерят
# ТОЛЬКО при наличии 719-ЯКОРЯ (реестр/промышленная продукция/ГИСП/Минпромторг/заявление). Вне-719
# админ-вопросы без якоря уходят в обычный отказ «вне сферы 719» (правило 1б), а не в этот дефер.
_STRONG_PATTERNS = [
    r"\bгисп\b",
    r"минпромторг",
    r"внесени\w*\s+в\s+реестр",
    r"включени\w*\s+в\s+реестр",
    r"внести\s+\w+(?:\s+\w+){0,4}\s+в\s+реестр",
    r"реестр\w*\s+(?:российской\s+)?промышленной\s+продукции",
    r"заявлени\w*\s+(?:о\s+)?(?:внесени|включени)",
    r"отказ\w*\s+во?\s+(?:внесени|включени)",
    r"пода(?:ть|ча|чи|чу)\s+заяв(?:ку|ки|ление|ления)",
    r"выдач\w*\s+заключени",
    r"как\s+получить\s+заключени\w*\s+о\s+производств",
    r"акт\s+экспертизы",
]
_GENERIC_PATTERNS = [
    r"порядок\s+(?:подач|внесени|включени|рассмотрени|получени|оформлени|регистрац)",
    r"как\s+(?:внести|включить|подать|оформить|зарегистрировать)\b",
    r"срок\w*\s+рассмотрени",
    r"в\s+течение\s+скольких\s+(?:дней|рабочих)",
    r"обжалов",
    # документы: собрать/подготовить/представить/подать/нужны (0-2 слова между «документы» и глаголом,
    # чтобы ловить «какие документы НУЖНО СОБРАТЬ»); + «перечень/состав/комплект документов». GENERIC —
    # срабатывает ТОЛЬКО с 719-якорем (реестр/заявление/ГИСП/…), поэтому вне-719 «документы» не задевает.
    r"какие\s+документы(?:\s+\w+){0,2}\s+(?:собра\w*|подгото\w*|представ\w*|пода|нужн\w*|необходим\w*|требу\w*)",
    r"(?:перечень|состав|список|комплект|пакет)\s+документ",
]
# 719-якорь для GENERIC-маркеров (без него общий глагол = не наш процедурный вопрос).
_ANCHOR_PATTERNS = [
    r"реестр",
    r"промышленной\s+продукции",
    r"\bгисп\b",
    r"минпромторг",
    r"заявлени\w*",
    r"заявк\w*",
    r"заключени\w*\s+о\s+производств",
    r"подтвержд\w*\s+производств",
]
_STRONG_RE = re.compile("|".join(_STRONG_PATTERNS), re.IGNORECASE)
_GENERIC_RE = re.compile("|".join(_GENERIC_PATTERNS), re.IGNORECASE)
_ANCHOR_RE = re.compile("|".join(_ANCHOR_PATTERNS), re.IGNORECASE)


def _has_procedural_marker(q: str) -> bool:
    """STRONG-маркер сам по себе ИЛИ GENERIC-глагол + 719-якорь."""
    return bool(_STRONG_RE.search(q)) or bool(_GENERIC_RE.search(q) and _ANCHOR_RE.search(q))

# Товарно-балльный сигнал: если он есть, вопрос про требования конкретной продукции (может быть
# смешанным) → НЕ короткозамыкаем, отвечаем по базе.
_PRODUCT_HINT_RE = re.compile(r"баллов?|локализац|требован\w*", re.IGNORECASE)

# Код ОКПД2 в тексте запроса («29.20.23») — товарная привязка.
_CODE_RE = re.compile(r"\b\d{2}\.\d{2}(?:\.\d+)*\b")


def procedural_markers(query: str) -> list[str]:
    """Совпавшие процедурные маркеры (для отладки/свипа ложных срабатываний)."""
    q = query or ""
    return [m.group(0) for m in list(_STRONG_RE.finditer(q)) + list(_GENERIC_RE.finditer(q))]


def is_procedural(query: str, has_code: bool = False) -> bool:
    """True — вопрос ЧИСТО процедурный (корпусом не покрыт, деферим).

    Возвращает False, если есть код ОКПД2 (в параметре или в тексте) либо товарно-балльный
    сигнал — такой вопрос товарный/смешанный, его обрабатывает обычный пайплайн."""
    q = query or ""
    if has_code or _CODE_RE.search(q):
        return False
    if not _has_procedural_marker(q):
        return False
    return not _PRODUCT_HINT_RE.search(q)


