"""Редакция ПП №719, на которой стоит корпус (K10-соседняя задача E1).

ЗАЧЕМ. Постановление правится 6+ раз в год, и отставание даже на одну редакцию = формально
неверный ответ по баллам, порогам и позициям. В отзывах июльского теста это уже звучало:
«Приведена ссылка на недействующую редакцию ПП №719», «ссылается на устаревшие редакции».
Показанная редакция делает устаревание **видимым** — это дешёвая функция против дорогого
класса ошибок.

Насколько это не теория: 12.08.2026 обнаружилось, что корпус отстал на ДВЕ редакции
(N 899 от 16.07 и N 923 от 22.07), причём тело постановления — сильнее приложения, и заметили
это только вручную. Если бы редакция выводилась, расхождение бросилось бы в глаза.

ПОЧЕМУ НЕ КОНСТАНТА В КОНФИГЕ. Константу надо помнить обновлять при каждой актуализации —
ровно тот ручной шаг, на котором корпус и отстал. Редакция **выводится из самого корпуса**
и потому не может разойтись с ним молча: обновили текст — обновилась и подпись.

ПОЧЕМУ СВОЙСТВО КОРПУСА, А НЕ ЗАПИСИ. Решение владельца 12.08.2026: в работе нужна **одна
действующая редакция**, история версий не поддерживается. Значит всё приложение проиндексировано
одной редакцией, и хранить её в payload каждой из 1380 записей незачем — переиндексация ради
подписи не нужна. У процедурного корпуса `edition` в payload есть и остаётся: там три документа
разной юридической силы, у каждого своя редакция.

ГДЕ ПОКАЗЫВАЕТСЯ (та же логика, что у пометки эксперта в R3): постоянной строкой в интерфейсе
и в шапке КАЖДОЙ выгрузки. В тело ответа не вставляем — это свойство сервиса, а не реплики,
и повтор в каждом сообщении был бы шумом.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

from loguru import logger

_ROOT = Path(__file__).resolve().parents[2]
# Тело постановления: 20 КБ против 5.3 МБ полного текста, а перечень изменяющих актов там тот же.
_BODY = _ROOT / "knowledge_base" / "pp719" / "chunks" / "01_postanovlenie.txt"

# «(в ред. Постановлений Правительства РФ от 22.07.2026 N 923, …)»
# ⚠ Форма номера и пробелы — как в `scripts/watch_edition.py` (ревью PR #94): «N», «№»,
# кириллическая «Н», неразрывный пробел. Здесь это не косметика — от разбора зависит ключ
# `KONTUR_719_BY_EDITION`, то есть ссылка на первоисточник в интерфейсе и в каждой выгрузке;
# не разобрали — редакция становится UNKNOWN. Ярлык на выходе всегда с латинской «N».
_AMEND_RE = re.compile(r"от\s*(\d{2})\.(\d{2})\.(\d{4})\s*[NН№]\s*(\d+)")

UNKNOWN = "редакция не определена"


@lru_cache(maxsize=1)
def corpus_edition() -> str:
    """Последний по дате изменяющий акт в тексте постановления → «ред. от ДД.ММ.ГГГГ N NNN».

    Тот же принцип, что у `detect_edition` в `scripts/load_rules_kb.py` (там штампуются пункты
    процедурного корпуса). Дубль намеренный: `app/` не импортирует из `scripts/` — это разные
    слои, и связывать рантайм с загрузчиком ради одной регулярки хуже, чем повторить её.
    """
    try:
        text = _BODY.read_text(encoding="utf-8")
    except OSError:
        return UNKNOWN
    best_key, best = (0, 0, 0, 0), None
    for m in _AMEND_RE.finditer(text):
        d, mth, y, num = int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4))
        key = (y, mth, d, num)
        if key > best_key:
            best_key = key
            best = f"ред. от {m.group(1)}.{m.group(2)}.{m.group(3)} N {m.group(4)}"
    return best or UNKNOWN


def corpus_line() -> str:
    """Строка для интерфейса и шапки выгрузки."""
    ed = corpus_edition()
    return f"База: Постановление Правительства РФ №719 в {ed}" if ed != UNKNOWN else (
        "База: Постановление Правительства РФ №719, редакция не определена")


