# ЗАЧЕМ ЗДЕСЬ. У Контура КАЖДАЯ редакция документа — свой `documentId`, и ссылка на вчерашнюю
# редакцию открывается с красной пометкой «Не действует». То есть адрес первоисточника — это
# свойство РЕДАКЦИИ, а не константа сервиса, и жить он обязан рядом с определением редакции.
#
# ПОЧЕМУ НЕ ПРОСТО КОНСТАНТА (урок 16.08.2026). Раньше `documentId` был захардкожен в двух местах
# (`app/api/chat.py` и `app/web/static/chat.js`) с комментарием «⚠ при вступлении в силу новой
# редакции обновить». Корпус за это время ушёл на две редакции вперёд (01.07 → 22.07), а ссылка
# осталась на 27.06 — эксперт третьей волны кликал источник и попадал на НЕДЕЙСТВУЮЩИЙ текст.
# Ровно тот ручной шаг, из-за которого редакция корпуса и выводится из текста, а не задаётся
# константой (см. шапку модуля). Теперь адрес привязан к редакции таблицей, а `tests/test_rag.py`
# краснеет, если корпус актуализировали, а ссылку — нет: молчаливый дрейф стал громким.
#
# КАК ОБНОВЛЯТЬ при актуализации корпуса: открыть текущую ссылку, Контур сам показывает
# «действующая версия» → взять из неё `documentId` и добавить строку в таблицу ниже.
KONTUR_BASE = "https://normativ.kontur.ru/document?moduleId=1&documentId="

# Редакция корпуса (как её печатает `corpus_edition`) → documentId этой редакции у Контура.
# Старые строки не удаляем: по ним видно историю и с ними работает откат на прошлый корпус.
KONTUR_719_BY_EDITION: dict[str, str] = {
    "ред. от 22.07.2026 N 923": "507406",   # действует с 24.07.2026 — текущая
    "ред. от 27.06.2026 N 794": "506899",   # действовала с 01.07.2026
}

# Приказ ТПП РФ №52 — ОТДЕЛЬНЫЙ документ со своей историей редакций, к редакции 719 не привязан
# (проверено 16.08.2026: действует, ред. от 29.10.2025).
KONTUR_PRIKAZ_52_URL = KONTUR_BASE + "505398"

# Якорь раздела «Правила формирования и ведения реестра» ВНУТРИ документа 719 (проверено в
# редакции 507406 — `<A NAME="h14240">`). Если в новой редакции он изменится, ссылка не сломается:
# рядом всегда идёт текст-фрагмент `:~:text=`, и браузер доскроллит по нему.
RULES_ANCHOR = "#h14240"


def kontur_719_url() -> str:
    """Ссылка на текст ПП №719 в ТОЙ редакции, на которой стоит корпус.

    Редакции нет в таблице (корпус обновили, ссылку забыли) — берём самую свежую известную и
    ГРОМКО пишем в лог: тихо отдать ссылку на чужую редакцию хуже, чем отдать устаревшую с
    записью в журнале. Тест на соответствие таблицы корпусу — `TestKonturLinks`."""
    ed = corpus_edition()
    doc_id = KONTUR_719_BY_EDITION.get(ed)
    if doc_id is None:
        doc_id = next(iter(KONTUR_719_BY_EDITION.values()))
        logger.warning(
            "редакция корпуса «{}» отсутствует в KONTUR_719_BY_EDITION — источники ведут на {}; "
            "добавь documentId новой редакции в app/rag/edition.py", ed, doc_id)
    return KONTUR_BASE + doc_id
