"""Справочник подтверждающих документов — ЗАКРЫТЫЙ перечень (`K15` #36).

ЗАЧЕМ. «Какие документы готовить» — самая частая тема отзывов июля (**31 упоминание**). И там же
самый заметный дефект ответов: модель выдумывала несуществующее «заключение ТПП» — «сертификаты
СТ-1 или заключения ТПП о происхождении сырья/материалов», «потребуется заключение ТПП о
подтверждении производства». Эксперты ДВАЖДЫ давали закрытый перечень; держать его надо
справочником, а не правилом промпта.

⚠⚠ ПОЧЕМУ НЕ ПРОМПТОМ. Действующее правило 1е товарного промпта запрещает термин, НАЗЫВАЯ его.
`EV12` уже измерила, чем это кончается: запрет слова не держится, пока слово живёт в самом
промпте (0.83 против 0.98) — модель воспроизводит то, что видит. Поэтому здесь ДАННЫЕ (закрытая
таблица в контекст) плюс РАНТАЙМ-ГАРД на выходе, а не третья формулировка запрета.

⚠⚠ «ЗАКЛЮЧЕНИЕ» — НЕ ЗАПРЕЩЁННОЕ СЛОВО. Сверка с корпусом (25.08.2026) показала, что слепой
запрет был бы дефектом:
* «экспертное заключение» — РЕАЛЬНЫЙ действующий документ: его формирует ТПП РФ по итогам
  ВЫЕЗДНОЙ ПРОВЕРКИ, и Минпромторг по нему исключает реестровую запись (п. 36-40 Правил).
  Это инструмент КОНТРОЛЯ, а не подтверждения производства;
* «заключение о выполнении обязательств инвестором» — из СПИК, тело ПП №719;
* «заключение специального инвестиционного контракта» — вообще не документ, а действие.
Не существует ровно одного: «заключения ТПП», ПОДТВЕРЖДАЮЩЕГО ПРОИЗВОДСТВО. Гард ловит именно
эту связку и обязан пропускать три законные.

⚠ ЧЕГО ЗДЕСЬ НЕТ: сроков, пошлин и порядка подачи. Справочник отвечает на вопрос «какой документ»,
а не «как его получить» — это Приказ №52 и Правила, они в корпусе и находятся поиском. Дублировать
их таблицей значило бы завести второй источник тех же фактов.
"""

from __future__ import annotations

import re

# --- Закрытый перечень -------------------------------------------------------------------------

# Порядок = порядок в таблице ответа. Первым идёт документ для продукции ИЗ приложения: сервис
# построен на приложении 719, и этот случай у пользователя основной.
CONFIRMING_DOCUMENTS: tuple[dict[str, str], ...] = (
    {
        "name": "Акт экспертизы уполномоченной ТПП",
        "when": "продукция ВКЛЮЧЕНА в приложение к ПП №719 — подтверждается соответствие "
                "требованиям локализации из приложения",
        "source": "ПП №719, п. 1; Приказ ТПП РФ №52",
    },
    {
        "name": "Сертификат о происхождении товара формы СТ-1",
        "when": "продукции НЕТ в приложении к ПП №719 — подтверждается, что страной происхождения "
                "является Российская Федерация (подпункт «г» пункта 1)",
        "source": "ПП №719, п. 1, подпункт «г»; Приказ ТПП РФ №52",
    },
    {
        "name": "Сведения о реестровой записи с выписками из реестра",
        "when": "результат: продукция внесена в реестр российской промышленной продукции; "
                "выписка подтверждает запись",
        "source": "Правила формирования и ведения реестра",
    },
)

# Документ, которого НЕ существует, и чем его путают. Хранится ДАННЫМИ, чтобы разъяснение можно
# было показать пользователю, а не только запретить слово.
NONEXISTENT_TERM = "заключение ТПП"
NONEXISTENT_EXPLANATION = (
    "Документа «заключение ТПП», подтверждающего производство, не существует. "
    "Производство подтверждает АКТ ЭКСПЕРТИЗЫ уполномоченной ТПП (для продукции из приложения) "
    "или СЕРТИФИКАТ СТ-1 (для продукции вне приложения). "
    "Отдельно существует «экспертное заключение» ТПП РФ — оно составляется по итогам выездной "
    "проверки уже внесённой продукции и служит основанием для ИСКЛЮЧЕНИЯ реестровой записи, "
    "а не для подтверждения производства."
)

TABLE_TITLE = "Подтверждающие документы (перечень закрытый)"


def documents_table() -> str:
    """Markdown-таблица закрытого перечня. Печатает КОД, а не модель.

    Тот же приём, что у `points_table` (P4): перечень, который обязан быть точным и полным,
    выводится из данных. Модели остаётся объяснение и привязка к случаю пользователя — то, что
    она делает хорошо, — а не воспроизведение списка по памяти."""
    rows = ["", f"**{TABLE_TITLE}:**", "",
            "| Документ | Когда применяется | Основание |", "|---|---|---|"]
    for d in CONFIRMING_DOCUMENTS:
        rows.append(f"| {d['name']} | {d['when']} | {d['source']} |")
    return "\n".join(rows)


def documents_context_block() -> str:
    """Блок для КОНТЕКСТА модели: закрытый перечень + разъяснение про несуществующий документ.

    ⚠ Разъяснение идёт в контекст ЦЕЛИКОМ, вместе с термином. Это не противоречит `EV12`: там речь
    о запрете в ПРОМПТЕ («не пиши слово X»), который модель нарушает тем охотнее, чем чаще слово
    в промпте. Здесь термин приходит как ФАКТ с объяснением — «такого документа нет, вот что есть
    вместо него», — то есть ответ на вопрос, который пользователь и так задаёт своими словами.
    Разница проверяется гардом `unverified_documents` на выходе, а не рассуждением."""
    lines = [f"СПРАВОЧНИК ПОДТВЕРЖДАЮЩИХ ДОКУМЕНТОВ (перечень ЗАКРЫТЫЙ, других документов нет):"]
    for d in CONFIRMING_DOCUMENTS:
        lines.append(f"- {d['name']} — {d['when']}. Основание: {d['source']}.")
    lines.append(NONEXISTENT_EXPLANATION)
    return "\n".join(lines)


# --- Гард: несуществующий документ в ответе ----------------------------------------------------

# Связка «заключение» + ТПП/палата в роли ПОДТВЕРЖДАЮЩЕГО документа.
# ⚠ Граница вправо и влево выбрана по реальным выдумкам из кейса эксперта:
#   «потребуется заключение ТПП о подтверждении производства»
#   «сертификаты СТ-1 или заключения ТПП о происхождении сырья/материалов»
# ⚠ «экспертное заключение» исключается ЯВНО — это действующий документ п. 36-40 Правил.
_EXPERT_CONCLUSION = re.compile(r"экспертн\w*\s+заключени\w*", re.I)
_FAKE_CONCLUSION = re.compile(
    r"заключени\w*\s+(?:уполномоченн\w+\s+)?(?:ТПП|торгово-промышленн\w+\s+палат\w+)"
    r"|(?:ТПП|торгово-промышленн\w+\s+палат\w+)\s+(?:выда\w+|оформля\w+)\s+заключени\w*",
    re.I,
)


def unverified_documents(text: str) -> list[str]:
    """Упоминания несуществующего «заключения ТПП» в ответе. Пусто — ответ чист.

    Гард РАНТАЙМОВЫЙ и работает по той же логике, что `unverified_numbers`: правило промпта может
    не сработать, и тогда дефект обязан быть виден, а не уехать пользователю молча.

    ⚠ Порядок проверок важен. Сначала вырезаем законные «экспертные заключения», потом ищем
    выдумку — иначе фраза «ТПП РФ формирует экспертное заключение» дала бы ложное срабатывание, а
    предохранитель, бьющий по верному тексту, дороже отсутствующего (урок выкатки 20.08)."""
    cleaned = _EXPERT_CONCLUSION.sub(" ", text)
    seen: set[str] = set()
    out: list[str] = []
    for m in _FAKE_CONCLUSION.finditer(cleaned):
        frag = " ".join(m.group(0).split())
        key = frag.lower()
        if key not in seen:
            seen.add(key)
            out.append(frag)
    return out
