"""Справочник подтверждающих документов — ЗАКРЫТЫЙ перечень (`K15` #36).

ЗАЧЕМ. «Какие документы готовить» — самая частая тема отзывов июля (**31 упоминание**). И там же
самый заметный дефект ответов: модель выдумывала несуществующее «заключение ТПП» — «сертификаты
СТ-1 или заключения ТПП о происхождении сырья/материалов», «потребуется заключение ТПП о
подтверждении производства». Эксперты ДВАЖДЫ давали закрытый перечень; держать его надо
справочником, а не правилом промпта.

⚠⚠ ПОЧЕМУ НЕ ПРОМПТОМ. Действующее правило 1е товарного промпта запрещает термин, НАЗЫВАЯ его.
`EV12` уже измерила, чем это кончается: запрет слова не держится, пока слово живёт в самом
промпте (0.83 против 0.98) — модель воспроизводит то, что видит. Поэтому здесь ДАННЫЕ (закрытая
таблица в контекст) плюс РАНТАЙМ-ГАРД на выходе, а не третья формулировка запрета.

⚠⚠ «ЗАКЛЮЧЕНИЕ» — НЕ ЗАПРЕЩЁННОЕ СЛОВО. Сверка с корпусом (25.08.2026) показала, что слепой
запрет был бы дефектом:
* «экспертное заключение» — РЕАЛЬНЫЙ действующий документ: его формирует ТПП РФ по итогам
  ВЫЕЗДНОЙ ПРОВЕРКИ, и Минпромторг по нему исключает реестровую запись (п. 36-40 Правил).
  Это инструмент КОНТРОЛЯ, а не подтверждения производства;
* «заключение о выполнении обязательств инвестором» — из СПИК, тело ПП №719;
* «заключение специального инвестиционного контракта» — вообще не документ, а действие.
Не существует ровно одного: «заключения ТПП», ПОДТВЕРЖДАЮЩЕГО ПРОИЗВОДСТВО. Гард ловит именно
эту связку и обязан пропускать три законные.

⚠ ЧЕГО ЗДЕСЬ НЕТ: сроков, пошлин и порядка подачи. Справочник отвечает на вопрос «какой документ»,
а не «как его получить» — это Приказ №52 и Правила, они в корпусе и находятся поиском. Дублировать
их таблицей значило бы завести второй источник тех же фактов.
"""

from __future__ import annotations

import re

# --- Закрытый перечень -------------------------------------------------------------------------

# Порядок = порядок в таблице ответа. Первым идёт документ для продукции ИЗ приложения: сервис
# построен на приложении 719, и этот случай у пользователя основной.
CONFIRMING_DOCUMENTS: tuple[dict[str, str], ...] = (
    {
        "name": "Акт экспертизы уполномоченной ТПП",
        "when": "продукция ВКЛЮЧЕНА в приложение к ПП №719 — подтверждается соответствие "
                "требованиям локализации из приложения",
        "source": "ПП №719, п. 1; Приказ ТПП РФ №52",
    },
    {
        "name": "Сертификат о происхождении товара формы СТ-1",
        "when": "продукции НЕТ в приложении к ПП №719 — подтверждается, что страной происхождения "
                "является Российская Федерация (подпункт «г» пункта 1)",
        "source": "ПП №719, п. 1, подпункт «г»; Приказ ТПП РФ №52",
    },
    {
        "name": "Сведения о реестровой записи с выписками из реестра",
        "when": "результат: продукция внесена в реестр российской промышленной продукции; "
                "выписка подтверждает запись",
        "source": "Правила формирования и ведения реестра",
    },
)

# Документ, которого НЕ существует, и чем его путают. Хранится ДАННЫМИ, чтобы разъяснение можно
# было показать пользователю, а не только запретить слово.
NONEXISTENT_TERM = "заключение ТПП"
NONEXISTENT_EXPLANATION = (
    "Документа «заключение ТПП», подтверждающего производство, не существует. "
    "Производство подтверждает АКТ ЭКСПЕРТИЗЫ уполномоченной ТПП (для продукции из приложения) "
    "или СЕРТИФИКАТ СТ-1 (для продукции вне приложения). "
    "Отдельно существует «экспертное заключение» ТПП РФ — оно составляется по итогам выездной "
    "проверки уже внесённой продукции и служит основанием для ИСКЛЮЧЕНИЯ реестровой записи, "
    "а не для подтверждения производства."
)

TABLE_TITLE = "Подтверждающие документы (перечень закрытый)"


def documents_table() -> str:
    """Markdown-таблица закрытого перечня. Печатает КОД, а не модель.

    Тот же приём, что у `points_table` (P4): перечень, который обязан быть точным и полным,
    выводится из данных. Модели остаётся объяснение и привязка к случаю пользователя — то, что
    она делает хорошо, — а не воспроизведение списка по памяти."""
    rows = ["", f"**{TABLE_TITLE}:**", "",
            "| Документ | Когда применяется | Основание |", "|---|---|---|"]
    for d in CONFIRMING_DOCUMENTS:
        rows.append(f"| {d['name']} | {d['when']} | {d['source']} |")
    return "\n".join(rows)


# Пользователь сам поднял тему «заключения». Ловим ЛЮБУЮ его форму: и выдуманное «заключение ТПП»,
# и законное «экспертное заключение» — во втором случае разъяснение тоже к месту, оно как раз их и
# разводит.
_ASKS_ABOUT_CONCLUSION = re.compile(r"заключени", re.I)

# ⚠⚠ «ЗАКЛЮЧЕНИЕ» — ЕЩЁ И ДЕЙСТВИЕ, А НЕ ТОЛЬКО ДОКУМЕНТ. Ревью пакета 26.08.2026 показало цену
# широкого детектора: «какие требования при ЗАКЛЮЧЕНИИ СПИК для 27.11.42» и «производим станки,
# ЗАКЛЮЧЕНИЕ ДОГОВОРА с поставщиком» — товарные вопросы, и справочник с разъяснением про
# несуществующий документ уезжал бы в них обоих. Это ровно тот дефект, который чинила `dbfc622`
# (термин приходит к пользователю, который про него не спрашивал), заново открытый на товарной
# ветке. Само тело постановления знает «заключение СПИК» как ДЕЙСТВИЕ — см. шапку модуля.
_CONCLUSION_AS_ACT = re.compile(
    r"заключени\w*(?:\s+\w+){0,3}\s+(?:договор|контракт|соглашени|сделк|\bспик\b)", re.I)
# Документ узнаём по соседству: ТПП / Минпромторг / «о подтверждении производства» /
# «о происхождении». Окно в четыре слова — «заключения ТПП о происхождении сырья» и
# «заключение о подтверждении производства промышленной продукции» помещаются с запасом.
_CONCLUSION_AS_DOC = re.compile(
    r"заключени\w*(?:\W+\w+){0,4}\W+(?:ТПП|торгово-промышленн|палат\w*|минпромторг|производств|происхожден)"
    r"|(?:ТПП|торгово-промышленн\w*\s+палат\w*|минпромторг\w*)(?:\W+\w+){0,4}\W+заключени", re.I)


def asks_about_conclusion(query: str) -> bool:
    """Пользователь сам поднял тему «заключения» КАК ДОКУМЕНТА.

    ⚠⚠ ЭТОТ ЖЕ ПРЕДИКАТ РЕШАЕТ И СУДЬБУ ВСЕГО БЛОКА, а не только разъяснения внутри него
    (`K15-1` #120). Прежде гейты расходились: СОДЕРЖИМОЕ блока зависело от ВОПРОСА (разъяснение —
    только если спросили), а САМ блок — от ТЕМЫ (`topics.DOCUMENTS`). На вопросе «нужно ли
    заключение ТПП для внесения продукции в реестр» тема — `registry_entry`, и справочника не было
    вовсе: модель оставалась наедине с памятью ровно там, где риск выдумать документ максимален.

    Замеренный радиус согласования — 4 вопроса всех наборов, и все четыре того самого класса:
    «сертификаты СТ-1 или заключения ТПП о происхождении сырья» (дословная выдумка из кейса
    эксперта), «порядок получения заключения о подтверждении производства» и «а что есть
    Заключение Минпромторга?» — два последних про шаг, ОТМЕНЁННЫЙ 29.06.2024.

    ⚠ УЖЕ, ЧЕМ ПРОСТО СЛОВО «заключение»: оно бывает ДЕЙСТВИЕМ («при заключении СПИК», «заключение
    договора»), и на таком вопросе справочник с разъяснением был бы той же утечкой термина к
    пользователю, который про него не спрашивал, — дефектом, который уже чинила `dbfc622`."""
    q = query or ""
    if _CONCLUSION_AS_ACT.search(q):
        return False
    return bool(_CONCLUSION_AS_DOC.search(q))


def documents_context_block(query: str = "") -> str:
    """Блок для КОНТЕКСТА модели: закрытый перечень; разъяснение — ТОЛЬКО если спросили.

    ⚠⚠ РАЗЪЯСНЕНИЕ УСЛОВНОЕ, И ЭТО ИСПРАВЛЕНИЕ ДЕФЕКТА, А НЕ ЭКОНОМИЯ. Первая редакция клала его
    в контекст БЕЗУСЛОВНО, на каждый документный вопрос. Живой прогон на бою 25.08.2026 показал,
    чем это кончается: на вопрос «какие документы подготовить» ответ содержал строку «Документа
    «заключение ТПП» не существует» — пользователю, который про этот документ не спрашивал и,
    возможно, впервые о нём слышит.

    То есть правка, задуманная чтобы термин ИСЧЕЗ из ответов, начала его туда ПРИНОСИТЬ. Ровно
    то, что измерила `EV12`: слово, живущее в контексте, модель воспроизводит — и неважно, что
    рядом стоит отрицание. Механизм сильнее намерения.

    Закрытый перечень остаётся всегда: он отвечает на ЗАДАННЫЙ вопрос («какие документы»).
    Разъяснение отвечает на НЕЗАДАННЫЙ — и приезжает, только когда его задали.

    ⚠ Правило 3б промпта при этом не меняется: оно велит не соглашаться с названием, которого нет
    в справочнике. Закрытого перечня для этого достаточно — модели не нужно знать заранее, КАКИЕ
    названия выдуманы, ей нужно знать, какие настоящие."""
    lines = ["СПРАВОЧНИК ПОДТВЕРЖДАЮЩИХ ДОКУМЕНТОВ (перечень ЗАКРЫТЫЙ, других документов нет):"]
    for d in CONFIRMING_DOCUMENTS:
        lines.append(f"- {d['name']} — {d['when']}. Основание: {d['source']}.")
    if query and _ASKS_ABOUT_CONCLUSION.search(query):
        lines.append(NONEXISTENT_EXPLANATION)
    return "\n".join(lines)


# --- Гард: несуществующий документ в ответе ----------------------------------------------------

# Связка «заключение» + ТПП/палата в роли ПОДТВЕРЖДАЮЩЕГО документа.
# ⚠ Граница вправо и влево выбрана по реальным выдумкам из кейса эксперта:
#   «потребуется заключение ТПП о подтверждении производства»
#   «сертификаты СТ-1 или заключения ТПП о происхождении сырья/материалов»
# ⚠ «экспертное заключение» исключается ЯВНО — это действующий документ п. 36-40 Правил.
_EXPERT_CONCLUSION = re.compile(r"экспертн\w*\s+заключени\w*", re.I)
# ⚠⚠ ОТРИЦАНИЕ — ЭТО ВЕРНЫЙ ОТВЕТ, А НЕ ДЕФЕКТ. Найдено живым прогоном на бою 25.08.2026, срезу
# после выкатки: гард сработал на ЛУЧШЕМ из возможных ответов —
#   «Перечень подтверждающих документов закрытый: производство подтверждается актом экспертизы
#    ТПП … или сертификатом СТ-1 …. Документа «заключение ТПП» НЕ СУЩЕСТВУЕТ.»
# Это ровно то поведение, ради которого K15 и делалась: справочник кладёт разъяснение в контекст,
# модель им пользуется. Гард наказывал её за это — и писал WARNING в админ-журнал, то есть
# эксперт видел «ответ называет несуществующий документ» на самых правильных ответах.
# Предохранитель, бьющий по верному, дороже отсутствующего.
#
# ⚠ Почему не заметил раньше: локально гоняю с ВЫКЛЮЧЕННЫМИ кейсами и на выборке из четырёх
# прогонов термин не появился ни разу. На бою — 2 раза из 5. Разброс генерации, который
# ловится только повтором, а не одним прогоном (правило трёх прогонов в силе).
_DENIAL = re.compile(
    r"не\s+существу|нет\s+так|так(ого|ой)\s+документа\s+нет|не\s+бывает|"
    r"не\s+использу|не\s+применя|отсутству|ошибочн|неверн|не\s+называ",
    re.I,
)
# Окно вокруг термина, в котором ищется отрицание. 200 символов — предложение целиком с запасом:
# отрицание в реальных ответах стоит сразу после названия («Документа «X» не существует»), но
# встречается и перед ним («не используйте термин X»).
_DENIAL_WINDOW = 200


_FAKE_CONCLUSION = re.compile(
    r"заключени\w*\s+(?:уполномоченн\w+\s+)?(?:ТПП|торгово-промышленн\w+\s+палат\w+)"
    r"|(?:ТПП|торгово-промышленн\w+\s+палат\w+)\s+(?:выда\w+|оформля\w+)\s+заключени\w*",
    re.I,
)


def unverified_documents(text: str) -> list[str]:
    """Упоминания несуществующего «заключения ТПП» в ответе. Пусто — ответ чист.

    Гард РАНТАЙМОВЫЙ и работает по той же логике, что `unverified_numbers`: правило промпта может
    не сработать, и тогда дефект обязан быть виден, а не уехать пользователю молча.

    ⚠ Порядок проверок важен. Сначала вырезаем законные «экспертные заключения», потом ищем
    выдумку — иначе фраза «ТПП РФ формирует экспертное заключение» дала бы ложное срабатывание, а
    предохранитель, бьющий по верному тексту, дороже отсутствующего (урок выкатки 20.08)."""
    cleaned = _EXPERT_CONCLUSION.sub(" ", text)
    seen: set[str] = set()
    out: list[str] = []
    for m in _FAKE_CONCLUSION.finditer(cleaned):
        # ⚠ ОТРИЦАНИЕ РЯДОМ = ответ ОБЪЯСНЯЕТ, а не советует. Это не дефект, а цель K15.
        lo = max(0, m.start() - _DENIAL_WINDOW)
        hi = min(len(cleaned), m.end() + _DENIAL_WINDOW)
        if _DENIAL.search(cleaned[lo:hi]):
            continue
        frag = " ".join(m.group(0).split())
        key = frag.lower()
        if key not in seen:
            seen.add(key)
            out.append(frag)
    return out
