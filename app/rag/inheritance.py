"""Наследование требований по группам приложения 719 (R6, шаг 3).

ЗАЧЕМ. В приложении 719 группа видов продукции делит ОДНУ вертикально объединённую ячейку
требований (доказано: в RTF 1235 меток `\\clvmrg`, а striprtf рендерит такую ячейку пустой).
После конвертации потомки группы остались без требований: 349 позиций из 1368 — каждый четвёртый
товарный вопрос упирался в «требований не найдено». Здесь мы возвращаем им требования ГРУППЫ.

ГЛАВНЫЙ ПРИНЦИП — АТРИБУЦИЯ, А НЕ ПОДМЕНА. Требования показываются не как «свои», а с явным
указанием, от какой позиции группы они взяты. Неверно приписанные баллы хуже отсутствия: эксперт
увидит правдоподобный перечень и не заметит подмены, а faithfulness-гард его не поймает (он
проверяет заземлённость числа в контексте, а не правильность привязки). Поэтому:
  * карта строится ТОЛЬКО из случаев INHERIT/HIGH (непрерывный блок пустых ячеек под родителем);
  * позиции с расколотой ячейкой (R29) исключены с обеих сторон;
  * родитель обязан иметь требования сам;
  * баллы НЕ суммируются автоматически — это делает эксперт по первоисточнику.

Карта генерируется детерминированно из чанков и структурированной базы:
    python scripts/diag_orphan_requirements.py --inheritance \\
        knowledge_base/pp719/inherited_requirements.json
Правится ТОЛЬКО перегенерацией. Переиндексация Qdrant НЕ нужна — сверка идёт в рантайме по
разделу и наименованию позиции.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

_PATH = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719"
         / "inherited_requirements.json")

_FOOTNOTE = re.compile(r"<[^>|\n]{1,16}>")


def _key(section: str | None, name: str | None) -> str:
    """Ключ позиции: раздел + первая строка наименования без сносок.

    Раздел в ключе обязателен: одноимённые позиции встречаются в разных разделах, и без него
    требования уехали бы в чужой раздел. Сноски (`<9>`) снимаем — в исходной таблице имя пишется
    со сноской, а в записи базы без неё."""
    first = _FOOTNOTE.sub(" ", (name or "").strip().split("\n")[0])
    return f"{section or '?'}|{re.sub(r'\s+', ' ', first).strip().lower()}"


@lru_cache(maxsize=1)
def _map() -> tuple[dict, dict]:
    """(parents, children) из файла карты. Файла нет/битый → пусто, наследование просто не работает."""
    if not _PATH.exists():
        return {}, {}
    try:
        data = json.loads(_PATH.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}, {}
    return data.get("parents") or {}, data.get("children") or {}


def lookup(section: str | None, product_name: str | None) -> dict | None:
    """Требования группы для позиции без своих требований, либо None.

    Возвращает запись родителя: product_name, okpd2_codes, min_threshold, operations."""
    parents, children = _map()
    p_key = children.get(_key(section, product_name))
    return parents.get(p_key) if p_key else None


def attribution(parent: dict) -> str:
    """Строка-атрибуция для контекста: откуда взяты требования и что с ними можно делать."""
    codes = ", ".join(parent.get("okpd2_codes") or [])
    where = f"«{parent.get('product_name', '')}»" + (f" (ОКПД2 {codes})" if codes else "")
    return (
        f"ТРЕБОВАНИЯ ГРУППЫ (своих у позиции в приложении нет): позиция входит в группу видов "
        f"продукции с ОБЩИМИ требованиями, которые в приложении приведены у позиции {where}. "
        f"Ниже — требования ЭТОЙ ГРУППЫ. В ответе обязательно укажи, что требования групповые и "
        f"взяты у названной позиции, и предложи сверить состав группы с первоисточником ПП №719."
    )
