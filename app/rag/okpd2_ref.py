"""Справочник ОКПД2 + переходные ключи ТН ВЭД↔ОКПД2 (T9) — детерминированные лукапы, без сети/модели.

Данные (сборка `scripts/build_classifiers.py` из xlsx заказчика, коммитятся в репо):
  - knowledge_base/classifiers/okpd2.tsv       — «код<TAB>наименование» (весь классификатор ~19k)
  - knowledge_base/classifiers/tnved_okpd2.tsv — «тнвэд_цифры<TAB>окпд2» (переходные ключи)

Закрывает частые запросы теста (боль «определение кода — вход в реестр»):
  - `okpd2_name(code)`          — официальное наименование по коду (валидация/подпись; иерарх. фолбэк);
  - `tnved_to_okpd2(tnved)`     — ОКПД2 по коду ТН ВЭД из сертификата (→ дальше проверка в приложении 719);
  - `okpd2_to_tnved(okpd2)`     — обратное;
  - `suggest_okpd2_by_name(...)`— подсказка кода по наименованию по ВСЕМУ классификатору (глубже, чем 719).

Всё лениво кэшируется на процесс. Числа/коды — дословно из первоисточника (не выдумываются)."""
from __future__ import annotations

import math
import re
from functools import lru_cache
from pathlib import Path

_DIR = Path(__file__).resolve().parents[2] / "knowledge_base" / "classifiers"
_OKPD2_TSV = _DIR / "okpd2.tsv"
_KEYS_TSV = _DIR / "tnved_okpd2.tsv"


@lru_cache(maxsize=1)
def _okpd2_names() -> dict[str, str]:
    if not _OKPD2_TSV.exists():
        return {}
    out: dict[str, str] = {}
    for ln in _OKPD2_TSV.read_text(encoding="utf-8").splitlines():
        if "\t" in ln:
            code, name = ln.split("\t", 1)
            out[code] = name
    return out


@lru_cache(maxsize=1)
def _keys() -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """(тнвэд→[окпд2], окпд2→[тнвэд]) из переходных ключей."""
    t2o: dict[str, list[str]] = {}
    o2t: dict[str, list[str]] = {}
    if _KEYS_TSV.exists():
        for ln in _KEYS_TSV.read_text(encoding="utf-8").splitlines():
            if "\t" not in ln:
                continue
            tn, ok = ln.split("\t", 1)
            t2o.setdefault(tn, []).append(ok)
            o2t.setdefault(ok, []).append(tn)
    return t2o, o2t


# --- Код ОКПД2 в свободном тексте — ЕДИНСТВЕННОЕ место разбора ------------------------
# ⚠ ДАТА ВЫГЛЯДИТ КАК КОД, и это не теория. Ревью PR #94 воспроизвело пять форм на живом коде:
# «27.12.2023г» давало РЕАЛЬНЫЙ код `27.12` («Аппаратура распределительная») — регулярка с `\b`
# откатывалась на префикс, потому что кириллическая «г» границей слова не является; «01.07.26»
# и «31.12.26» проходили как коды (двузначный год короче трёх цифр); «09.00»/«18.00» — часы работы.
# С `EV8` каждый найденный код становится ЦЕЛЕВЫМ и приносит в контекст полные требования своей
# позиции: дата в вопросе снова открывала утечку чужих чисел, которую закрывала `EV7`, и утечку
# НЕВИДИМУЮ — числа лежат в контексте, поэтому ни `unverified_numbers`, ни гейт их не помечают.
#
# ⚠ Прежний фильтр стоял В ОДНОЙ копии регулярки из семи (`navigator.OKPD2_IN_TEXT`), а `_anchor_code`,
# `_HAS_CODE_RE`, `retriever._CODE_IN_TEXT` разбирали текст сами. Поэтому разбор переехал СЮДА:
# одно решение — одно место (иначе правка чинит метрику, а не продукт).
#
# Два признака, оба из ДАННЫХ, а не из смысла фразы:
#   1) ФОРМА. Токен берётся ЦЕЛИКОМ (`\d+(?:\.\d+)+` без отката на префикс), у ОКПД2 сегменты
#      2, 2 и далее 1–3 цифры, не более четырёх. `27.12.2023` отбрасывается как целое.
#   2) КЛАССИФИКАТОР. Форму «ДД.ММ», «ЧЧ.ММ» и «ДД.ММ.ГГ» отличить от кода нельзя — обе
#      правдоподобны. Спрашиваем справочник (19 200 кодов + их точечные префиксы): `27.12` и
#      `29.10` в нём есть и остаются кодами, `09.00`, `01.07`, `01.07.26`, `31.12.26` — нет и
#      отбрасываются. Именно ПРЕФИКСЫ, а не точное вхождение: см. `_code_prefixes`.
# Если файла классификатора нет (усечённая выкатка), сомнительный токен ПРИНИМАЕТСЯ — прежнее
# поведение: молча ослепнуть на реальных кодах хуже, чем пропустить дату.
_CODE_IN_TEXT = re.compile(r"(?<![\d.])\d+(?:\.\d+)+(?!\d|\.\d)")


@lru_cache(maxsize=1)
def _code_prefixes() -> frozenset[str]:
    """Все коды классификатора И их точечные префиксы: «26.11.22.200» → 26 · 26.11 · 26.11.22.

    ⚠ Почему префиксы, а не точное вхождение. Файл классификатора неполон на уровне КЛАССОВ:
    `29.10` (автомобилестроение), `32.50` (медизделия), `21.20`, `26.30`, `21.10` в нём
    отсутствуют, хотя это ходовые коды корпуса. Точная проверка отбрасывала бы их как «дату»
    — правка под один запрос сломала бы соседние (радиус измерен: 1000 кодов корпуса)."""
    out: set[str] = set()
    for code in _okpd2_names():
        segs = code.split(".")
        for i in range(1, len(segs) + 1):
            out.add(".".join(segs[:i]))
    return frozenset(out)


def _shape_is_okpd2(segs: list[str]) -> bool:
    # ОКПД2: раздел XX · группа XX.X · класс XX.XX · категория XX.XX.X · подкатегория XX.XX.XX ·
    # вид XX.XX.XX.XXX. Второй сегмент бывает и однозначным («27.2», «13.2» — в корпусе есть).
    return (2 <= len(segs) <= 4 and len(segs[0]) == 2 and 1 <= len(segs[1]) <= 2
            and all(1 <= len(x) <= 3 for x in segs[2:]))


def _date_or_clock_like(segs: list[str]) -> bool:
    """Токен неотличим по форме от даты или времени — решать должен справочник, не форма."""
    try:
        a, b = int(segs[0]), int(segs[1])
    except ValueError:
        return False
    if len(segs) == 2:
        return (1 <= a <= 31 and 1 <= b <= 12) or (a <= 23 and b <= 59)  # ДД.ММ либо ЧЧ.ММ
    if len(segs) == 3 and len(segs[2]) == 2:
        return 1 <= a <= 31 and 1 <= b <= 12                              # ДД.ММ.ГГ
    return False


def is_okpd2_code(token: str | None) -> bool:
    """Токен — код ОКПД2, а не дата, время или номер пункта."""
    if not token:
        return False
    segs = token.split(".")
    if not _shape_is_okpd2(segs):
        return False
    if _date_or_clock_like(segs):
        known = _code_prefixes()
        return token in known if known else True
    return True


def extract_codes(text: str | None) -> list[str]:
    """ВСЕ коды ОКПД2 из текста, в порядке появления, без повторов."""
    out: list[str] = []
    for m in _CODE_IN_TEXT.finditer(text or ""):
        tok = m.group(0)
        if is_okpd2_code(tok) and tok not in out:
            out.append(tok)
    return out


def has_okpd2_code(text: str | None) -> bool:
    r"""В тексте есть код ОКПД2. ⚠ Не `\d{2}\.\d{2}`: дата в вопросе выключала мультитёрн."""
    for m in _CODE_IN_TEXT.finditer(text or ""):
        if is_okpd2_code(m.group(0)):
            return True
    return False


def normalize_tnved(s: str | None) -> str:
    """ТН ВЭД → только цифры («0101 21» / «8407 34 000 0» → «010121» / «8407340000»)."""
    return "".join(ch for ch in (s or "") if ch.isdigit())


# Детект кода ТН ВЭД в свободном тексте. КОНСЕРВАТИВНО (иначе ловим номера договоров/ИНН/годы):
# либо явный маркер «ТН ВЭД <код>», либо код с ПРОБЕЛЬНОЙ группировкой («8471 30», «8407 34 100 0») —
# так его пишут в сертификатах/декларациях. Голый слитный 10-значный без маркера НЕ трогаем.
_TNVED_CUE_RE = re.compile(r"(?:тн\s*вэд|тнвэд)\D{0,6}(\d{4}\s?\d{2}(?:\s?\d{2,4}){0,3})", re.IGNORECASE)
_TNVED_GROUPED_RE = re.compile(r"(?<![\d.,])(\d{4}\s\d{2}(?:\s?\d{2,4}){0,3})(?![\d.,])")


def extract_tnved(text: str | None) -> str | None:
    """Код ТН ВЭД из текста (маркер «ТН ВЭД …» ИЛИ пробел-группированный код), иначе None."""
    t = text or ""
    m = _TNVED_CUE_RE.search(t) or _TNVED_GROUPED_RE.search(t)
    return m.group(1).strip() if m else None


# --- ТОВАРНАЯ ПОЗИЦИЯ для оси СТ-1 (`K14` #35) -------------------------------------------------
#
# ⚠⚠ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ПРАВКА `extract_tnved`, И ПРИЧИНА В ГРАНУЛЯРНОСТИ КЛЮЧА.
# `extract_tnved` требует не меньше ШЕСТИ цифр (`\d{4}\s?\d{2}`) — он писался под переходные ключи
# ТН ВЭД↔ОКПД2, которые живут на уровне HS6. А Перечень условий Соглашения СНГ ключуется на
# ЧЕТЫРЁХЗНАЧНОЙ товарной позиции (8403, 8501, 8704): собственная гранулярность второго ключа
# прежнему извлекателю НЕ ВИДНА ВОВСЕ — ни один вопрос приёмочного набора он не разбирал.
# Править его на месте нельзя: радиус ляжет на `translate.py`, у которого своя приёмка.
#
# ⚠ Маркер ОБЯЗАТЕЛЕН. Четыре цифры подряд — слишком частый узор («в 2026 году», «приказ 1392»),
# и без явного «ТН ВЭД» / «товарная позиция» блок условий уезжал бы в чужие вопросы. Номер
# документа исключён отдельно: «постановление № 1392» маркер бы не спас, если он рядом.
_TNVED_POSITION_CUE_RE = re.compile(r"тн\s*вэд|тнвэд|товарн\w*\s+позици", re.IGNORECASE)
# ⚠ Хвост запрещает ПРОДОЛЖЕНИЕ ЧИСЛА, а не пунктуацию. Первая редакция стояла `(?![\d.,])` и
# роняла «мой код ТН ВЭД 8501, какие условия» — код отвергался обычной запятой предложения.
# Найдено прогоном приёмочного набора, а не чтением регулярки.
#
# ⚠⚠ ГРУППЫ РЕАЛЬНОГО КОДА — 4+2+3+1, А НЕ ПО ДВЕ (находка 1 второго раунда ревью PR #137).
# Первая редакция брала `\d{4}(?:\s?\d{2}){0,3}` — только ДВУЗНАЧНЫЕ группы, и на стандартной
# записи «0710 40 000» трёхзначную группу съесть не могла: матч обрывался на шести знаках.
# Цена — не «неполный код», а НЕВЕРНЫЙ ОТВЕТ: `0710 40` в Перечне отсутствует, и лукап уверенно
# печатал «НЕ включён — применяется общее правило» про позицию, которая в Перечне ЕСТЬ и которую
# пользователь назвал ПОЛНОСТЬЮ. У «8544 70 000 0» условие подменялось родительским.
# ⚠ Кодов длиннее шести знаков в Перечне 61 из 244 — четверть таблицы. Не поймал ни один сторож:
# все приёмочные кейсы и релизная проверка используют ЧЕТЫРЁХЗНАЧНЫЕ коды, а `test_st1_ref`
# кормит полные коды прямо в `conditions_for`, минуя извлекатель.
_TNVED_POSITION_RE = re.compile(
    r"(?<![\d.,№])(\d{4}(?:\s?\d{2}(?:\s?\d{2,4}){0,3}(?:\s?\d)?)?)(?!\d|[.,]\d)")

# ⚠⚠ ЧЕТЫРЕ ЦИФРЫ РЯДОМ С МАРКЕРОМ — ЕЩЁ НЕ КОД (находка 2 второго раунда). Правка первого раунда
# («брать ближайшее к маркеру») помогает лишь когда настоящий код в тексте ЕСТЬ; без него
# ближайшим оказывается год или сумма: «какие условия … по ТН ВЭД в 2026 году» → `2026`, и блок
# уезжает в промпт под указанием «используй ТОЛЬКО это значение».
# ⚠ Диапазоном лет отсечь нельзя: 1902 и 2009 — НАСТОЯЩИЕ товарные позиции ТН ВЭД. Отсекаем по
# СОСЕДНЕМУ СЛОВУ, которое делает число годом или суммой, а не кодом.
# ⚠ «г» БЕЗ ТОЧКИ ТОЖЕ ГОД (находка MED-3 четвёртого раунда ревью): «в 2026 г» и «2026г» пишут не
# реже, чем «2026 г.». Требование точки пропускало год обратно в код.
# ⚠⚠ СУММА УЗНАЁТСЯ И ПО СЛОВУ ПЕРЕД ЧИСЛОМ (находка 3 шестого раунда). Прежняя редакция
# смотрела только СЛЕДОМ за числом («500000 рублей»), и голая сумма проходила: «сумма
# контракта 250000» давала код `250000`, а лукап печатал «в Перечень НЕ включён — применяется
# общее правило» под указанием «используй ТОЛЬКО это значение». Та же половина дефекта, что
# закрывалась раундом 2, — только с другой стороны числа.
# ⚠ Слово-триггер вынесено в ГРУППУ: без неё `m.end()` указывал на конец всего матча, то есть
# ровно на начало числа, и проверка «есть ли маркер МЕЖДУ словом и числом» смотрела в пустую
# строку — она не могла сработать никогда (находка 3 седьмого раунда, вторая половина).
_TNVED_AMOUNT_BEFORE_RE = re.compile(
    r"(?P<word>сумм\w*|оборот\w*|стоимост\w*|цен[аыу]|выручк\w*|бюджет\w*|контракт\w*)"
    r"[^.;|]{0,24}$", re.IGNORECASE)
# ⚠⚠ СПИСОК РАЗДЕЛЁН НАДВОЕ ПО НАПРАВЛЕНИЮ ОШИБКИ (находка 5 восьмого раунда ревью PR #137).
# Раунд 7 положил `позиц\w*|единиц\w*` в общий список — и голый четырёхзначный код перестал
# извлекаться вовсе: «ТН ВЭД 1902 позиций» → None, при том что 1902 НАСТОЯЩАЯ товарная позиция.
# Причина в том, что у списка ДВЕ работы, а правило было одно:
#   • ОТСЕЧЬ приклеившийся счётчик, когда групп больше одной («ТН ВЭД 8403 12 шт» → «8403»);
#   • ОТВЕРГНУТЬ число целиком, когда группа одна и она не код («в 2026 году», «250000 рублей»).
# Счётчик количества (шт/позиций/единиц) обосновывает ТОЛЬКО первую: число перед ним может быть
# кодом, который пересчитывают. Денежная и временная единица (рублей/года/%) обосновывает обе —
# после них число кодом не бывает никогда.
# ⚠ «Позиция» вдобавок ПОЛОВИНА собственного признака модуля (`товарн\w*\s+позици`): токен,
# означающий «это ЕСТЬ код», лежал в списке «это НЕ код».
# ⚠ Объединение ВЫВОДИТСЯ из половин, а не выписывается третьим списком. Ровно на «двух таблицах
# про одно» проект уже обжигался (находка раунда 6): расходятся они молча, и побеждает та, которую
# читает горячий путь. Здесь инвариант держится ПО ПОСТРОЕНИЮ, тестом его проверять нечего.
_TNVED_UNIT = r"год\w*|г(?![а-яё])\.?|рубл\w*|руб\.?|₽|тыс\w*|млн|млрд|процент\w*|%"
_TNVED_COUNTER = r"шт\.?|штук\w*|позиц\w*|единиц\w*"
_TNVED_UNIT_RE = re.compile(rf"^\s*(?:{_TNVED_UNIT})", re.IGNORECASE)
_TNVED_NOT_A_CODE_RE = re.compile(rf"^\s*(?:{_TNVED_UNIT}|{_TNVED_COUNTER})", re.IGNORECASE)
# ⚠ Последний пробельный знак, а НЕ ASCII-пробел (находка MED-5 восьмого раунда). `_TNVED_POSITION_RE`
# склеивает группы через `\s?`, то есть допускает TAB и NBSP, а срез искал `rfind(" ")` и при NBSP
# уходил в ветку «одна группа» → None. NBSP — норма для кодов из Word, выгрузок ГИСП и деклараций.
_TNVED_LAST_SPACE_RE = re.compile(r"\s(?=\S*$)")
_DIGIT_RE = re.compile(r"\d")
# ⚠ РЕКВИЗИТ АКТА УЗНАЁТСЯ НЕ ТОЛЬКО ВПЛОТНУЮ (вторая половина находки MED-3 четвёртого раунда).
# Прежняя форма требовала, чтобы слово «постановление» стояло непосредственно перед числом, и
# «постановление 719 ОТ 2020» отдавало `2020` как код ТН ВЭД. Дата акта отделена от его названия
# номером — значит и окно должно быть шире, но в пределах одного оборота: до 30 знаков и без
# точки, чтобы не захватить соседнее предложение.
# ⚠⚠ БЕЗУСЛОВНЫЙ «№» УБРАН ИЗ ОТСЕЧКИ (находка 2 шестого раунда ревью PR #137). Альтернатива
# `(?:№|N)\s*$` не была привязана ни к какому слову акта и отсекала КОД, записанный обычным
# образом: «код ТН ВЭД № 8403», «условия по ТН ВЭД N 8403», «товарная позиция № 8403 ТН ВЭД» —
# а «товарная позиция» это одна из ДВУХ объявленных форм маркера. Блок условий молча исчезал, и
# ответ строился по одним пунктам. Реквизит акта отсекается по СЛОВУ акта, а не по значку номера.
_TNVED_POSITION_SKIP_RE = re.compile(
    r"\b(?:постановлени\w*|приказ\w*|распоряжени\w*|закон\w*|соглашени\w*|протокол\w*|ред\.)\s*(?:№|N)?\s*$"
    r"|\b(?:постановлени\w*|приказ\w*|распоряжени\w*|закон\w*|соглашени\w*|протокол\w*|ред\.)[^.;|]{0,30}"
    r"(?:от|№|N)\s*$",
    re.IGNORECASE)


_TNVED_POSITION_MAX_GAP = 30  # знаков между маркером и кодом


def _trim_to_code(text: str, m: re.Match) -> tuple[str | None, int]:
    """Матч → (код, конец) с ОТСЕЧЕНИЕМ приклеившегося постороннего числа.

    Шаблон жадный: «ТН ВЭД 8403 12 шт» даёт «8403 12». Проверка «не код» смотрит слово ПОСЛЕ
    матча и на этом матче видит « шт» — прежняя редакция отбрасывала весь матч, теряя код 8403.
    Отсекаем приклеившееся число и возвращаем позицию.

    ⚠⚠ ОТСЕКАЕТСЯ РОВНО ОДНА ГРУППА И ТОЛЬКО У ЧЕТЫРЁХЗНАЧНОЙ ОСНОВЫ. Первая редакция этой
    правки резала в цикле «пока следом стоит слово-опровержение» — и на проверке краёв усекла
    НАСТОЯЩИЕ полные коды: «ТН ВЭД 8544 70 000 0 позиции» → «8544 70 000», «0710 40 000 единиц»
    → «0710 40». Это класс HIGH первого раунда (усечённый ключ даёт УВЕРЕННЫЙ ответ про ДРУГУЮ
    позицию), то есть правка чинила мелкий дефект ценой крупного.

    ⚠ Направление ошибки задаёт форму правила. Свернуть «8403 10» до «8403» — это подъём к
    РОДИТЕЛЬСКОЙ позиции, к которой сам «8403 10» и относится: цена ошибки — более общее
    условие. Срезать хвост у десятизначного кода — это переход к ЧУЖОЙ позиции. Поэтому
    отсечение разрешено, только когда основа состоит ровно из первой четырёхзначной группы:
    пользователь, написавший шесть и более знаков, дальше пишет код, а не количество.
    """
    token = m.group(1).strip()
    end = m.start() + len(token)
    if not _TNVED_NOT_A_CODE_RE.match(text[end:end + 16]):
        return token, end
    cut = token.rstrip()
    m_sp = _TNVED_LAST_SPACE_RE.search(cut)
    pos = m_sp.start() if m_sp else -1
    if pos <= 0:
        # ⚠⚠ ОДНА ГРУППА — ОТСЕКАТЬ НЕЧЕГО, И ТУТ ДВА СПИСКА РАСХОДЯТСЯ (находка 5 раунда 8).
        # Счётчик количества группу НЕ опровергает: «ТН ВЭД 1902 позиций» называет настоящую
        # позицию 1902, а прежнее общее правило роняло её в None. Опровергает только денежная
        # или временная единица — после «рублей», «года», «%» число кодом не бывает.
        if _TNVED_UNIT_RE.match(text[end:end + 16]):
            return None, end
        return token, end
    base = cut[:pos]
    if len(normalize_tnved(base)) != 4:
        # ⚠ Основа длиннее позиции: хвост принадлежит КОДУ, а слово-опровержение — шум за ним
        # («ТН ВЭД 8544 70 000 0 позиции»). Отдаём код целиком. Отбросить его было бы третьим
        # способом ошибиться на том же месте: сперва склейка сужала ключ, потом отсечение его
        # усекало, теперь молчание оставило бы вопрос вовсе без второго ключа.
        return token, end
    return base, m.start() + len(base)


def _amount_word_owns(text: str, num_start: int) -> bool:
    """Слово о деньгах/объёме описывает ИМЕННО ЭТО число, а не соседнее.

    ⚠⚠ Находка 3 седьмого раунда ревью PR #137: прежняя проверка дисквалифицировала ЛЮБОЕ число
    в 24 знаках после слова-триггера, и настоящий код выбрасывался — «сумма контракта 250000,
    ТН ВЭД 8403» → None, «по контракту ТН ВЭД 8403 какие условия» → None. «Контракт» здесь
    бытовая лексика этих вопросов («по контракту», «по госконтракту»).
    Различитель: если между словом-триггером и числом стоит МАРКЕР «ТН ВЭД», слово описывает не
    это число — маркер начал новый оборот.
    """
    m = _TNVED_AMOUNT_BEFORE_RE.search(text[:num_start])
    if not m:
        return False
    return not _TNVED_POSITION_CUE_RE.search(text[m.end("word"):num_start])


def _amount_word_shadows(text: str, num_start: int) -> bool:
    """Слово о деньгах стоит перед числом, но МЕЖДУ ними маркер ТН ВЭД — зона неоднозначности.

    ⚠⚠ Находка 1 восьмого раунда ревью PR #137. Раунд 7 объявил такой случай БЕЗУСЛОВНО кодом —
    и сумма стала ПОБЕЖДАТЬ настоящий код: «по контракту ТН ВЭД 250000 за товарную позицию 8703»
    → `250000`, доезжая в промпт дословно под «использовать ТОЛЬКО это значение». Обратное
    решение (безусловный отказ раунда 6) роняло «по контракту ТН ВЭД 8403 какие условия» → None.
    ⚠ Неверны ОБА, потому что вопрос НЕ ЛОКАЛЬНЫЙ: одна и та же строка «деньги + маркер + число»
    читается как код, когда другого кандидата нет, и как сумма, когда рядом есть чистый. Поэтому
    здесь не ФИЛЬТР, а РАНГ — неоднозначный кандидат проигрывает чистому и выигрывает у пустоты.
    Два раунда чинили это порогом «да/нет» на одном кандидате, а решает СРАВНЕНИЕ кандидатов.

    ⚠⚠ Слово о деньгах, у которого своё число уже ЕСТЬ, этого кандидата не затеняет: в «сумма
    контракта 250000, ТН ВЭД 8403» между «контракта» и 8403 стоит 250000 — сумма названа, и 8403
    чист. Без этой оговорки правка уронила бы положительный контроль раунда 7, ради которого
    безусловный отказ раунда 6 и сужали.
    """
    m = _TNVED_AMOUNT_BEFORE_RE.search(text[:num_start])
    if not m:
        return False
    between = text[m.end("word"):num_start]
    if _DIGIT_RE.search(between):
        return False                  # у слова о деньгах уже есть своё число, ближе этого
    return bool(_TNVED_POSITION_CUE_RE.search(between))


def extract_tnved_position(text: str | None) -> str | None:
    """Товарная позиция ТН ВЭД (4+ знака) для условий Перечня СТ-1, иначе None.

    Маркер «ТН ВЭД» / «товарная позиция» обязателен и может стоять ДО или ПОСЛЕ кода: реальный
    вопрос пишет и «код ТН ВЭД 8403», и «для товарной позиции 8402 по ТН ВЭД».

    ⚠⚠ КОД БЕРЁТСЯ РЯДОМ С МАРКЕРОМ, А НЕ ПЕРВЫМ ПОПАВШИМСЯ (находка 2 ревью PR #137).
    Первая редакция возвращала ПЕРВОЕ четырёхзначное число, как только маркер встретился где-то в
    тексте, — и «в 2026 году какие условия достаточной переработки для кода ТН ВЭД 8403» давало
    `2026`, а вопрос с суммой давал `500000`. Дальше лукап уверенно печатал «Код ТН ВЭД 2026: в
    Перечень НЕ включён — применяется общее правило», а промпт велел модели пользоваться ТОЛЬКО
    этим значением. Это ровно тот отказ, о котором предупреждает шапка модуля условий:
    правдоподобное и НЕВЕРНОЕ условие, снаружи неотличимое от верного.
    ⚠ Отрицательные контроли первой редакции этого не поймали, потому что проверяли год и сумму
    БЕЗ маркера — то есть случай, который отсекался ещё до разбора.
    """
    t = text or ""
    cues = [(m.start(), m.end()) for m in _TNVED_POSITION_CUE_RE.finditer(t)]
    if not cues:
        return None
    best: tuple[tuple[int, int], str] | None = None
    for m in _TNVED_POSITION_RE.finditer(t):
        if _TNVED_POSITION_SKIP_RE.search(t[:m.start()]):
            continue  # номер нормативного акта, а не товарная позиция
        # ⚠⚠ ПРИ ОТКАЗЕ ПРОБУЕМ КОРОЧЕ, А НЕ ВЫБРАСЫВАЕМ ЦЕЛИКОМ (находка 4 седьмого раунда ревью
        # PR #137). Шаблон жадный, и он приклеивал к коду ПОСТОРОННЕЕ число: «ТН ВЭД 8403 12 шт»
        # давало матч «8403 12», а проверка «не код» видела « шт» и отбрасывала ВЕСЬ матч — код
        # 8403 терялся, хотя стоит прямо в тексте. Так же уходили «8403 500000 рублей»,
        # «8403 2026 года», «8403 50 % цены». Хуже того, склейка молча СУЖАЛА ключ:
        # «код ТН ВЭД 8403 10 позиций» давало «8403 10», а у позиций с родительской и
        # подсубпозиционными строками (2106, 3806, 8521, 8544, 4012) это выбор ДРУГОЙ строки.
        token, end = _trim_to_code(t, m)
        if token is None:
            continue
        if _amount_word_owns(t, m.start()):
            continue  # «сумма контракта 250000» — слово ПЕРЕД числом описывает ЭТО число
        # Расстояние до ближайшего маркера — с любой стороны: код пишут и после «ТН ВЭД», и до.
        gap = min(max(cs - m.start() - len(token), m.start() - ce, 0) for cs, ce in cues)
        if gap > _TNVED_POSITION_MAX_GAP:
            continue
        # ⚠⚠ ЗАТЕНЁННОСТЬ СУММОЙ — РАНГ, А НЕ ФИЛЬТР (находка 1 восьмого раунда ревью PR #137).
        # Кандидат, перед которым стоит слово о деньгах с маркером между, уступает ЛЮБОМУ чистому
        # и берётся только при отсутствии чистого. Ключ сравнения — (затенён, расстояние): раунды
        # 6 и 7 решали это порогом «да/нет» на ОДНОМ кандидате, а вопрос решается СРАВНЕНИЕМ.
        key = (1 if _amount_word_shadows(t, m.start()) else 0, gap)
        if best is None or key < best[0]:
            best = (key, token)
    return best[1] if best else None


def okpd2_name(code: str | None) -> str | None:
    """Наименование по коду ОКПД2. Точного нет → иерархический фолбэк на родителя (28.13.14.190 → 28.13.14)."""
    names = _okpd2_names()
    code = (code or "").strip()
    if not code:
        return None
    if code in names:
        return names[code]
    parts = code.split(".")
    while len(parts) > 1:
        parts = parts[:-1]
        parent = ".".join(parts)
        if parent in names:
            return names[parent]
    return None


def tnved_to_okpd2(tnved: str | None) -> list[str]:
    """Коды ОКПД2 по коду ТН ВЭД (переходные ключи, уровень HS6). Для 8/10-значного — фолбэк на 6-знач. префикс."""
    t2o, _ = _keys()
    d = normalize_tnved(tnved)
    if not d:
        return []
    if d in t2o:
        return t2o[d]
    if len(d) > 6 and d[:6] in t2o:  # ключи на 6-значном уровне ГС
        return t2o[d[:6]]
    return []


def okpd2_to_tnved(okpd2: str | None) -> list[str]:
    """Коды ТН ВЭД по коду ОКПД2 (обратное направление ключей)."""
    _, o2t = _keys()
    return o2t.get((okpd2 or "").strip(), [])


@lru_cache(maxsize=1)
def _name_index() -> tuple[list[tuple[str, str]], dict[str, list[int]], dict[str, float]]:
    """Инвертированный IDF-индекс по наименованиям классификатора (для подсказки кода по имени).
    Строится один раз (~тысячи коротких строк, стем-токенизация BM25). Кэш на процесс."""
    from app.rag import sparse

    entries = list(_okpd2_names().items())  # [(код, наименование)]
    postings: dict[str, list[int]] = {}
    for i, (_code, name) in enumerate(entries):
        for tok in set(sparse.tokenize(name)):
            postings.setdefault(tok, []).append(i)
    n = len(entries) or 1
    idf = {t: math.log(1 + n / len(p)) for t, p in postings.items()}
    return entries, postings, idf


# Служебные/общие термины: их совпадение не должно перевешивать (иначе «прочие»/«для» тянут мусор наверх).
_STOP = {"прочий", "прочее", "проч", "друг", "включ", "групп", "издел", "продукц", "услуг"}


def suggest_okpd2_by_name(text: str, k: int = 5) -> list[tuple[str, str, float]]:
    """Подсказка кодов ОКПД2 по наименованию продукции — по ВСЕМУ классификатору (не только 719).
    top-k [(код, наименование, score)] по IDF-взвешенному пересечению стем-токенов запроса и наименования.
    Пусто, если значимого пересечения нет."""
    from app.rag import sparse

    entries, postings, idf = _name_index()
    qterms = {t for t in sparse.tokenize(text) if t not in _STOP}
    if not qterms:
        return []
    scores: dict[int, float] = {}
    matched: dict[int, int] = {}
    for t in qterms:
        w = idf.get(t)
        if w is None:
            continue
        for i in postings[t]:
            scores[i] = scores.get(i, 0.0) + w
            matched[i] = matched.get(i, 0) + 1
    if not scores:
        return []
    # Приоритет: больше совпавших уникальных терминов, затем IDF-сумма (специфичные термины важнее).
    top = sorted(scores, key=lambda i: (matched[i], scores[i]), reverse=True)[:k]
    return [(entries[i][0], entries[i][1], round(scores[i], 3)) for i in top]
