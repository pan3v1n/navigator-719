"""Чек-лист документов — из Приказа ТПП РФ №52, а не из головы (R25).

ЧТО БЫЛО. `navigator.BASE_CHECKLIST` — шесть пунктов, зашитых в код без единой ссылки на
первоисточник: «Заявление по форме ТПП», «Учредительные документы», «Технологические карты»…
Формулировки правдоподобные, но это ровно то, за что проект ругает языковую модель: перечень
документов, придуманный разработчиком и выданный эксперту как норма. Принцип №1 проекта
(«ничего не выдумывать») к коду относится не меньше, чем к промпту.

ЧТО СТАЛО. Пункты берутся ДОСЛОВНО из раздела 4 Приказа ТПП РФ №52 «Документы, необходимые для
получения акта экспертизы…», который с 21.07 лежит в корпусе (172 пункта) и в репозитории
(`knowledge_base/pp719/prikaz52_tpp_full.txt`). У каждого пункта чек-листа есть НОМЕР, по которому
эксперт сверится с первоисточником.

СТРУКТУРА РАЗДЕЛА 4 (она же логика чек-листа):
  * 4.2.1–4.2.3 — БАЗОВЫЕ документы, нужны всегда: правоустанавливающие, производственные фонды,
    документы на производство продукции;
  * 4.3.x — УСЛОВНЫЕ, «для подтверждения <критерия>»: их набор зависит от того, какие требования
    предъявляет позиция приложения 719 (права на КД/ТД, сервисный центр, техоперации, процентная
    доля). Поэтому подбираются по тексту требований найденной позиции.

Парсер здесь свой и минимальный (только раздел 4), чтобы `app/` не импортировал из `scripts/`.
Файла нет — чек-лист пуст, а не выдуман: `navigate` отдаёт пустой список, и это честнее.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

_ORDER52 = (Path(__file__).resolve().parents[2] / "knowledge_base" / "pp719"
            / "prikaz52_tpp_full.txt")

# Начало пункта раздела 4: «4.2.1. …», «4.3.10. …»
_POINT_RE = re.compile(r"^\s*(4(?:\.\d+){1,3})\.\s+(\S.*)$")
# Любой другой нумерованный пункт — граница раздела 4.
_ANY_POINT_RE = re.compile(r"^\s*(\d+(?:\.\d+){0,3})\.\s+\S")

# Всегда обязательные пункты (базовый комплект заявки).
_ALWAYS = ("4.2.1", "4.2.2", "4.2.3")

# Условные пункты: какой критерий требования приложения 719 их включает.
# Ключ — номер пункта Приказа, значение — регулярка по ТЕКСТУ требований найденной позиции.
_TRIGGERS: dict[str, re.Pattern] = {
    "4.3.1": re.compile(r"прав\w*\s+на\s+конструкторск|техническ\w*\s+документац|технологическ\w*\s+документац", re.I),
    "4.3.2": re.compile(r"прав\w*\s+собственност|модификац|модернизац\w*\s+программн", re.I),
    "4.3.3": re.compile(r"топологи\w*\s+интегральных", re.I),
    "4.3.4": re.compile(r"сервисн\w*\s+центр", re.I),
    "4.3.5": re.compile(r"операц|осуществлени\w*\s+на\s+территори|балл", re.I),
    "4.3.6": re.compile(r"процентн\w*\s+дол\w*\s+(?:количеств|стоимост)|иностранн\w*\s+материал", re.I),
    "4.3.7": re.compile(r"дол\w*\s+массы|российск\w*\s+материал", re.I),
    "4.3.8": re.compile(r"адвалорн", re.I),
}


def _title(text: str) -> str:
    """Заголовок пункта — фраза до первого перечисления («: -») или до конца первого предложения."""
    t = re.sub(r"\s+", " ", text).strip()
    cut = t.find(": -")
    if cut > 0:
        return t[:cut].rstrip(" :")
    m = re.search(r"\.\s", t)
    return (t[:m.start()] if m else t)[:300].rstrip(" :.")


@lru_cache(maxsize=1)
def _points() -> dict[str, str]:
    """{номер пункта раздела 4 → дословный текст}. Кэш на процесс."""
    if not _ORDER52.exists():
        return {}
    lines = _ORDER52.read_text(encoding="utf-8", errors="replace").split("\n")
    out: dict[str, list[str]] = {}
    cur: str | None = None
    for ln in lines:
        m = _POINT_RE.match(ln)
        if m:
            cur = m.group(1)
            out[cur] = [m.group(2)]
            continue
        if cur and _ANY_POINT_RE.match(ln):  # начался пункт вне раздела 4 — секция кончилась
            cur = None
            continue
        if cur and ln.strip():
            out[cur].append(ln.strip())
    return {p: " ".join(parts) for p, parts in out.items()}


def checklist_for(requirements_text: str = "", *, has_points: bool = False,
                  threshold: str | None = None) -> list[str]:
    """Перечень документов для позиции: базовые пункты + условные по её требованиям.

    `requirements_text` — склеенный текст требований найденной позиции (по нему включаются
    условные пункты 4.3.x). `has_points` / `threshold` — балльная модель и порог: добавляют
    пункт про подтверждение техопераций и напоминание про расчёт баллов."""
    pts = _points()
    if not pts:
        return []

    chosen: list[str] = list(_ALWAYS)
    text = requirements_text or ""
    for point, trigger in _TRIGGERS.items():
        if point in chosen or point not in pts:
            continue
        if trigger.search(text) or (point == "4.3.5" and has_points):
            chosen.append(point)

    items = [f"{_title(pts[p])} [Приказ ТПП РФ №52, п. {p}]" for p in chosen if p in pts]
    if threshold:
        # Не документ Приказа, а прикладное напоминание — помечено как таковое, без ложной ссылки.
        items.append(f"Расчёт набранных баллов с привязкой к подтверждающим документам "
                     f"(порог позиции: {threshold}).")
    return items
